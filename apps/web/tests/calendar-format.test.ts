import { describe, expect, it } from "vitest";

import {
  давностьНаБлоке,
  деньНедели,
  интервалСобытия,
  метаСобытия,
  подписьПериода,
  подписьПометки,
  подписьЧаса,
  пояснениеДня,
  фразаДавности,
  числоДня,
} from "@/calendar/format";
import type { День, Событие, Сетка } from "@/calendar/layout";

function сетка(параметры: {
  view?: "day" | "week";
  starts_on?: string;
  ends_on?: string;
  today?: string;
  freshness?: Partial<Сетка["freshness"]>;
}): Сетка {
  return {
    timezone: "Europe/Moscow",
    period: {
      view: параметры.view ?? "week",
      starts_on: параметры.starts_on ?? "2026-10-12",
      ends_on: параметры.ends_on ?? "2026-10-18",
      today: параметры.today ?? "2026-10-14",
    },
    freshness: {
      state: "fresh",
      portal: "ok",
      fetched_at: null,
      covered_from: null,
      covered_to: null,
      ...параметры.freshness,
    },
    days: [],
  };
}

const пара: Событие = {
  key: "пара",
  source: "itmo",
  starts_at: "2026-10-14T08:20:00+03:00",
  ends_at: "2026-10-14T09:50:00+03:00",
  title: "Физика",
  conflict: false,
  lesson_kind: "лекция",
  teacher: "Иванов",
  room: "ауд. 101",
  building: "Кронверкский 49",
  mode: "Очный",
  online_url: null,
  location: null,
  description: null,
};

function день(параметры: Partial<День> & { date: string }): День {
  return {
    date: параметры.date,
    is_today: параметры.is_today ?? false,
    mirror_covers: параметры.mirror_covers ?? true,
    flags: параметры.flags ?? [],
    events: параметры.events ?? [],
  };
}

describe("заголовок экрана", () => {
  it("неделя внутри одного месяца - как в макете", () => {
    expect(подписьПериода(сетка({}))).toBe("12–18 October");
  });

  it("неделя на стыке месяцев называет оба", () => {
    expect(
      подписьПериода(сетка({ starts_on: "2026-09-28", ends_on: "2026-10-04", today: "2026-09-30" })),
    ).toBe("28 September – 4 October");
  });

  it("день - день недели и дата", () => {
    expect(подписьПериода(сетка({ view: "day", starts_on: "2026-10-14", ends_on: "2026-10-14" }))).toBe(
      "Wednesday, 14 October",
    );
  });

  // На своей неделе год - шум; пролистав на год вперёд, owner обязан это увидеть.
  it("чужой год дописывается", () => {
    expect(подписьПериода(сетка({ starts_on: "2027-10-11", ends_on: "2027-10-17" }))).toBe(
      "11–17 October 2027",
    );
  });
});

describe("подписи сетки", () => {
  it("шапка недели сокращает день недели, шапка дня - нет", () => {
    expect(деньНедели("2026-10-12", "week")).toBe("Пн");
    expect(деньНедели("2026-10-14", "day")).toBe("Среда");
  });

  it("число дня без месяца: месяц стоит в заголовке экрана", () => {
    expect(числоДня("2026-10-12")).toBe("12");
  });

  it("час подписан без ведущего нуля - как в макете", () => {
    expect(подписьЧаса(8)).toBe("8:00");
    expect(подписьЧаса(14 + 10 / 60)).toBe("14:10");
  });

  it("время блока - интервал, в половинном блоке только начало", () => {
    expect(интервалСобытия(пара, false)).toBe("8:20–9:50");
    expect(интервалСобытия(пара, true)).toBe("8:20");
  });

  // Поля разных источников не сливаются: у пары аудитория, у события место.
  it("корпус попадает во вторую строку только на экране дня", () => {
    expect(метаСобытия(пара, "week")).toBe("лекция · ауд. 101");
    expect(метаСобытия(пара, "day")).toBe("лекция · ауд. 101 · Кронверкский 49");
  });

  it("у личного события во второй строке место, а не поля пары", () => {
    const событие: Событие = { ...пара, source: "event", location: "ул. Марата 12" };

    expect(метаСобытия(событие, "day")).toBe("ул. Марата 12");
  });
});

describe("давность", () => {
  it("свежее расписание полосы не даёт", () => {
    expect(фразаДавности(сетка({}))).toBeNull();
  });

  // Один и тот же момент двумя форматами - требование §8.4.
  it("полоса и пометка на блоке говорят про один момент", () => {
    const данные = сетка({
      freshness: { state: "stale", portal: "failing", fetched_at: "2026-10-12T07:10:00+03:00" },
    });

    expect(фразаДавности(данные)).toBe("Расписание от 12 октября, 07:10 — портал не отвечает.");
    expect(давностьНаБлоке(данные.freshness.fetched_at)).toBe("от 12.10");
  });

  it("портал жив, но расписание старое - без обвинения портала", () => {
    expect(
      фразаДавности(
        сетка({ freshness: { state: "stale", portal: "ok", fetched_at: "2026-10-12T07:10:00+03:00" } }),
      ),
    ).toBe("Расписание от 12 октября, 07:10.");
  });

  it("забор не проходил ни разу - это отдельное состояние, а не пустой экран", () => {
    expect(фразаДавности(сетка({ freshness: { state: "never", portal: "unknown" } }))).toContain(
      "ни разу",
    );
  });
});

describe("объяснение под сеткой дня", () => {
  it("период owner назван его же словом", () => {
    const текст = пояснениеДня(
      день({
        date: "2026-10-15",
        flags: [
          {
            id: 1,
            reason: "отъезд",
            note: null,
            starts_on: "2026-10-10",
            ends_on: "2026-10-20",
            manual: true,
          },
        ],
      }),
    );

    expect(текст?.заголовок).toBe("Период «отъезд».");
    expect(текст?.подробности).toContain("С 10 октября по 20 октября");
    expect(текст?.подробности).toContain("не входит в отставание");
  });

  it("автопометка объясняется как системная", () => {
    const текст = пояснениеДня(
      день({
        date: "2026-10-16",
        flags: [
          {
            id: 2,
            reason: "late_classes",
            note: null,
            starts_on: "2026-10-16",
            ends_on: "2026-10-16",
            manual: false,
          },
        ],
      }),
    );

    expect(текст?.заголовок).toBe("Поздние пары.");
    expect(текст?.подробности).toContain("система");
  });

  // Три вида пустоты §8.4 различимы, иначе экран врёт (инвариант 9).
  it("день вне окна забора и пустой день говорят разное", () => {
    const безДанных = пояснениеДня(день({ date: "2026-10-16", mirror_covers: false }));
    const пустой = пояснениеДня(день({ date: "2026-10-18" }));

    expect(безДанных?.заголовок).toContain("Сохранённых данных");
    expect(пустой?.заголовок).toBe("Ничего не запланировано.");
  });

  it("день с событиями объяснения не требует", () => {
    expect(пояснениеДня(день({ date: "2026-10-14", events: [пара] }))).toBeNull();
  });
});

describe("метка дня в шапке", () => {
  it("машинная причина переводится, причина owner остаётся как есть", () => {
    expect(подписьПометки("late_classes")).toBe("поздние пары");
    expect(подписьПометки("отъезд")).toBe("отъезд");
  });
});
