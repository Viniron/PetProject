import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

import { чегоНет } from "@/capture/Capture";
import { размер, страниц, этоPdf } from "@/capture/files";
import { собратьТекст, причинаОтказа } from "@/capture/speech";
import { вМомент, местное, минутМежду } from "@/capture/zone";
import { ШИРИНА_ТЕЛЕФОНА } from "@/shell/phone";

describe("время формы - в зоне owner", () => {
  it("часы берутся со стены, как их написал сервер, без зоны браузера", () => {
    expect(местное("2026-10-22T17:00:00+03:00")).toEqual({ дата: "2026-10-22", время: "17:00" });
    expect(местное(null)).toEqual({ дата: "", время: "" });
  });

  it("подтверждение уходит со смещением зоны owner", () => {
    expect(вМомент("2026-10-22", "17:00", "Europe/Moscow")).toBe("2026-10-22T17:00:00+03:00");
  });

  // У owner переходов нет, но зона - настройка, и правило обязано работать на любой.
  it("смещение берётся на дату события, а не на сегодня", () => {
    expect(вМомент("2026-07-01", "10:00", "Europe/Berlin")).toBe("2026-07-01T10:00:00+02:00");
    expect(вМомент("2026-12-01", "10:00", "Europe/Berlin")).toBe("2026-12-01T10:00:00+01:00");
  });

  it("зона к западу от UTC - со знаком минус", () => {
    expect(вМомент("2026-10-22", "09:30", "America/New_York")).toBe("2026-10-22T09:30:00-04:00");
  });

  it("неполная дата или время - не момент", () => {
    expect(вМомент("", "17:00", "Europe/Moscow")).toBeNull();
    expect(вМомент("2026-10-22", "", "Europe/Moscow")).toBeNull();
  });

  it("минуты между моментами разбора", () => {
    expect(минутМежду("2026-10-22T17:00:00+03:00", "2026-10-22T18:00:00+03:00")).toBe(60);
  });
});

describe("чего не хватает для подтверждения", () => {
  const полные = { название: "Зубной", дата: "2026-10-16", с: "16:30", до: "17:30", место: "", описание: "" };

  it("всё на месте - подтверждать можно", () => {
    expect(чегоНет(полные)).toBeNull();
  });

  it.each([
    [{ название: "", дата: "" }, "Укажите название и дату"],
    [{ дата: "" }, "Укажите дату, чтобы продолжить"],
    [{ название: "  " }, "Укажите название"],
    [{ до: "" }, "Укажите время начала и конца"],
    [{ до: "16:30" }, "Конец раньше начала — поправьте время"],
  ])("%o -> %s", (правка, подпись) => {
    expect(чегоНет({ ...полные, ...правка })).toBe(подпись);
  });
});

describe("файл захвата", () => {
  it("PDF узнаётся по типу или по имени", () => {
    expect(этоPdf(new File(["x"], "afisha.PDF"))).toBe(true);
    expect(этоPdf(new File(["x"], "a", { type: "application/pdf" }))).toBe(true);
    expect(этоPdf(new File(["x"], "IMG_2041.jpg", { type: "image/jpeg" }))).toBe(false);
  });

  it.each([
    [1, "1 страница"],
    [2, "2 страницы"],
    [5, "5 страниц"],
    [11, "11 страниц"],
    [22, "22 страницы"],
  ])("%i -> %s", (число, подпись) => {
    expect(страниц(число)).toBe(подпись);
  });

  it("размер - как в макете", () => {
    expect(размер(380_000)).toBe("380 КБ");
    expect(размер(1_400_000)).toBe("1,4 МБ");
  });
});

describe("речь", () => {
  it("окончательные и промежуточные куски собираются в одну строку", () => {
    const событие = {
      results: {
        length: 2,
        0: { isFinal: true, length: 1, 0: { transcript: "в среду в три " } },
        1: { isFinal: false, length: 1, 0: { transcript: " в деканат" } },
      },
    };
    expect(собратьТекст(событие)).toBe("в среду в три в деканат");
  });

  it("запрет микрофона назван своими словами", () => {
    expect(причинаОтказа("not-allowed")).toContain("Нет доступа к микрофону");
  });
});

describe("граница телефона", () => {
  // Хук и CSS решают «телефон или ПК» порознь; разойдутся - и на ширине
  // между ними капсула встанет по-телефонному, а вкладка покажет сетку ПК.
  it("совпадает с медиазапросом телефонной раскладки", () => {
    const css = readFileSync(resolve(__dirname, "../src/app/shell-mobile.css"), "utf-8");
    expect(css).toContain(`@media (max-width: ${ШИРИНА_ТЕЛЕФОНА}px)`);
  });
});
