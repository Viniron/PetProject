import { describe, expect, it } from "vitest";

import {
  границыДня,
  границыНедели,
  датаДляВида,
  разложитьДень,
  разобратьМомент,
  сдвинутьДату,
  сейчасВЗоне,
  часыШкалы,
  ПУСТОЙ_ДЕНЬ_С,
  ПУСТОЙ_ДЕНЬ_ПО,
  type День,
  type Событие,
  type Сетка,
} from "@/calendar/layout";

function событие(параметры: Partial<Событие> & { key: string }): Событие {
  return {
    key: параметры.key,
    source: параметры.source ?? "itmo",
    starts_at: параметры.starts_at ?? "2026-10-14T10:00:00+03:00",
    ends_at: параметры.ends_at ?? "2026-10-14T11:30:00+03:00",
    title: параметры.title ?? "Мат. анализ",
    conflict: параметры.conflict ?? false,
    lesson_kind: параметры.lesson_kind ?? null,
    teacher: null,
    room: параметры.room ?? null,
    building: параметры.building ?? null,
    mode: null,
    online_url: null,
    location: параметры.location ?? null,
    description: null,
  };
}

function день(параметры: Partial<День> & { date: string }): День {
  return {
    date: параметры.date,
    is_today: параметры.is_today ?? false,
    mirror_covers: параметры.mirror_covers ?? true,
    flags: параметры.flags ?? [],
    events: параметры.events ?? [],
  };
}

describe("разбор момента", () => {
  // Момент приходит в зоне owner. new Date() перевёл бы его в зону браузера,
  // и у owner в поездке пара уехала бы на несколько часов - молча.
  it("часы берутся из строки, а не из зоны браузера", () => {
    expect(разобратьМомент("2026-10-14T08:20:00+03:00")).toEqual({
      дата: "2026-10-14",
      часы: 8 + 20 / 60,
    });
  });

  it("смещение зоны не влияет на часы", () => {
    const восток = разобратьМомент("2026-10-14T08:20:00+12:00");
    const запад = разобратьМомент("2026-10-14T08:20:00-05:00");
    expect(восток?.часы).toBe(запад?.часы);
  });

  it("не разобранный момент не роняет экран", () => {
    expect(разобратьМомент("вчера вечером")).toBeNull();
  });
});

describe("раскладка дня", () => {
  it("непересекающиеся события занимают всю ширину", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({ key: "a" }),
          событие({
            key: "b",
            starts_at: "2026-10-14T11:40:00+03:00",
            ends_at: "2026-10-14T13:10:00+03:00",
          }),
        ],
      }),
    );

    expect(блоки.map((блок) => блок.колонок)).toEqual([1, 1]);
    expect(блоки[0]).toMatchObject({ начало: 10, конец: 11.5, колонка: 0 });
  });

  // §8.4: «кончилось в 11:30, началось в 11:30» - это расписание, а не наложение.
  it("смежные по времени события делят одну колонку", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({ key: "a" }),
          событие({
            key: "b",
            starts_at: "2026-10-14T11:30:00+03:00",
            ends_at: "2026-10-14T12:30:00+03:00",
          }),
        ],
      }),
    );

    expect(блоки.every((блок) => блок.колонок === 1)).toBe(true);
  });

  it("два наложения дают половины - геометрию утверждённого макета", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({
            key: "пара",
            starts_at: "2026-10-14T15:20:00+03:00",
            ends_at: "2026-10-14T16:50:00+03:00",
          }),
          событие({
            key: "врач",
            source: "event",
            starts_at: "2026-10-14T16:30:00+03:00",
            ends_at: "2026-10-14T17:30:00+03:00",
          }),
        ],
      }),
    );

    expect(блоки.map((блок) => [блок.колонка, блок.колонок])).toEqual([
      [0, 2],
      [1, 2],
    ]);
  });

  // Решение owner (ADR-035): третье событие не прячется - оба соседних
  // настоящие, и к третьему это относится ровно так же.
  it("три наложения дают три колонки, ни одно событие не пропадает", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({ key: "a", starts_at: "2026-10-14T10:00:00+03:00", ends_at: "2026-10-14T12:00:00+03:00" }),
          событие({ key: "b", starts_at: "2026-10-14T10:30:00+03:00", ends_at: "2026-10-14T11:30:00+03:00" }),
          событие({ key: "c", starts_at: "2026-10-14T11:00:00+03:00", ends_at: "2026-10-14T12:30:00+03:00" }),
        ],
      }),
    );

    expect(блоки).toHaveLength(3);
    expect(блоки.every((блок) => блок.колонок === 3)).toBe(true);
    expect(блоки.map((блок) => блок.колонка).sort()).toEqual([0, 1, 2]);
  });

  // Освободившаяся колонка переиспользуется: иначе весь день сжимался бы
  // до ширины самой плотной пары часов.
  it("группы наложений независимы", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({ key: "a", starts_at: "2026-10-14T10:00:00+03:00", ends_at: "2026-10-14T11:00:00+03:00" }),
          событие({ key: "b", starts_at: "2026-10-14T10:30:00+03:00", ends_at: "2026-10-14T11:00:00+03:00" }),
          событие({ key: "c", starts_at: "2026-10-14T14:00:00+03:00", ends_at: "2026-10-14T15:00:00+03:00" }),
        ],
      }),
    );

    expect(блоки[2]).toMatchObject({ колонка: 0, колонок: 1 });
  });

  it("событие через полночь подрезается границей своего дня", () => {
    const вечер = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({
            key: "ночь",
            starts_at: "2026-10-14T23:30:00+03:00",
            ends_at: "2026-10-15T01:00:00+03:00",
          }),
        ],
      }),
    );
    const утро = разложитьДень(
      день({
        date: "2026-10-15",
        events: [
          событие({
            key: "ночь",
            starts_at: "2026-10-14T23:30:00+03:00",
            ends_at: "2026-10-15T01:00:00+03:00",
          }),
        ],
      }),
    );

    expect(вечер[0]).toMatchObject({ начало: 23.5, конец: 24 });
    expect(утро[0]).toMatchObject({ начало: 0, конец: 1 });
  });

  // Событие нулевой длительности дало бы отрицательную высоту, то есть
  // пропало бы с экрана совсем. Пропавшее событие хуже неточной высоты.
  it("мгновенное событие остаётся видимым", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({
            key: "точка",
            source: "event",
            starts_at: "2026-10-14T10:00:00+03:00",
            ends_at: "2026-10-14T10:00:00+03:00",
          }),
        ],
      }),
    );

    expect(блоки[0]!.конец).toBeGreaterThan(блоки[0]!.начало);
  });

  it("неразобранный момент не роняет день, а пропускает блок", () => {
    const блоки = разложитьДень(
      день({ date: "2026-10-14", events: [событие({ key: "битое", starts_at: "" })] }),
    );

    expect(блоки).toEqual([]);
  });
});

describe("границы шкалы", () => {
  it("на неделе обычные сутки: 8-22", () => {
    expect(границыНедели([день({ date: "2026-10-12" })])).toEqual({ с: 8, по: 22 });
  });

  it("ранняя пара расширяет окно недели, а не прячется за краем", () => {
    const окно = границыНедели([
      день({
        date: "2026-10-12",
        events: [
          событие({
            key: "рано",
            starts_at: "2026-10-12T06:30:00+03:00",
            ends_at: "2026-10-12T08:00:00+03:00",
          }),
        ],
      }),
    ]);

    expect(окно.с).toBe(6);
  });

  it("день подрезается под свои события", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({
            key: "a",
            starts_at: "2026-10-14T13:30:00+03:00",
            ends_at: "2026-10-14T15:00:00+03:00",
          }),
        ],
      }),
    );

    expect(границыДня(блоки, null)).toEqual({ с: 13, по: 17 });
  });

  it("пустой день получает окно макета", () => {
    expect(границыДня([], null)).toEqual({ с: ПУСТОЙ_ДЕНЬ_С, по: ПУСТОЙ_ДЕНЬ_ПО });
  });

  it("линия «сейчас» входит в окно: за краем сетки её не нарисовать", () => {
    const блоки = разложитьДень(
      день({
        date: "2026-10-14",
        events: [
          событие({
            key: "a",
            starts_at: "2026-10-14T13:30:00+03:00",
            ends_at: "2026-10-14T15:00:00+03:00",
          }),
        ],
      }),
    );

    expect(границыДня(блоки, 9.5).с).toBe(9);
  });

  it("шкала подписывает целые часы окна, кроме его нижней границы", () => {
    expect(часыШкалы({ с: 9, по: 12 })).toEqual([9, 10, 11]);
  });
});

describe("время в зоне owner", () => {
  it("считается по зоне из ответа, а не по зоне браузера", () => {
    const момент = new Date("2026-10-14T11:10:00Z");

    expect(сейчасВЗоне("Europe/Moscow", момент)).toBeCloseTo(14 + 10 / 60, 5);
    expect(сейчасВЗоне("Asia/Novosibirsk", момент)).toBeCloseTo(18 + 10 / 60, 5);
  });

  // Испорченная настройка не должна ронять экран - линия просто не рисуется.
  it("неизвестная зона даёт null, а не исключение", () => {
    expect(сейчасВЗоне("Мордор/Барад-дур")).toBeNull();
  });
});

describe("листание", () => {
  it("сдвиг считается по календарным суткам", () => {
    expect(сдвинутьДату("2026-10-12", 7)).toBe("2026-10-19");
    expect(сдвинутьДату("2026-01-01", -1)).toBe("2025-12-31");
  });

  // Переход на летнее время: местный Date прибавил бы не то число суток.
  it("переход на летнее время не сдвигает дату", () => {
    expect(сдвинутьДату("2026-03-28", 1)).toBe("2026-03-29");
  });

  it("смена масштаба открывает сегодня, если оно внутри периода", () => {
    const сетка = {
      period: { view: "week", starts_on: "2026-10-12", ends_on: "2026-10-18", today: "2026-10-14" },
    } as Сетка;

    expect(датаДляВида(сетка)).toBe("2026-10-14");
  });

  it("сегодня вне периода - открывается его начало", () => {
    const сетка = {
      period: { view: "week", starts_on: "2026-10-19", ends_on: "2026-10-25", today: "2026-10-14" },
    } as Сетка;

    expect(датаДляВида(сетка)).toBe("2026-10-19");
  });
});
