import { fileURLToPath } from "node:url";

import type { NextConfig } from "next";

/**
 * Статический экспорт (ADR-020): на Pi раздаётся готовая статика, Node
 * в рантайме нет. Рендерить на сервере нечего — источник истины backend
 * (инвариант 1).
 *
 * `output: "export"` включается только в сборке. В `next dev` он не нужен,
 * зато нужен прокси: браузер обязан ходить к API по тому же адресу, что
 * и в проде, иначе на плате всплывает CORS, которого в разработке не было.
 * Путь `/api` одинаков в обоих режимах — различается лишь то, кто его
 * проксирует: в разработке next dev, на плате Caddy (infra/Caddyfile).
 */
const РАЗРАБОТКА = process.env.NODE_ENV === "development";

// Куда next dev отправляет /api. Локальный API слушает 8000 (Makefile: make dev).
const API_В_РАЗРАБОТКЕ = process.env.JARVIS_API_ORIGIN ?? "http://127.0.0.1:8000";

// Корень монорепо. Сборщик не выпускает импорты за пределы корня проекта,
// а `design/tokens.css` лежит выше `apps/web`: без этой строки палитру
// пришлось бы держать копией, и копия разъехалась бы с оригиналом молча.
const КОРЕНЬ_РЕПОЗИТОРИЯ = fileURLToPath(new URL("../..", import.meta.url));

const nextConfig: NextConfig = {
  output: РАЗРАБОТКА ? undefined : "export",
  turbopack: { root: КОРЕНЬ_РЕПОЗИТОРИЯ },
  // Ссылки вида /settings должны работать и как файл settings.html, который
  // отдаёт статик-сервер: без слэша Caddy пришлось бы учить угадывать.
  trailingSlash: true,
  // ...но дописывать слэш чужим путям Next не должен. Без этой строки
  // `next dev` отвечает на /api/calendar редиректом на /api/calendar/,
  // которого в контракте нет: в разработке каждый запрос к API упирался бы
  // в 308. На плате редиректов нет вовсе - там статика и Caddy.
  skipTrailingSlashRedirect: true,
  reactStrictMode: true,
  // Экспорт не умеет оптимизировать картинки на лету: оптимизатору негде
  // выполняться. Своих растровых картинок у интерфейса нет, но выключить
  // надо явно — иначе сборка падает на первом же <Image>.
  images: { unoptimized: true },
  // Ключ добавляется только в разработке. Пустой список в сборке экспорта
  // тоже считается «есть rewrites» и печатает предупреждение на каждую
  // сборку - предупреждение, которое ничего не значит, учит не читать их.
  ...(РАЗРАБОТКА
    ? {
        async rewrites() {
          return [
            { source: "/api/:path*", destination: `${API_В_РАЗРАБОТКЕ}/api/:path*` },
            { source: "/health", destination: `${API_В_РАЗРАБОТКЕ}/health` },
          ];
        },
      }
    : {}),
};

export default nextConfig;
