/**
 * Список вкладок капсулы - SPEC §8.1.
 *
 * Инвариант 3: вкладки генерируются из списка курсов. Хардкод списка -
 * баг, он ломает требование добавлять и удалять курсы. Поэтому здесь
 * функция от данных, а не константа: календарь первым, дальше по одной
 * вкладке на установленный курс в порядке, в котором курсы пришли.
 */

/** Курс в том виде, в каком он нужен капсуле. */
export type Курс = {
  readonly id: string;
  /** Подпись вкладки. Английская - это интерфейс продукта (этап 1 дизайна). */
  readonly title: string;
  /** Глиф из манифеста курса: специфика предмета живёт в данных, не в коде. */
  readonly icon: string;
  /** Точка «есть чем заняться сегодня» - метка, а не счётчик (этап 1 дизайна). */
  readonly hasWorkToday: boolean;
};

export type Вкладка = {
  readonly id: string;
  readonly подпись: string;
  readonly иконка: string;
  readonly путь: string;
  readonly точка: boolean;
  /**
   * Вкладка вне генерируемого списка курсов: в капсуле она отделена
   * разделителем и потолка в пять курсов не касается (этап 1 дизайна).
   */
  readonly внеСписка: boolean;
};

/** Потолок капсулы - §8.1. Дальше нужен другой паттерн, а не прокрутка. */
export const ПОТОЛОК_КУРСОВ = 5;

const КАЛЕНДАРЬ: Вкладка = {
  id: "calendar",
  подпись: "Calendar",
  иконка: "▦",
  путь: "/",
  точка: false,
  внеСписка: false,
};

const НАСТРОЙКИ: Вкладка = {
  id: "settings",
  подпись: "Settings",
  иконка: "⚙",
  путь: "/settings/",
  точка: false,
  внеСписка: true,
};

export function собратьВкладки(курсы: readonly Курс[]): readonly Вкладка[] {
  // Курсов больше потолка мы не прячем и не обрезаем: пропавшая вкладка -
  // это потерянный курс, а интерфейс деградирует тихо, но не врёт
  // (инвариант 9). Потолок - ограничение установки на сервере; здесь он
  // только повод сказать в консоль, что установка его уже нарушила.
  if (курсы.length > ПОТОЛОК_КУРСОВ) {
    console.warn(
      `курсов установлено ${курсы.length}, потолок капсулы - ${ПОТОЛОК_КУРСОВ} (SPEC §8.1)`,
    );
  }

  const вкладкиКурсов = курсы.map(
    (курс): Вкладка => ({
      id: курс.id,
      подпись: курс.title,
      иконка: курс.icon,
      путь: `/courses/${курс.id}/`,
      точка: курс.hasWorkToday,
      внеСписка: false,
    }),
  );

  return [КАЛЕНДАРЬ, ...вкладкиКурсов, НАСТРОЙКИ];
}

/** Контекстное действие капсулы - §8.1: смысл зависит от открытой вкладки. */
export type Действие = {
  readonly подпись: string;
  readonly иконка: string;
  /** Что действие делает. `null` - пока нечего делать, кнопка неактивна. */
  readonly пояснение: string;
};

const СОБЫТИЕ: Действие = {
  подпись: "Event",
  иконка: "＋",
  // Захват события - Э8 (вход → модель → черновик → подтверждение).
  // До него кнопка неактивна: живая кнопка, не делающая ничего, хуже
  // погашенной - она обещает работу, которой нет.
  пояснение: "Захват события появится вместе со слоем моделей",
};

const ЗАНЯТИЕ: Действие = {
  подпись: "Lesson",
  иконка: "▶",
  пояснение: "Занятие начнётся вместе с движком курсов",
};

export function действиеДляВкладки(вкладка: Вкладка): Действие | null {
  if (вкладка.id === "calendar") return СОБЫТИЕ;
  if (вкладка.внеСписка) return null; // в настройках создавать нечего
  return ЗАНЯТИЕ;
}
