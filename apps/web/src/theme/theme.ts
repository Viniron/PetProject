/**
 * Тема экрана - SPEC §8.1, макет `design/mockups/16-settings-theme.html`.
 *
 * Выбор хранится на устройстве (ADR-057): телефон и ПК могут стоять на
 * разных темах, а сервер про тему не знает вовсе. Палитры обеих тем
 * лежат в `design/tokens.css`; код только ставит `data-theme` на `<html>`.
 * Без атрибута тема берётся от системы - так JARVIS вёл себя до Э10,
 * и выкатка не перекрашивает экран без спроса.
 *
 * Модуль без React намеренно: его читает серверный `layout.tsx` ради
 * `СКРИПТ_ТЕМЫ`, а хук в серверной сборке Next - ошибка. Хук живёт
 * в `settings/ThemePicker.tsx`.
 */
export type Тема = "light" | "dark";

export const ТЕМЫ: readonly Тема[] = ["light", "dark"];

export const КЛЮЧ_ТЕМЫ = "jarvis.theme";

const ЗАПРОС_ТЁМНОЙ = "(prefers-color-scheme: dark)";

/**
 * Строка в `<head>`, которая ставит тему до первой отрисовки.
 *
 * Только так палитра не мигает: React доходит до страницы позже, чем
 * браузер успевает нарисовать её темой системы. Хранилище может бросить
 * (приватное окно, запрещённые данные сайта) - тогда атрибута нет и тема
 * системная, а не белый экран. Чужое значение в хранилище - тоже
 * «выбора нет»: подставлять его в `data-theme` значит получить страницу
 * без палитры вовсе.
 *
 * Ключ подставляется из константы, а не пишется в строке второй раз:
 * разойдутся - и скрипт перестанет видеть выбор, который пишет `выбратьТему`.
 */
export const СКРИПТ_ТЕМЫ =
  `try{var t=localStorage.getItem(${JSON.stringify(КЛЮЧ_ТЕМЫ)});` +
  `if(t==="light"||t==="dark")document.documentElement.setAttribute("data-theme",t)}catch(e){}`;

// Подписчики экрана настроек. Нажатие меняет атрибут, а React об атрибуте
// не знает - без явного оповещения карточка осталась бы прежней.
const подписчики = new Set<() => void>();

export function подписатьсяНаТему(уведомить: () => void): () => void {
  const система = window.matchMedia(ЗАПРОС_ТЁМНОЙ);
  подписчики.add(уведомить);
  система.addEventListener("change", уведомить);
  return () => {
    подписчики.delete(уведомить);
    система.removeEventListener("change", уведомить);
  };
}

/**
 * Действующая тема: выбранная, если она стоит на `<html>`, иначе системная.
 *
 * Читается атрибут, а не хранилище: атрибут ставят и скрипт в `<head>`,
 * и нажатие, поэтому он верен и тогда, когда хранилище записи не приняло -
 * выбор доживёт до перезагрузки, а карточка не соврёт.
 */
export function текущаяТема(): Тема {
  const атрибут = document.documentElement.getAttribute("data-theme");
  if (атрибут === "light" || атрибут === "dark") {
    return атрибут;
  }
  return window.matchMedia(ЗАПРОС_ТЁМНОЙ).matches ? "dark" : "light";
}

/** Применить сразу и запомнить на устройстве - кнопки «Сохранить» нет (макет 16). */
export function выбратьТему(тема: Тема): void {
  document.documentElement.setAttribute("data-theme", тема);
  try {
    window.localStorage.setItem(КЛЮЧ_ТЕМЫ, тема);
  } catch {
    // Хранилище закрыто: тема действует до перезагрузки, потом вернётся
    // системная. Интерфейс деградирует тихо (инвариант 9).
  }
  подписчики.forEach((уведомить) => уведомить());
}
