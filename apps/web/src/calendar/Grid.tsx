import type { CSSProperties, ReactNode } from "react";

import {
  границыДня,
  границыНедели,
  разложитьДень,
  часыШкалы,
  ПОРОГ_КОМПАКТНОГО,
  type Блок,
  type День,
  type Вид,
  type Сетка as Данные,
} from "./layout";
import {
  давностьНаБлоке,
  деньНедели,
  интервалСобытия,
  метаСобытия,
  подписьЧаса,
  подписьПометки,
  пояснениеДня,
  числоДня,
} from "./format";

/**
 * Сетка календаря - SPEC §8.4, макеты `02-calendar-week.html`
 * и `02b-calendar-day.html`.
 *
 * Компоненты (`cal`, `cal-ev`, `cal-chip`, `cal-note`, `cal-now`) утверждены
 * на этапах 2 и 2b дизайна и живут в `design/tokens.css`. Здесь - разметка
 * и выбор класса по данным, ни одного собственного значения.
 *
 * Чего экран не рисует в календарном релизе: занятий курсов, черновиков
 * захвата, пометок «сдвинуто» и `fallback`. Их в контракте нет, а рисовать
 * правдоподобное вместо настоящего запрещает инвариант 9.
 */
export function Сетка({
  данные,
  вид,
  сейчас,
  шапка,
  заглушка,
}: {
  /** `null` - ответа ещё нет. Сетка при этом не выдумывается (инвариант 9). */
  данные: Данные | null;
  /** Масштаб из адреса страницы: он известен до ответа и задаёт раскладку. */
  вид: Вид;
  /** Текущее время в зоне owner, десятичными часами. `null` - не показывать. */
  сейчас: number | null;
  /** Панель управления и полоса давности: по макету они внутри `.cal`. */
  шапка?: ReactNode;
  /** Что стоит вместо сетки, пока данных нет: ожидание или причина отказа. */
  заглушка?: ReactNode;
}) {
  const дни = данные?.days ?? [];
  const блокиПоДням = дни.map((день) => разложитьДень(день));
  const окно =
    вид === "day" ? границыДня(блокиПоДням[0] ?? [], сейчас) : границыНедели(дни);
  const устарело = данные?.freshness.state === "stale";
  const давность = устарело ? давностьНаБлоке(данные.freshness.fetched_at) : null;

  // Обёртка `.cal` и шапка стоят на месте и до ответа: перенос панели
  // в другое поддерево пересоздавал бы её узлы, а вместе с ними терялись
  // бы фокус и нажатие, случившееся в момент загрузки.
  if (!данные) {
    return (
      <div className={вид === "day" ? "cal cal--day" : "cal"}>
        {шапка}
        {заглушка}
      </div>
    );
  }

  return (
    <div
      className={вид === "day" ? "cal cal--day" : "cal"}
      style={переменные({ "--h0": окно.с, "--h1": окно.по })}
    >
      {шапка}

      <div className="cal-head" style={колонки(дни.length)}>
        <div className="cal-corner" />
        {дни.map((день) => (
          <ШапкаДня key={день.date} день={день} вид={вид} />
        ))}
      </div>

      <div className="cal-body" style={колонки(дни.length)}>
        <div className="cal-hours">
          {часыШкалы(окно).map((час) => (
            <div key={час} className="cal-hour" style={переменные({ "--t": час })}>
              {подписьЧаса(час)}
            </div>
          ))}
          {сейчас === null ? null : (
            <div className="cal-hour cal-hour--now" style={переменные({ "--t": сейчас })}>
              {подписьЧаса(сейчас)}
            </div>
          )}
        </div>

        {дни.map((день, индекс) => (
          <div
            key={день.date}
            className={день.flags.length > 0 ? "cal-col is-flagged" : "cal-col"}
          >
            {сейчас !== null && день.is_today ? (
              <div className="cal-now" style={переменные({ "--s": сейчас })} />
            ) : null}
            {(блокиПоДням[индекс] ?? []).map((блок) => (
              <БлокСобытия
                key={`${блок.событие.key}-${блок.начало}`}
                блок={блок}
                вид={вид}
                давность={блок.событие.source === "itmo" ? давность : null}
              />
            ))}
          </div>
        ))}
      </div>

      {вид === "day" ? <Пояснение день={дни[0]} /> : null}

      {/* Легенда подписывает ровно те виды блоков, которые на экране бывают.
          Занятия курсов и черновики захвата в календарном релизе не приходят,
          и строка про них обещала бы работу, которой нет. */}
      <div className="cal-legend">
        <div>
          <i className="l-itmo" />
          пара ИТМО
        </div>
        <div>
          <i className="l-event" />
          личное событие
        </div>
      </div>
    </div>
  );
}

function ШапкаДня({ день, вид }: { день: День; вид: Вид }) {
  return (
    <div className={день.is_today ? "cal-day is-today" : "cal-day"}>
      <div className="cal-dow">{деньНедели(день.date, вид)}</div>
      <div className="cal-date">{числоДня(день.date)}</div>
      {день.flags.map((пометка) => (
        <div key={пометка.id} className="cal-chip" title={пометка.note ?? undefined}>
          {подписьПометки(пометка.reason)}
        </div>
      ))}
      {/* День вне окна забора помечается словом: пустая колонка иначе
          читается как «пар нет», а это разные вещи (§8.4). */}
      {день.mirror_covers ? null : <div className="cal-chip">нет данных</div>}
    </div>
  );
}

function БлокСобытия({
  блок,
  вид,
  давность,
}: {
  блок: Блок;
  вид: Вид;
  давность: string | null;
}) {
  const событие = блок.событие;
  const делит = блок.колонок > 1;
  // Компактная раскладка только на неделе: там час - это 46px, и три строки
  // в короткий блок не влезают. В дне час выше, прятать нечего.
  //
  // Устаревшая пара компактна независимо от длительности: пометка «от 08.09»
  // - это четвёртая строка, и в обычной раскладке её срезает нижняя граница
  // блока. Тот же приём в макете §10: там пары под полосой давности тоже
  // компактные.
  const компактный =
    вид === "week" && (блок.конец - блок.начало <= ПОРОГ_КОМПАКТНОГО || давность !== null);
  const классы = [
    "cal-ev",
    событие.source === "itmo" ? "cal-ev--itmo" : "cal-ev--event",
    компактный ? "cal-ev--compact" : "",
    делит ? "cal-ev--split" : "",
    событие.conflict ? "cal-ev--clash" : "",
    давность ? "is-stale" : "",
  ]
    .filter(Boolean)
    .join(" ");

  const мета = метаСобытия(событие, вид);
  // В половинном блоке недели остаётся только время начала: полный интервал
  // рядом со значком «⚠» не помещается (этап 2 дизайна, измерено).
  const время = интервалСобытия(событие, делит && вид === "week");

  return (
    <div
      className={классы}
      style={переменные({
        "--s": блок.начало,
        "--e": блок.конец,
        "--col": блок.колонка,
        "--cols": блок.колонок,
      })}
    >
      <div className="cal-ev-time">
        {время}
        {давность && вид === "day" ? <span className="cal-flag">{давность}</span> : null}
      </div>
      <div className="cal-ev-title">{событие.title}</div>
      {мета ? <div className="cal-ev-meta">{мета}</div> : null}
      {давность && вид === "week" ? <div className="cal-flag">{давность}</div> : null}
    </div>
  );
}

/** Объяснение под сеткой дня: почему день пуст или помечен (§8.4, §2.5). */
function Пояснение({ день }: { день: День | undefined }) {
  if (!день) return null;
  const текст = пояснениеДня(день);
  if (!текст) return null;
  return (
    <div className="cal-note" style={{ marginTop: "var(--space-3)" }}>
      <span>
        <b>{текст.заголовок}</b> {текст.подробности}
      </span>
    </div>
  );
}

/**
 * Сетка колонок под число дней периода.
 *
 * В токенах описаны две раскладки - семь колонок и одна. Период приходит
 * от сервера, и день недели, попавший в неполную неделю (первая неделя
 * семестра), не должен ломать шапку: ширина считается от длины ответа.
 */
function колонки(дней: number): CSSProperties {
  if (дней === 7 || дней === 1) return {};
  return { gridTemplateColumns: `56px repeat(${дней}, 1fr)` };
}

/** CSS-переменные из данных. Числа - это данные, а не оформление (токены). */
function переменные(значения: Record<string, number>): CSSProperties {
  return значения as CSSProperties;
}
