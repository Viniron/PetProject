/**
 * Подписи экрана календаря - SPEC §8.4.
 *
 * Два языка на экране не случайность: заголовок экрана английский, как
 * и вкладки капсулы, всё остальное - русское (этап 1 дизайна). Поэтому
 * здесь две локали, а не одна с переключателем.
 *
 * Даты форматируются в зоне UTC поверх строки `YYYY-MM-DD`. Это не
 * небрежность: дата от сервера уже календарная, в зоне owner, и любая
 * другая зона в форматере сдвинула бы её на сутки у полуночи.
 */

import {
  разобратьМомент,
  type День,
  type Момент,
  type Событие,
  type Сетка,
  type Вид,
} from "./layout";

const ЗОНА_ФОРМАТА = { timeZone: "UTC" } as const;

function вДату(дата: string): Date | null {
  const части = /^(\d{4})-(\d{2})-(\d{2})$/.exec(дата);
  if (!части) return null;
  const [, год, месяц, день] = части;
  return new Date(Date.UTC(Number(год), Number(месяц) - 1, Number(день)));
}

function собрать(дата: string, настройки: Intl.DateTimeFormatOptions, локаль: string): string {
  const момент = вДату(дата);
  if (!момент) return дата;
  return new Intl.DateTimeFormat(локаль, { ...ЗОНА_ФОРМАТА, ...настройки }).format(момент);
}

function сБольшой(слово: string): string {
  return слово.charAt(0).toUpperCase() + слово.slice(1);
}

/**
 * Подзаголовок экрана: «12–18 October», «Wednesday, 14 October».
 *
 * Год дописывается, только когда период не в текущем году: на своей неделе
 * год - это шум, а пролистав на год вперёд, owner обязан это увидеть.
 */
export function подписьПериода(сетка: Сетка): string {
  const { view, starts_on, ends_on, today } = сетка.period;
  const другойГод = starts_on.slice(0, 4) !== today.slice(0, 4);
  const год = другойГод ? ` ${starts_on.slice(0, 4)}` : "";

  if (view === "day") {
    const деньНедели = собрать(starts_on, { weekday: "long" }, "en-GB");
    const число = собрать(starts_on, { day: "numeric", month: "long" }, "en-GB");
    return `${деньНедели}, ${число}${год}`;
  }

  const одинМесяц = starts_on.slice(0, 7) === ends_on.slice(0, 7);
  if (одинМесяц) {
    const первое = собрать(starts_on, { day: "numeric" }, "en-GB");
    const последнее = собрать(ends_on, { day: "numeric", month: "long" }, "en-GB");
    return `${первое}–${последнее}${год}`;
  }
  const первое = собрать(starts_on, { day: "numeric", month: "long" }, "en-GB");
  const последнее = собрать(ends_on, { day: "numeric", month: "long" }, "en-GB");
  return `${первое} – ${последнее}${год}`;
}

/** Шапка колонки: «Пн» на неделе, «Среда» в дне - макеты `02` и `02b`. */
export function деньНедели(дата: string, вид: Вид): string {
  return сБольшой(собрать(дата, { weekday: вид === "day" ? "long" : "short" }, "ru-RU"));
}

/** Число в шапке дня. Месяц не подписывается: он в заголовке экрана. */
export function числоДня(дата: string): string {
  return собрать(дата, { day: "numeric" }, "ru-RU");
}

/** Время момента: «8:20». Час без ведущего нуля - как в утверждённом макете. */
export function время(момент: Момент): string {
  return часыИМинуты(момент.часы, false);
}

function часыИМинуты(часы: number, ведущийНоль: boolean): string {
  const час = Math.floor(часы);
  const минуты = Math.round((часы - час) * 60);
  const левая = ведущийНоль ? String(час).padStart(2, "0") : String(час);
  return `${левая}:${String(минуты).padStart(2, "0")}`;
}

function времяСтрокой(момент: string): string | null {
  const разобранный = разобратьМомент(момент);
  return разобранный ? время(разобранный) : null;
}

/**
 * Время блока: «10:00–11:30» или только начало.
 *
 * В половинном блоке недели помещается лишь начало - конец виден по нижней
 * границе (решение этапа 2 дизайна, там же измерено). В дне половина колонки
 * широкая, и интервал печатается целиком.
 */
export function интервалСобытия(событие: Событие, толькоНачало: boolean): string {
  const начало = времяСтрокой(событие.starts_at) ?? "";
  if (толькоНачало) return начало;
  const конец = времяСтрокой(событие.ends_at);
  return конец ? `${начало}–${конец}` : начало;
}

/** Подпись часа в шкале: «8:00», «14:10» у линии текущего времени. */
export function подписьЧаса(часы: number): string {
  return часыИМинуты(часы, false);
}

/**
 * Вторая строка блока.
 *
 * Поля разных источников не сливаются (контракт): у пары - вид занятия,
 * аудитория и корпус, у личного события - место. В дне места больше, туда
 * попадает и корпус; на неделе он не помещается.
 */
export function метаСобытия(событие: Событие, вид: Вид): string {
  const части =
    событие.source === "itmo"
      ? [событие.lesson_kind, событие.room, вид === "day" ? событие.building : null]
      : [событие.location];
  return части.filter((часть): часть is string => Boolean(часть)).join(" · ");
}

/** Пометка давности на блоке пары: «от 12.10» - тот же момент, что в полосе. */
export function давностьНаБлоке(fetched_at: string | null): string | null {
  const момент = разобратьМомент(fetched_at ?? "");
  if (!момент) return null;
  const [, месяц, день] = момент.дата.split("-");
  return `от ${день}.${месяц}`;
}

/**
 * Полоса давности - §10 и §8.4.
 *
 * Пометка одна на ответ, и фразу собирает клиент: «от 12 октября, 07:10»
 * в полосе и «от 12.10» на блоке - один и тот же момент двумя форматами.
 * Про занятия курсов в календарном релизе не говорится ничего: курсов ноль,
 * и обещать их актуальность было бы выдумкой.
 */
export function фразаДавности(сетка: Сетка): string | null {
  const { state, portal, fetched_at } = сетка.freshness;
  if (state === "fresh") return null;
  if (state === "never") {
    return "Расписание ещё ни разу не загружалось: забор с портала не проходил.";
  }

  const момент = разобратьМомент(fetched_at ?? "");
  const когда = момент
    // В полосе час двузначный («07:10»), в сетке - нет («8:20»). Это не
    // разнобой, а макет: полоса печатает момент забора, и ведущий ноль
    // отличает его от времени пары с одного взгляда.
    ? `от ${собрать(момент.дата, { day: "numeric", month: "long" }, "ru-RU")}, ${часыИМинуты(
        момент.часы,
        true,
      )}`
    : "неизвестной давности";
  const причина = portal === "failing" ? " — портал не отвечает." : ".";
  return `Расписание ${когда}${причина}`;
}

/**
 * Подпись метки дня в шапке: причина периода словом.
 *
 * `late_classes` - единственная причина, которую ставит система (§4 п.4),
 * и она приходит машинным словом; причину, напечатанную owner, экран
 * показывает как есть - словаря причин нет нигде (`domain/day_flags.py`).
 */
export const АВТОПОМЕТКА = "late_classes";

export function подписьПометки(reason: string): string {
  return reason === АВТОПОМЕТКА ? "поздние пары" : reason;
}

/**
 * Объяснение под сеткой дня - §8.4 и макет `02b`.
 *
 * Три причины пустоты нельзя путать: период owner, автопометка системы
 * и просто пустой день. Четвёртая строка - день вне окна забора: про него
 * неизвестно ничего, и сказать «пар нет» было бы выдумкой (инвариант 9).
 *
 * Про занятия курсов не говорится: курсов ноль (ADR-019), и фраза
 * «занятия не ставятся» обещала бы работу, которой в релизе нет.
 */
export function пояснениеДня(
  день: День,
): { заголовок: string; подробности: string } | null {
  const пометка = день.flags[0];
  if (пометка) {
    const период = `С ${собрать(пометка.starts_on, { day: "numeric", month: "long" }, "ru-RU")} по ${собрать(
      пометка.ends_on,
      { day: "numeric", month: "long" },
      "ru-RU",
    )}, включительно.`;
    return пометка.manual
      ? {
          заголовок: `Период «${пометка.reason}».`,
          подробности: `${период} Внесён owner, день не входит в отставание.`,
        }
      : {
          заголовок: "Поздние пары.",
          подробности: `${период} Пометку поставила система, день не входит в отставание.`,
        };
  }

  if (!день.mirror_covers) {
    return {
      заголовок: "Сохранённых данных на этот день нет.",
      подробности: "Забор расписания до него не доходил — что здесь будет, неизвестно.",
    };
  }

  if (день.events.length === 0) {
    return {
      заголовок: "Ничего не запланировано.",
      подробности: "Пар и событий на этот день нет. Это пустой день, а не сбой загрузки.",
    };
  }

  return null;
}
