"use client";

import { useRouter, useSearchParams } from "next/navigation";
import { useCallback, useEffect, useState } from "react";

import { ОшибкаAPI, ОшибкаСети, получить } from "@/api/client";

import { Сетка } from "./Grid";
import { подписьПериода, фразаДавности } from "./format";
import {
  датаДляВида,
  сдвинутьДату,
  сейчасВЗоне,
  шагЛистания,
  type Вид,
  type Сетка as Данные,
} from "./layout";

/**
 * Экран календаря - SPEC §8.4.
 *
 * Масштаб и дата живут в адресе страницы (`?view=day&date=2026-10-14`) -
 * решение owner от 2026-09-13, ADR-035: ссылку на неделю можно сохранить,
 * а «назад» листает обратно. Отсюда же берётся и первое состояние экрана:
 * своего дублирующего `useState` для вида нет, иначе адрес и экран
 * разъезжаются на первой же кнопке «назад».
 *
 * Сетку целиком считает сервер (инвариант 1). Клиент не знает ни зоны
 * owner, ни границ его недели и не вычисляет их: листание двигает **дату
 * из ответа**, а не свой счётчик.
 */
export function CalendarScreen() {
  const router = useRouter();
  const параметры = useSearchParams();
  const вид = разобратьВид(параметры.get("view"));
  const дата = разобратьДату(параметры.get("date"));

  const [данные, установитьДанные] = useState<Данные | null>(null);
  const [отказ, установитьОтказ] = useState<Отказ | null>(null);
  const [попытка, повторить] = useState(0);

  useEffect(() => {
    const управление = new AbortController();
    let живой = true;

    получить("/api/calendar", { view: вид, date: дата ?? undefined }, управление.signal)
      .then((ответ) => {
        if (!живой) return;
        установитьДанные(ответ);
        установитьОтказ(null);
      })
      .catch((причина: unknown) => {
        // Отменённый запрос - не отказ: экран уже ушёл на другой период.
        if (причина instanceof DOMException && причина.name === "AbortError") return;
        if (!живой) return;
        установитьОтказ(описатьОтказ(причина));
      });

    // Уход с периода отменяет запрос: иначе ответ прилетает в экран,
    // который показывает уже другую неделю, и подменяет её задним числом.
    return () => {
      живой = false;
      управление.abort();
    };
  }, [вид, дата, попытка]);

  // Линия «сейчас» обязана идти, а не замереть на времени загрузки экрана.
  // Раз в минуту: шкала подписана с точностью до минуты, чаще нечего менять.
  // Само значение счётчика не нужно: важен сам факт перерисовки, при которой
  // время линии считается заново.
  const [, тикнуть] = useState(0);
  useEffect(() => {
    if (вид !== "day") return; // на неделе линии нет по решению owner (этап 2)
    const таймер = setInterval(() => тикнуть((значение) => значение + 1), 60_000);
    return () => clearInterval(таймер);
  }, [вид]);

  const сейчас = времяЛинии(данные);

  const перейти = useCallback(
    (новыйВид: Вид, новаяДата: string | null) => {
      const адрес = new URLSearchParams({ view: новыйВид });
      if (новаяДата) адрес.set("date", новаяДата);
      router.push(`/?${адрес.toString()}`);
    },
    [router],
  );

  const шапка = (
    <>
      <div className="cal-toolbar">
        <div className="cal-nav">
          <button
            type="button"
            aria-label="Предыдущий период"
            disabled={!данные}
            onClick={() =>
              данные && перейти(вид, сдвинутьДату(данные.period.starts_on, -шагЛистания(вид)))
            }
          >
            ‹
          </button>
          {/* «Сегодня» убирает дату из адреса, а не подставляет свою:
              сегодняшний день считается в зоне owner, которой у клиента нет. */}
          <button type="button" onClick={() => перейти(вид, null)}>
            Сегодня
          </button>
          <button
            type="button"
            aria-label="Следующий период"
            disabled={!данные}
            onClick={() =>
              данные && перейти(вид, сдвинутьДату(данные.period.starts_on, шагЛистания(вид)))
            }
          >
            ›
          </button>
        </div>
        <div className="seg">
          <КнопкаВида
            вид="day"
            подпись="День"
            текущий={вид}
            onClick={() => перейти("day", данные ? датаДляВида(данные) : дата)}
          />
          <КнопкаВида
            вид="week"
            подпись="Неделя"
            текущий={вид}
            onClick={() => перейти("week", данные ? датаДляВида(данные) : дата)}
          />
        </div>
      </div>
      {данные ? <ПолосаДавности данные={данные} /> : null}
    </>
  );

  return (
    <>
      <h1 className="screen-title">Calendar</h1>
      <p className="screen-sub">{данные ? подписьПериода(данные) : "Расписание ИТМО и события"}</p>

      {/* Отказ поверх старой сетки: показать последнее полученное расписание
          с честной подписью - это инвариант 9, а пустой экран вместо него -
          его нарушение. */}
      {отказ ? <ПлашкаОтказа отказ={отказ} повторить={() => повторить(попытка + 1)} /> : null}

      <Сетка
        данные={данные}
        вид={вид}
        сейчас={сейчас}
        шапка={шапка}
        заглушка={
          отказ ? null : (
            <div className="cal-note">
              <span>Расписание загружается…</span>
            </div>
          )
        }
      />
    </>
  );
}

function КнопкаВида({
  вид,
  подпись,
  текущий,
  onClick,
}: {
  вид: Вид;
  подпись: string;
  текущий: Вид;
  onClick: () => void;
}) {
  const активна = вид === текущий;
  return (
    <button
      type="button"
      className={активна ? "is-active" : undefined}
      aria-pressed={активна}
      onClick={onClick}
    >
      {подпись}
    </button>
  );
}

function ПолосаДавности({ данные }: { данные: Данные }) {
  const фраза = фразаДавности(данные);
  if (!фраза) return null;
  return <div className="stale-bar">{фраза}</div>;
}

/** Отказ в том виде, в каком его показывает экран. */
type Отказ = {
  readonly заголовок: string;
  readonly подробности: string;
  /** Кнопка повтора. `вход` - лечится перезагрузкой страницы, а не повтором. */
  readonly действие: "повтор" | "вход" | "нет";
};

function ПлашкаОтказа({ отказ, повторить }: { отказ: Отказ; повторить: () => void }) {
  return (
    <div className="cal-note" role="alert">
      <span>
        <b>{отказ.заголовок}</b> {отказ.подробности}
      </span>
      {отказ.действие === "повтор" ? (
        <button type="button" className="btn btn--ghost" onClick={повторить}>
          Повторить
        </button>
      ) : null}
      {отказ.действие === "вход" ? (
        <button type="button" className="btn btn--ghost" onClick={() => window.location.reload()}>
          Обновить страницу
        </button>
      ) : null}
    </div>
  );
}

/**
 * Причина отказа словами owner, а не кодом статуса.
 *
 * Признак «повторять» берётся из тела ответа (`retryable`), потому что
 * решение это серверное (ADR-034). 401 и 403 повтором не лечатся: вход
 * проводит Cloudflare Access на переходе, а не на `fetch` (ADR-033).
 */
export function описатьОтказ(причина: unknown): Отказ {
  if (причина instanceof ОшибкаСети) {
    return {
      заголовок: "Сервер не отвечает.",
      подробности: "Расписание не загрузилось: нет связи с платой.",
      действие: "повтор",
    };
  }
  if (причина instanceof ОшибкаAPI) {
    if (причина.нуженВход) {
      return {
        заголовок: "Сессия кончилась.",
        подробности: "Вход проводит Cloudflare Access при переходе на страницу.",
        действие: "вход",
      };
    }
    // Тело не наше - 502 от прокси, 500 из-под упавшего API: сервер своего
    // решения о повторе не сообщил, и «нельзя» из этого не следует. Отказ
    // инфраструктуры повтором как раз и лечится.
    const чужойСбой = причина.код === "unknown" && причина.статус >= 500;
    return {
      заголовок: "Расписание не загрузилось.",
      подробности: причина.message,
      действие: причина.повторить || чужойСбой ? "повтор" : "нет",
    };
  }
  return {
    заголовок: "Расписание не загрузилось.",
    подробности: "Неизвестная ошибка на стороне интерфейса.",
    действие: "повтор",
  };
}

/** Вид из адреса. Чужое значение игнорируется - умолчание держит сервер. */
export function разобратьВид(значение: string | null): Вид {
  return значение === "day" ? "day" : "week";
}

/**
 * Дата из адреса.
 *
 * Проверяется только форма: любая дата внутри периода законна, а сам
 * период считает сервер. Мусор не передаётся - иначе экран получал бы 422
 * вместо расписания там, где хватает умолчания.
 */
export function разобратьДату(значение: string | null): string | null {
  return значение && /^\d{4}-\d{2}-\d{2}$/.test(значение) ? значение : null;
}

/** Линия текущего времени - только на экране дня и только если день сегодняшний. */
function времяЛинии(данные: Данные | null): number | null {
  if (!данные || данные.period.view !== "day") return null;
  if (!данные.days.some((день) => день.is_today)) return null;
  return сейчасВЗоне(данные.timezone);
}
