"""Проверка перед включением туннеля: дверь заперта раньше, чем открыта (Э7).

ADR-031 п. 3 ставит условие «туннель не включается раньше аутентификации»,
ADR-033 его выполняет. Условие, записанное только словами, держится на
внимательности того, кто правит `.env` на плате в одиннадцать вечера, -
поэтому оно живёт ещё и здесь, прогоном.

**Что именно ловится.** Незаполненная строчка `CF_ACCESS_*` при включённом
туннеле - это публичный доступ к расписанию и к правке периодов. Отказ при
этом не громкий: экран продолжает работать у owner, потому что ходит на тот
же адрес; наружу он тоже работает - у кого угодно. Заметить такое глазами
нельзя, а прогоном - можно: `/api/*` обязан отвечать 401 тому, кто пришёл
без токена Access.

**Чего проверка НЕ делает.** Она не трогает `CF_TUNNEL_TOKEN` и
`COMPOSE_PROFILES`: ошибка в них громкая по построению - неверный токен не
даёт `cloudflared` подняться, и это видно в `docker compose logs`. Проверять
имеет смысл тихие отказы, а не громкие. Их и нет в окружении контейнера
`api` намеренно: токен двери незачем класть внутрь комнаты.

**Второй маршрут - ssh (Э9б, ADR-045).** У него та же природа отказа и
худшая цена: приложение Access перед именем правится мышкой в панели, а за
маршрутом стоит не расписание, а вход на плату. Проверяется он единственным
доступным способом - походом снаружи на само имя, потому что запрос по нему
идёт мимо кода. Маршрут, который не завели, и маршрут, который не проверили,
в отчёте разные: первый печатается как SKIP, второй роняет прогон.

**Ничего не пишет.** Ни `job_runs`, ни `audit_log`: это не работа, а взгляд.
Строки в журнале прогонов от неё означали бы, что кто-то может принять
проверку за сделанную работу.

Запуск - `make tunnel-check` на хосте, `make tunnel-check-pi` внутри
работающего стека. Нужен поднятый API: половина проверок - живые запросы.
"""

import argparse
import dataclasses
import logging
import re
import sys
from collections.abc import Sequence

import httpx2

from jarvis_api.api.auth import ЗАГОЛОВОК_ТОКЕНА
from jarvis_api.config import Settings, get_settings

logger = logging.getLogger("jarvis.tunnel_check")

# Таймаут живых запросов. Короткий: и API, и Caddy здесь - соседи по хосту,
# а не внешний сервис. Настройкой не делается намеренно: это инструмент
# проверки, а не поведение сервиса (конфиг только env, инвариант хоста 2).
ТАЙМАУТ_СЕКУНД = 5.0

# Адреса по умолчанию - те, на которых сервисы слушают на плате. Наружу
# смотрит web (Caddy), поэтому проверяются оба: маршрут туннеля ведёт
# на web:8080, и дыра в нём не видна со стороны API.
API_ПО_УМОЛЧАНИЮ = "http://127.0.0.1:8000"
WEB_ПО_УМОЛЧАНИЮ = "http://127.0.0.1:8080"

# Путь, на котором проверяется запертость. Любой из /api/*: зависимость
# повешена на подключении роутеров, а не на эндпоинт (ADR-033).
ЗАЩИЩЁННЫЙ_ПУТЬ = "/api/calendar"

# AUD приложения - 64 шестнадцатеричных знака. Форма проверяется потому,
# что опечатка в ней даёт 401 на законном токене, и причина ищется в подписи.
ФОРМА_AUD = re.compile(r"^[0-9a-f]{64}$")

# Заглушки из .env.example. Строка, скопированная из примера целиком, -
# это заполненное поле для кода и незаполненное для человека.
ЗАГЛУШКИ = ("CHANGE_ME", "CHANGE_ME.cloudflareaccess.com")


@dataclasses.dataclass(frozen=True, slots=True)
class Проверка:
    """Один пункт отчёта. `подсказка` - что делать, а не что случилось.

    `пропущена` - третье состояние, заведённое на Э9б: проверять было нечего.
    Оно не сливается ни с пройденным, ни с провалом. С пройденным - потому
    что незаполненная строчка в `.env` иначе выглядела бы как проверенный
    маршрут; с провалом - потому что до Э9б ssh-маршрута не существовало
    вовсе, и его отсутствие не повод запрещать туннель.
    """

    название: str
    прошла: bool
    подсказка: str = ""
    пропущена: bool = False


def провалено(пункты: Sequence[Проверка]) -> list[Проверка]:
    """Что именно запрещает включать туннель. Пропущенное сюда не входит."""
    return [пункт for пункт in пункты if not пункт.прошла and not пункт.пропущена]


def _строка(проверка: Проверка) -> str:
    """Подсказка печатается у провалов и у пропущенных.

    У пройденного пункта она описывает не то, что случилось, а то, чего
    не случилось: «получено 200» рядом с OK читается как замечание.
    У пропущенного подсказка обязательна: строка [SKIP] без причины - это
    отчёт, по которому нельзя понять, чего именно не проверили.
    """
    if проверка.пропущена:
        return f"[SKIP] {проверка.название} - {проверка.подсказка}"
    знак = "OK  " if проверка.прошла else "FAIL"
    хвост = "" if проверка.прошла or not проверка.подсказка else f" - {проверка.подсказка}"
    return f"[{знак}] {проверка.название}{хвост}"


def проверить_настройки(settings: Settings) -> list[Проверка]:
    """Три значения Access на месте и похожи на настоящие.

    Пустое и заглушка разделены намеренно: «не вписал» и «вписал пример»
    лечатся по-разному, а выглядят одинаково - в обоих случаях дверь
    не заперта.
    """
    пункты: list[Проверка] = []

    пункты.append(
        Проверка(
            "ENV=prod",
            settings.env != "dev",
            f"ENV={settings.env}: на машине разработки аутентификация выключена (ADR-033), "
            "туннель к такому процессу включать нельзя",
        )
    )

    значения = {
        "CF_ACCESS_TEAM_DOMAIN": settings.cf_access_team_domain,
        "CF_ACCESS_AUD": settings.cf_access_aud,
        "CF_ACCESS_ALLOWED_EMAIL": settings.cf_access_allowed_email,
    }
    for имя, значение in значения.items():
        текст = значение.strip()
        if not текст:
            пункты.append(Проверка(f"{имя} заполнена", False, "пусто в .env на плате"))
        elif текст in ЗАГЛУШКИ or текст.startswith("CHANGE_ME"):
            пункты.append(Проверка(f"{имя} заполнена", False, "стоит заглушка из .env.example"))
        else:
            пункты.append(Проверка(f"{имя} заполнена", True))

    домен = settings.cf_access_team_domain.strip()
    if домен and not домен.startswith("CHANGE_ME"):
        пункты.append(
            Проверка(
                "CF_ACCESS_TEAM_DOMAIN похож на домен команды",
                домен.endswith(".cloudflareaccess.com"),
                f"ожидалось имя вида team.cloudflareaccess.com, получено {домен!r}",
            )
        )

    aud = settings.cf_access_aud.strip()
    if aud and not aud.startswith("CHANGE_ME"):
        пункты.append(
            Проверка(
                "CF_ACCESS_AUD похож на Application Audience Tag",
                bool(ФОРМА_AUD.match(aud)),
                "ожидались 64 шестнадцатеричных знака из карточки приложения Access",
            )
        )

    почта = settings.cf_access_allowed_email.strip()
    if почта and not почта.startswith("CHANGE_ME"):
        пункты.append(
            Проверка(
                "CF_ACCESS_ALLOWED_EMAIL похож на почту",
                "@" in почта and "." in почта.split("@")[-1],
                f"ожидалась почта owner, получено {почта!r}",
            )
        )

    return пункты


def проверить_ключи(settings: Settings, клиент: httpx2.Client) -> list[Проверка]:
    """Домен команды настоящий: по нему отдаются публичные ключи.

    Опечатка в домене иначе всплывает первым же входом - отказом 401 на
    законном токене, причём с текстом про подпись. Здесь она стоит одного
    запроса и называется своим именем.
    """
    домен = settings.cf_access_team_domain.strip()
    if not домен or домен.startswith("CHANGE_ME"):
        return []

    адрес = f"https://{домен}/cdn-cgi/access/certs"
    try:
        ответ = клиент.get(адрес, timeout=settings.cf_access_jwks_timeout_seconds)
        ответ.raise_for_status()
        ключи = ответ.json().get("keys")
    except (httpx2.HTTPError, ValueError, AttributeError) as сбой:
        return [
            Проверка(
                "ключи команды Cloudflare отдаются",
                False,
                f"{адрес} недоступен ({сбой.__class__.__name__}): проверьте домен команды",
            )
        ]

    return [
        Проверка(
            "ключи команды Cloudflare отдаются",
            bool(ключи),
            f"{адрес} ответил без ключей",
        )
    ]


def проверить_сервис(клиент: httpx2.Client, база: str, *, имя: str) -> list[Проверка]:
    """Живость и запертость одного адреса: `/health` открыт, `/api/*` заперт.

    Оба пункта нужны вместе. Отдельно «заперт» ничего не доказывает:
    упавший сервис тоже не отдаёт расписания.
    """
    пункты: list[Проверка] = []

    try:
        живость = клиент.get(f"{база}/health", timeout=ТАЙМАУТ_СЕКУНД)
    except httpx2.HTTPError as сбой:
        return [
            Проверка(
                f"{имя}: /health отвечает",
                False,
                f"{база} недоступен ({сбой.__class__.__name__}): поднят ли стек?",
            )
        ]
    пункты.append(
        Проверка(
            f"{имя}: /health отвечает",
            живость.status_code == 200,
            f"получено {живость.status_code}",
        )
    )

    try:
        закрытость = клиент.get(
            f"{база}{ЗАЩИЩЁННЫЙ_ПУТЬ}",
            timeout=ТАЙМАУТ_СЕКУНД,
            headers={"Accept": "application/json"},
        )
    except httpx2.HTTPError as сбой:
        return [
            *пункты,
            Проверка(
                f"{имя}: {ЗАЩИЩЁННЫЙ_ПУТЬ} заперт",
                False,
                f"запрос не дошёл ({сбой.__class__.__name__})",
            ),
        ]

    # 401 - единственный правильный ответ. 200 означает открытую дверь;
    # 503 - что настройки пусты и API отказывает всем подряд, включая owner:
    # дверь заперта, но и владелец внутрь не попадёт.
    подсказка = {
        200: "ДВЕРЬ ОТКРЫТА: запрос без токена Cloudflare Access получил данные",
        503: "аутентификация не настроена - отказ получит и owner, см. CF_ACCESS_* в .env",
    }.get(закрытость.status_code, f"ожидался 401, получено {закрытость.status_code}")
    пункты.append(
        Проверка(f"{имя}: {ЗАЩИЩЁННЫЙ_ПУТЬ} заперт", закрытость.status_code == 401, подсказка)
    )

    return пункты


def проверить_подделку(клиент: httpx2.Client, база: str, *, имя: str) -> list[Проверка]:
    """Заголовок с мусором вместо токена не пускается.

    Проверяется не подпись - её проверяют тесты, - а то, что заголовок
    вообще читается той самой второй дверью. Промах конфигурации, при
    котором `Cf-Access-Jwt-Assertion` доезжает до API нетронутым, но
    никем не проверяется, выглядит на экране ровно как рабочий сервис.
    """
    try:
        ответ = клиент.get(
            f"{база}{ЗАЩИЩЁННЫЙ_ПУТЬ}",
            timeout=ТАЙМАУТ_СЕКУНД,
            # Значение строго ASCII: заголовки HTTP не переносят кириллицу,
            # и запрос упал бы на кодировании, не дойдя до двери.
            headers={ЗАГОЛОВОК_ТОКЕНА: "not-a-token"},
        )
    except httpx2.HTTPError as сбой:
        return [
            Проверка(
                f"{имя}: мусорный токен не пускается",
                False,
                f"запрос не дошёл ({сбой.__class__.__name__})",
            )
        ]

    return [
        Проверка(
            f"{имя}: мусорный токен не пускается",
            ответ.status_code in (401, 403),
            f"ожидался 401, получено {ответ.status_code}",
        )
    ]


# Название пункта про ssh одно на все исходы: по нему owner ищет строку
# в отчёте, а адрес и причина живут в подсказке.
ПУНКТ_SSH = "ssh-маршрут заперт Access"

# Коды, которыми отвечает незапертое имя. 502 и 530 - подпись именно
# открытого маршрута: запрос дошёл до `cloudflared`, тот попробовал говорить
# HTTP с sshd и не смог. Будь перед именем приложение Access, до туннеля
# запрос не добрался бы вовсе - край Cloudflare отправил бы на вход.
ОТВЕТЫ_НЕЗАПЕРТОГО = {
    200: "ДВЕРЬ ОТКРЫТА: имя отвечает без входа в Access",
    404: (
        "перед именем нет приложения Access: ответил catch-all туннеля "
        "(http_status:404), а маршрута на ssh нет вовсе"
    ),
    502: "ДВЕРЬ ОТКРЫТА: запрос дошёл до cloudflared - перед маршрутом нет приложения Access",
    530: "ДВЕРЬ ОТКРЫТА: запрос дошёл до cloudflared - перед маршрутом нет приложения Access",
}

# Редирект на вход - обычный ответ запертого имени. Коды перечислены все
# перенаправляющие: какой именно выберет край Cloudflare, его дело.
РЕДИРЕКТЫ = frozenset({301, 302, 303, 307, 308})

# Прямой отказ - тоже запертое имя. Access отвечает так не всякому запросу,
# и полагаться на один только редирект значило бы однажды получить FAIL
# на исправной двери. Пустить открытый маршрут это не может: за ним sshd,
# а `cloudflared` перед ним отвечает 502, 503 и 404 - не 401.
ОТКАЗЫ = frozenset({401, 403})


def проверить_ssh_маршрут(settings: Settings, клиент: httpx2.Client) -> list[Проверка]:
    """Второй маршрут туннеля заперт Access (Э9б, ADR-045).

    Первый маршрут ведёт на web, и его запертость видно изнутри: API отвечает
    401 тому, кто пришёл без токена. У ssh-маршрута такой проверки нет
    в принципе - он идёт мимо кода, прямо на sshd платы, и единственная дверь
    перед ним стоит на краю Cloudflare. Спросить о ней можно только снаружи,
    походом на само имя.

    **Что ловится.** Приложение Access забыли создать, повесили на другое имя
    или удалили вместе со старым туннелем. Отказ тихий и хуже веб-дыры:
    открытым оказывается не расписание, а порт входа на плату, и заметить это
    нечем - owner ходит с токеном и разницы не видит.

    **Чем доказывается запертость.** Ответом с краю: редирект на вход домена
    команды owner, либо прямой 401/403. Не «не 200»: `cloudflared` на
    незапертом маршруте отвечает 502, и трактовка «раз не 200, то заперт»
    назвала бы открытую дверь закрытой. Чужой домен в редиректе - тоже
    провал: чужая команда впускает по своей политике, а не по почте owner.
    """
    имя = settings.cf_access_ssh_hostname.strip()
    if not имя:
        return [
            Проверка(
                ПУНКТ_SSH,
                False,
                "CF_ACCESS_SSH_HOSTNAME пусто: проверять нечего. Если маршрут на ssh "
                "в панели Cloudflare всё-таки заведён, впишите его имя - иначе он "
                "остаётся без присмотра",
                пропущена=True,
            )
        ]
    if имя in ЗАГЛУШКИ or имя.startswith("CHANGE_ME"):
        return [
            Проверка(
                ПУНКТ_SSH,
                False,
                "в CF_ACCESS_SSH_HOSTNAME стоит заглушка из .env.example: проверять нечего",
                пропущена=True,
            )
        ]

    похоже_на_имя = "." in имя and "/" not in имя and " " not in имя
    пункты = [
        Проверка(
            "CF_ACCESS_SSH_HOSTNAME похож на имя",
            похоже_на_имя,
            f"ожидалось имя вида ssh.example.ru, получено {имя!r}",
        )
    ]
    if not похоже_на_имя:
        # Живой запрос не делается намеренно: адрес из такой строки либо
        # не соберётся, либо уедет не туда, и его отказ прочитают как отказ
        # маршрута.
        return пункты

    адрес = f"https://{имя}/"
    try:
        ответ = клиент.get(адрес, timeout=ТАЙМАУТ_СЕКУНД)
    except httpx2.HTTPError as сбой:
        return [
            *пункты,
            Проверка(
                ПУНКТ_SSH,
                False,
                f"{адрес} не ответил ({сбой.__class__.__name__}): маршрут остался "
                "непроверенным, а непроверенный не значит запертый",
            ),
        ]

    if ответ.status_code in ОТКАЗЫ:
        return [*пункты, Проверка(ПУНКТ_SSH, True)]

    if ответ.status_code not in РЕДИРЕКТЫ:
        подсказка = ОТВЕТЫ_НЕЗАПЕРТОГО.get(
            ответ.status_code,
            f"ожидался редирект на вход Access, получено {ответ.status_code}",
        )
        return [*пункты, Проверка(ПУНКТ_SSH, False, подсказка)]

    куда = httpx2.URL(ответ.headers.get("location", ""))
    домен = settings.cf_access_team_domain.strip()
    if not куда.host:
        подсказка = "редирект без адреса: по нему не видно, чья дверь стоит перед маршрутом"
    else:
        подсказка = (
            f"вход ведёт на {куда.host}, а не на домен команды owner ({домен or 'не задан'}): "
            "чужая команда впускает по своей политике"
        )
    return [*пункты, Проверка(ПУНКТ_SSH, bool(домен) and куда.host == домен, подсказка)]


def выполнить(
    settings: Settings,
    клиент: httpx2.Client,
    *,
    api: str,
    web: str,
) -> list[Проверка]:
    """Все пункты подряд. Отказ одного не отменяет остальные.

    Останавливаться на первом нельзя: owner правит `.env` один раз, и знать
    он должен весь список сразу, а не по строчке за прогон.
    """
    пункты = проверить_настройки(settings)
    пункты += проверить_ключи(settings, клиент)
    if api:
        пункты += проверить_сервис(клиент, api.rstrip("/"), имя="api")
        пункты += проверить_подделку(клиент, api.rstrip("/"), имя="api")
    if web:
        # Через Caddy - тем же путём, каким пойдёт запрос из туннеля.
        # Дыра в прокси со стороны API не видна.
        пункты += проверить_сервис(клиент, web.rstrip("/"), имя="web")
    # Второй маршрут - последним: он про край Cloudflare, а не про соседние
    # контейнеры, и в отчёте читается отдельным хвостом.
    пункты += проверить_ssh_маршрут(settings, клиент)

    return пункты


def run(settings: Settings, *, api: str, web: str) -> int:
    """Отчёт списком и код возврата. Ненулевой - туннель включать нельзя."""
    with httpx2.Client(follow_redirects=False) as клиент:
        пункты = выполнить(settings, клиент, api=api, web=web)

    for пункт in пункты:
        logger.info("%s", _строка(пункт))

    провалы = провалено(пункты)
    if провалы:
        logger.error(
            "не пройдено пунктов: %d. Туннель включать нельзя (ADR-031 п. 3), "
            "порядок настройки - docs/RUNBOOK.md, раздел «Cloudflare»",
            len(провалы),
        )
        return 1

    logger.info("всё на месте: дверь заперта, можно включать туннель")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Точка входа. Ничего не пишет и не меняет - флага --apply здесь нет."""
    parser = argparse.ArgumentParser(
        description="Проверка перед включением Cloudflare Tunnel (Э7, ADR-033; ssh - Э9б, ADR-045)"
    )
    parser.add_argument(
        "--api",
        default=API_ПО_УМОЛЧАНИЮ,
        help=f"адрес API (по умолчанию {API_ПО_УМОЛЧАНИЮ}); пустая строка - пропустить",
    )
    parser.add_argument(
        "--web",
        default=WEB_ПО_УМОЛЧАНИЮ,
        help=f"адрес Caddy (по умолчанию {WEB_ПО_УМОЛЧАНИЮ}); пустая строка - пропустить",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        stream=sys.stdout,
    )
    # Отчёт читают глазами и по нему принимают решение включать туннель.
    # Строка httpx на каждый запрос делает список втрое длиннее ровно там,
    # где важно увидеть единственный FAIL среди десяти строк.
    logging.getLogger("httpx2").setLevel(logging.WARNING)
    return run(get_settings(), api=args.api, web=args.web)


