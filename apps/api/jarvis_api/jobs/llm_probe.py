"""Живая проба назначенных моделей: настоящий вызов с платы (Э12б, ADR-046).

**Зачем нужна отдельная команда, если есть тесты.** Тесты сеть мокают всегда
(CLAUDE.md), и правильно делают: прогон, звонящий в модель, стоил бы денег
на каждом запуске и краснел бы от чужой недоступности. Но ровно поэтому
тесты не отвечают на три вопроса, ответ на которые есть только у провайдера:

1. **Ключ рабочий и модель этому ключу доступна.** Имя модели приходит
   из `.env`, и опечатка в нём до первого живого вызова неотличима от
   верного назначения.
2. **Батч доступен на этом тарифе** (ADR-046). Ответ панели надёжнее
   документации: батч есть не на всяком уровне доступа.
3. **Выход наружу ведёт не из России.** Провайдеры геоблокируют по адресу
   запроса, и отказ по этой причине выделен отдельным типом
   (`ВыходЗаблокирован`), потому что чинится он не кодом, а маршрутом платы
   (ADR-050).

**Без `--apply` не делается ни одного сетевого вызова.** Печатается, что
было бы вызвано и почём, - и это проверяется тестом. Причина та же, по
которой `--dry-run` стоит на всём, что пишет наружу: вызов модели тратит
деньги owner, и команда, тратящая их от одного нажатия Enter, однажды будет
запущена «просто посмотреть».

**Каждый живой вызов пробы пишется в `audit_log`** (инвариант 8). Проба
дешевле сотой доли цента, но незаписанный расход - это расход, которого
месячный потолок не видит, а таких в системе быть не должно ни одного.
"""

import argparse
import datetime as dt
import logging
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from decimal import Decimal

from pydantic import BaseModel, Field, ValidationError
from sqlalchemy.orm import Session

from jarvis_api.config import Settings, get_settings
from jarvis_api.db.session import get_sessionmaker
from jarvis_api.integrations.llm.base import (
    Адаптер,
    ВыходЗаблокирован,
    Запрос,
    ОтказПровайдера,
    ПровайдерНедоступен,
)
from jarvis_api.integrations.llm.budget import потрачено_за_месяц
from jarvis_api.integrations.llm.client import записать_вызов, стоимость
from jarvis_api.integrations.llm.prompts import Промпт, собрать
from jarvis_api.integrations.llm.registry import собрать_адаптеры
from jarvis_api.integrations.llm.routing import Маршрут, МаршрутИспорчен, загрузить_маршруты
from jarvis_api.integrations.llm.tasks import Задача
from jarvis_api.jobs.common import owner_timezone

logger = logging.getLogger("jarvis.llm.probe")

АКТОР = "jobs.llm_probe"
ПРОМПТ = "probe"


class ОтветПробы(BaseModel):
    """Схема пробы: одно поле, чтобы проверялась дорога, а не модель.

    Умышленно скучная. Задача пробы - убедиться, что вызов доходит, схема
    доезжает и счётчики возвращаются; сложный ответ проверял бы качество
    модели, а это другой вопрос и другой инструмент (§5.3).
    """

    ready: bool = Field(description="Всегда true")


@dataclass(frozen=True)
class Строка:
    """Одна проверенная модель в отчёте."""

    задача: Задача
    роль: str
    маршрут: Маршрут
    исход: str
    подробность: str
    стоимость_usd: Decimal


def run(settings: Settings, *, apply: bool) -> int:
    """Прогон целиком: свой код возврата, и база - только когда она нужна.

    Сухой прогон не открывает соединения вовсе. Иначе `make llm-probe`
    на машине без `DATABASE_URL` падал бы, ничего не проверив, - и обещание
    «только план, ничего не трогаем» оказалось бы неправдой в первой же
    строке трассировки.
    """
    if not apply:
        return run_once(None, settings, apply=False)
    with get_sessionmaker()() as session:
        return run_once(session, settings, apply=True)


def run_once(
    session: Session | None,
    settings: Settings,
    *,
    apply: bool,
    адаптеры: dict[str, Адаптер] | None = None,
) -> int:
    """`адаптеры` подставляются тестами: сеть в прогоне замокана всегда.

    `session` обязателен только при `apply`: живые вызовы пишутся в аудит,
    а сухому прогону писать нечего.
    """
    try:
        маршруты = загрузить_маршруты(settings.llm_routing)
    except МаршрутИспорчен as ошибка:
        logger.error("LLM_ROUTING не разобрался: %s", ошибка)
        return 2

    адаптеры = собрать_адаптеры(settings) if адаптеры is None else адаптеры
    logger.info(
        "подключённые провайдеры: %s", ", ".join(sorted(адаптеры)) or "ни одного (ключей нет)"
    )

    к_проверке = list(_разложить(маршруты))
    if not к_проверке:
        logger.info(
            "назначено: ничего. Проверять нечего - впишите LLM_ROUTING в .env "
            "(готовая строка календаря есть в .env.example)"
        )
        return 0

    if not apply:
        logger.info("СУХОЙ ПРОГОН: ни одного сетевого вызова, только план")
        for задача, роль, маршрут in к_проверке:
            logger.info(
                "%-22s %-10s %s/%s, ответ до %s токенов, $%s/$%s за 1M%s",
                задача.value,
                роль,
                маршрут.provider,
                маршрут.model,
                маршрут.max_tokens,
                маршрут.price_in,
                маршрут.price_out,
                ", батч" if маршрут.batch else "",
            )
        logger.info("вызвать по-настоящему: та же команда с --apply")
        return 0

    if session is None:
        raise ValueError("живая проба пишется в audit_log: без сессии её делать нельзя")

    потрачено = потрачено_за_месяц(
        session, сейчас=dt.datetime.now(dt.UTC), зона=owner_timezone(session)
    )
    if потрачено >= settings.llm_monthly_cap_usd:
        # Проба стоит доли цента, но обойти потолок «ради диагностики» -
        # это ровно та дырка, из-за которой предохранитель перестаёт быть
        # предохранителем.
        logger.error(
            "месячный потолок $%s исчерпан (потрачено $%s): живая проба тоже тратит",
            settings.llm_monthly_cap_usd,
            потрачено,
        )
        return 1

    строки = [
        _проверить(session, задача, роль, маршрут, адаптеры, settings)
        for задача, роль, маршрут in к_проверке
    ]
    session.commit()

    _напечатать(строки)
    _проверить_батч(адаптеры, строки)

    провалы = [строка for строка in строки if строка.исход != "OK"]
    if провалы:
        logger.error("не ответили: %d из %d", len(провалы), len(строки))
        return 1

    logger.info("все назначенные модели ответили по схеме")
    return 0


def _разложить(
    маршруты: dict[Задача, Маршрут],
) -> Sequence[tuple[Задача, str, Маршрут]]:
    """Все модели назначения поимённо: основная, резервы, деградация.

    Проверяются все, а не только основная: резерв, о недоступности которого
    узнаёшь в момент отказа основной, - это не резерв, а вторая поломка.
    """
    собранное: list[tuple[Задача, str, Маршрут]] = []
    for задача, маршрут in маршруты.items():
        собранное.append((задача, "основная", маршрут))
        собранное.extend(
            (задача, f"резерв {номер}", резерв)
            for номер, резерв in enumerate(маршрут.fallback, start=1)
        )
        if маршрут.degraded is not None:
            собранное.append((задача, "при потолке", маршрут.degraded))
    return собранное


def _проверить(
    session: Session,
    задача: Задача,
    роль: str,
    маршрут: Маршрут,
    адаптеры: dict[str, Адаптер],
    settings: Settings,
) -> Строка:
    адаптер = адаптеры.get(маршрут.provider)
    if адаптер is None:
        return Строка(
            задача=задача,
            роль=роль,
            маршрут=маршрут,
            исход="НЕТ КЛЮЧА",
            подробность=f"провайдер {маршрут.provider!r} не подключён: ключа в .env нет",
            стоимость_usd=Decimal(0),
        )

    промпт = _промпт()
    запрос = Запрос(
        модель=маршрут.model,
        стабильная_часть=промпт.стабильная_часть,
        переменная_часть=промпт.переменная_часть,
        схема=ОтветПробы.model_json_schema(),
        max_tokens=маршрут.max_tokens,
        таймаут_секунд=settings.llm_timeout_seconds,
        temperature=маршрут.temperature,
    )
    общее = {"probe": True, "role": роль, "prompt": промпт.имя, "prompt_version": промпт.версия}

    try:
        ответ = адаптер.выполнить(запрос)
    except ВыходЗаблокирован as ошибка:
        записать_вызов(
            session,
            актор=АКТОР,
            задача=задача,
            маршрут=маршрут,
            статус="error",
            ответ=None,
            стоимость=None,
            detail={**общее, "reason": "выход заблокирован", "error": str(ошибка)},
        )
        return Строка(
            задача=задача,
            роль=роль,
            маршрут=маршрут,
            исход="ВЫХОД",
            подробность=f"{ошибка}",
            стоимость_usd=Decimal(0),
        )
    except (ПровайдерНедоступен, ОтказПровайдера) as ошибка:
        записать_вызов(
            session,
            актор=АКТОР,
            задача=задача,
            маршрут=маршрут,
            статус="error",
            ответ=None,
            стоимость=None,
            detail={**общее, "reason": "провайдер не ответил", "error": str(ошибка)},
        )
        return Строка(
            задача=задача,
            роль=роль,
            маршрут=маршрут,
            исход="ОТКАЗ",
            подробность=str(ошибка),
            стоимость_usd=Decimal(0),
        )

    цена = стоимость(маршрут, ответ)
    try:
        ОтветПробы.model_validate_json(ответ.текст)
    except ValidationError as ошибка:
        записать_вызов(
            session,
            актор=АКТОР,
            задача=задача,
            маршрут=маршрут,
            статус="error",
            ответ=ответ,
            стоимость=цена,
            detail={**общее, "reason": "ответ мимо схемы", "error": str(ошибка)},
        )
        return Строка(
            задача=задача,
            роль=роль,
            маршрут=маршрут,
            исход="МИМО СХЕМЫ",
            подробность=f"ответ {ответ.текст[:120]!r}",
            стоимость_usd=цена,
        )

    записать_вызов(
        session,
        актор=АКТОР,
        задача=задача,
        маршрут=маршрут,
        статус="ok",
        ответ=ответ,
        стоимость=цена,
        detail={**общее, "schema_first_try": True},
    )
    подробность = f"{ответ.токенов_вход} вход / {ответ.токенов_выход} выход"
    if ответ.токенов_мыслей:
        подробность += f" (из них мыслей {ответ.токенов_мыслей})"
    return Строка(
        задача=задача,
        роль=роль,
        маршрут=маршрут,
        исход="OK",
        подробность=подробность,
        стоимость_usd=цена,
    )


def _проверить_батч(адаптеры: dict[str, Адаптер], строки: Sequence[Строка]) -> None:
    """Доступен ли батч на этом ключе (ADR-046). Ответ панели, не документации.

    Спрашиваются только провайдеры, которым батч назначен: лишний вопрос
    третьему ничего не проверяет, а в отчёте выглядит как проверенное
    требование.
    """
    нужен = {строка.маршрут.provider for строка in строки if строка.маршрут.batch}
    if not нужен:
        logger.info("батч ни одной задаче не назначен - проверять нечего")
        return

    for имя in sorted(нужен):
        адаптер = адаптеры.get(имя)
        проверка = getattr(адаптер, "проверить_батч", None)
        if проверка is None:
            logger.error("батч: %-10s адаптер пачек не умеет", имя)
            continue
        доступ = проверка()
        logger.info(
            "батч: %-10s %s (%s)",
            имя,
            "доступен" if доступ.доступен else "НЕДОСТУПЕН",
            доступ.подробность,
        )


def _напечатать(строки: Sequence[Строка]) -> None:
    for строка in строки:
        logger.info(
            "%-22s %-12s %-10s %-12s %s",
            строка.задача.value,
            строка.роль,
            строка.маршрут.provider,
            строка.исход,
            строка.подробность,
        )
    итог = sum((строка.стоимость_usd for строка in строки), Decimal(0))
    logger.info("проба стоила $%s", итог)


def _промпт() -> Промпт:
    return собрать(ПРОМПТ)


def main(argv: Sequence[str] | None = None) -> int:
    """Точка входа. По умолчанию сухой прогон: без флага в сеть не ходим."""
    parser = argparse.ArgumentParser(
        description="Живая проба назначенных моделей с платы (Э12б, ADR-046)"
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="сделать настоящие вызовы (тратит деньги owner и пишется в audit_log)",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stdout)
    # Отчёт читают глазами: строка httpx на каждый запрос удлиняет его вдвое
    # ровно там, где важно увидеть единственный отказ среди десяти строк.
    logging.getLogger("httpx2").setLevel(logging.WARNING)
    return run(get_settings(), apply=args.apply)


if __name__ == "__main__":
    raise SystemExit(main())
