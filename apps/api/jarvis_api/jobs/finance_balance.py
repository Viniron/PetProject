"""Обзор месяца поверх базы: сальдо, «Отложено» и «Осталось» (§15.5).

Арифметика живёт в `domain/finance_balance.py` и базы не знает; здесь -
чтение книжки и печать. Разделение то же, что у гашения и разбора, и по
той же причине: что считать расходом owner, проверяется прямым вызовом.

**Команда, а не только домен, потому что экрана ещё нет.** Сальдо приезжает
в API на Ф6 и на вкладку `Finance` на Ф7, а август уже разобран, и цифру
по нему owner хочет видеть сейчас. Без команды домен Ф5 был бы кодом,
который до Ф7 никто не выполнял.

**`--apply` здесь нет намеренно.** Команда только читает: сальдо нигде
не хранится, оно пересчитывается из операций при каждом показе. Хранимая
копия разошлась бы с книжкой ровно в тот день, когда гашение задним числом
пересчитает закрытый месяц.
"""

import argparse
import datetime as dt
import logging
from collections.abc import Sequence

from sqlalchemy.orm import Session

from jarvis_api.db.session import get_sessionmaker
from jarvis_api.domain.finance_balance import Обзор, собрать
from jarvis_api.jobs.common import OwnerZoneError, owner_timezone

logger = logging.getLogger("jarvis.finance_balance")


def разобрать_месяц(текст: str) -> dt.date:
    """«2026-08» -> первое августа. Иначе - отказ с названным форматом.

    Разбором на части, а не `strptime`: тот строит наивный `datetime`
    (инвариант 7 и правило ruff DTZ007), хотя нужна одна календарная дата.
    """
    отказ = ValueError(f"месяц {текст!r} не вида ГГГГ-ММ, например 2026-08")
    части = текст.split("-")
    if len(части) != 2 or len(части[0]) != 4:
        raise отказ
    try:
        return dt.date(int(части[0]), int(части[1]), 1)
    except ValueError as ошибка:
        raise отказ from ошибка


def описать(обзор: Обзор) -> list[str]:
    """Человекочитаемый обзор. Отдельной функцией - её проверяет тест.

    Оговорки печатаются рядом с цифрами, а не вместо них: неполный месяц,
    окно пересчёта и неразмеченные счета меняют то, как цифру читать,
    и молчание о них делает промежуточное сальдо похожим на итоговое.
    """
    данные = обзор.данные
    строки = [f"месяц {данные.месяц:%Y-%m}: операций в сальдо {данные.операций}"]

    if обзор.покрыт_по is None:
        строки.append("  выписок нет: сальдо только по операциям, введённым руками")
    elif обзор.неполный:
        строки.append(f"  данные загружены по {обзор.покрыт_по:%Y-%m-%d} - месяц неполный")

    строки.append(f"  пришло   {данные.пришло} ₽")
    строки.append(f"  ушло     {данные.ушло} ₽")
    строки.append(f"  сальдо   {данные.сальдо} ₽")
    if данные.отложено is None:
        # Словами, а не нулём: ноль здесь неотличим от «ничего не откладывал».
        строки.append("  отложено: счета не размечены (make finance-accounts)")
    else:
        строки.append(f"  отложено {данные.отложено} ₽")
    строки.append(f"  осталось {данные.осталось} ₽ - накопленный итог с начала ведения")

    if данные.вне_переводов:
        строки.append(
            f"  на накопительных счетах {данные.вне_переводов} операц. не опознаны"
            " переводом себе - в «Отложено» они не вошли"
        )
    if данные.пересчитан_позже:
        строки.append("  цифра пересчитана позже: расход месяца погасило поступление следующего")
    if обзор.в_окне_пересчёта:
        строки.append("  месяц в окне пересчёта: гашение задним числом ещё может его изменить")
    else:
        строки.append("  месяц окончателен: окно пересчёта пройдено (§15.5)")
    return строки


def run_once(
    session: Session,
    *,
    месяц: str | None,
    сейчас: dt.datetime | None = None,
) -> int:
    """Прогон поверх готовой сессии. Возвращает код возврата процесса.

    `сейчас` передаётся тестом: окно пересчёта считается от него, и проверить
    «месяц окончателен» иначе можно было бы только сменой системных часов.
    """
    момент = сейчас or dt.datetime.now(dt.UTC)
    try:
        зона = owner_timezone(session)
        # Месяц по умолчанию - текущий в зоне owner. В UTC ночь первого числа
        # показала бы предыдущий, и обзор молча уехал бы на месяц назад.
        нужный = (
            разобрать_месяц(месяц)
            if месяц is not None
            else момент.astimezone(зона).date().replace(day=1)
        )
    except OwnerZoneError as сбой:
        logger.error("обзор не собран: %s", сбой)
        return 1
    except ValueError as отказ:
        logger.error("обзор не собран: %s", отказ)
        return 2

    обзор = собрать(session, месяц_обзора=нужный, сейчас=момент, зона=зона)
    # Чтение, но откат явный: сессия могла подгрузить объекты, и оставлять
    # открытую транзакцию висеть на базе Pi незачем.
    session.rollback()

    for строка in описать(обзор):
        logger.info("%s", строка)
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Сальдо месяца в книжке JARVIS (§15.5)")
    parser.add_argument(
        "--month",
        default=None,
        help="месяц вида ГГГГ-ММ; без него - текущий в зоне owner",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    with get_sessionmaker()() as session:
        return run_once(session, месяц=args.month)


if __name__ == "__main__":
    raise SystemExit(main())
