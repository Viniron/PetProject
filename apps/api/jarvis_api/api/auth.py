"""Аутентификация owner: Cloudflare Access перед туннелем (Э7, ADR-033).

Дверь запирается снаружи, а не здесь. Запрос с улицы доходит до Pi, только
пройдя политику Access в панели Cloudflare; `cloudflared` подписывает его
токеном и кладёт в заголовок `Cf-Access-Jwt-Assertion`. Этот модуль -
вторая дверь: он проверяет подпись, адресата и почту. Одной первой было бы
мало - политика правится мышкой в браузере, и промах в ней не должен
означать доступ к расписанию owner.

**Три вещи, каждая из которых открывает дверь молча, если её забыть.**

*Подпись.* Проверяется по публичным ключам команды (JWKS), алгоритм задан
жёстко списком: без этого токен с `alg: none` или подписанный HS256, где
секретом подставлен наш же публичный ключ, проходит проверку.

*Адресат (`aud`).* В одной команде Cloudflare живёт сколько угодно
приложений, и токен, выписанный любому другому, - валидный токен с валидной
подписью. Без сверки `aud` он пустил бы сюда.

*Почта.* Access пускает того, кого разрешает политика; мы сверяем результат
с `CF_ACCESS_ALLOWED_EMAIL`. Сервисные токены (`common_name` вместо почты)
не пускаются вовсе: в проекте с одним пользователем им неоткуда взяться.

**Ненастроенная аутентификация - закрытая дверь.** Пустые `CF_ACCESS_*`
в prod дают отказ на каждом `/api/*`, а не тихий пропуск. Правило выбрано
из того, как ошибаются на самом деле: строчку в `.env` забывают, а флаг
«выключить защиту» ставят один раз и не убирают. Исключение одно и узкое -
`ENV=dev`, то есть машина разработки, где туннеля нет по построению.
"""

import datetime as dt
import logging
import threading
from dataclasses import dataclass, field
from typing import Annotated, Any

import httpx2
import jwt
from fastapi import Depends, Request

from jarvis_api.api.deps import Настройки, Сейчас
from jarvis_api.api.errors import ErrorBody, ОтказAPI
from jarvis_api.config import Settings

logger = logging.getLogger("jarvis.api.auth")

# Заголовок, который ставит cloudflared. Регистр неважен - Starlette ищет
# заголовки без учёта регистра.
ЗАГОЛОВОК_ТОКЕНА = "Cf-Access-Jwt-Assertion"

# Алгоритм подписи Access. Списком из одного элемента, а не «какой в токене»:
# это и есть защита от подмены алгоритма.
АЛГОРИТМЫ = ["RS256"]

# Поля, без которых токен не рассматривается. `aud` и `iss` требуются явно:
# PyJWT молча пропустит их отсутствие, если не сказать обратного, а токен
# без адресата - это токен, годный куда угодно.
ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ = ["exp", "iat", "aud", "iss"]

# Кого возвращаем на машине разработки. Значение попадает только в логи -
# ни в базу, ни в аудит: записей, подписанных пользователем, у нас нет
# (инвариант 12, пользователь один).
DEV_OWNER = "dev@localhost"

# Отказы, которые эндпоинты за этой зависимостью объявляют в контракте.
# Без объявления клиент Э7, разбирая ответы по `openapi.json`, не узнает,
# что 401 и 403 бывают, - и обработает их как неизвестную ошибку.
ОТКАЗЫ_ДОСТУПА: dict[int | str, dict[str, Any]] = {
    401: {"model": ErrorBody, "description": "Нет действующего токена Cloudflare Access"},
    403: {"model": ErrorBody, "description": "Токен принадлежит не owner"},
}


def настроена(настройки: Settings) -> bool:
    """Все три значения на месте. Два из трёх - это ненастроенная защита."""
    return bool(
        настройки.cf_access_team_domain
        and настройки.cf_access_aud
        and настройки.cf_access_allowed_email
    )


def предупредить_о_режиме(настройки: Settings) -> None:
    """Сказать в лог при старте, если защиты нет. Один раз, а не на запрос.

    Строка в логе - единственный способ заметить, что процесс поднялся без
    аутентификации, до того как это заметит кто-то другой. На запрос такое
    писать нельзя: экран опрашивает сетку, и предупреждение утонуло бы
    в собственном повторе.
    """
    if настроена(настройки):
        return
    if настройки.env == "dev":
        logger.warning(
            "аутентификация выключена: ENV=dev и CF_ACCESS_* пусты. "
            "Туннель в таком режиме включать нельзя (ADR-033)"
        )
        return
    logger.error(
        "CF_ACCESS_* не заполнены при ENV=%s: эндпоинты /api/* будут отказывать. "
        "См. .env.example и docs/RUNBOOK.md",
        настройки.env,
    )


@dataclass(slots=True)
class НаборКлючей:
    """Публичные ключи команды Cloudflare, кэшированные на процесс.

    Кэш здесь не оптимизация ради скорости: без него каждый запрос экрана
    означал бы поход в Cloudflare, то есть внешнюю зависимость на пути
    каждого ответа. С кэшем недоступность Cloudflare перестаёт быть
    мгновенным отказом - ключи живут в памяти и продолжают проверять
    подпись (см. `_обновить`).

    Замок нужен, потому что эндпоинты синхронные и выполняются в пуле
    потоков: без него всплеск запросов на протухшем кэше отправил бы
    в Cloudflare столько запросов, сколько потоков в пуле.
    """

    настройки: Settings
    _ключи: dict[str, Any] = field(default_factory=dict)
    _загружено: dt.datetime | None = None
    _замок: threading.Lock = field(default_factory=threading.Lock)

    def ключ(self, kid: str, момент: dt.datetime) -> Any:
        """Ключ по идентификатору из заголовка токена.

        Незнакомый `kid` - законное состояние: Cloudflare ротирует ключи,
        и новый приходит раньше, чем протухает кэш. Перечитываем, но не
        чаще `cf_access_jwks_retry_seconds`, иначе мусорный токен со
        случайным kid превращается в способ гонять нас наружу запрос
        за запросом.
        """
        with self._замок:
            if self._просрочен(момент, self.настройки.cf_access_jwks_ttl_seconds):
                self._обновить(момент)
            elif kid not in self._ключи and self._просрочен(
                момент, self.настройки.cf_access_jwks_retry_seconds
            ):
                self._обновить(момент)
            найденный = self._ключи.get(kid)

        if найденный is None:
            raise ОтказAPI(
                статус=401,
                code="unauthenticated",
                message="Токен подписан неизвестным ключом Cloudflare Access",
            )
        return найденный

    def _просрочен(self, момент: dt.datetime, секунд: int) -> bool:
        if self._загружено is None:
            return True
        return момент - self._загружено >= dt.timedelta(seconds=секунд)

    def _обновить(self, момент: dt.datetime) -> None:
        """Перечитать JWKS. Отказ наружу не роняет проверку, пока есть кэш.

        §10 требует деградации вместо падения, и здесь она уместна ровно
        потому, что старые ключи не становятся опасными: ключ Cloudflare
        остаётся действующим неделями после ротации, а подделать подпись
        устаревшим публичным ключом нельзя. Пустой кэш - другое дело:
        проверить нечем, и это честный 503.
        """
        адрес = f"https://{self.настройки.cf_access_team_domain}/cdn-cgi/access/certs"
        try:
            with httpx2.Client(timeout=self.настройки.cf_access_jwks_timeout_seconds) as клиент:
                ответ = клиент.get(адрес)
                ответ.raise_for_status()
                данные = ответ.json()
            набор = jwt.PyJWKSet.from_dict(данные)
        except (httpx2.HTTPError, ValueError, jwt.PyJWTError) as ошибка:
            if self._ключи:
                logger.warning(
                    "ключи Cloudflare Access не перечитаны (%s), работаю по кэшу от %s",
                    ошибка.__class__.__name__,
                    self._загружено,
                )
                return
            logger.error("ключи Cloudflare Access недоступны: %s", ошибка)
            raise ОтказAPI(
                статус=503,
                code="auth_unavailable",
                message="Не удалось получить ключи Cloudflare Access. Повторите позже",
                retryable=True,
            ) from ошибка

        self._ключи = {ключ.key_id: ключ.key for ключ in набор.keys if ключ.key_id}
        self._загружено = момент


# Набор один на процесс: кэш, переживающий запрос, иначе бессмыслен.
# Хранится в переменной модуля, а не в `lru_cache`, потому что ключ кэша -
# объект `Settings`, а он не хэшируется.
_НАБОР: НаборКлючей | None = None


def получить_ключи(настройки: Настройки) -> НаборКлючей:
    """Зависимость, чтобы тест подменял источник ключей, не трогая сеть.

    Сверка настроек по идентичности, а не по значению: `get_settings`
    кэширован на процесс, поэтому в бою объект один и набор создаётся один
    раз. В тестах настройки подменены другим объектом - и набор пересоздаётся,
    вместо того чтобы протащить чужой кэш ключей между прогонами.
    """
    global _НАБОР
    if _НАБОР is None or _НАБОР.настройки is not настройки:
        _НАБОР = НаборКлючей(настройки=настройки)
    return _НАБОР


Ключи = Annotated[НаборКлючей, Depends(получить_ключи)]


def требуется_owner(
    request: Request,
    настройки: Настройки,
    момент: Сейчас,
    ключи: Ключи,
) -> str:
    """Пропустить запрос дальше или отказать. Возвращает почту owner.

    Возвращаемое значение сегодня никем не используется - записей,
    подписанных пользователем, в проекте нет (инвариант 12). Но зависимость,
    возвращающая почту, а не `None`, ничего не стоит и избавляет от соблазна
    разбирать токен второй раз там, где она понадобится.
    """
    if not настроена(настройки):
        if настройки.env == "dev":
            return DEV_OWNER
        raise ОтказAPI(
            статус=503,
            code="auth_not_configured",
            message=(
                "Аутентификация не настроена: в .env на плате пусты CF_ACCESS_*. "
                "Повтор не поможет - см. .env.example"
            ),
            retryable=False,
        )

    токен = request.headers.get(ЗАГОЛОВОК_ТОКЕНА)
    if not токен:
        raise ОтказAPI(
            статус=401,
            code="unauthenticated",
            message="Нет токена Cloudflare Access. Откройте приложение по адресу туннеля",
        )

    try:
        # Заголовок читается без проверки подписи - иначе не узнать, каким
        # ключом проверять. Ничего, кроме `kid`, отсюда брать нельзя:
        # содержимое этой половины токена подконтрольно отправителю.
        kid = jwt.get_unverified_header(токен).get("kid")
    except jwt.PyJWTError as ошибка:
        raise _не_пущен(ошибка) from ошибка

    if not isinstance(kid, str) or not kid:
        raise ОтказAPI(
            статус=401, code="unauthenticated", message="В токене нет идентификатора ключа"
        )

    try:
        полезное = jwt.decode(
            токен,
            ключи.ключ(kid, момент),
            algorithms=АЛГОРИТМЫ,
            audience=настройки.cf_access_aud,
            issuer=f"https://{настройки.cf_access_team_domain}",
            leeway=настройки.cf_access_leeway_seconds,
            options={"require": ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ},
        )
    except jwt.PyJWTError as ошибка:
        raise _не_пущен(ошибка) from ошибка

    почта = str(полезное.get("email") or "").strip().lower()
    if not почта:
        # Сервисный токен Access: в нём `common_name`, а не почта. Машинам
        # здесь делать нечего - джобы ходят в базу напрямую, а не по HTTP.
        logger.warning("отказ: токен без почты (сервисный токен Access)")
        raise ОтказAPI(
            статус=403, code="forbidden", message="Сервисные токены доступа сюда не пускаются"
        )

    if почта != настройки.cf_access_allowed_email.strip().lower():
        logger.warning("отказ: токен выписан на %s", почта)
        raise ОтказAPI(статус=403, code="forbidden", message="Этой почте доступ не разрешён")

    return почта


def _не_пущен(ошибка: jwt.PyJWTError) -> ОтказAPI:
    """Один текст на все причины непрохождения проверки.

    Различать в ответе «просрочен», «чужая подпись» и «чужой адресат» не
    нужно и вредно: экрану во всех трёх случаях делать одно - отправить
    owner на логин Cloudflare. Причина остаётся в логе, но не в ответе:
    подсказывать отправителю, что именно в его токене не так, - это
    подсказка для подбора. Сам токен не логируется никогда (CLAUDE.md).
    """
    logger.warning("токен Cloudflare Access отклонён: %s", ошибка.__class__.__name__)
    return ОтказAPI(
        статус=401,
        code="unauthenticated",
        message="Токен Cloudflare Access недействителен. Обновите страницу",
    )
