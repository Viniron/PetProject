"""Эндпоинты периодов исключений `day_flags` (Э6, §2.5, §8.4).

Отдельный экран в макете, отдельный роутер здесь: сетка календаря только
показывает пометки, а вносит и убирает их owner.

`PATCH` нет намеренно. Период правится удалением и вводом заново: экран
внесения периодов (этап 9 дизайна) не нарисован, а частичное обновление
трёх полей - это форма, которой никто не заказывал.

Как и роутер календаря, функции объявлены `def`, а не `async def`
(ADR-021): движок синхронный, и запрос в базу внутри `async def`
заблокировал бы цикл событий вместе с `/health`.
"""

import datetime as dt
from typing import Annotated, Any

from fastapi import APIRouter, Query, status

from jarvis_api.api.deps import Настройки, Сейчас, Сессия
from jarvis_api.api.errors import ОТКАЗЫ, ErrorBody, ОтказAPI
from jarvis_api.api.schemas import DayFlagIn, DayFlagOut, DayFlagsOut
from jarvis_api.domain import day_flags
from jarvis_api.domain.calendar import сегодня
from jarvis_api.domain.day_flags import АВТОПОМЕТКА
from jarvis_api.jobs.common import owner_timezone, sync_window

маршрутизатор = APIRouter(prefix="/api/day-flags", tags=["day-flags"])

# Отказы сверх общих. Объявлять их обязательно: необъявленный код ответа
# в контракте не появится, и клиент Э7 не узнает, что 409 бывает.
КОНФЛИКТ: dict[int | str, dict[str, Any]] = {
    409: {"model": ErrorBody, "description": "Ограничение базы или системная пометка"}
}
НЕ_НАЙДЕНО: dict[int | str, dict[str, Any]] = {
    404: {"model": ErrorBody, "description": "Периода с таким id нет"}
}

# Текст один на два отказа: причину `late_classes` нельзя ни внести
# (422 валидатором `DayFlagIn`), ни снять (409 здесь). Оба запрета про одно
# и то же - её ставит и снимает джоб расчёта времени занятий (§4).
СИСТЕМНАЯ = f"Пометку {АВТОПОМЕТКА!r} ставит и снимает система (SPEC §4), руками она не трогается"


@маршрутизатор.get("", responses=ОТКАЗЫ, summary="Периоды исключений за интервал")
def список_периодов(
    сессия: Сессия,
    настройки: Настройки,
    момент: Сейчас,
    начало: Annotated[
        dt.date | None,
        Query(alias="from", description="Не задано - начало окна забора расписания"),
    ] = None,
    конец: Annotated[
        dt.date | None,
        Query(alias="to", description="Включительно. Не задано - конец окна забора"),
    ] = None,
) -> DayFlagsOut:
    """Периоды, **пересекающие** интервал, а не лежащие внутри него.

    Умолчание - окно забора расписания (`sync_window`), а не «все периоды»:
    экран открывается на текущей неделе, и период из позапрошлого семестра
    ему не нужен. Параметры называются `from` и `to`, потому что `from` -
    ключевое слово Python: имя в контракте задаётся `alias`, иначе клиент
    получил бы `начало` транслитом или второе имя поля.
    """
    зона = owner_timezone(сессия)
    окно_с, окно_по = sync_window(настройки, сегодня(момент, зона))
    с_даты = начало if начало is not None else окно_с
    по_дату = конец if конец is not None else окно_по
    if по_дату < с_даты:
        raise ОтказAPI(
            статус=422,
            code="validation_error",
            message=f"Интервал задом наперёд: с {с_даты} по {по_дату}",
        )
    найденные = day_flags.пометки(сессия, с_даты, по_дату)
    return DayFlagsOut(
        flags=[DayFlagOut.model_validate(day_flags.из_строки(строка)) for строка in найденные]
    )


@маршрутизатор.post(
    "",
    status_code=status.HTTP_201_CREATED,
    responses=ОТКАЗЫ | КОНФЛИКТ,
    summary="Внести период исключений",
)
def внести_период(сессия: Сессия, тело: DayFlagIn) -> DayFlagOut:
    """Создать период.

    Законны и дают 201: период в один день, перекрытие с уже внесённым,
    период задним числом. §2.5 требует по ним **пересчёта отставания**,
    а не запрета: «я болел позапрошлую неделю» вносится именно так.

    Коммит явный: период и строка аудита обязаны уехать одной транзакцией,
    а `session_scope` границу транзакции не ставит.
    """
    строка = day_flags.создать(
        сессия,
        starts_on=тело.starts_on,
        ends_on=тело.ends_on,
        reason=тело.reason,
        note=тело.note,
    )
    сессия.commit()
    return DayFlagOut.model_validate(day_flags.из_строки(строка))


@маршрутизатор.delete(
    "/{flag_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    responses=ОТКАЗЫ | НЕ_НАЙДЕНО | КОНФЛИКТ,
    summary="Убрать период исключений",
)
def убрать_период(сессия: Сессия, flag_id: int) -> None:
    """Удалить период owner. Системную пометку удалить нельзя.

    Отказ на `late_classes` - 409, а не 403: дело не в правах, а в том, что
    снятая руками пометка вернулась бы сама следующим прогоном джоба (§4).
    Обещать owner результат, который не сохранится, - та же ложь, что
    правдоподобная выдумка на экране (инвариант 9).

    Имя параметра латиницей не только ради контракта: Starlette разбирает
    шаблон пути ASCII-регуляркой, и `{id_периода}` не распознаётся как
    параметр вовсе - маршрут превращается в литерал, а любой `DELETE`
    отвечает 404 «Not Found». Найдено тестом, не ревью.
    """
    строка = day_flags.найти(сессия, flag_id)
    if строка is None:
        raise ОтказAPI(
            статус=404,
            code="not_found",
            message=f"Периода с id {flag_id} нет",
        )
    if строка.reason == АВТОПОМЕТКА:
        raise ОтказAPI(статус=409, code="conflict", message=СИСТЕМНАЯ)
    day_flags.удалить(сессия, строка)
    сессия.commit()
