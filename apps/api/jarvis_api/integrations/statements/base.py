"""Нормализованная выписка и общая механика CSV. Банк знает только наследник.

Разделений здесь два, и оба важные.

**Формат файла - дело адаптера, а не ядра** (ADR-044). `BankAdapter` умеет
ровно две вещи: узнать свой файл и разобрать его целиком. Ни колонок, ни
кодировки, ни разделителя в нём нет - Т-Банк отдаёт CSV, Ozon Bank PDF,
и реестр обязан спрашивать оба одинаково.

**Общая механика CSV - в `CsvBankAdapter`, смысл колонок - в наследнике.**
Иначе каждый новый CSV-адаптер приносил бы с собой копию сверки заголовка,
и «отказ целиком с указанием колонки» из §15.1 выполнялся бы в одном банке
и не выполнялся в другом. PDF-адаптер при этом не наследует ни заголовка,
ни разделителя: наследовать нечего, и притворяться, что CSV-механика
у него есть, - значит звать её по ошибке.

**Отказ всегда целиком.** Частичного импорта нет ни при изменившемся
формате, ни при одной непарсящейся строке: молча пропущенная колонка суммы
даёт правдоподобную, но неверную книжку - худший из отказов по §10.

**Строки отдаются как есть в источнике.** Ни `fingerprint`, ни
`occurrence_no`, ни `kind` здесь не считаются: дедупликация - это Ф3,
разделение переводов и возвратов - Ф4. Адаптер обязан отвечать на один
вопрос: что в файле написано.
"""

import csv
import datetime as dt
import io
import re
from abc import ABC, abstractmethod
from dataclasses import dataclass
from decimal import Decimal
from typing import ClassVar
from zoneinfo import ZoneInfo

# Написание суммы, встреченное в выгрузках: целая часть, запятая, две цифры.
# Минус только ведущий - расход банк пишет со знаком.
_СУММА = re.compile(r"-?\d+,\d{2}")


class StatementError(ValueError):
    """Файл выписки не разобран. Общий тип, чтобы импорт ловил одним except.

    Наследников три, и они отвечают на разные вопросы owner: «какого банка
    этот файл?», «что в нём поменялось?», «какая строка сломана?». Один тип
    на все три заставлял бы читать текст сообщения, чтобы понять, чинить
    формат или ждать нового адаптера.
    """


class UnknownBankError(StatementError):
    """Заголовок не узнал ни один адаптер (§15.1).

    Сообщение перечисляет **пришедшие** колонки: искать адаптер по имени
    файла нельзя (файл переименовывают), а по колонкам owner сразу видит,
    выписка это вообще или посторонний CSV.
    """


class ColumnMismatchError(StatementError):
    """Банк опознан, но состав колонок разошёлся с ожидаемым (§15.1).

    Отдельно от `UnknownBankError` не для порядка: это два разных действия
    owner. Здесь - «Т-Банк сменил формат, чинить адаптер», там - «банка
    мы ещё не видели, нужен новый адаптер». Без различия файл со одной
    переименованной колонкой выглядел бы неизвестным банком.
    """


class TotalsMismatchError(StatementError):
    """Файл разобран, но контрольные итоги банка не сошлись с разобранным.

    Четвёртый вопрос owner - «всё ли мы прочитали?». Ни `ColumnMismatchError`,
    ни `RowError` на него не отвечают: обе означают, что разбор остановился
    на понятном месте, а здесь он прошёл до конца и тем не менее неполон.
    Так выглядит потерянная строка - единственная беда, которую по одному
    только тексту файла не увидишь.

    Не все банки дают итоги; те, что дают (Ozon Bank), обязаны их проверять.
    """


class RowError(StatementError):
    """Строка не разбирается: сумма, дата, статус или число полей не те.

    Номер строки в сообщении - номер **в файле**, считая заголовок первой:
    owner открывает файл и видит именно её.
    """


@dataclass(frozen=True, slots=True)
class StatementRow:
    """Операция в том виде, в каком её отдал банк, приведённая к нашим типам.

    Не ORM-объект: разбор проверяется тестами без базы вообще (прецедент
    `itmo/mapping.py`), а собрать `FinTransaction` из этого набора - дело Ф3,
    которое добавит к строке то, чего в файле нет: `fingerprint`,
    `occurrence_no` и `kind`.

    `source_row` - вся строка CSV словарём. Хранится не для истории:
    без сырья вопрос «почему эта операция попала в такую категорию»
    неотвечаем (§15.2).
    """

    # Номер строки в файле, заголовок - первая. Нужен в сообщениях об отказе.
    row_no: int
    # Всегда tz-aware и всегда UTC (инвариант 7). Зона owner нужна была,
    # чтобы понять, что за «13:36:02» написано в файле, - и остаётся в прошлом.
    occurred_at: dt.datetime
    account: str
    card_last4: str | None
    amount: Decimal
    currency: str
    amount_rub: Decimal
    merchant: str | None
    bank_category: str | None
    own_category: str | None
    mcc: str | None
    message: str | None
    # Колонка «учитывать в аналитике» - подсказка для `excluded`, а не сам
    # `excluded`: решение остаётся за owner (§15.2).
    analytics_hint: bool | None
    # Уже наш словарь статусов (`posted`/`pending`), а не написание банка.
    status: str
    source_row: dict[str, str]


@dataclass(frozen=True, slots=True)
class ParsedStatement:
    """Разобранный файл целиком.

    `period_start`/`period_end` считаются по операциям, а не берутся из имени
    файла: имя переименовывают, а период нужен Ф3, чтобы понять, какие
    операции банк из выгрузки убрал (§15.3). Границы - **даты в зоне owner**:
    выгрузка «за август» обязана дать 1-31 августа, а не 31 июля из-за
    приведения к UTC.

    У файла без операций границ нет - это не отказ, а неделя без трат.
    """

    bank: str
    period_start: dt.date | None
    period_end: dt.date | None
    rows: tuple[StatementRow, ...]


class BankAdapter(ABC):
    """Адаптер одного банка: опознаёт свой файл и разбирает его целиком.

    Всё, что знает ядро о банке, - эти три вещи. Формат файла сюда не
    входит намеренно (ADR-044): реестр спрашивает CSV-адаптер и PDF-адаптер
    одним и тем же вопросом, а чем файл разбирать - забота адаптера.
    """

    bank: ClassVar[str]

    @abstractmethod
    def claims(self, data: bytes) -> bool:
        """Этот файл - выписка нашего банка?

        Ответ по содержимому, а не по имени файла: имя переименовывают
        (§15.1).
        """

    @abstractmethod
    def parse(self, data: bytes, zone: ZoneInfo) -> ParsedStatement:
        """Разбирает файл целиком. Любая беда - отказ, ничего не отдаётся."""

    def describe(self, data: bytes) -> str | None:
        """Чем чужой файл представился этому адаптеру - для отказа реестра.

        `None` - адаптеру нечего сказать: файл не в его кодировке или не
        того типа. Смысл метода в сообщении об ошибке: owner должен увидеть,
        что за файл он загрузил, а не «неизвестный банк» без подробностей.
        Реализация по умолчанию молчит, потому что честно сказать нечего.
        """
        return None


class CsvBankAdapter(BankAdapter):
    """Банк, отдающий CSV. Формат объявляется классовыми полями.

    `signature` - подмножество колонок, по которому банк опознаётся.
    Не весь заголовок: по всему заголовку файл с одной переименованной
    колонкой перестал бы опознаваться вовсе, и owner получил бы «неизвестный
    банк» вместо имени сломанной колонки. В сигнатуру идут колонки,
    которых заведомо нет у других банков.
    """

    columns: ClassVar[tuple[str, ...]]
    signature: ClassVar[frozenset[str]]
    encoding: ClassVar[str]
    delimiter: ClassVar[str]

    def header(self, data: bytes) -> tuple[str, ...] | None:
        """Заголовок файла в кодировке **этого** банка. `None` - файл не в ней.

        Кодировка объявляется адаптером, потому что она у банков разная,
        а опознать банк надо до того, как файл прочитан. Поэтому заголовок
        читается столько раз, сколько адаптеров, - на одной строке это
        дешевле любой схемы с угадыванием кодировки.
        """
        try:
            текст = data.decode(self.encoding)
        except (UnicodeDecodeError, LookupError):
            return None
        первая = текст.splitlines()[:1]
        if not первая:
            return None
        return tuple(next(csv.reader(первая, delimiter=self.delimiter)))

    def claims(self, data: bytes) -> bool:
        """Этот файл - выписка нашего банка?"""
        заголовок = self.header(data)
        return заголовок is not None and self.signature <= set(заголовок)

    def describe(self, data: bytes) -> str | None:
        """Колонки чужого CSV - то единственное, что о нём стоит сказать.

        По ним owner сразу видит, выписка это вообще или посторонний файл,
        и какие колонки должен читать новый адаптер.

        Нет разделителя в первой строке - значит, это и не таблица, и
        колонок здесь нет. Молчим, чтобы сказать успел тот, кто такой файл
        понимает: без этого правила `%PDF-1.4` из заголовка PDF приезжал бы
        owner как «пришли колонки», а описание от PDF-адаптера в сообщение
        уже не попадало.
        """
        заголовок = self.header(data)
        if заголовок is None or len(заголовок) < 2:
            return None
        return f"пришли колонки: {list(заголовок)}"

    def parse(self, data: bytes, zone: ZoneInfo) -> ParsedStatement:
        """Разбирает файл целиком. Любая беда - отказ, ничего не отдаётся.

        Сверка заголовка идёт до чтения строк намеренно: при сменившемся
        формате owner должен получить имя колонки, а не тысячу ошибок разбора.
        """
        заголовок = self.header(data)
        if заголовок is None:
            raise ColumnMismatchError(
                f"выписка {self.bank}: файл не читается в кодировке {self.encoding}"
            )
        self.check_columns(заголовок)

        # Через StringIO с `newline=""`, а не по `splitlines()`: перевод строки
        # внутри кавычек - законная часть поля, и в комментарии к переводу
        # он однажды окажется. Разбей мы файл по строкам заранее, такая
        # операция обвалила бы импорт целиком «числом полей», и причину
        # пришлось бы искать глазами в CSV.
        читатель = csv.reader(
            io.StringIO(data.decode(self.encoding), newline=""), delimiter=self.delimiter
        )
        next(читатель)  # заголовок уже сверен выше
        строки: list[StatementRow] = []
        for сырая in читатель:
            if not сырая:
                continue  # пустая строка в хвосте файла - не операция
            # Номер у самого `csv`, а не счётчиком записей: при поле
            # с переводом строки внутри они расходятся, и owner нужен номер
            # строки файла - тот, что он видит в редакторе.
            номер = читатель.line_num
            if len(сырая) != len(self.columns):
                raise RowError(
                    f"выписка {self.bank}, строка {номер}: полей {len(сырая)},"
                    f" а колонок {len(self.columns)}"
                )
            строки.append(self.row(номер, dict(zip(self.columns, сырая, strict=True)), zone))

        даты = [с.occurred_at.astimezone(zone).date() for с in строки]
        return ParsedStatement(
            bank=self.bank,
            period_start=min(даты) if даты else None,
            period_end=max(даты) if даты else None,
            rows=tuple(строки),
        )

    def check_columns(self, заголовок: tuple[str, ...]) -> None:
        """Сверяет заголовок с ожидаемым и называет расхождение.

        Сравнивается порядок, а не множество: строки читаются по позициям,
        и переставленные колонки - это другой формат, даже если имена все
        на месте. Сообщение называет пропавшую колонку первой: именно она
        отвечает на вопрос «что чинить».
        """
        if заголовок == self.columns:
            return
        пришли = set(заголовок)
        нет = [к for к in self.columns if к not in пришли]
        ждали = set(self.columns)
        лишние = [к for к in заголовок if к not in ждали]
        if нет:
            raise ColumnMismatchError(
                f"выписка {self.bank}: в заголовке нет колонок {нет}"
                + (f", зато пришли лишние {лишние}" if лишние else "")
            )
        if лишние:
            raise ColumnMismatchError(f"выписка {self.bank}: лишние колонки {лишние}")
        raise ColumnMismatchError(
            f"выписка {self.bank}: колонки те же, но порядок другой - {list(заголовок)}"
        )

    @abstractmethod
    def row(self, номер: int, сырая: dict[str, str], zone: ZoneInfo) -> StatementRow:
        """Смысл колонок этого банка. Единственное, что обязан знать наследник."""


def деньги(значение: str, банк: str, колонка: str, номер: int) -> Decimal:
    """Сумма с десятичной запятой в `Decimal`. `float` для денег запрещён.

    Шаблон, а не один `Decimal(...)`: конструктор принимает `NaN`,
    `Infinity`, `1e5` и `1_000` - то есть молча пропустил бы в книжку
    значения, от которых арифметика сальдо не падает, а врёт. Ради денег
    проверка идёт по написанию, и только прошедшее превращается в число.

    Разделитель тысяч шаблоном не принят: в выгрузке Т-Банка за август его
    нет ни в одной из 62 строк (максимум 5 000,00), а принять выдуманное
    написание - тот же класс ошибки, что угадать статус. Встретится
    «10 000,00» - парсер откажет с указанием значения, owner пришлёт файл,
    и написание добавится по факту.
    """
    очищенное = значение.strip()
    if not очищенное:
        raise RowError(f"выписка {банк}, строка {номер}: колонка {колонка!r} пуста")
    if _СУММА.fullmatch(очищенное) is None:
        raise RowError(
            f"выписка {банк}, строка {номер}: колонка {колонка!r} - {значение!r} не похоже на сумму"
        )
    return Decimal(очищенное.replace(",", "."))


def момент(значение: str, формат: str, zone: ZoneInfo, банк: str, номер: int) -> dt.datetime:
    """Время банка (местное, без смещения) в UTC.

    Зона приходит параметром, а не читается из настроек: разбор обязан
    проверяться без базы. Наивного `datetime` из этой функции не выходит
    ни одним путём - `replace(tzinfo=...)` стоит в том же выражении,
    что `strptime` (инвариант 7).
    """
    try:
        return (
            dt.datetime.strptime(значение.strip(), формат).replace(tzinfo=zone).astimezone(dt.UTC)
        )
    except ValueError as ошибка:
        raise RowError(
            f"выписка {банк}, строка {номер}: дата {значение!r} не в формате {формат}"
        ) from ошибка


def пусто_в_none(значение: str) -> str | None:
    """Пустая строка CSV - это `NULL`, а не пустое значение.

    Нужно почти в каждой колонке: номер карты пуст у 25 операций из 62,
    MCC - у 18, «Ваша категория» и «Сообщение» - во всех.
    """
    очищенное = значение.strip()
    return очищенное or None
