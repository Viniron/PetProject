"""Адаптер Ozon Bank. Формат зафиксирован по настоящей справке, не по догадке.

Источник: «Справка о движении средств» за 16.08-16.09.2026, 10 операций,
получена от owner 2026-09-17. Обезличенная копия лежит
в `tests/fixtures/statements/ozon_2026-09.pdf`.

**Формат PDF, а не CSV** (ADR-044): другой выгрузки Ozon Bank не даёт.
Отсюда и устройство модуля - он не наследует `CsvBankAdapter` и не знает
ни разделителя, ни заголовка файла.

Четыре факта этого формата стоят того, чтобы быть написанными здесь.

**Таблица читается по ячейкам, а не по строкам текста.** Номер документа
переносится внутри ячейки (`1300000000` + `7` - это один номер), и в плоском
тексте вторая половина неотличима от начала соседнего поля. Склеивать её
по догадке значило бы писать в книжку правдоподобный, но чужой номер.

**Суммы написаны иначе, чем у Т-Банка:** `- 250.00 ₽` - точка, пробел после
знака, символ валюты; в итогах ещё и разделитель тысяч (`2 178.00 ₽`).
Поэтому `деньги()` из `base` здесь не годится: её шаблон требует запятую
и запрещает пробел, и это правильно - написание Т-Банка не должно молча
подойти чужому банку.

**Половины полей в справке нет.** Ни номера карты, ни MCC, ни категории
банка, ни статуса. Статус ставится `posted` всем строкам: справка о движении
средств показывает только состоявшееся движение, ожидающих операций в ней
не бывает. Это допущение, и оно названо допущением в §15.1 - встретится
справка с ожидающей операцией, формат придётся уточнять по ней.

**Банк даёт контрольные итоги, и они проверяются.** Зачисления, списания
и остатки сверяются с суммой разобранных строк. Это единственная в проекте
выписка, которая позволяет поймать потерянную строку арифметикой, а не
глазами, - и потому не сошедшиеся итоги отклоняют файл целиком.
"""

import datetime as dt
import io
import re
from decimal import Decimal
from typing import ClassVar, NamedTuple
from zoneinfo import ZoneInfo

import pdfplumber

from jarvis_api.integrations.statements.base import (
    BankAdapter,
    ColumnMismatchError,
    ParsedStatement,
    RowError,
    StatementRow,
    TotalsMismatchError,
    момент,
)

# Имя банка попадает в `fin_imports.bank` и в ключ дедупликации
# `fin_transactions` (§15.3). Менять его нельзя: банк в ключе - это то,
# что не даёт одинаковой покупке из двух банков схлопнуться в одну.
BANK = "ozon"

# Дата операции: местное время owner, без смещения в самом файле.
DATE_FORMAT = "%d.%m.%Y %H:%M:%S"
# Границы периода в шапке - календарные дни без времени.
_ДАТА = re.compile(r"(?P<день>\d{2})\.(?P<месяц>\d{2})\.(?P<год>\d{4})")

# По этим двум строкам справка опознаётся. Название банка одно не годится:
# оно встретится в любом документе, где Ozon упомянут, - в том числе
# в выписке другого банка с покупкой на Ozon.
ПРИЗНАКИ = ("ОЗОН Банк", "Справка о движении средств")

# Шапка таблицы занимает две строки: во второй «Сумма операции» разбивается
# на рубли и валюту. Обе сверяются целиком - это тот же контроль формата,
# что сверка заголовка CSV у Т-Банка.
ЗАГОЛОВОК = ("Дата операции", "Документ", "Назначение платежа", "Сумма операции", None)
ПОДЗАГОЛОВОК = (None, None, None, "Российские рубли", "Валюта")
# Имена ячеек строки данных - для `source_row` и сообщений об отказе.
КОЛОНКИ = ("Дата операции", "Документ", "Назначение платежа", "Российские рубли", "Валюта")

# Валюта счёта пишется словами и только одна на справку. Незнакомое
# написание - отказ, а не догадка: подставить «RUB» неизвестно чему
# значит сложить в одну книжку рубли с чем угодно.
ВАЛЮТЫ = {"РОССИЙСКИЙ РУБЛЬ": "RUB"}

# Сумма: знак, пробел, целая часть с необязательным разделителем тысяч,
# точка, две цифры, символ валюты. Разделитель тысяч принят и обычным
# пробелом, и неразрывным: в строках операций сентября тысяч нет вовсе,
# а в итогах («2 178.00 ₽») банк ставит именно неразрывный - и увидеть
# разницу глазами в PDF невозможно.
#
# Знак необязателен в шаблоне, но обязателен у операции: направление
# движения банк пишет только знаком, и строка без него означает, что формат
# сменился. У остатков и итогов знака нет вовсе - там он и не нужен,
# «Итого списаний» уже сказано словом.
_СУММА = re.compile(r"(?P<знак>[-+])?\s*(?P<целая>\d{1,3}(?:[\s ]\d{3})*)\.(?P<дробная>\d{2})\s?₽")

# Строки шапки и подвала. Каждая обязана найтись: это не украшение бланка,
# а период выписки, валюта, счёт и контрольные итоги.
_СЧЁТ = re.compile(r"Номер лицевого счёта:\s*№\s*(?P<номер>\d+)")
_ВАЛЮТА = re.compile(r"Валюта:\s*(?P<валюта>.+)")
# Тире между датами - типографское (U+2013), а не дефис.
_ПЕРИОД = re.compile(r"Период выписки:\s*(?P<начало>[\d.]+)\s*[–-]\s*(?P<конец>[\d.]+)")
_ВХОДЯЩИЙ = re.compile(r"Входящий остаток:\s*(?P<сумма>.+)")
_ИСХОДЯЩИЙ = re.compile(r"Исходящий остаток:\s*(?P<сумма>.+)")
_ЗАЧИСЛЕНИЯ = re.compile(r"Итого зачислений за период:\s*(?P<сумма>.+)")
_СПИСАНИЯ = re.compile(r"Итого списаний за период:\s*(?P<сумма>.+)")

# Сколько последних цифр счёта попадает в имя счёта. Полный номер в книжку
# не кладётся: он персональный, а различать счета хватает хвоста (решение
# owner 2026-09-17).
ХВОСТ_СЧЁТА = 4


class Шапка(NamedTuple):
    """То, чего нет в строках таблицы и что приходится брать из бланка."""

    account: str
    currency: str
    period_start: dt.date
    period_end: dt.date
    opening: Decimal


class Итоги(NamedTuple):
    """Контрольные суммы банка - по ним проверяется полнота разбора."""

    credit: Decimal
    debit: Decimal
    closing: Decimal


class OzonBank(BankAdapter):
    """Справка о движении средств: PDF с таблицей из пяти колонок."""

    bank: ClassVar[str] = BANK

    def claims(self, data: bytes) -> bool:
        текст = _первая_страница(data)
        return текст is not None and all(признак in текст for признак in ПРИЗНАКИ)

    def describe(self, data: bytes) -> str | None:
        if not data.startswith(b"%PDF"):
            return None
        текст = _первая_страница(data)
        if текст is None:
            return "файл PDF, но текста в нём нет: похоже, страницы - картинки"
        строки = [строка.strip() for строка in текст.splitlines() if строка.strip()][:3]
        return f"файл PDF, первые строки: {строки}"

    def parse(self, data: bytes, zone: ZoneInfo) -> ParsedStatement:
        """Разбирает справку целиком. Любая беда - отказ, ничего не отдаётся.

        Порядок шагов не случаен: сперва шапка, потом строки, и только потом
        сверка итогов. Сменился бланк - owner получает имя ненайденной строки
        шапки, а не десяток одинаковых отказов на операциях.
        """
        страницы, ячейки = _прочитать(data)
        шапка = _шапка(страницы[0])
        строки = _строки(ячейки, шапка, zone)
        _сверить_итоги(строки, шапка, _итоги(страницы[-1]))
        return ParsedStatement(
            bank=BANK,
            # Период берётся из шапки, а не по датам операций (в отличие
            # от CSV, где его больше взять неоткуда). Разница существенна
            # для §15.3: по операциям период сжался бы до 01.09-10.09,
            # и операции остальных недель не проверялись бы на исчезновение
            # из выгрузки - то есть отменённая банком операция осталась бы
            # в книжке живой.
            period_start=шапка.period_start,
            period_end=шапка.period_end,
            rows=строки,
        )


def _первая_страница(data: bytes) -> str | None:
    """Текст первой страницы или `None`, если файл не открылся как PDF.

    Отдельно от `_прочитать`, потому что зовётся на **чужом** файле - при
    опознании банка и при отказе реестра. Там любая беда означает «это
    не наш файл», а не отказ импорта, поэтому исключения гасятся все:
    чужой PDF вправе быть зашифрованным, битым или вовсе не PDF.
    """
    if not data.startswith(b"%PDF"):
        return None
    try:
        with pdfplumber.open(io.BytesIO(data)) as pdf:
            if not pdf.pages:
                return None
            return pdf.pages[0].extract_text() or None
    except Exception:  # noqa: BLE001 - чужой файл, разбирать причину незачем
        return None


def _прочитать(data: bytes) -> tuple[list[str], list[list[str | None]]]:
    """Текст страниц и строки всех таблиц справки одним списком.

    Одним списком потому, что шапка таблицы есть только на первой странице,
    на второй сразу идут операции, и трактовать страницы по-разному нечем.
    """
    try:
        with pdfplumber.open(io.BytesIO(data)) as pdf:
            страницы = [страница.extract_text() or "" for страница in pdf.pages]
            строки = [
                строка
                for страница in pdf.pages
                for таблица in страница.extract_tables()
                for строка in таблица
            ]
    except Exception as ошибка:
        raise ColumnMismatchError(
            f"выписка {BANK}: файл не читается как PDF - {ошибка}"
        ) from ошибка
    if not страницы:
        raise ColumnMismatchError(f"выписка {BANK}: в файле нет ни одной страницы")
    return страницы, строки


def _шапка(текст: str) -> Шапка:
    """Счёт, валюта, период и входящий остаток из бланка первой страницы."""
    счёт = _обязательная(_СЧЁТ, текст, "Номер лицевого счёта").group("номер")
    написание = _обязательная(_ВАЛЮТА, текст, "Валюта").group("валюта").strip()
    if написание not in ВАЛЮТЫ:
        raise ColumnMismatchError(
            f"выписка {BANK}: незнакомая валюта счёта {написание!r}." f" Известны: {sorted(ВАЛЮТЫ)}"
        )
    период = _обязательная(_ПЕРИОД, текст, "Период выписки")
    return Шапка(
        account=f"Ozon ·{счёт[-ХВОСТ_СЧЁТА:]}",
        currency=ВАЛЮТЫ[написание],
        period_start=_дата(период.group("начало"), "Период выписки"),
        period_end=_дата(период.group("конец"), "Период выписки"),
        opening=_сумма(
            _обязательная(_ВХОДЯЩИЙ, текст, "Входящий остаток").group("сумма"),
            "Входящий остаток",
        ),
    )


def _итоги(текст: str) -> Итоги:
    """Контрольные суммы из подвала последней страницы."""
    return Итоги(
        credit=_сумма(
            _обязательная(_ЗАЧИСЛЕНИЯ, текст, "Итого зачислений за период").group("сумма"),
            "Итого зачислений за период",
        ),
        debit=_сумма(
            _обязательная(_СПИСАНИЯ, текст, "Итого списаний за период").group("сумма"),
            "Итого списаний за период",
        ),
        closing=_сумма(
            _обязательная(_ИСХОДЯЩИЙ, текст, "Исходящий остаток").group("сумма"),
            "Исходящий остаток",
        ),
    )


def _строки(
    ячейки: list[list[str | None]], шапка: Шапка, zone: ZoneInfo
) -> tuple[StatementRow, ...]:
    """Строки таблицы в операции. Шапка таблицы сверяется до чтения строк."""
    if len(ячейки) < 2:
        raise ColumnMismatchError(
            f"выписка {BANK}: в справке не нашлась таблица операций."
            " Справки без операций мы ещё не видели - формат придётся"
            " уточнить по ней, а не угадать"
        )
    _сверить_шапку_таблицы(ячейки[0], ЗАГОЛОВОК)
    _сверить_шапку_таблицы(ячейки[1], ПОДЗАГОЛОВОК)
    return tuple(
        _строка(номер, строка, шапка, zone)
        # Номер - порядковый номер операции в справке, считая с единицы.
        # «Строки файла», как у CSV, у PDF нет, а номер по порядку owner
        # находит глазами в той же таблице.
        for номер, строка in enumerate(ячейки[2:], start=1)
    )


def _строка(номер: int, ячейки: list[str | None], шапка: Шапка, zone: ZoneInfo) -> StatementRow:
    if len(ячейки) != len(КОЛОНКИ):
        raise RowError(
            f"выписка {BANK}, операция {номер}: ячеек {len(ячейки)}," f" а колонок {len(КОЛОНКИ)}"
        )
    сырая = dict(zip(КОЛОНКИ, (_склеить(ячейка) for ячейка in ячейки), strict=True))

    рубли = _сумма(сырая["Российские рубли"], "Российские рубли", номер)
    в_валюте = _сумма(сырая["Валюта"], "Валюта", номер)
    if рубли != в_валюте:
        # Валютных операций по счёту не проходило, и как справка их пишет -
        # неизвестно: в какой валюте вторая колонка, банк отдельно не
        # называет. Записать рублёвую сумму как валютную (или наоборот)
        # значило бы завести в книжку неверную операцию молча.
        raise RowError(
            f"выписка {BANK}, операция {номер}: сумма в рублях {рубли}"
            f" разошлась с суммой в валюте {в_валюте} - похоже на валютную"
            " операцию, формат которой мы ещё не видели"
        )

    return StatementRow(
        row_no=номер,
        occurred_at=момент(сырая["Дата операции"], DATE_FORMAT, zone, BANK, номер),
        # Счёт один на справку и стоит в шапке, а не в строке: одна справка -
        # одна карта (уточнено owner 2026-09-17).
        account=шапка.account,
        # Ни номера карты, ни MCC, ни категорий в справке нет. `None` -
        # это «банк не сказал», и подставлять вместо него нечего.
        card_last4=None,
        amount=в_валюте,
        currency=шапка.currency,
        amount_rub=рубли,
        # Назначение платежа - единственное описание операции, какое есть.
        # В нём же лежит номер заказа или идентификатор перевода, то есть
        # оно уникально, и ключ дедупликации §15.3 на нём работает.
        merchant=сырая["Назначение платежа"] or None,
        bank_category=None,
        own_category=None,
        mcc=None,
        message=None,
        analytics_hint=None,
        # Справка о движении средств показывает состоявшееся движение:
        # ожидающих операций в ней не бывает (§15.1).
        status="posted",
        source_row=сырая,
    )


def _сверить_итоги(строки: tuple[StatementRow, ...], шапка: Шапка, итоги: Итоги) -> None:
    """Сверяет разобранное с контрольными суммами банка.

    Три равенства, а не одно: остаток сошёлся бы и при двух ошибках,
    погасивших друг друга, - потерянном зачислении и потерянном списании
    на ту же сумму. Это не выдуманный случай: в этой справке зачисления
    и списания ходят парами (перевод себе и тут же оплата).
    """
    зачисления = sum((с.amount_rub for с in строки if с.amount_rub > 0), Decimal(0))
    списания = -sum((с.amount_rub for с in строки if с.amount_rub < 0), Decimal(0))
    остаток = шапка.opening + зачисления - списания
    расхождения = [
        f"{имя}: разобрано {наше}, в справке {банковское}"
        for имя, наше, банковское in (
            ("зачисления", зачисления, итоги.credit),
            ("списания", списания, итоги.debit),
            ("исходящий остаток", остаток, итоги.closing),
        )
        if наше != банковское
    ]
    if расхождения:
        raise TotalsMismatchError(
            f"выписка {BANK}: итоги не сошлись ({'; '.join(расхождения)})."
            f" Разобрано операций: {len(строки)}"
        )


def _сверить_шапку_таблицы(пришла: list[str | None], ждали: tuple[str | None, ...]) -> None:
    """Шапка таблицы - тот же контроль формата, что заголовок CSV.

    Сверяется целиком и по порядку: ячейки читаются по позициям, и
    переставленные колонки - это другой формат, даже если имена все на месте.
    """
    приведённая = tuple(_склеить(ячейка) or None for ячейка in пришла)
    if приведённая != ждали:
        raise ColumnMismatchError(
            f"выписка {BANK}: шапка таблицы разошлась с ожидаемой."
            f" Пришла {list(приведённая)}, ждали {list(ждали)}"
        )


def _обязательная(шаблон: re.Pattern[str], текст: str, имя: str) -> re.Match[str]:
    """Строка бланка, без которой справку разбирать нечем."""
    найдено = шаблон.search(текст)
    if найдено is None:
        raise ColumnMismatchError(f"выписка {BANK}: в справке не нашлась строка «{имя}»")
    return найдено


def _сумма(значение: str, поле: str, номер: int | None = None) -> Decimal:
    """Сумма в написании Ozon Bank в `Decimal`. `float` для денег запрещён.

    Шаблоном, а не `Decimal(значение)`: конструктор принимает `NaN`,
    `Infinity` и `1e5`, то есть молча пропустил бы в книжку значения,
    от которых арифметика сальдо не падает, а врёт.

    Знак хранится в сумме, как у Т-Банка: расход - отрицательное число.
    `+ 250.00 ₽` даёт `Decimal("250.00")`, а не `Decimal("+250.00")` -
    иначе сравнение с итогами зависело бы от написания.
    """
    где = f", операция {номер}" if номер is not None else ""
    очищенное = значение.strip()
    найдено = _СУММА.fullmatch(очищенное)
    if найдено is None:
        raise RowError(f"выписка {BANK}{где}: поле «{поле}» - {значение!r} не похоже на сумму")
    # У операции знак обязателен: без него неизвестно, приход это или расход,
    # а угадать по назначению платежа - значит выдумать половину книжки.
    if номер is not None and найдено.group("знак") is None:
        raise RowError(
            f"выписка {BANK}{где}: в поле «{поле}» сумма {значение!r} без знака -"
            " по ней не понять, зачисление это или списание"
        )
    целая = re.sub(r"[\s ]", "", найдено.group("целая"))
    знак = "-" if найдено.group("знак") == "-" else ""
    return Decimal(f"{знак}{целая}.{найдено.group('дробная')}")


def _дата(значение: str, имя: str) -> dt.date:
    """Дата границы периода. Собирается по частям, а не `strptime`.

    `strptime` здесь дал бы наивный `datetime`, из которого дата достаётся
    следующим вызовом, - то есть наивный `datetime` всё-таки появился бы
    в коде, пусть и на одну строку (инвариант 7). Границе периода время
    не нужно вовсе: это календарный день, а не момент.
    """
    найдено = _ДАТА.fullmatch(значение.strip())
    if найдено is None:
        raise ColumnMismatchError(
            f"выписка {BANK}: в строке «{имя}» дата {значение!r} не вида ДД.ММ.ГГГГ"
        )
    try:
        return dt.date(
            int(найдено.group("год")), int(найдено.group("месяц")), int(найдено.group("день"))
        )
    except ValueError as ошибка:
        raise ColumnMismatchError(
            f"выписка {BANK}: в строке «{имя}» даты {значение!r} не существует"
        ) from ошибка


def _склеить(ячейка: str | None) -> str:
    """Перенос внутри ячейки - вёрстка, а не часть значения.

    В номере перенос убирается без следа (`1300000000` + `7` - один номер,
    `0101443304-` + `0080` - один номер заказа), в тексте - заменяется
    пробелом. Различить их можно только по соседям переноса: цифра или
    дефис слева и цифра справа означают, что банк разорвал число.
    """
    if ячейка is None:
        return ""
    без_переносов = re.sub(r"(?<=[\d-])\n(?=\d)", "", ячейка)
    return re.sub(r"\s+", " ", без_переносов.replace("\n", " ")).strip()


