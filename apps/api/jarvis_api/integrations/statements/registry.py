"""Реестр адаптеров: единственная дверь из байтов файла в разобранную выписку.

**Банк определяется по заголовку файла** (§15.1), а не по имени файла
и не выбором owner. Имя файла переименовывают, а выбор руками - лишний
вопрос на каждой загрузке и лишний способ ошибиться: файл Т-Банка,
загруженный как Сбер, прошёл бы сверку заголовка отказом, но при похожих
форматах мог бы и не пройти.

**Ядро импорта банка не знает** (ADR-030). Добавить банк - добавить модуль
рядом с `tbank.py` и строку в `АДАПТЕРЫ`. Всё, что дальше - сверка,
дедупликация, категории - работает для всех банков одинаково.
"""

from zoneinfo import ZoneInfo

from jarvis_api.integrations.statements.base import (
    BankAdapter,
    ParsedStatement,
    UnknownBankError,
)

# Адаптеры импортируются поимённо, а не модулями: `from ... import ozon`
# внутри собственного пакета mypy читает как обращение к атрибуту пакета,
# который к этому моменту ещё не собран, и ругается на несуществующее имя.
from jarvis_api.integrations.statements.ozon import ADAPTER as ОЗОН
from jarvis_api.integrations.statements.tbank import ADAPTER as ТБАНК

# Порядок значения не имеет: адаптеры опознают себя по содержимому файла,
# и пересекающихся признаков быть не должно. Появится второй банк с теми же
# служебными колонками - это повод менять признак, а не порядок здесь.
АДАПТЕРЫ: tuple[BankAdapter, ...] = (ТБАНК, ОЗОН)


def parse_statement(data: bytes, zone: ZoneInfo) -> ParsedStatement:
    """Разбирает файл выписки. Байты, а не путь: файл приезжает и загрузкой.

    Отказ - всегда целиком и всегда с причиной, по которой понятно, что
    делать: `UnknownBankError` - нужен новый адаптер, `ColumnMismatchError` -
    банк сменил формат, `RowError` - сломана конкретная строка.
    """
    for адаптер in АДАПТЕРЫ:
        if адаптер.claims(data):
            return адаптер.parse(data, zone)
    raise UnknownBankError(
        "файл не узнал ни один адаптер."
        f" {чем_представился(data)}."
        f" Известные банки: {[а.bank for а in АДАПТЕРЫ]}"
    )


def чем_представился(data: bytes) -> str:
    """Описание чужого файла для сообщения об отказе.

    Спрашиваем сами адаптеры: что видно в файле, знает тот, кто умеет его
    открывать. У CSV это колонки - в кодировке, в какой прочлись, потому
    что кодировка неизвестна ровно тогда, когда неизвестен банк. У PDF -
    начало текста первой страницы.

    Не сказал никто - показываем первую строку как есть, заменяя нечитаемое.
    Без этого сообщение об отказе падало бы само на `UnicodeDecodeError`,
    и owner увидел бы трассировку вместо подсказки.
    """
    for адаптер in АДАПТЕРЫ:
        описание = адаптер.describe(data)
        if описание is not None:
            return описание
    первая = data.decode("utf-8", errors="replace").splitlines()[:1]
    return f"файл начинается с {первая[0][:120]!r}" if первая else "файл пуст"
