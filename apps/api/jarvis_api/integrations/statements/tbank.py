"""Адаптер Т-Банка. Формат зафиксирован по настоящей выгрузке, не по догадке.

Источник: выгрузка owner за август 2026, 62 операции, получена 2026-09-05.
Обезличенная копия лежит в `tests/fixtures/statements/tbank_august.csv`.

Три факта этого формата стоят того, чтобы быть написанными здесь, а не
только в §15.1, - потому что каждый из них легко «исправить» в обратную
сторону:

**Кодировка UTF-8, а не `windows-1251`.** Ожидание `cp1251` для русского CSV
распространено и здесь неверно. Цена ошибки не в падении: файл разобрался бы
в кракозябры, и вся категоризация по мерчантам молча поехала бы.

**Секунды в дате обязательны.** Полных совпадений ключа дедупликации
за август нет ни одного именно из-за секунд, но по дню, сумме и описанию
совпадают две пары операций. Выбросить время из даты - потерять деньги
owner на Ф3 (§15.3).

**Даты платежа в выгрузке нет,** только дата операции. Поэтому момент
проведения из файла не берётся и в модели не хранится.
"""

from typing import ClassVar
from zoneinfo import ZoneInfo

from jarvis_api.integrations.statements.base import (
    CsvBankAdapter,
    RowError,
    StatementRow,
    деньги,
    момент,
    пусто_в_none,
)

# Имя банка попадает в `fin_imports.bank` и в ключ дедупликации
# `fin_transactions` (§15.3). Менять его нельзя: банк в ключе - это то,
# что не даёт одинаковой покупке из двух банков схлопнуться в одну.
BANK = "tbank"

# Дата операции: местное время owner, без смещения в самом файле.
DATE_FORMAT = "%d.%m.%Y %H:%M:%S"

# Единственное встреченное значение статуса. Незнакомое - отказ, а не
# догадка: принять неудавшийся платёж за состоявшийся расход дороже,
# чем подождать выгрузку с таким случаем (§15.1).
STATUSES = {"Ок": "posted"}

# Колонка «Учёт в аналитике». В выгрузке за август - `Да` во всех 62 строках;
# `Нет` - допущение о второй половине булевой пары, и оно названо допущением
# в §15.1. Всё остальное - отказ по тому же правилу, что у статуса.
ANALYTICS = {"Да": True, "Нет": False}


class TBank(CsvBankAdapter):
    """Семнадцать колонок в фиксированном порядке (§15.1)."""

    bank: ClassVar[str] = BANK
    columns: ClassVar[tuple[str, ...]] = (
        "Имя счёта",
        "Номер карты",
        "Дата операции",
        "Сумма операции",
        "Валюта операции",
        "Сумма в валюте счёта",
        "Валюта счёта",
        "Статус",
        "Категория по-умолчанию",
        "Ваша категория",
        "MCC",
        "Описание",
        "Сообщение",
        "Округление",
        "Сумма операции с округлением",
        "Бонусы (включая кэшбэк)",
        "Учёт в аналитике",
    )
    # Три колонки, которых не будет у чужой выписки. Не берём «Дата операции»
    # и «Статус» - такие колонки есть у всех, и по ним адаптер Т-Банка
    # присвоил бы себе файл любого банка.
    signature: ClassVar[frozenset[str]] = frozenset(
        {
            "Сумма операции с округлением",
            "Бонусы (включая кэшбэк)",
            "Учёт в аналитике",
        }
    )
    # `utf-8-sig`, а не `utf-8`: BOM в выгрузке за август отсутствует, но
    # приехав однажды, он прилип бы к имени первой колонки - и файл перестал
    # бы опознаваться как выписка Т-Банка вовсе. Отличить эту беду от смены
    # формата по сообщению было бы нельзя.
    encoding: ClassVar[str] = "utf-8-sig"
    delimiter: ClassVar[str] = ";"

    def row(self, номер: int, сырая: dict[str, str], zone: ZoneInfo) -> StatementRow:
        статус = сырая["Статус"].strip()
        if статус not in STATUSES:
            raise RowError(
                f"выписка {BANK}, строка {номер}: незнакомый статус {статус!r}."
                f" Известны: {sorted(STATUSES)}"
            )
        аналитика = сырая["Учёт в аналитике"].strip()
        if аналитика not in ANALYTICS:
            raise RowError(
                f"выписка {BANK}, строка {номер}: незнакомое значение"
                f" «Учёт в аналитике» {аналитика!r}. Известны: {sorted(ANALYTICS)}"
            )
        счёт = сырая["Имя счёта"].strip()
        if not счёт:
            raise RowError(f"выписка {BANK}, строка {номер}: пустое имя счёта")
        валюта = сырая["Валюта операции"].strip()
        if not валюта:
            raise RowError(f"выписка {BANK}, строка {номер}: пустая валюта операции")

        return StatementRow(
            row_no=номер,
            occurred_at=момент(сырая["Дата операции"], DATE_FORMAT, zone, BANK, номер),
            account=счёт,
            card_last4=_карта(сырая["Номер карты"], номер),
            amount=деньги(сырая["Сумма операции"], BANK, "Сумма операции", номер),
            currency=валюта,
            # Сумма в валюте счёта: валютная покупка записывается суммой
            # списания, полноценной мультивалютности в v1 нет (§15.8).
            amount_rub=деньги(сырая["Сумма в валюте счёта"], BANK, "Сумма в валюте счёта", номер),
            merchant=пусто_в_none(сырая["Описание"]),
            bank_category=пусто_в_none(сырая["Категория по-умолчанию"]),
            # Пусто во всех 62 строках августа: банковскими категориями owner
            # не пользуется. Ступень разбора всё равно читается - она бесплатна.
            own_category=пусто_в_none(сырая["Ваша категория"]),
            mcc=_mcc(сырая["MCC"], номер),
            message=пусто_в_none(сырая["Сообщение"]),
            analytics_hint=ANALYTICS[аналитика],
            status=STATUSES[статус],
            source_row=dict(сырая),
        )


def _карта(значение: str, номер: int) -> str | None:
    """`*3417` - это четыре цифры карты. Пусто у 25 операций из 62.

    Звёздочка не хранится: в базе колонка называется `card_last4`, и хранить
    в ней банковское оформление значило бы сравнивать его при дедупликации
    (номер карты входит в `fingerprint`, §15.3).
    """
    очищенное = значение.strip()
    if not очищенное:
        return None
    if not очищенное.startswith("*") or not очищенное[1:].isdigit():
        raise RowError(f"выписка {BANK}, строка {номер}: номер карты {значение!r} не вида *1234")
    return очищенное[1:]


def _mcc(значение: str, номер: int) -> str | None:
    """Код категории мерчанта, четыре цифры. Пусто у 18 операций из 62.

    Строкой, а не числом: ведущий ноль в MCC значащий, и `int` его потеряет.
    """
    очищенное = значение.strip()
    if not очищенное:
        return None
    if not очищенное.isdigit():
        raise RowError(f"выписка {BANK}, строка {номер}: MCC {значение!r} не из цифр")
    return очищенное


ADAPTER = TBank()
