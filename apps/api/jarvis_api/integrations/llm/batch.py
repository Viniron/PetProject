"""Отложенная пачка: отправка, опрос, разбор результатов (§5.1, ADR-046).

**Зачем она вообще.** Две задачи в §5.1 помечены «не срочно» и назначены
в батч (ADR-046): категоризация операций книжки и подбор материалов. Скидка
вдвое там не косметическая - это единственные задачи, где объём считается
сотнями вызовов, а ответ нужен не сейчас.

**Чем это отличается от `вызвать`, и почему не общая функция.**

1. **Фолбэка нет.** Уйти на резервную модель посреди суточного ожидания
   означало бы оплатить всю пачку дважды. Провайдер недоступен - пачка не
   отправилась, и вызывающий джоб просто попробует в следующий раз.
2. **Повтора при промахе мимо схемы нет.** Переспросить можно вызов, а не
   пачку: повтор одного задания - это новая пачка и ещё сутки. Задание,
   ответ которого не прошёл схему, возвращается отказом, и что с ним делать,
   решает вызывающий (у книжки - оставить операцию без категории, §15.6).
3. **Отправка и разбор разнесены во времени.** Между ними перезагрузка платы
   - джоб переживает её (инвариант 11), потому что состояние живёт у
   провайдера, а не в памяти процесса.

**Аудит пишется при разборе, а не при отправке.** На отправке нет ни токенов,
ни стоимости: провайдер их ещё не посчитал. Строка на каждое задание - иначе
месячный потолок видел бы пачку из ста операций как один дешёвый вызов.
"""

import logging
from collections.abc import Mapping
from dataclasses import dataclass
from decimal import Decimal

from pydantic import BaseModel, ValidationError
from sqlalchemy.orm import Session

from jarvis_api.config import Settings
from jarvis_api.integrations.llm.base import (
    Адаптер,
    АдаптерБатча,
    Запрос,
    Изображение,
    СостояниеБатча,
)
from jarvis_api.integrations.llm.client import ОшибкаСлоя, записать_вызов, стоимость
from jarvis_api.integrations.llm.prompts import Промпт
from jarvis_api.integrations.llm.routing import Маршрут
from jarvis_api.integrations.llm.tasks import Задача

logger = logging.getLogger("jarvis.llm.batch")


class БатчНеПоддержан(ОшибкаСлоя):
    """Провайдер маршрута пачек не умеет. Ошибка назначения, а не вызова."""


@dataclass(frozen=True)
class Задание:
    """Один вход пачки: переменная часть промпта и картинки при них."""

    промпт: Промпт
    изображения: tuple[Изображение, ...] = ()


@dataclass(frozen=True)
class РазобранноеЗадание[T: BaseModel]:
    """Что вышло из одного задания пачки."""

    ключ: str
    значение: T | None
    ошибка: str | None
    стоимость_usd: Decimal


def батчевый(адаптер: Адаптер) -> АдаптерБатча:
    """Адаптер как умеющий пачки - или внятный отказ.

    Проверка по методу, а не по `isinstance`: `АдаптерБатча` - протокол,
    и адаптер не обязан его наследовать, чтобы ему соответствовать.
    """
    if not hasattr(адаптер, "отправить_батч"):
        raise БатчНеПоддержан(
            f"провайдер {адаптер.имя!r} пачек не умеет; "
            "уберите batch у задачи в LLM_ROUTING или назначьте другого"
        )
    return адаптер  # type: ignore[return-value]


def отправить(
    *,
    маршрут: Маршрут,
    задания: Mapping[str, Задание],
    схема: type[BaseModel],
    настройки: Settings,
    адаптеры: Mapping[str, Адаптер],
) -> str:
    """Отправить пачку и вернуть её идентификатор у провайдера.

    Идентификатор обязан сохранить вызывающий: без него готовая и оплаченная
    пачка остаётся у провайдера невостребованной.
    """
    if not задания:
        raise ОшибкаСлоя("пустая пачка: отправлять нечего")

    адаптер = адаптеры.get(маршрут.provider)
    if адаптер is None:
        raise ОшибкаСлоя(
            f"провайдер {маршрут.provider!r} не подключён; "
            f"есть: {', '.join(sorted(адаптеры)) or 'ни одного'}"
        )

    запросы = {
        ключ: Запрос(
            модель=маршрут.model,
            стабильная_часть=задание.промпт.стабильная_часть,
            переменная_часть=задание.промпт.переменная_часть,
            схема=схема.model_json_schema(),
            max_tokens=маршрут.max_tokens,
            таймаут_секунд=настройки.llm_timeout_seconds,
            изображения=задание.изображения,
            temperature=маршрут.temperature,
        )
        for ключ, задание in задания.items()
    }

    идентификатор = батчевый(адаптер).отправить_батч(запросы)
    logger.info(
        "пачка %s отправлена провайдеру %s: заданий %d",
        идентификатор,
        маршрут.provider,
        len(запросы),
    )
    return идентификатор


def состояние(
    *, маршрут: Маршрут, идентификатор: str, адаптеры: Mapping[str, Адаптер]
) -> СостояниеБатча:
    """Готова ли пачка. Опрашивает джоб по своему расписанию, не слой."""
    адаптер = адаптеры.get(маршрут.provider)
    if адаптер is None:
        raise ОшибкаСлоя(f"провайдер {маршрут.provider!r} не подключён")
    return батчевый(адаптер).состояние_батча(идентификатор)


def забрать[T: BaseModel](
    session: Session,
    *,
    задача: Задача,
    маршрут: Маршрут,
    идентификатор: str,
    схема: type[T],
    актор: str,
    промпты: Mapping[str, Промпт],
    адаптеры: Mapping[str, Адаптер],
) -> list[РазобранноеЗадание[T]]:
    """Разобрать готовую пачку: по строке аудита на задание, ответы - вызывающему.

    Отказ по одному заданию не роняет остальные: пачка на сотню операций,
    где одна не разобралась, обязана отдать девяносто девять - иначе один
    мусорный вход стоил бы повторной оплаты всей пачки.
    """
    адаптер = адаптеры.get(маршрут.provider)
    if адаптер is None:
        raise ОшибкаСлоя(f"провайдер {маршрут.provider!r} не подключён")

    собранное: list[РазобранноеЗадание[T]] = []

    for ключ, исход in батчевый(адаптер).результаты_батча(идентификатор):
        промпт = промпты.get(ключ)
        общее = {
            "task": задача.value,
            "batch_id": идентификатор,
            "key": ключ,
            "prompt": промпт.имя if промпт else None,
            "prompt_version": промпт.версия if промпт else None,
        }

        if isinstance(исход, Exception):
            # Провайдер отказал по этому заданию. Токенов он за него не
            # назвал, поэтому стоимости нет: платим за ответы, а не за отказы.
            записать_вызов(
                session,
                актор=актор,
                задача=задача,
                маршрут=маршрут,
                статус="error",
                ответ=None,
                стоимость=None,
                detail={**общее, "reason": "отказ по заданию пачки", "error": str(исход)},
            )
            собранное.append(
                РазобранноеЗадание(
                    ключ=ключ, значение=None, ошибка=str(исход), стоимость_usd=Decimal(0)
                )
            )
            continue

        цена = стоимость(маршрут, исход)
        try:
            значение = схема.model_validate_json(исход.текст)
        except ValidationError as ошибка:
            # Ответ оплачен, даже если он мимо схемы (ADR-047). Повтора нет:
            # переспросить можно вызов, а не пачку.
            записать_вызов(
                session,
                актор=актор,
                задача=задача,
                маршрут=маршрут,
                статус="error",
                ответ=исход,
                стоимость=цена,
                detail={**общее, "reason": "ответ мимо схемы", "error": _первая(ошибка)},
            )
            собранное.append(
                РазобранноеЗадание(
                    ключ=ключ, значение=None, ошибка="ответ мимо схемы", стоимость_usd=цена
                )
            )
            continue

        записать_вызов(
            session,
            актор=актор,
            задача=задача,
            маршрут=маршрут,
            статус="ok",
            ответ=исход,
            стоимость=цена,
            detail={**общее, "schema_first_try": True},
        )
        собранное.append(
            РазобранноеЗадание(ключ=ключ, значение=значение, ошибка=None, стоимость_usd=цена)
        )

    # Коммит здесь, а не у вызывающего: токены за пачку списаны провайдером,
    # и откат работы вызывающего не должен уносить запись о расходе (ADR-047).
    session.commit()
    return собранное


def _первая(ошибка: ValidationError) -> str:
    детали = ошибка.errors()
    if not детали:
        return "ответ не разобрался"
    поле = ".".join(str(часть) for часть in детали[0]["loc"]) or "<корень>"
    return f"{поле} - {детали[0]['msg']}"
