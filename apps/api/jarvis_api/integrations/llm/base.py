"""Протокол адаптера провайдера: что ядро вправе требовать от любого из них.

**Протокол намеренно тонкий.** Здесь нет ни кэша, ни потоковой выдачи -
только «отправь запрос, верни текст и счётчики токенов». Причина в CLAUDE.md
и §5.2: механики скидок у провайдеров устроены по-разному, и общая абстракция
поверх них течёт молча. Протечка выглядит не ошибкой в логе, а выросшим
счётом, поэтому кэш остаётся свойством конкретного адаптера, а не полем
этого класса.

**Батч вынесен во второй протокол, а не в поле первого.** У Google это
долгая операция с опросом состояния и своей, отличной от обычного вызова,
формой запроса; у Anthropic - отдельный ресурс, отвечающий файлом JSONL,
где порядок строк не совпадает с порядком запросов. Общее у них ровно одно:
скидка вдвое. Провайдер, у которого батча нет, просто не реализует этот
протокол - и это видно по типу, а не выясняется отказом в рантайме.

**Три разных отказа, и разница между ними стоит денег.** `ПровайдерНедоступен`
- повод уйти на фолбэк: сеть, 429, 5xx, таймаут. `ОтказПровайдера` - повод
остановиться: неверный ключ, запрещённая модель, слишком длинный вход. Уход
на резервную модель во втором случае означал бы второй платный вызов с тем же
исходом, и так по всей цепочке. `ВыходЗаблокирован` - частный случай второго,
выделенный потому, что чинится он не в коде вовсе (маршрут платы, ADR-050),
а без отдельного имени опознавался бы сравнением строк в тексте чужой ошибки.

**Счётчики токенов приходят от провайдера, а не считаются на глаз.** Стоимость
вызова (инвариант 8) выводится из них умножением на цену маршрута, и своя
оценка длины в токенах разошлась бы с биллингом у первой же модели с другим
токенизатором.
"""

from collections.abc import Iterator, Mapping
from dataclasses import dataclass
from decimal import Decimal
from typing import Any, Protocol


class ПровайдерНедоступен(RuntimeError):
    """Временный отказ: сеть, таймаут, 429, 5xx. Повод попробовать фолбэк."""


class ОтказПровайдера(RuntimeError):
    """Отказ по существу запроса: ключ, доступ, размер входа. Фолбэк не поможет."""


class ВыходЗаблокирован(ОтказПровайдера):
    """Провайдер не обслуживает страну, из которой пришёл запрос.

    Ответ не о запросе и не о ключе, а о маршруте платы (ADR-050): трафик
    к моделям ушёл мимо VPN. Отдельное имя нужно живой пробе и RUNBOOK -
    иначе эта причина, единственная из всех чинящаяся не кодом, опознавалась
    бы поиском подстроки в чужом тексте ошибки.
    """


@dataclass(frozen=True)
class Изображение:
    """Картинка во входе вызова: фото доски или расписания (ADR-046).

    Байты, а не base64-строка: кодировка - дело адаптера, у провайдеров она
    заезжает в разные поля, а хранить в памяти обе формы одного снимка незачем.
    """

    media_type: str
    данные: bytes


@dataclass(frozen=True)
class Запрос:
    """Один вызов модели в том виде, в каком его получает адаптер.

    **Промпт приходит двумя частями, и порядок - часть контракта.** Стабильная
    часть идёт строго первой (CLAUDE.md): кэш провайдеров работает по общему
    префиксу, и любая подстановка, заехавшая в начало, молча обнуляет попадание
    - счёт вырастет, ошибок не появится. Собирать их в одну строку здесь нельзя
    именно поэтому: адаптер обязан видеть границу, чтобы пометить префикс
    кэшируемым по-своему.
    """

    модель: str
    стабильная_часть: str
    переменная_часть: str
    # JSON Schema ожидаемого ответа в том виде, в каком её выдал Pydantic.
    # Приведение к подмножеству провайдера - забота адаптера (`schema.py`):
    # ядро обязано её передать и проверить ответ по ней, но не знать, чем
    # схема Google отличается от схемы Anthropic.
    схема: dict[str, Any]
    # Потолок ответа. Обязателен на каждом типе вызова (§5.2): выход дороже
    # входа кратно у всех провайдеров, и неограниченный ответ - самая дорогая
    # покупка, какую можно сделать одним забытым параметром.
    max_tokens: int
    таймаут_секунд: int
    # Картинки идут тем же вызовом, что и текст (§5.1, ADR-046): разносить
    # фото и текст по разным моделям значило бы удвоить промпт, схему
    # и адаптер ради долей цента.
    изображения: tuple[Изображение, ...] = ()
    # Пусто - параметр не уходит провайдеру вовсе, и это умолчание не от лени.
    # Сэмплинг доступен не на всяком поколении: на моделях, назначенных
    # ADR-046 книжке, `temperature` то работает, то отвергается с 400, причём
    # у одного и того же провайдера. Значение приходит маршрутом (ADR-049),
    # потому что это свойство назначенной модели, а знать имена моделей коду
    # запрещено.
    temperature: Decimal | None = None


@dataclass(frozen=True)
class Ответ:
    """Что адаптер обязан вернуть: текст ответа и потраченные токены.

    **`токенов_выход` - это всё, за что берут по ставке выхода,** включая
    мысленные токены. Они приходят отдельным счётчиком и в «выход» провайдера
    не входят, но тарифицируются по той же ставке: адаптер, сложивший только
    видимый ответ, занизил бы стоимость - и `audit_log` начал бы врать тихо,
    ровно так, как запрещает ADR-047.

    `токенов_мыслей` и `токенов_кэша` идут в аудит подробностями. Они не
    участвуют в умножении на цену: первое уже сложено в выход, второе у обоих
    провайдеров считается по своей ставке, а кэш в календаре и книжке выключен
    (ADR-046) - ненулевое значение здесь означает, что его кто-то включил,
    и это должно быть видно.
    """

    текст: str
    токенов_вход: int
    токенов_выход: int
    токенов_мыслей: int = 0
    токенов_кэша: int = 0


@dataclass(frozen=True)
class ДоступБатча:
    """Ответ провайдера на вопрос «батч на этом ключе есть?» (ADR-046).

    Вопрос задан живой пробой и отвечается панелью провайдера, а не
    документацией: батч доступен не на всяком уровне доступа. Проверка
    обязана обходиться без отправки заданий - иначе ответ стоил бы денег
    и ждал бы сутки.
    """

    доступен: bool
    подробность: str


@dataclass(frozen=True)
class СостояниеБатча:
    """Готов ли батч и что провайдер об этом говорит.

    `сырое` - провайдерское слово как есть (`JOB_STATE_SUCCEEDED`, `ended`).
    Оно идёт в лог нетронутым: перевод в своё словечко пришлось бы
    расшифровывать обратно при разборе на плате.
    """

    готов: bool
    сырое: str


class Адаптер(Protocol):
    """Провайдер глазами ядра."""

    имя: str

    def выполнить(self, запрос: Запрос) -> Ответ:
        """Отправить запрос провайдеру. Соблюдение таймаута - обязанность адаптера."""
        ...


class АдаптерБатча(Адаптер, Protocol):
    """Провайдер, умеющий отложенную пачку со скидкой вдвое (§5.1, ADR-046).

    Ключи пачки задаёт вызывающий и по ним же получает результаты: порядок
    ответов не совпадает с порядком запросов ни у одного из провайдеров,
    и сопоставление по номеру строки однажды приписало бы категорию чужой
    операции - потеря денег owner, а не ошибка в логе.
    """

    def проверить_батч(self) -> ДоступБатча:
        """Есть ли батч на этом ключе. Без отправки заданий и без трат."""
        ...

    def отправить_батч(self, запросы: Mapping[str, Запрос]) -> str:
        """Отправить пачку и вернуть её идентификатор у провайдера."""
        ...

    def состояние_батча(self, идентификатор: str) -> СостояниеБатча:
        """Готова ли пачка. Опрос - дело вызывающего джоба, не адаптера."""
        ...

    def результаты_батча(self, идентификатор: str) -> Iterator[tuple[str, Ответ | Exception]]:
        """Пары «ключ - ответ». Отказ по одному заданию не роняет остальные.

        Исключение в паре, а не выброшенное наружу: пачка на сотню операций,
        где одна не разобралась, обязана отдать девяносто девять - иначе
        один мусорный вход стоил бы повторной оплаты всей пачки.
        """
        ...
