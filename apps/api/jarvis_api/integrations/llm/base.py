"""Протокол адаптера провайдера: что ядро вправе требовать от любого из них.

**Протокол намеренно тонкий.** Здесь нет ни кэша, ни батча, ни потоковой
выдачи - только «отправь запрос, верни текст и счётчики токенов». Причина
в CLAUDE.md и §5.2: механики скидок у провайдеров устроены по-разному, и общая
абстракция поверх них течёт молча. Протечка выглядит не ошибкой в логе,
а выросшим счётом, поэтому кэш и батч останутся свойствами конкретного
адаптера (Э12б), а не полями этого класса.

**Два разных отказа, и разница между ними стоит денег.** `ПровайдерНедоступен`
- повод уйти на фолбэк: сеть, 429, 5xx, таймаут. `ОтказПровайдера` - повод
остановиться: неверный ключ, запрещённая модель, слишком длинный вход. Уход
на резервную модель во втором случае означал бы второй платный вызов с тем же
исходом, и так по всей цепочке.

**Счётчики токенов приходят от провайдера, а не считаются на глаз.** Стоимость
вызова (инвариант 8) выводится из них умножением на цену маршрута, и своя
оценка длины в токенах разошлась бы с биллингом у первой же модели с другим
токенизатором.
"""

from dataclasses import dataclass
from typing import Any, Protocol


class ПровайдерНедоступен(RuntimeError):
    """Временный отказ: сеть, таймаут, 429, 5xx. Повод попробовать фолбэк."""


class ОтказПровайдера(RuntimeError):
    """Отказ по существу запроса: ключ, доступ, размер входа. Фолбэк не поможет."""


@dataclass(frozen=True)
class Запрос:
    """Один вызов модели в том виде, в каком его получает адаптер.

    **Промпт приходит двумя частями, и порядок - часть контракта.** Стабильная
    часть идёт строго первой (CLAUDE.md): кэш провайдеров работает по общему
    префиксу, и любая подстановка, заехавшая в начало, молча обнуляет попадание
    - счёт вырастет, ошибок не появится. Собирать их в одну строку здесь нельзя
    именно поэтому: адаптер обязан видеть границу, чтобы пометить префикс
    кэшируемым по-своему (Э12б).
    """

    модель: str
    стабильная_часть: str
    переменная_часть: str
    # JSON Schema ожидаемого ответа. Провайдеры принимают её по-разному
    # (structured output, tool call, инструкция в промпте) - это забота
    # адаптера; ядро лишь обязано её передать и проверить ответ по ней.
    схема: dict[str, Any]
    # Потолок ответа. Обязателен на каждом типе вызова (§5.2): выход дороже
    # входа кратно у всех провайдеров, и неограниченный ответ - самая дорогая
    # покупка, какую можно сделать одним забытым параметром.
    max_tokens: int
    таймаут_секунд: int


@dataclass(frozen=True)
class Ответ:
    """Что адаптер обязан вернуть: текст ответа и потраченные токены."""

    текст: str
    токенов_вход: int
    токенов_выход: int


class Адаптер(Protocol):
    """Провайдер глазами ядра.

    Реализации живут в соседних модулях и приезжают на Э12б. До тех пор
    реестр адаптеров пуст, и это рабочее состояние: ключи у owner есть
    (строка 7 BUILD-PROGRESS), а кода, который их читает, ещё нет.
    """

    имя: str

    def выполнить(self, запрос: Запрос) -> Ответ:
        """Отправить запрос провайдеру. Соблюдение таймаута - обязанность адаптера."""
        ...
