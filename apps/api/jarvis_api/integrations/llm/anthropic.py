"""Адаптер Anthropic: Messages и пачка (§5.2, ADR-046, ADR-049).

**Схема доезжает жёсткой, и ради этого выбран инструмент, а не свободный
текст.** ADR-046 выбрал провайдера на категоризацию именно за `strict: true`
со схемой, где `additionalProperties: false`: аргументы инструмента либо
валидны по схеме, либо ответа нет. Поэтому вызов всегда идёт одним
объявленным инструментом с принудительным выбором, а «ответом модели» ядру
отдаётся JSON его аргументов. Просить JSON текстом значило бы добровольно
разменять единственную жёсткую гарантию в слое на надежду.

**Стабильная часть промпта уходит в `system`.** Она рендерится первой -
раньше сообщений, - то есть граница кэшируемого префикса совпадает с границей
из `prompts.py`. Кэш при этом выключен (ADR-046): TTL пять минут или час,
а выписки приходят раз в неделю.

**Пачка отвечает файлом, а не объектом,** и порядок строк в нём не совпадает
с порядком запросов. Сопоставление идёт по ключу, который задал вызывающий,
- по номеру строки оно однажды приписало бы категорию чужой операции.
"""

import base64
import json
import logging
from collections.abc import Iterator, Mapping
from typing import Any

import httpx2

from jarvis_api.config import Settings
from jarvis_api.integrations.llm.base import (
    ДоступБатча,
    Запрос,
    Ответ,
    ОтказПровайдера,
    СостояниеБатча,
)
from jarvis_api.integrations.llm.http import Транспорт
from jarvis_api.integrations.llm.schema import для_anthropic

logger = logging.getLogger("jarvis.llm.anthropic")

ИМЯ = "anthropic"
БАЗА = "https://api.anthropic.com"
ВЕРСИЯ_API = "2023-06-01"

# Имя инструмента, которым модель отдаёт ответ. Латиницей и одно на все
# задачи: провайдер допускает в имени только ASCII, а смысл у инструмента
# ровно один - «верни структуру по схеме», и второе имя ничего бы не различало.
ИНСТРУМЕНТ = "answer"

# Как выглядит отказ по стране. **Проверено живой пробой 21.09.2026**, и
# первая версия этого списка была неверной: ожидались слова про страну или
# регион, а провайдер отвечает безлико -
# `403 {"type": "forbidden", "message": "Request not allowed"}`. Ни одного
# слова о географии в ответе нет, и геоблок выглядел отказом по ключу - то
# есть отправлял чинить не туда, где сломано.
#
# Поэтому признак - **пара** «403 + этот текст», а не текст сам по себе:
# 403 с другой формулировкой (организация отключена, ключ без доступа
# к модели) остаётся обычным отказом, который правда чинится у провайдера.
СТАТУС_ГЕОБЛОКА = 403
МЕТКИ_ГЕОБЛОКА = (
    "request not allowed",
    "unsupported_country",
    "not available in your country",
    "region is not supported",
)

СОСТОЯНИЕ_КОНЦА = "ended"


def опознать_геоблок(статус: int, тело: str) -> bool:
    """Отказ по стране выхода, а не по ключу и не по запросу (ADR-050)."""
    if статус != СТАТУС_ГЕОБЛОКА:
        return False
    нижний = тело.lower()
    return any(метка in нижний for метка in МЕТКИ_ГЕОБЛОКА)


class АдаптерAnthropic:
    """Anthropic глазами ядра. Имён моделей здесь нет: они приходят маршрутом."""

    имя = ИМЯ

    def __init__(self, транспорт: Транспорт, *, база: str = БАЗА) -> None:
        self._транспорт = транспорт
        self._база = база.rstrip("/")

    # --- обычный вызов ------------------------------------------------------

    def выполнить(self, запрос: Запрос) -> Ответ:
        тело = self._тело(запрос)
        ответ = self._транспорт.отправить(
            f"{self._база}/v1/messages", тело, таймаут=запрос.таймаут_секунд
        )
        return _разобрать_ответ(ответ)

    # --- батч ---------------------------------------------------------------

    def проверить_батч(self) -> ДоступБатча:
        """Спрашиваем список пачек: ключ либо вправе их видеть, либо нет.

        Список, а не пробная пачка: ответ тот же, стоит ноль и приходит сразу,
        тогда как настоящая пачка ждала бы до суток.
        """
        try:
            тело = self._транспорт.получить(f"{self._база}/v1/messages/batches?limit=1", таймаут=30)
        except ОтказПровайдера as ошибка:
            return ДоступБатча(доступен=False, подробность=str(ошибка))
        есть = тело.get("data")
        return ДоступБатча(
            доступен=True,
            подробность=f"пачек видно: {len(есть) if isinstance(есть, list) else 0}",
        )

    def отправить_батч(self, запросы: Mapping[str, Запрос]) -> str:
        тело = {
            "requests": [
                {"custom_id": ключ, "params": self._тело(запрос)}
                for ключ, запрос in запросы.items()
            ]
        }
        таймаут = max(запрос.таймаут_секунд for запрос in запросы.values())
        ответ = self._транспорт.отправить(
            f"{self._база}/v1/messages/batches", тело, таймаут=таймаут
        )
        идентификатор = ответ.get("id")
        if not isinstance(идентификатор, str) or not идентификатор:
            raise ОтказПровайдера(f"Anthropic не вернул id пачки: {json.dumps(ответ)[:400]}")
        return идентификатор

    def состояние_батча(self, идентификатор: str) -> СостояниеБатча:
        тело = self._описание(идентификатор)
        состояние = тело.get("processing_status")
        состояние = состояние if isinstance(состояние, str) else "unknown"
        return СостояниеБатча(готов=состояние == СОСТОЯНИЕ_КОНЦА, сырое=состояние)

    def результаты_батча(self, идентификатор: str) -> Iterator[tuple[str, Ответ | Exception]]:
        тело = self._описание(идентификатор)
        адрес = тело.get("results_url")
        if not isinstance(адрес, str) or not адрес:
            состояние = тело.get("processing_status")
            raise ОтказПровайдера(
                f"пачка {идентификатор} в состоянии {состояние!r}, результатов ещё нет"
            )
        yield from _разобрать_jsonl(self._транспорт.скачать(адрес, таймаут=120))

    def _описание(self, идентификатор: str) -> dict[str, Any]:
        return self._транспорт.получить(
            f"{self._база}/v1/messages/batches/{идентификатор}", таймаут=60
        )

    # --- сборка запроса -----------------------------------------------------

    def _тело(self, запрос: Запрос) -> dict[str, Any]:
        # Картинки идут перед текстом: провайдер разбирает такой порядок
        # заметно лучше, а стабильный префикс от него не сдвигается - он
        # живёт в `system`, до сообщений.
        содержимое: list[dict[str, Any]] = [
            {
                "type": "image",
                "source": {
                    "type": "base64",
                    "media_type": кадр.media_type,
                    "data": base64.b64encode(кадр.данные).decode("ascii"),
                },
            }
            for кадр in запрос.изображения
        ]
        содержимое.append({"type": "text", "text": запрос.переменная_часть})

        тело: dict[str, Any] = {
            "model": запрос.модель,
            "max_tokens": запрос.max_tokens,
            "system": [{"type": "text", "text": запрос.стабильная_часть}],
            "messages": [{"role": "user", "content": содержимое}],
            "tools": [
                {
                    "name": ИНСТРУМЕНТ,
                    "description": "Единственный способ ответить: аргументы и есть ответ.",
                    "input_schema": для_anthropic(запрос.схема),
                    "strict": True,
                }
            ],
            "tool_choice": {"type": "tool", "name": ИНСТРУМЕНТ},
        }
        if запрос.temperature is not None:
            # float, а не Decimal: JSON Decimal не знает, а это параметр
            # сэмплинга, не деньги.
            тело["temperature"] = float(запрос.temperature)
        return тело


def _разобрать_ответ(тело: Mapping[str, Any]) -> Ответ:
    """Аргументы вызванного инструмента как JSON-текст плюс счётчики токенов."""
    блоки = тело.get("content")
    блоки = блоки if isinstance(блоки, list) else []

    аргументы: Any = None
    for блок in блоки:
        if isinstance(блок, dict) and блок.get("type") == "tool_use":
            аргументы = блок.get("input")
            break

    if аргументы is None:
        # Инструмент был принудительным, значит его отсутствие - не каприз
        # модели, а упёршийся потолок ответа или сработавший фильтр. Резерв
        # ответит тем же, поэтому отказ по существу.
        причина = тело.get("stop_reason")
        raise ОтказПровайдера(
            f"Anthropic не вызвал инструмент {ИНСТРУМЕНТ!r} (stop_reason={причина!r})"
        )

    учёт = тело.get("usage")
    учёт = учёт if isinstance(учёт, dict) else {}
    return Ответ(
        # `ensure_ascii=False` - чтобы в логе отказа по схеме был читаемый
        # русский текст, а не со.
        текст=json.dumps(аргументы, ensure_ascii=False),
        токенов_вход=_целое(учёт, "input_tokens"),
        токенов_выход=_целое(учёт, "output_tokens"),
        токенов_кэша=_целое(учёт, "cache_read_input_tokens"),
    )


def _целое(учёт: Mapping[str, Any], имя: str) -> int:
    значение = учёт.get(имя)
    return значение if isinstance(значение, int) else 0


def _разобрать_jsonl(сырое: str) -> Iterator[tuple[str, Ответ | Exception]]:
    for номер, строка in enumerate(сырое.splitlines(), start=1):
        голая = строка.strip()
        if not голая:
            continue
        try:
            разобранная = json.loads(голая)
        except json.JSONDecodeError:
            # Одна испорченная строка не роняет пачку: остальные задания
            # оплачены и разобраны.
            logger.warning("строка %d файла результатов Anthropic не разобралась", номер)
            yield f"<строка {номер}>", ОтказПровайдера(f"строка {номер} файла результатов не JSON")
            continue

        if not isinstance(разобранная, dict):
            continue

        ключ = разобранная.get("custom_id")
        ключ = ключ if isinstance(ключ, str) else f"<строка {номер}>"
        исход = разобранная.get("result")
        исход = исход if isinstance(исход, dict) else {}
        вид = исход.get("type")

        if вид != "succeeded":
            yield ключ, ОтказПровайдера(f"задание {ключ} завершилось как {вид!r}: {исход}")
            continue

        try:
            yield ключ, _разобрать_ответ(исход.get("message") or {})
        except ОтказПровайдера as сбой:
            yield ключ, сбой


def собрать(настройки: Settings, *, клиент: httpx2.Client | None = None) -> АдаптерAnthropic | None:
    """Адаптер, если ключ задан. Пустой ключ - провайдер просто не подключён."""
    ключ = настройки.anthropic_api_key.strip()
    if not ключ:
        return None
    return АдаптерAnthropic(
        Транспорт(
            имя=ИМЯ,
            заголовки={
                "x-api-key": ключ,
                "anthropic-version": ВЕРСИЯ_API,
                "Content-Type": "application/json",
            },
            попыток=настройки.llm_retries,
            пауза_секунд=настройки.llm_retry_backoff_seconds,
            геоблок=опознать_геоблок,
            клиент=клиент,
        )
    )
