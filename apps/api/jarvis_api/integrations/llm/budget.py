"""Месячный потолок расходов на модели (§5.2, решение owner 2026-09-21).

**Потолок один на все модели разом.** Счёт от провайдера приходит один,
и потолки по задачам удержали бы каждую в своих рамках, оставив сумму без
присмотра: десять задач по доллару - это десять долларов, каждая из которых
«в пределах».

**Считается по `audit_log`, а не по отдельному счётчику.** Счётчик - это
вторая правда о потраченном: он разъедется с аудитом при первом же откате
транзакции, и разойдётся молча. Колонки стоимости в `audit_log` заведены
на Э2 ровно под это (см. докстринг `AuditLogEntry`), а индекс `kind, at`
делает сумму за месяц дешёвой.

**Месяц - календарный, в зоне owner.** Провайдер считает свой месяц по UTC,
и на границе месяца расхождение до трёх часов существует. Оно осознанное:
потолок защищает кошелёк owner, а не сверяется с инвойсом, и вторая зона
в коде стоила бы дороже этих трёх часов.
"""

import datetime as dt
from decimal import Decimal
from zoneinfo import ZoneInfo

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from jarvis_api.db.models import AuditLogEntry

# Вид записи аудита, по которому считаются деньги. Записи календаря стоимости
# не несут, и сумма по всему `audit_log` совпала бы с этой только до первого
# вызова модели - то есть выглядела бы верной ровно до того момента, когда
# начинает что-то значить.
ВИД_ВЫЗОВА = "llm_call"


def начало_месяца(сейчас: dt.datetime, зона: ZoneInfo) -> dt.datetime:
    """Полночь первого числа текущего месяца, в UTC - как лежит в базе.

    Наивного `datetime` здесь не появляется ни на шаг (инвариант 7):
    местное время строится сразу с зоной, в UTC переводится `astimezone`.
    """
    местное = сейчас.astimezone(зона)
    первое = местное.replace(day=1, hour=0, minute=0, second=0, microsecond=0)
    return первое.astimezone(dt.UTC)


def потрачено_за_месяц(session: Session, *, сейчас: dt.datetime, зона: ZoneInfo) -> Decimal:
    """Сумма стоимости вызовов модели с первого числа месяца.

    Строки без стоимости (отказ до ответа провайдера - таймаут, 429) в сумму
    не входят и не должны: заплачено за них не было. А вот вызов, чей ответ
    не прошёл схему, в сумму входит - токены за него списаны, и потолок
    обязан их видеть, иначе неудачные разборы тратили бы деньги мимо счёта.
    """
    граница = начало_месяца(сейчас, зона)
    запрос = select(func.coalesce(func.sum(AuditLogEntry.cost_usd), 0)).where(
        AuditLogEntry.kind == ВИД_ВЫЗОВА,
        AuditLogEntry.at >= граница,
    )
    итог = session.execute(запрос).scalar_one()
    # coalesce не даёт NULL, но типу об этом неизвестно: пустой месяц - это
    # ноль потраченного, а не «неизвестно сколько».
    return Decimal(итог) if итог is not None else Decimal(0)
