"""JSON Schema ядра — в тот вид, который принимает конкретный провайдер (§5.2).

**Почему это не одна функция и не общая абстракция.** Ядро отдаёт адаптеру
схему, как её выдал Pydantic: с `$defs`, `$ref`, `title` и `anyOf` для
необязательных полей. Дальше пути расходятся принципиально, и разница видна
в ADR-046: у Anthropic `strict: true` со схемой, где `additionalProperties:
false`, — это гарантия валидности аргументов; у Google схема лишь направляет
модель, и подмножество ключей там своё, урезанное до OpenAPI. Одна функция
на оба случая означала бы наименьшее общее подмножество, то есть добровольный
отказ от единственной жёсткой гарантии, какая в слое есть.

**Почему преобразование, а не «писать схемы под провайдера руками».** Схема
ответа принадлежит точке вызова (Э12в, Ф9), а не адаптеру: это её контракт
с `domain/`. Вторая, «провайдерская» копия схемы разошлась бы с первой в день,
когда в разбор события добавят поле, — и разошлась бы тихо: модель вернула бы
ответ без нового поля, а Pydantic ядра отверг бы его как мимо схемы.
"""

from typing import Any, cast

# Ключи, которых нет в подмножестве Google (OpenAPI 3.0 Schema). Они не
# вызывают отказа, но и не значат ничего, а `additionalProperties` ещё и
# обманывает: у Google это не запрет лишних полей, как у Anthropic, - его
# там просто нет.
ЧУЖИЕ_КЛЮЧИ_GOOGLE = frozenset(
    {
        "$schema",
        "$defs",
        "$ref",
        "additionalProperties",
        "default",
        "definitions",
        "discriminator",
        "examples",
        "title",
    }
)

# Глубина вложенности, дальше которой разбор считает схему закольцованной.
# Прямой проверки на цикл нет намеренно: схема ответа модели - плоская
# структура из двух-трёх уровней, и модель, ссылающаяся сама на себя,
# означает ошибку в точке вызова, а не законный случай.
ПРЕДЕЛ_ГЛУБИНЫ = 16

# Ключи, под которыми лежит не схема, а словарь «имя поля - схема». Внутри
# них имена принадлежат ответу модели, а не языку схем, и относиться к ним
# как к словам схемы значит однажды выбросить поле `title` из разбора
# события - молча, оставив модель без половины ответа.
КАРТЫ_ПОЛЕЙ = frozenset({"properties", "$defs", "definitions"})


class СхемаНеПоддерживается(RuntimeError):
    """Схему не перевести в форму провайдера. Отказ громкий и до вызова.

    Тихий вариант хуже во всех отношениях: схема доехала бы урезанной,
    модель ответила бы по ней, а Pydantic ядра отверг бы ответ как мимо
    схемы - и выглядело бы это виной модели, а не потерянным ключом.
    """


def для_anthropic(схема: dict[str, Any]) -> dict[str, Any]:
    """Схема для `strict: true` (ADR-046): всюду `additionalProperties: false`.

    Больше ничего не трогаем: `$defs` и `$ref` Anthropic понимает сам, и
    разворачивать их значило бы чинить то, что не сломано. Добавляется ровно
    запрет лишних полей - без него `strict` не включается, а с ним ответ
    либо валиден по схеме, либо его нет вовсе.
    """
    return cast(dict[str, Any], _запретить_лишнее(схема, глубина=0))


def для_google(схема: dict[str, Any]) -> dict[str, Any]:
    """Схема для `responseSchema`: `$ref` развёрнуты, чужие ключи убраны.

    Три преобразования, каждое вынужденное:

    1. **`$ref` разворачивается на месте.** Подмножество Google ссылок
       не знает, а Pydantic заводит `$defs` на каждую вложенную модель.
    2. **`anyOf` из типа и `null` превращается в `nullable`.** Именно так
       Pydantic записывает `X | None`, то есть любое необязательное поле
       разбора события, - а у Google необязательность выражается флагом.
    3. **Типы заглавными.** В подмножестве это перечисление (`STRING`,
       `OBJECT`), и строчное написание там не гарантировано.
    """
    определения = схема.get("$defs", {})
    if not isinstance(определения, dict):
        определения = {}
    return cast(dict[str, Any], _в_форму_google(схема, определения=определения, глубина=0))


def _запретить_лишнее(узел: Any, *, глубина: int) -> Any:
    if глубина > ПРЕДЕЛ_ГЛУБИНЫ:
        raise СхемаНеПоддерживается(
            f"схема вложена глубже {ПРЕДЕЛ_ГЛУБИНЫ} уровней - похоже на ссылку на саму себя"
        )

    if isinstance(узел, list):
        return [_запретить_лишнее(элемент, глубина=глубина + 1) for элемент in узел]

    if not isinstance(узел, dict):
        return узел

    собранное: dict[str, Any] = {}
    for ключ, значение in узел.items():
        if ключ in КАРТЫ_ПОЛЕЙ and isinstance(значение, dict):
            # Ключи здесь - имена полей ответа. Спускаемся в значения, но
            # сами имена не трогаем: поле, названное `properties`, иначе
            # получило бы запрет лишних полей вместо своего объекта.
            собранное[ключ] = {
                имя: _запретить_лишнее(тело, глубина=глубина + 1) for имя, тело in значение.items()
            }
            continue
        собранное[ключ] = _запретить_лишнее(значение, глубина=глубина + 1)

    # Признак объекта - `properties`, а не `type`: у Pydantic объект внутри
    # `anyOf` приходит без `type` на верхнем уровне ветки.
    if "properties" in собранное:
        собранное["additionalProperties"] = False

    return собранное


def _в_форму_google(узел: Any, *, определения: dict[str, Any], глубина: int) -> Any:
    if глубина > ПРЕДЕЛ_ГЛУБИНЫ:
        raise СхемаНеПоддерживается(
            f"схема вложена глубже {ПРЕДЕЛ_ГЛУБИНЫ} уровней - похоже на ссылку на саму себя"
        )

    if isinstance(узел, list):
        return [
            _в_форму_google(элемент, определения=определения, глубина=глубина + 1)
            for элемент in узел
        ]

    if not isinstance(узел, dict):
        return узел

    if "$ref" in узел:
        return _в_форму_google(
            _развернуть(узел["$ref"], определения), определения=определения, глубина=глубина + 1
        )

    свёрнутое = _свернуть_необязательное(узел)
    if свёрнутое is not None:
        return _в_форму_google(свёрнутое, определения=определения, глубина=глубина + 1)

    собранное: dict[str, Any] = {}
    for ключ, значение in узел.items():
        if ключ in ЧУЖИЕ_КЛЮЧИ_GOOGLE:
            continue
        if ключ in КАРТЫ_ПОЛЕЙ and isinstance(значение, dict):
            # Здесь ключи - имена полей ответа, а не слова схемы. Фильтровать
            # их нельзя: поле, названное `title` или `items`, исчезло бы
            # из схемы молча, а модель просто перестала бы его заполнять.
            собранное[ключ] = {
                имя: _в_форму_google(тело, определения=определения, глубина=глубина + 1)
                for имя, тело in значение.items()
            }
            continue
        if ключ == "type" and isinstance(значение, str):
            собранное[ключ] = значение.upper()
            continue
        собранное[ключ] = _в_форму_google(значение, определения=определения, глубина=глубина + 1)

    return собранное


def _развернуть(ссылка: Any, определения: dict[str, Any]) -> dict[str, Any]:
    """`#/$defs/Имя` - в само определение."""
    if not isinstance(ссылка, str) or not ссылка.startswith("#/$defs/"):
        raise СхемаНеПоддерживается(
            f"ссылка {ссылка!r} ведёт наружу схемы; подмножество Google понимает "
            "только вложенные определения Pydantic"
        )

    имя = ссылка.removeprefix("#/$defs/")
    тело = определения.get(имя)
    if not isinstance(тело, dict):
        raise СхемаНеПоддерживается(f"определение {имя!r} не найдено в $defs")
    return тело


def _свернуть_необязательное(узел: dict[str, Any]) -> dict[str, Any] | None:
    """`anyOf` из одного типа и `null` - в тот же тип с `nullable: true`.

    Именно в такой форме Pydantic записывает `str | None`, то есть каждое
    поле разбора события, которое модель вправе не заполнить. Оставить
    `anyOf` как есть нельзя: `null` в подмножестве Google не тип, а флаг,
    и ветка с ним сделала бы схему недействительной целиком.

    `anyOf` из двух непустых типов не сворачивается - он законен и передаётся
    как есть.
    """
    ветки = узел.get("anyOf")
    if not isinstance(ветки, list):
        return None

    непустые = [ветка for ветка in ветки if _не_null(ветка)]
    if len(непустые) != 1 or len(непустые) == len(ветки):
        return None

    остальное = {ключ: значение for ключ, значение in узел.items() if ключ != "anyOf"}
    return {**непустые[0], **остальное, "nullable": True}


def _не_null(ветка: Any) -> bool:
    return not (isinstance(ветка, dict) and ветка.get("type") == "null")
