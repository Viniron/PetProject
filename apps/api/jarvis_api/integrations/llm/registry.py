"""Какие провайдеры подключены в этом процессе (Э12б).

**Ключ не задан - провайдера просто нет,** и это рабочее состояние, а не
поломка. Ядро на такой случай уже отвечает внятно: маршрут, ведущий
к неподключённому провайдеру, роняет вызов с перечислением тех, кто есть
(`client.py`). Заглушка вместо адаптера была бы хуже во всех отношениях:
она отвечала бы выдумкой там, где нужен отказ (инвариант 9).

**Реестр собирается один раз и передаётся параметром.** Глобального
состояния здесь нет намеренно - по тому же принципу, по которому маршруты
приходят в `вызвать` аргументом: слой обязан проверяться прямым вызовом,
без подмены модулей на ходу.
"""

import httpx2

from jarvis_api.config import Settings
from jarvis_api.integrations.llm import anthropic, google
from jarvis_api.integrations.llm.base import Адаптер


def собрать_адаптеры(
    настройки: Settings, *, клиент: httpx2.Client | None = None
) -> dict[str, Адаптер]:
    """Подключённые провайдеры по именам, которыми их зовёт `LLM_ROUTING`.

    `клиент` подставляется тестами: сеть в прогоне замокана всегда
    (CLAUDE.md), и реестр, создающий соединение внутри себя, проверить
    без сети было бы нечем.
    """
    собранное: dict[str, Адаптер] = {}
    for модуль in (google, anthropic):
        адаптер = модуль.собрать(настройки, клиент=клиент)
        if адаптер is not None:
            собранное[адаптер.имя] = адаптер
    return собранное
