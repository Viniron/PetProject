"""Задачи, на которые платформа зовёт модель (§5.1).

**Список задач фиксирован в коде, назначение моделей - нет.** Это прямое
требование §5: платформа обязана работать с любым назначением и уметь сменить
его без правок кода. Профиль требований у каждой задачи свой (объём против
качества, интерактивно против «не срочно»), поэтому одна модель на всё - либо
переплата, либо низкое качество там, где оно важно.

**Значения - латиницей,** потому что это ключи JSON в `LLM_ROUTING`: owner
правит их в `.env` на плате, где кириллица в ключах конфига - лишний способ
получить `KeyError` из-за раскладки.

**Задачи курсов перечислены, но не назначены** (решение owner 2026-09-21:
трогаем календарь). Перечисление - не обещание, что вызов заработает: без
строки в `LLM_ROUTING` он отказывает, и это честное «модель не назначена»
вместо подставленной наугад (инвариант 9).
"""

from enum import StrEnum


class Задача(StrEnum):
    """Точка вызова модели. Порядок - как в таблице §5.1."""

    # --- Курсы. Назначения нет и в этом релизе не будет ----------------------
    ЗАКРЫТЫЕ_ЗАДАНИЯ = "closed_assignments"
    КАРТОЧКИ = "cards"
    УПРАЖНЕНИЯ = "exercises"
    ОТКРЫТЫЕ_ОТВЕТЫ = "open_answers"
    ПРОВЕРКА_ПИСЬМА = "written_review"
    КОНТРОЛЬНЫЙ_СРЕЗ = "checkpoint"
    ВОПРОСЫ = "qa"

    # --- Календарь. Ради разбора события и делается слой (Э12в) --------------
    # Текст и фото идут одним вызовом (§5.1, ADR-046): разносить их по разным
    # моделям значило бы удвоить промпт, схему и адаптер ради долей цента.
    РАЗБОР_СОБЫТИЯ = "capture_parse"
    # Остаётся в перечислении, но живёт в `БЕЗ_МОДЕЛИ`: расшифровку делает
    # браузер (ADR-046).
    РАСШИФРОВКА_ГОЛОСА = "capture_audio"

    # --- Книжка (Ф9-Ф11, после Э12б) -----------------------------------------
    КНИЖКА_КАТЕГОРИЯ = "finance_categorize"
    КНИЖКА_НАБОР_КАТЕГОРИЙ = "finance_categories"
    КНИЖКА_РЕЗЮМЕ = "finance_summary"


# Задачи, на которых вызова модели нет вовсе. Их две, и по разным причинам.
#
# **Закрытые задания** (§5.1, первая строка таблицы) сверяются
# детерминированно: платить за сравнение строк незачем, а проверяющая модель,
# которой дали закрытый вопрос, однажды засчитает неверный ответ - это баг
# уровня потери данных (инвариант 10).
#
# **Расшифровка надиктованного** - работа браузера, а не платформы: ADR-046
# назначил на неё Web Speech API. Строка в §5.1 писалась до этого решения,
# и оставить задачу «назначаемой» значило бы держать маршрут, по которому
# никто никогда не поедет, - а однажды кто-нибудь его заполнит и заплатит.
#
# Причина хранится рядом с задачей, а не пересказывается в отказе разбора,
# в отказе вызова и в печати назначения: три пересказа разойдутся, и owner
# получит про браузерную расшифровку текст про сравнение строк.
ПРИЧИНА_БЕЗ_МОДЕЛИ: dict[Задача, str] = {
    Задача.ЗАКРЫТЫЕ_ЗАДАНИЯ: "детерминированная сверка (§5.1)",
    Задача.РАСШИФРОВКА_ГОЛОСА: "расшифровку делает браузер (ADR-046)",
}

# Множество, а не комментарий в таблице: назначение такой задачи в конфиге
# отвергается разбором, а вызов из кода - исключением. Иначе правило жило бы
# только в спецификации.
БЕЗ_МОДЕЛИ = frozenset(ПРИЧИНА_БЕЗ_МОДЕЛИ)
