"""Промпты: файлы `prompts/*.md` с версией и границей кэша (CLAUDE.md, §5.2).

**Промпт - не строковый литерал в коде.** Правка формулировки не должна быть
правкой Python-файла: у промпта своя история, свой номер версии и свой повод
для повторного прогона эталонного набора (§5.2).

**Стабильная часть отделена от переменной, и это не косметика.** Кэш
провайдеров работает по общему префиксу запроса: пока начало совпадает
байт в байт, вход дешевеет кратно. Подстановка, заехавшая в начало,
не ломает ничего видимого - ответы те же, ошибок нет, - но попадание в кэш
исчезает, и обнаруживается это счётом в конце месяца. Поэтому граница
проходит по файлу маркером, а подстановки разрешены только после него;
нарушение отвергается при загрузке.

Формат файла:

    <!-- prompt: capture_parse, version: 1 -->
    ...стабильная часть: роль, правила, описание схемы ответа...
    <!-- variable -->
    ...переменная часть с подстановками вида $text...

Подстановка - `string.Template` (`$имя`), а не `str.format`: в промптах
встречаются фигурные скобки примеров JSON, и `format` спотыкался бы о них,
требуя удваивать каждую.

**Имена подстановок - латиницей,** в отличие от остального кода: `Template`
разбирает только ASCII-идентификаторы, и `$текст` для него не подстановка,
а «неверный placeholder». Текст самого промпта при этом какой угодно.
"""

import re
from dataclasses import dataclass
from pathlib import Path
from string import Template

# Каталог промптов. Внутри пакета, а не в корне репозитория: в образ едет
# пакет, и промпт, лежащий рядом с README, не попал бы в контейнер - отказ
# обнаружился бы первым живым вызовом на плате.
КАТАЛОГ = Path(__file__).resolve().parents[2] / "prompts"

# Заголовок первой строки: имя и версия. Имя дублирует имя файла намеренно -
# переименованный файл без правки заголовка иначе тихо стал бы другим
# промптом с прежней версией в аудите.
ЗАГОЛОВОК = re.compile(
    r"^<!--\s*prompt:\s*(?P<имя>[a-z0-9_]+),\s*version:\s*(?P<версия>\d+)\s*-->$"
)

# Граница кэшируемого префикса.
РАЗДЕЛИТЕЛЬ = "<!-- variable -->"


class ПромптИспорчен(RuntimeError):
    """Файл промпта не читается по формату. Отказ громкий: молча взятый
    наполовину промпт дал бы ответы, которые не с чем сравнить."""


@dataclass(frozen=True)
class Промпт:
    """Собранный промпт: что уйдёт провайдеру и чем это подписано в аудите."""

    имя: str
    версия: int
    стабильная_часть: str
    переменная_часть: str


def собрать(имя: str, *, каталог: Path | None = None, **поля: str) -> Промпт:
    """Читает `<имя>.md` и подставляет поля в переменную часть.

    Поля подставляются только после разделителя. Нехватка поля - `KeyError`
    от `Template.substitute`, и это правильный исход: промпт с дырой вместо
    текста события уехал бы в модель и вернул бы разбор пустоты.
    """
    путь = (каталог or КАТАЛОГ) / f"{имя}.md"
    try:
        сырое = путь.read_text(encoding="utf-8")
    except FileNotFoundError as ошибка:
        raise ПромптИспорчен(f"промпт {имя!r} не найден: {путь}") from ошибка

    версия, стабильная, переменная = _разобрать(имя, сырое)

    try:
        подставленная = Template(переменная).substitute(поля)
    except KeyError as ошибка:
        raise ПромптИспорчен(
            f"промпт {имя!r}: не передано поле {ошибка.args[0]!r} для подстановки"
        ) from ошибка
    except ValueError as ошибка:
        raise ПромптИспорчен(
            f"промпт {имя!r}: переменная часть содержит неверную подстановку ({ошибка})"
        ) from ошибка

    return Промпт(
        имя=имя,
        версия=версия,
        стабильная_часть=стабильная,
        переменная_часть=подставленная,
    )


def _разобрать(имя: str, сырое: str) -> tuple[int, str, str]:
    """Заголовок, стабильная часть, переменная часть - с проверками формата."""
    строки = сырое.splitlines()
    if not строки:
        raise ПромптИспорчен(f"промпт {имя!r} пуст")

    совпадение = ЗАГОЛОВОК.match(строки[0].strip())
    if совпадение is None:
        raise ПромптИспорчен(
            f"промпт {имя!r}: первая строка обязана быть "
            "'<!-- prompt: имя, version: N -->', а она "
            f"{строки[0].strip()!r}"
        )

    if совпадение.group("имя") != имя:
        raise ПромптИспорчен(
            f"промпт в файле {имя}.md подписан именем {совпадение.group('имя')!r}: "
            "имя в заголовке и имя файла обязаны совпадать, иначе в аудите "
            "окажется версия не того промпта"
        )

    тело = "\n".join(строки[1:])
    куски = тело.split(РАЗДЕЛИТЕЛЬ)
    if len(куски) != 2:
        raise ПромптИспорчен(
            f"промпт {имя!r}: разделитель {РАЗДЕЛИТЕЛЬ!r} должен встречаться ровно один раз, "
            f"а встречается {len(куски) - 1}"
        )

    стабильная = куски[0].strip()
    переменная = куски[1].strip()

    if not стабильная:
        raise ПромптИспорчен(
            f"промпт {имя!r}: стабильная часть пуста - кэшировать нечего, "
            "и весь вход будет оплачен по полной цене на каждом вызове"
        )

    # Подстановка в стабильной части ломает кэш молча - ровно тот отказ,
    # который CLAUDE.md требует ловить тестом. Здесь он ловится ещё раньше,
    # при чтении файла.
    чужие = Template(стабильная).get_identifiers()
    if чужие:
        raise ПромптИспорчен(
            f"промпт {имя!r}: в стабильной части есть подстановки {sorted(чужие)}. "
            "Стабильная часть обязана быть одинаковой байт в байт на каждом вызове, "
            "иначе кэш провайдера молча перестаёт попадать"
        )

    return int(совпадение.group("версия")), стабильная, переменная
