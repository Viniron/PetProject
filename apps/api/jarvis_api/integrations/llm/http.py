"""HTTP под адаптерами моделей: таймаут, повторы, разбор отказа в классы.

**Почему это общее, хотя адаптеры провайдер-специфичные.** §5.2 запрещает
общую абстракцию над кэшем и батчем - механики скидок там устроены по-разному,
и абстракция над ними течёт молча. Над номерами статусов HTTP такой опасности
нет: 429 у обоих означает «подожди», 401 у обоих - «ключ не тот», и повторять
эти двадцать строк в каждом адаптере значит однажды исправить их в одном.
Граница проведена ровно здесь: транспорт знает про коды и повторы и не знает
ни одного имени поля из тела запроса.

**Повторы только там, где они уместны.** Повторяется недоступность: сеть,
таймаут, 429, 5xx. Отказ по существу (ключ, доступ, длина входа) не
повторяется - тот же запрос вернёт тот же отказ, а у платных вызовов каждая
попытка ещё и стоит денег.

**Геоблок опознаёт адаптер, а не транспорт.** Провайдеры сообщают о нём
разными кодами и разными словами, и зашить сюда обе формулировки значило бы
завести третье место, где надо помнить про обоих. Транспорт лишь спрашивает
переданный предикат - и этим отделяет «плата ходит не через VPN» (ADR-050)
от «ключ неверный», которые чинятся в разных местах и разными людьми.
"""

import json
import logging
import time
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Any

import httpx2

from jarvis_api.integrations.llm.base import (
    ВыходЗаблокирован,
    ОтказПровайдера,
    ПровайдерНедоступен,
)

logger = logging.getLogger("jarvis.llm.http")

# Сколько символов чужого тела попадает в текст исключения. Ответ провайдера
# об ошибке бывает страницей на килобайты; целиком она забивает лог платы,
# а причина всегда в первых строках.
ХВОСТ_ОШИБКИ = 400


def _не_геоблок(статус: int, тело: str) -> bool:
    """Умолчание: провайдер о стране ничего не говорил."""
    return False


@dataclass
class Транспорт:
    """Один провайдер: адрес, заголовки, повторы.

    `клиент` подставляется тестами (`httpx2.MockTransport`): сеть в прогоне
    замокана всегда (CLAUDE.md), и адаптер, создающий соединение внутри себя,
    проверить без сети было бы нечем.
    """

    имя: str
    заголовки: Mapping[str, str]
    попыток: int
    пауза_секунд: float
    геоблок: Callable[[int, str], bool] = _не_геоблок
    клиент: httpx2.Client | None = None

    def получить(self, адрес: str, *, таймаут: int) -> dict[str, Any]:
        """GET с разбором JSON. Опрос состояния батча и проверка доступа."""
        return self._с_повторами("GET", адрес, None, таймаут)

    def отправить(self, адрес: str, тело: dict[str, Any], *, таймаут: int) -> dict[str, Any]:
        """POST с разбором JSON. Обычный вызов и отправка пачки."""
        return self._с_повторами("POST", адрес, тело, таймаут)

    def скачать(self, адрес: str, *, таймаут: int) -> str:
        """Ответ как текст: результаты пачки приезжают файлом JSONL, не объектом."""
        ответ = self._выполнить("GET", адрес, None, таймаут)
        return ответ.text

    # --- внутреннее ---------------------------------------------------------

    def _с_повторами(
        self, метод: str, адрес: str, тело: dict[str, Any] | None, таймаут: int
    ) -> dict[str, Any]:
        последняя: Exception | None = None

        for попытка in range(1, max(1, self.попыток) + 1):
            try:
                ответ = self._выполнить(метод, адрес, тело, таймаут)
                return self._разобрать(ответ)
            except ПровайдерНедоступен as ошибка:
                последняя = ошибка
                if попытка == max(1, self.попыток):
                    break
                пауза = self.пауза_секунд * попытка
                logger.warning(
                    "%s не ответил (попытка %d из %d): %s; жду %.1f с",
                    self.имя,
                    попытка,
                    self.попыток,
                    ошибка,
                    пауза,
                )
                time.sleep(пауза)

        raise ПровайдерНедоступен(f"{self.имя} не ответил за {self.попыток} попыток: {последняя}")

    def _выполнить(
        self, метод: str, адрес: str, тело: dict[str, Any] | None, таймаут: int
    ) -> httpx2.Response:
        клиент = self.клиент or httpx2.Client()
        свой = self.клиент is None
        try:
            ответ = клиент.request(
                метод,
                адрес,
                json=тело,
                headers=dict(self.заголовки),
                timeout=таймаут,
            )
        except httpx2.RequestError as ошибка:
            # Сетевой отказ и таймаут - ровно тот случай, ради которого
            # существует фолбэк: ответа не было, токены не списаны.
            raise ПровайдерНедоступен(f"{self.имя}: {type(ошибка).__name__}: {ошибка}") from ошибка
        finally:
            if свой:
                клиент.close()

        self._проверить_статус(ответ)
        return ответ

    def _проверить_статус(self, ответ: httpx2.Response) -> None:
        if ответ.status_code < httpx2.codes.BAD_REQUEST:
            return

        хвост = ответ.text[:ХВОСТ_ОШИБКИ]

        if self.геоблок(ответ.status_code, ответ.text):
            raise ВыходЗаблокирован(
                f"{self.имя} не обслуживает страну, из которой пришёл запрос "
                f"({ответ.status_code}): {хвост!r}. Это маршрут платы, а не код - "
                "см. RUNBOOK, выход к моделям"
            )

        # 429 и 5xx лечатся ожиданием, остальные 4xx - нет. Повтор отказа
        # по существу означал бы ещё один платный вызов с тем же исходом.
        временный = ответ.status_code == httpx2.codes.TOO_MANY_REQUESTS or (
            ответ.status_code >= httpx2.codes.INTERNAL_SERVER_ERROR
        )
        if временный:
            raise ПровайдерНедоступен(f"{self.имя} ответил {ответ.status_code}: {хвост!r}")

        raise ОтказПровайдера(f"{self.имя} ответил {ответ.status_code}: {хвост!r}")

    def _разобрать(self, ответ: httpx2.Response) -> dict[str, Any]:
        try:
            тело = ответ.json()
        except ValueError as ошибка:
            # Не JSON при коде 200 - это почти всегда чужая страница на пути
            # (прокси, портал сети), то есть помеха связи, а не ответ модели.
            raise ПровайдерНедоступен(
                f"{self.имя} вернул не JSON: {ответ.text[:ХВОСТ_ОШИБКИ]!r}"
            ) from ошибка

        if not isinstance(тело, dict):
            raise ОтказПровайдера(
                f"{self.имя} вернул {type(тело).__name__} вместо объекта: "
                f"{json.dumps(тело)[:ХВОСТ_ОШИБКИ]}"
            )
        return тело
