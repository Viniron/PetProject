"""Один вызов модели целиком: маршрут, потолок, схема, фолбэк, аудит (§5.2).

Порядок шагов здесь - не стиль, а перечень требований §5.2, каждое из которых
ломается тихо, если его пропустить:

1. **Задача без назначения отказывает.** Не подставляет модель «по умолчанию»:
   выдумка дороже отказа (инвариант 9).
2. **Потолок проверяется до вызова, а не после.** После - это уже потраченные
   деньги, и деградация в §5.2 перестала бы что-либо защищать.
3. **`max_tokens` уходит с каждым запросом** - он в маршруте, и маршрут без
   него не разбирается вовсе (`routing.py`).
4. **Ответ проверяется схемой,** невалидный - переспрашивается один раз,
   потом уходит на резервную модель. Модель, дважды промахнувшаяся мимо
   схемы, промахнётся и в третий: это её свойство, а не случайность.
5. **Каждая попытка пишется в `audit_log`** с провайдером, моделью, токенами
   и стоимостью (инвариант 8) - включая ту, чей ответ не прошёл схему:
   токены за неё списаны, и потолок обязан их видеть.

**Про транзакцию.** Записи аудита добавляются в переданную сессию, и при
успехе её коммитит вызывающий - вместе со своей работой. Но если вызов
проваливается, вызывающий откатит транзакцию, а деньги провайдер уже списал:
вместе с откатом исчезла бы единственная запись о расходе, и месячный потолок
считал бы не всё потраченное. Поэтому перед тем как поднять исключение, ядро
коммитит аудит само.
"""

import datetime as dt
import logging
from collections.abc import Mapping
from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal
from typing import Any
from zoneinfo import ZoneInfo

from pydantic import BaseModel, ValidationError
from sqlalchemy.orm import Session

from jarvis_api.config import Settings
from jarvis_api.db.models import AuditLogEntry
from jarvis_api.integrations.llm.base import (
    Адаптер,
    Запрос,
    Изображение,
    Ответ,
    ОтказПровайдера,
    ПровайдерНедоступен,
)
from jarvis_api.integrations.llm.budget import потрачено_за_месяц
from jarvis_api.integrations.llm.prompts import Промпт
from jarvis_api.integrations.llm.routing import Маршрут, МаршрутИспорчен, цепочка
from jarvis_api.integrations.llm.tasks import БЕЗ_МОДЕЛИ, ПРИЧИНА_БЕЗ_МОДЕЛИ, Задача

logger = logging.getLogger("jarvis.llm")

# Виды записей аудита. Разные намеренно: по `llm_call` считается потраченное
# (`budget.py`), и смешанный с ним `llm_budget` завысил бы сумму на строки,
# за которые никто не платил.
ВИД_ВЫЗОВА = "llm_call"
ВИД_ПОТОЛКА = "llm_budget"

# Цена в маршруте - за миллион токенов, как её печатает прайс провайдера.
МИЛЛИОН = Decimal(1_000_000)
# Колонка `audit_log.cost_usd` - numeric(12,6). Округляем здесь, а не оставляем
# базе: иначе сумма за месяц зависела бы от того, сколько знаков сохранил
# драйвер, и расходилась бы с тем, что видно в аудите построчно.
ТОЧНОСТЬ = Decimal("0.000001")

# Во что обходится отложенная пачка относительно обычного вызова. Половина
# у обоих назначенных провайдеров (ADR-046, сверено с их прайсами 21.09.2026);
# появится третий с другой скидкой - это станет полем маршрута, а не ещё одной
# константой рядом.
ДОЛЯ_БАТЧА = Decimal("0.5")

# Приписка к переменной части при повторе. Дословный повтор того же запроса
# у модели с низкой температурой даёт тот же ответ, то есть второй платный
# вызов с гарантированно тем же исходом. Приписка идёт в конец переменной
# части: стабильный префикс от неё не сдвигается, и кэш продолжает попадать.
ПРИПИСКА_РЕТРАЯ = (
    "\n\nПредыдущий ответ не прошёл проверку схемой. "
    "Верни только JSON по схеме, без пояснений и без markdown-обрамления."
)


class ОшибкаСлоя(RuntimeError):
    """Общий предок отказов слоя моделей."""


class ВызовЗапрещён(ОшибкаСлоя):
    """Задача выполняется без модели (§5.1). Это ошибка вызывающего кода."""


class МаршрутНеНастроен(ОшибкаСлоя):
    """Модель на задачу не назначена. Рабочее состояние, а не поломка."""


class ПотолокИсчерпан(ОшибкаСлоя):
    """Месячный потолок достигнут, а дешёвого маршрута для деградации нет."""


class ВсеМаршрутыОтказали(ОшибкаСлоя):
    """Ни основная модель, ни резервы не дали ответа по схеме."""


@dataclass(frozen=True)
class Результат[T: BaseModel]:
    """Разобранный ответ и всё, что о нём нужно знать вызывающему.

    `деградация` и `схема_с_первого_раза` вынесены наружу не для статистики:
    первое экран обязан показать owner (§5.2 требует уведомления, а не тихой
    подмены модели), второе - метрика пригодности модели (§5.2), по которой
    owner решает, оставлять ли назначение.
    """

    значение: T
    провайдер: str
    модель: str
    токенов_вход: int
    токенов_выход: int
    стоимость: Decimal
    деградация: bool
    схема_с_первого_раза: bool


def вызвать[T: BaseModel](
    session: Session,
    *,
    задача: Задача,
    промпт: Промпт,
    схема: type[T],
    актор: str,
    сейчас: dt.datetime,
    зона: ZoneInfo,
    настройки: Settings,
    маршруты: Mapping[Задача, Маршрут],
    адаптеры: Mapping[str, Адаптер],
    изображения: tuple[Изображение, ...] = (),
) -> Результат[T]:
    """Отправить задачу назначенной модели и вернуть разобранный ответ.

    `маршруты` и `адаптеры` приходят параметрами, а не берутся из глобального
    реестра: слой обязан быть проверяемым прямым вызовом, без подмены модулей
    на ходу, - тот же принцип, по которому `domain/` отделён от `api/`.

    `изображения` идут тем же вызовом, что и текст (§5.1, ADR-046). Ядро их
    не разглядывает: размер, формат и способ уложить картинку в запрос -
    забота адаптера, у провайдеров она разная.
    """
    if задача in БЕЗ_МОДЕЛИ:
        raise ВызовЗапрещён(
            f"задача {задача.value!r} выполняется без модели: " f"{ПРИЧИНА_БЕЗ_МОДЕЛИ[задача]}"
        )

    назначенный = маршруты.get(задача)
    if назначенный is None:
        raise МаршрутНеНастроен(
            f"модель на задачу {задача.value!r} не назначена: "
            "назначение приходит от owner в LLM_ROUTING"
        )

    рабочий, деградация = _с_учётом_потолка(
        session,
        задача=задача,
        актор=актор,
        маршрут=назначенный,
        сейчас=сейчас,
        зона=зона,
        настройки=настройки,
    )

    последняя_причина = "ни одна модель не ответила"
    писали_аудит = деградация

    for резерв, текущий in enumerate(цепочка(рабочий)):
        адаптер = адаптеры.get(текущий.provider)
        if адаптер is None:
            # Не уходим на следующий маршрут: неизвестный провайдер - это
            # опечатка в конфиге или не приехавший адаптер, и тихий переход
            # на резерв скрыл бы обе причины, оставив owner с работающей,
            # но не той моделью.
            _сохранить(session, писали_аудит)
            raise МаршрутИспорчен(
                f"провайдер {текущий.provider!r} не подключён; "
                f"есть: {', '.join(sorted(адаптеры)) or 'ни одного (адаптеры приезжают на Э12б)'}"
            )

        приписка = ""
        for попытка in range(1, max(0, настройки.llm_schema_retries) + 2):
            запрос = Запрос(
                модель=текущий.model,
                стабильная_часть=промпт.стабильная_часть,
                переменная_часть=промпт.переменная_часть + приписка,
                схема=схема.model_json_schema(),
                max_tokens=текущий.max_tokens,
                таймаут_секунд=настройки.llm_timeout_seconds,
                изображения=изображения,
                temperature=текущий.temperature,
            )

            общее: dict[str, Any] = {
                "task": задача.value,
                "prompt": промпт.имя,
                "prompt_version": промпт.версия,
                "attempt": попытка,
                "degraded": деградация,
                "fallback": резерв > 0,
                "images": len(изображения),
            }

            try:
                ответ = адаптер.выполнить(запрос)
            except ПровайдерНедоступен as ошибка:
                # Токенов не списано: ответа не было. Стоимость не пишем,
                # иначе потолок начнёт съедать несуществующие деньги.
                записать_вызов(
                    session,
                    актор=актор,
                    задача=задача,
                    маршрут=текущий,
                    статус="error",
                    ответ=None,
                    стоимость=None,
                    detail={**общее, "reason": "провайдер недоступен", "error": str(ошибка)},
                )
                писали_аудит = True
                последняя_причина = f"{текущий.provider}: {ошибка}"
                logger.warning(
                    "модель %s/%s недоступна: %s", текущий.provider, текущий.model, ошибка
                )
                break

            except ОтказПровайдера as ошибка:
                # Неверный ключ, запрещённая модель, слишком длинный вход -
                # резерв ответит тем же, только за деньги.
                записать_вызов(
                    session,
                    актор=актор,
                    задача=задача,
                    маршрут=текущий,
                    статус="error",
                    ответ=None,
                    стоимость=None,
                    detail={**общее, "reason": "отказ провайдера", "error": str(ошибка)},
                )
                _сохранить(session, True)
                raise

            цена = стоимость(текущий, ответ)

            try:
                значение = схема.model_validate_json(ответ.текст)
            except ValidationError as ошибка:
                записать_вызов(
                    session,
                    актор=актор,
                    задача=задача,
                    маршрут=текущий,
                    статус="error",
                    ответ=ответ,
                    стоимость=цена,
                    detail={**общее, "reason": "ответ мимо схемы", "error": _первая(ошибка)},
                )
                писали_аудит = True
                последняя_причина = f"{текущий.model}: ответ мимо схемы"
                приписка = ПРИПИСКА_РЕТРАЯ
                continue

            записать_вызов(
                session,
                актор=актор,
                задача=задача,
                маршрут=текущий,
                статус="ok",
                ответ=ответ,
                стоимость=цена,
                detail={**общее, "schema_first_try": попытка == 1},
            )
            return Результат(
                значение=значение,
                провайдер=текущий.provider,
                модель=текущий.model,
                токенов_вход=ответ.токенов_вход,
                токенов_выход=ответ.токенов_выход,
                стоимость=цена,
                деградация=деградация,
                схема_с_первого_раза=попытка == 1,
            )

    _сохранить(session, писали_аудит)
    raise ВсеМаршрутыОтказали(
        f"задача {задача.value!r}: ни одна модель не дала ответа по схеме " f"({последняя_причина})"
    )


def стоимость(маршрут: Маршрут, ответ: Ответ) -> Decimal:
    """Цена вызова в долларах. Decimal на всём пути: это деньги (CLAUDE.md).

    **Скидка батча применяется здесь, а не в цене маршрута.** Цена в `.env`
    записана так, как её печатает прайс провайдера, - иначе owner, сверяя
    конфиг с сайтом, каждый раз видел бы половину и не знал, опечатка это
    или скидка. Половина у обоих провайдеров одна и та же (ADR-046), и место
    её применения ровно одно.
    """
    сумма = (
        маршрут.price_in * ответ.токенов_вход + маршрут.price_out * ответ.токенов_выход
    ) / МИЛЛИОН
    if маршрут.batch:
        сумма *= ДОЛЯ_БАТЧА
    return сумма.quantize(ТОЧНОСТЬ, rounding=ROUND_HALF_UP)


def _с_учётом_потолка(
    session: Session,
    *,
    задача: Задача,
    актор: str,
    маршрут: Маршрут,
    сейчас: dt.datetime,
    зона: ZoneInfo,
    настройки: Settings,
) -> tuple[Маршрут, bool]:
    """Маршрут, которым пойдём, и признак деградации (§5.2).

    Потолок достигнут и дешёвого маршрута нет - отказ, а не тихое продолжение:
    §10 запрещает и падать молча, и тратить молча, а из двух зол перерасход
    необратим.
    """
    потрачено = потрачено_за_месяц(session, сейчас=сейчас, зона=зона)
    потолок = настройки.llm_monthly_cap_usd
    if потрачено < потолок:
        return маршрут, False

    общее = {
        "task": задача.value,
        "spent_usd": str(потрачено),
        "cap_usd": str(потолок),
    }

    if маршрут.degraded is None:
        session.add(
            AuditLogEntry(
                kind=ВИД_ПОТОЛКА,
                actor=актор,
                status="error",
                target=задача.value,
                detail={**общее, "reason": "потолок исчерпан, дешёвого маршрута нет"},
            )
        )
        _сохранить(session, True)
        raise ПотолокИсчерпан(
            f"месячный потолок ${потолок} исчерпан (потрачено ${потрачено}), "
            f"а дешёвого маршрута у задачи {задача.value!r} нет"
        )

    # Строка на каждый деградировавший вызов, а не одна на месяц: деградация -
    # свойство конкретного ответа, и вопрос «почему разбор в тот вторник был
    # хуже» иначе остаётся без ответа. Настоящее уведомление owner приедет
    # push-каналом на Э11; до него это запись в аудите и строка в логе.
    session.add(
        AuditLogEntry(
            kind=ВИД_ПОТОЛКА,
            actor=актор,
            status="degraded",
            target=задача.value,
            provider=маршрут.degraded.provider,
            model=маршрут.degraded.model,
            detail={**общее, "reason": "потолок исчерпан, уходим на дешёвую модель"},
        )
    )
    logger.warning(
        "месячный потолок $%s исчерпан (потрачено $%s): задача %s уходит на %s/%s",
        потолок,
        потрачено,
        задача.value,
        маршрут.degraded.provider,
        маршрут.degraded.model,
    )
    return маршрут.degraded, True


def записать_вызов(
    session: Session,
    *,
    актор: str,
    задача: Задача,
    маршрут: Маршрут,
    статус: str,
    ответ: Ответ | None,
    стоимость: Decimal | None,
    detail: dict[str, Any],
) -> None:
    """Строка аудита на одну попытку (инвариант 8)."""
    session.add(
        AuditLogEntry(
            kind=ВИД_ВЫЗОВА,
            actor=актор,
            status=статус,
            target=задача.value,
            provider=маршрут.provider,
            model=маршрут.model,
            tokens_in=ответ.токенов_вход if ответ else None,
            tokens_out=ответ.токенов_выход if ответ else None,
            cost_usd=стоимость,
            detail={**detail, **подробности_токенов(маршрут, ответ)},
        )
    )


def подробности_токенов(маршрут: Маршрут, ответ: Ответ | None) -> dict[str, Any]:
    """Что стоит за колонками токенов: батч, мысли, кэш.

    Колонка `tokens_out` хранит всё, за что берут по ставке выхода, - вместе
    с мысленными токенами (`base.py`). Без этой расшифровки вопрос «почему
    ответ в три строки стоил как в тридцать» остался бы без ответа, а кэш,
    выключенный ADR-046, мог бы незаметно включиться на стороне провайдера.
    """
    собранное: dict[str, Any] = {"batch": маршрут.batch}
    if ответ is None:
        return собранное
    if ответ.токенов_мыслей:
        собранное["tokens_thoughts"] = ответ.токенов_мыслей
    if ответ.токенов_кэша:
        собранное["tokens_cached"] = ответ.токенов_кэша
    return собранное


def _сохранить(session: Session, писали: bool) -> None:
    """Коммит аудита перед подъёмом исключения. См. докстринг модуля."""
    if писали:
        session.commit()


def _первая(ошибка: ValidationError) -> str:
    """Первая претензия схемы одной строкой - остальное в логе не нужно."""
    детали = ошибка.errors()
    if not детали:
        return "ответ не разобрался"
    поле = ".".join(str(часть) for часть in детали[0]["loc"]) or "<корень>"
    return f"{поле} - {детали[0]['msg']}"
