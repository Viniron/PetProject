"""Назначение «задача - модель»: разбор `LLM_ROUTING` (§5.1, §5.2).

**Смена модели обязана быть правкой конфига, а не деплоем** (§5.2). Отсюда
форма: одна переменная окружения с JSON, где ключ - задача из `tasks.py`,
значение - куда её отправлять и почём. В исходниках нет ни одного имени
модели: назначение приходит от owner (Phase 0), и код, знающий про
«gemini» или «claude», пришлось бы править на каждую смену.

**Пустое значение - рабочее состояние.** Ни одна задача не назначена, API
поднимается, вызов отказывает внятно. Состояние не гипотетическое: назначение
записано ADR-046, но в `.env` на плате оно попадает руками owner, и между
этими двумя моментами платформа обязана жить, ничего не выдумывая.

**Что назначено - решает ADR-046, а не этот модуль.** Здесь только форма
записи и её проверки; ни одного имени модели в коде нет, и смена назначения
остаётся правкой строки в `.env` (риск, записанный в том же ADR: линейки
и цены менялись дважды за месяц).

**Испорченный маршрут - громкий отказ, а не тихий пропуск.** Опечатка в имени
задачи, забытый `max_tokens`, цена числом с плавающей точкой - всё это
отвергается с названием места. Пропущенная строка означала бы задачу, которая
молча перестала работать, а обнаружилось бы это первым отказом на живом
захвате.
"""

from __future__ import annotations

import json
from decimal import Decimal
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from jarvis_api.integrations.llm.tasks import БЕЗ_МОДЕЛИ, ПРИЧИНА_БЕЗ_МОДЕЛИ, Задача

# Сколько резервных моделей допускается на одну задачу. Каждый резерв - ещё
# один платный вызов на том же запросе, и цепочка из пяти моделей превращает
# один неудачный разбор в пять оплаченных попыток. Двух хватает: первый
# резерв закрывает отказ провайдера, второй - отказ второго провайдера,
# а дальше отказывает уже не модель, а связь платы с миром.
ПРЕДЕЛ_РЕЗЕРВОВ = 2


class МаршрутИспорчен(RuntimeError):
    """`LLM_ROUTING` не разбирается. Текст называет место, а не «invalid json»."""


class Маршрут(BaseModel):
    """Куда отправлять задачу и почём считать вызов.

    **Цены - часть маршрута, а не отдельная таблица.** Стоимость вызова
    (инвариант 8) и месячный потолок (§5.2) считаются из них, и разнесённые
    по двум местам цена и модель разойдутся в день, когда owner сменит одну,
    забыв про другую: счёт останется прежним, а `audit_log` начнёт врать.

    `extra="forbid"` намеренно: опечатка вроде `max_token` иначе прошла бы
    молча, и вызов ушёл бы без потолка ответа.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    provider: str = Field(min_length=1)
    model: str = Field(min_length=1)
    # Потолок ответа обязателен (§5.2). Умолчания здесь нет намеренно: разумное
    # значение у разбора события и у проверки письменной работы отличается на
    # порядок, и общее умолчание было бы неверным для обеих.
    max_tokens: int = Field(gt=0)
    # Доллары за миллион токенов, как их печатает прайс провайдера.
    price_in: Decimal = Field(ge=0)
    price_out: Decimal = Field(ge=0)
    # Отложенная пачка вместо обычного вызова: вдвое дешевле, отвечает часами
    # (§5.1 - «не срочно», ADR-046 - категоризация и упражнения). Свойство
    # задачи, а не провайдера: одна и та же модель обслуживает и то и другое,
    # а скидка обязана попасть в `audit_log`, иначе месячный потолок посчитает
    # вдвое больше потраченного.
    batch: bool = False
    # Пусто - параметр не уходит провайдеру вовсе (ADR-049). Сэмплинг доступен
    # не на всяком поколении: ADR-046 выбрал модель категоризации в том числе
    # за доступный `temperature=0`, но соседние модели того же провайдера
    # отвечают на него отказом. Поле здесь, а не в коде адаптера, потому что
    # это свойство назначенной модели, а имён моделей в исходниках нет.
    temperature: Decimal | None = Field(default=None, ge=0)
    # Резерв на случай недоступности провайдера (§5.2). Пустой список - тоже
    # ответ: задача без резерва отказывает, а не молчит.
    fallback: tuple[Маршрут, ...] = ()
    # Куда уходить при достигнутом месячном потолке (§5.2: деградация на
    # дешёвую модель). Пусто - вызов отказывает, и это лучше тихого
    # перерасхода: деньги owner кончились, а не подешевели.
    degraded: Маршрут | None = None

    @field_validator("price_in", "price_out", mode="before")
    @classmethod
    def _цена_не_плавающей_точкой(cls, значение: Any) -> Any:
        """Деньги - Decimal, `float` для сумм запрещён (CLAUDE.md).

        JSON не различает 0.25 и "0.25", поэтому запрет проверяется здесь:
        число с плавающей точкой в файле конфига доедет до умножения на токены
        и даст стоимость вида 0.2500000000000000138 - не ошибку, а тихий
        мусор в колонке, по которой считается месячный потолок.
        """
        if isinstance(значение, float):
            raise ValueError(
                f"цена {значение!r} записана числом с плавающей точкой; "
                'в JSON её пишут строкой: "0.25"'
            )
        return значение


Маршрут.model_rebuild()


def загрузить_маршруты(значение: str) -> dict[Задача, Маршрут]:
    """Разбирает `LLM_ROUTING`. Пустая строка - пустое назначение, не ошибка."""
    текст = значение.strip()
    if not текст:
        return {}

    try:
        сырое = json.loads(текст)
    except json.JSONDecodeError as ошибка:
        raise МаршрутИспорчен(
            f"LLM_ROUTING не разбирается как JSON: {ошибка.msg} "
            f"(строка {ошибка.lineno}, символ {ошибка.colno})"
        ) from ошибка

    if not isinstance(сырое, dict):
        raise МаршрутИспорчен(
            "LLM_ROUTING должен быть объектом вида "
            '{"capture_parse": {"provider": ..., "model": ...}}, '
            f"а пришёл {type(сырое).__name__}"
        )

    известные = sorted(задача.value for задача in Задача)
    собранное: dict[Задача, Маршрут] = {}

    for ключ, тело in сырое.items():
        try:
            задача = Задача(ключ)
        except ValueError as ошибка:
            raise МаршрутИспорчен(
                f"LLM_ROUTING: задачи {ключ!r} не существует. " f"Известные: {', '.join(известные)}"
            ) from ошибка

        # Назначить модель задаче, которая обходится без неё, - не опечатка,
        # а нарушение: на закрытых заданиях платная проверка однажды засчитает
        # неверный ответ (инвариант 10), а на расшифровке заплатит за работу,
        # которую уже сделал браузер. Поэтому отказ, а не игнорирование.
        if задача in БЕЗ_МОДЕЛИ:
            raise МаршрутИспорчен(
                f"LLM_ROUTING: задача {ключ!r} выполняется без модели: "
                f"{ПРИЧИНА_БЕЗ_МОДЕЛИ[задача]}"
            )

        try:
            маршрут = Маршрут.model_validate(тело)
        except ValidationError as ошибка:
            raise МаршрутИспорчен(f"LLM_ROUTING, задача {ключ!r}: {_коротко(ошибка)}") from ошибка

        _проверить_резервы(ключ, маршрут)
        собранное[задача] = маршрут

    return собранное


def цепочка(маршрут: Маршрут) -> tuple[Маршрут, ...]:
    """Маршрут и его резервы в порядке, в котором их пробуют."""
    return (маршрут, *маршрут.fallback)


def _проверить_резервы(ключ: str, маршрут: Маршрут) -> None:
    """Резерв - это конечная остановка: своих резервов у него нет.

    Иначе цепочка ветвится, и один неудачный разбор превращается в дерево
    платных вызовов, глубину которого по конфигу не видно.
    """
    if len(маршрут.fallback) > ПРЕДЕЛ_РЕЗЕРВОВ:
        raise МаршрутИспорчен(
            f"LLM_ROUTING, задача {ключ!r}: резервов {len(маршрут.fallback)}, "
            f"допускается не больше {ПРЕДЕЛ_РЕЗЕРВОВ} - каждый это ещё один платный вызов"
        )

    вложенные = [*маршрут.fallback, *([маршрут.degraded] if маршрут.degraded else [])]
    for вложенный in вложенные:
        if вложенный.fallback or вложенный.degraded is not None:
            raise МаршрутИспорчен(
                f"LLM_ROUTING, задача {ключ!r}: у резервной модели "
                f"{вложенный.model!r} заданы свои fallback или degraded - "
                "цепочка обязана быть плоской, иначе её длину не видно по конфигу"
            )


def _коротко(ошибка: ValidationError) -> str:
    """Первая претензия Pydantic человеческим текстом.

    Полный `str(ValidationError)` - это несколько строк с url документации;
    в логе платы от него остаётся шум, из которого owner не поймёт, какое
    поле он забыл.
    """
    куски: list[str] = []
    for деталь in ошибка.errors():
        поле = ".".join(str(часть) for часть in деталь["loc"]) or "<корень>"
        куски.append(f"{поле} - {деталь['msg']}")
    return "; ".join(куски)
