"""Сигнал живости во внешнего сторожа: один GET, ничего больше.

Сторож - это сервис «мёртвой руки» снаружи дома: он молчит, пока сигналы
приходят, и пишет owner, когда сигнал не пришёл в срок. Смысл именно
в отсутствии: узнать о тихо лежащей плате иначе нечем, потому что смотреть
на неё в этот момент некому (инвариант 9, §11.1).

**Почему модуль общий.** Сигналов на плате три, и все три - один и тот же
запрос по разным адресам: ночной бэкап (Э1), ежедневная цепочка календаря
и ежемесячная проверка восстановления (оба - Э9, ADR-043). Три копии
`urllib.request` расходятся на первой же правке таймаута.

**Почему `urllib`, а не `httpx2`.** Тот же запрет, из-за которого модуль
не импортирует ничего из `jarvis_api`, кроме себя: бэкап и проверка
восстановления живут в образе `Dockerfile.backup`, где из зависимостей
стоят только `pydantic` и `pydantic-settings`. Импорт httpx2 здесь означал
бы отказ на импорте внутри контейнера - то есть ровно там, где увидеть его
некому до первого ночного прогона.

**Отправитель сам решает, что значит отказ.** Модуль только поднимает
`HeartbeatError`. Для бэкапа это отказ джоба (копия без контроля не
считается копией, ADR-020), для цепочки календаря - строка в логе:
расписание уже доехало, и отменять сделанную работу из-за молчания
стороннего сервиса незачем.
"""

import logging
import urllib.error
import urllib.request

logger = logging.getLogger("jarvis.heartbeat")


class HeartbeatError(RuntimeError):
    """Сигнал не дошёл до сторожа."""


def отправить(url: str, *, timeout: int, имя: str) -> None:
    """GET по адресу сторожа. `имя` - чей это сигнал, для лога и для текста ошибки.

    Пустой адрес сюда не передаётся: «сторож не настроен» - это решение
    вызывающего, и у бэкапа оно другое, чем у цепочки календаря.
    """
    if not url:
        raise HeartbeatError(f"{имя}: адрес сторожа пуст")

    request = urllib.request.Request(url, method="GET")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            code = int(response.status)
    except urllib.error.URLError as error:
        raise HeartbeatError(f"{имя}: ping не дошёл ({error.reason})") from error

    # 4xx и 5xx - это «сторож не принял сигнал»: удалённый монитор, опечатка
    # в адресе, исчерпанный план. Молчаливое согласие с таким ответом даёт
    # худший из исходов - сторожа, которого считают живым.
    if code >= 400:
        raise HeartbeatError(f"{имя}: сторож ответил {code}")

    logger.info("%s: ping отправлен, ответ %s", имя, code)
