"""Конфигурация. Единственный источник значений - переменные окружения.

Инвариант хоста 2: платформенных API хостера на Pi нет, а самодельных
конфигов в файлах на диске быть не должно - всё, что приложение пишет мимо
Postgres, не попадёт в pg_dump и не восстановится (инвариант хоста 1).
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Настройки процесса. Читаются один раз при первом обращении."""

    model_config = SettingsConfigDict(extra="ignore", case_sensitive=False)

    env: str = "dev"
    # На Э0 базы ещё нет, и это рабочее состояние, а не ошибка конфигурации:
    # /health обязан отвечать до того, как DATABASE_URL заполнен, иначе
    # нечем проверять поднятие стека на Э1.
    database_url: str = ""

    # --- Подключение к базе для pg_dump (Э1) ---------------------------------
    # Отдельными полями, а не разбором database_url: pg_dump принимает именно
    # такие параметры, и вытаскивать их регуляркой из URL - лишний способ
    # ошибиться в пароле со спецсимволами.
    postgres_host: str = "db"
    postgres_port: int = 5432
    postgres_db: str = "jarvis"
    postgres_user: str = "jarvis"
    postgres_password: str = ""

    # --- Бэкап (Э1) ----------------------------------------------------------
    # Каталог локальных копий. Единственное место, куда приложение пишет файлы,
    # и это осознанное исключение из инварианта хоста 1: том, а не диск
    # контейнера, и содержимое дублируется в B2.
    backup_dir: str = "/backups"
    # Глубина локальных копий. Число в конфиге, а не в коде: на карте памяти
    # места меньше, чем на SSD, и менять это придётся без правки образа.
    backup_keep_local: int = 7
    # Префиксы в бакете. По ним на стороне B2 висят правила жизненного цикла,
    # поэтому это часть контракта с облаком, а не косметика: глубина
    # 7 ежедневных / 4 недельных / 6 месячных (ADR-020) задаётся тремя
    # правилами, и разложить дамп по ним может только джоб - правила B2
    # различают копии исключительно по префиксу имени.
    backup_prefix: str = "daily"
    backup_prefix_weekly: str = "weekly"
    backup_prefix_monthly: str = "monthly"

    b2_bucket: str = ""
    b2_key_id: str = ""
    b2_app_key: str = ""
    # Точка входа B2. Переопределяется в сквозной проверке на подставной сервер:
    # иначе тракт "дамп - выгрузка - ping" нечем проверить, не трогая живой бакет.
    b2_api_url: str = "https://api.backblazeb2.com"

    # Ping шлётся только после успешной выгрузки (ADR-020). Пустое значение
    # означает "контроль не настроен" и допустимо лишь в dry-run.
    heartbeat_url: str = ""
    # Таймаут внешних вызовов. CLAUDE.md требует таймаут на каждом.
    http_timeout_seconds: int = 30


@lru_cache
def get_settings() -> Settings:
    """Кэшируется намеренно: env за время жизни процесса не меняется."""
    return Settings()
