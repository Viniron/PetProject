"""Конфигурация. Единственный источник значений - переменные окружения.

Инвариант хоста 2: платформенных API хостера на Pi нет, а самодельных
конфигов в файлах на диске быть не должно - всё, что приложение пишет мимо
Postgres, не попадёт в pg_dump и не восстановится (инвариант хоста 1).
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Настройки процесса. Читаются один раз при первом обращении."""

    model_config = SettingsConfigDict(extra="ignore", case_sensitive=False)

    env: str = "dev"
    # На Э0 базы ещё нет, и это рабочее состояние, а не ошибка конфигурации:
    # /health обязан отвечать до того, как DATABASE_URL заполнен, иначе
    # нечем проверять поднятие стека на Э1.
    database_url: str = ""

    # --- Подключение к базе для pg_dump (Э1) ---------------------------------
    # Отдельными полями, а не разбором database_url: pg_dump принимает именно
    # такие параметры, и вытаскивать их регуляркой из URL - лишний способ
    # ошибиться в пароле со спецсимволами.
    postgres_host: str = "db"
    postgres_port: int = 5432
    postgres_db: str = "jarvis"
    postgres_user: str = "jarvis"
    postgres_password: str = ""

    # --- Бэкап (Э1) ----------------------------------------------------------
    # Каталог локальных копий. Единственное место, куда приложение пишет файлы,
    # и это осознанное исключение из инварианта хоста 1: том, а не диск
    # контейнера, и содержимое дублируется в B2.
    backup_dir: str = "/backups"
    # Глубина локальных копий. Число в конфиге, а не в коде: на карте памяти
    # места меньше, чем на SSD, и менять это придётся без правки образа.
    backup_keep_local: int = 7
    # Префиксы в бакете. По ним на стороне B2 висят правила жизненного цикла,
    # поэтому это часть контракта с облаком, а не косметика: глубина
    # 7 ежедневных / 4 недельных / 6 месячных (ADR-020) задаётся тремя
    # правилами, и разложить дамп по ним может только джоб - правила B2
    # различают копии исключительно по префиксу имени.
    backup_prefix: str = "daily"
    backup_prefix_weekly: str = "weekly"
    backup_prefix_monthly: str = "monthly"

    b2_bucket: str = ""
    b2_key_id: str = ""
    b2_app_key: str = ""
    # Точка входа B2. Переопределяется в сквозной проверке на подставной сервер:
    # иначе тракт "дамп - выгрузка - ping" нечем проверить, не трогая живой бакет.
    b2_api_url: str = "https://api.backblazeb2.com"

    # Ping шлётся только после успешной выгрузки (ADR-020). Пустое значение
    # означает "контроль не настроен" и допустимо лишь в dry-run.
    heartbeat_url: str = ""
    # Таймаут внешних вызовов. CLAUDE.md требует таймаут на каждом.
    http_timeout_seconds: int = 30

    # --- Э3: my.itmo.ru ------------------------------------------------------
    # Логин и пароль ИСУ. Пароль читается отсюда ровно один раз - при первом
    # входе, после чего живёт в базе шифротекстом (jarvis_api/crypto.py).
    # Из env он при этом не убирается: плата может остаться без базы, и тогда
    # это единственный способ войти заново.
    isu_login: str = ""
    isu_password: str = ""
    # Ключ шифрования пароля. Пустой означает, что шифровать нечем: джоб
    # откажется работать вместо того, чтобы положить пароль открытым текстом.
    isu_cred_key: str = ""

    # Адреса портала и ITMO ID. В конфиге, а не в коде, по двум причинам:
    # схема неофициальная и может переехать, а тесты обязаны бить в подставной
    # сервер, ни разу не задев настоящий (CLAUDE.md: сеть в тестах замокана).
    itmo_api_base_url: str = "https://my.itmo.ru/api"
    itmo_auth_provider_url: str = "https://id.itmo.ru/auth/realms/itmo"
    # client_id и redirect_uri принадлежат личному кабинету портала, а не нам:
    # мы притворяемся именно им, потому что своего клиента в ITMO ID завести
    # негде. Значения взяты из референса iburakov/my-itmo-ru-to-ical.
    itmo_client_id: str = "student-personal-cabinet"
    itmo_redirect_uri: str = "https://my.itmo.ru/login/callback"

    # Окно забора расписания вокруг сегодняшнего дня. Референс тянет учебный
    # год целиком на каждый прогон; нам это не нужно - в календаре важны
    # ближайшие недели, а прошлое уже записано. Назад заглядываем тоже: пара,
    # перенесённая задним числом, иначе останется в календаре навсегда.
    itmo_sync_days_back: int = 7
    itmo_sync_days_ahead: int = 28

    # Запас перед истечением access-токена. Без него токен, живой на момент
    # проверки, успевает протухнуть по дороге до портала.
    itmo_token_leeway_seconds: int = 60
    # Повторы при отказе портала. Единственный внешний источник расписания,
    # и сетевая икота не повод оставить календарь без обновления.
    itmo_retries: int = 3
    itmo_retry_backoff_seconds: float = 2.0

    # --- Э4: Google Calendar -------------------------------------------------
    # JSON-ключ service account целиком, одной строкой (ADR-019: не OAuth
    # пользователя). Пустое значение - рабочее состояние, а не ошибка: API
    # обязан подниматься до того, как owner заведёт ключ, ровно как с ISU_*.
    # Отказывается работать при этом джоб, и с внятным текстом.
    google_sa_json: str = ""
    # Почта owner, которой расшариваются календари. Не секрет: календари
    # создаёт сервисный аккаунт, и без расшаривания owner их не увидит вовсе.
    google_calendar_owner_email: str = ""

    # Повторы при отказе Google. Отрабатывает их сам SDK внутри execute()
    # рандомизированным exponential backoff, поэтому своего цикла повторов
    # здесь нет - в отличие от портала, где повторы наши (integrations/itmo).
    gcal_retries: int = 3
    # Максимум событий на страницу выдачи. Потолок Google - 2500; берём его,
    # чтобы окно в 35 дней читалось одним запросом, а не десятком.
    gcal_page_size: int = 2500


@lru_cache
def get_settings() -> Settings:
    """Кэшируется намеренно: env за время жизни процесса не меняется."""
    return Settings()
