"""Конфигурация. Единственный источник значений - переменные окружения.

Инвариант хоста 2: платформенных API хостера на Pi нет, а самодельных
конфигов в файлах на диске быть не должно - всё, что приложение пишет мимо
Postgres, не попадёт в pg_dump и не восстановится (инвариант хоста 1).
"""

import datetime as dt
from decimal import Decimal
from functools import lru_cache
from typing import Any

from pydantic import ValidationInfo, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Настройки процесса. Читаются один раз при первом обращении."""

    model_config = SettingsConfigDict(extra="ignore", case_sensitive=False)

    env: str = "dev"
    # На Э0 базы ещё нет, и это рабочее состояние, а не ошибка конфигурации:
    # /health обязан отвечать до того, как DATABASE_URL заполнен, иначе
    # нечем проверять поднятие стека на Э1.
    database_url: str = ""

    # --- Подключение к базе для pg_dump (Э1) ---------------------------------
    # Отдельными полями, а не разбором database_url: pg_dump принимает именно
    # такие параметры, и вытаскивать их регуляркой из URL - лишний способ
    # ошибиться в пароле со спецсимволами.
    postgres_host: str = "db"
    postgres_port: int = 5432
    postgres_db: str = "jarvis"
    postgres_user: str = "jarvis"
    postgres_password: str = ""

    # --- Бэкап (Э1) ----------------------------------------------------------
    # Каталог локальных копий. Единственное место, куда приложение пишет файлы,
    # и это осознанное исключение из инварианта хоста 1: том, а не диск
    # контейнера, и содержимое дублируется в B2.
    backup_dir: str = "/backups"
    # Глубина локальных копий. Число в конфиге, а не в коде: на карте памяти
    # места меньше, чем на SSD, и менять это придётся без правки образа.
    backup_keep_local: int = 7
    # Префиксы в бакете. По ним на стороне B2 висят правила жизненного цикла,
    # поэтому это часть контракта с облаком, а не косметика: глубина
    # 7 ежедневных / 4 недельных / 6 месячных (ADR-020) задаётся тремя
    # правилами, и разложить дамп по ним может только джоб - правила B2
    # различают копии исключительно по префиксу имени.
    backup_prefix: str = "daily"
    backup_prefix_weekly: str = "weekly"
    backup_prefix_monthly: str = "monthly"

    b2_bucket: str = ""
    b2_key_id: str = ""
    b2_app_key: str = ""
    # Точка входа B2. Переопределяется в сквозной проверке на подставной сервер:
    # иначе тракт "дамп - выгрузка - ping" нечем проверить, не трогая живой бакет.
    b2_api_url: str = "https://api.backblazeb2.com"

    # Ping шлётся только после успешной выгрузки (ADR-020). Пустое значение
    # означает "контроль не настроен" и допустимо лишь в dry-run.
    # Это сторож ночного бэкапа; у цепочки календаря и у проверки
    # восстановления свои адреса - см. блок Э9 ниже (ADR-043).
    heartbeat_url: str = ""
    # Таймаут внешних вызовов. CLAUDE.md требует таймаут на каждом.
    http_timeout_seconds: int = 30

    # --- Э3: my.itmo.ru ------------------------------------------------------
    # Логин и пароль ИСУ. Пароль читается отсюда ровно один раз - при первом
    # входе, после чего живёт в базе шифротекстом (jarvis_api/crypto.py).
    # Из env он при этом не убирается: плата может остаться без базы, и тогда
    # это единственный способ войти заново.
    isu_login: str = ""
    isu_password: str = ""
    # Ключ шифрования пароля. Пустой означает, что шифровать нечем: джоб
    # откажется работать вместо того, чтобы положить пароль открытым текстом.
    isu_cred_key: str = ""

    # Адреса портала и ITMO ID. В конфиге, а не в коде, по двум причинам:
    # схема неофициальная и может переехать, а тесты обязаны бить в подставной
    # сервер, ни разу не задев настоящий (CLAUDE.md: сеть в тестах замокана).
    itmo_api_base_url: str = "https://my.itmo.ru/api"
    itmo_auth_provider_url: str = "https://id.itmo.ru/auth/realms/itmo"
    # client_id и redirect_uri принадлежат личному кабинету портала, а не нам:
    # мы притворяемся именно им, потому что своего клиента в ITMO ID завести
    # негде. Значения взяты из референса iburakov/my-itmo-ru-to-ical.
    itmo_client_id: str = "student-personal-cabinet"
    itmo_redirect_uri: str = "https://my.itmo.ru/login/callback"

    # Окно забора расписания вокруг сегодняшнего дня. Референс тянет учебный
    # год целиком на каждый прогон; нам это не нужно - в календаре важны
    # ближайшие недели, а прошлое уже записано. Назад заглядываем тоже: пара,
    # перенесённая задним числом, иначе останется в календаре навсегда.
    itmo_sync_days_back: int = 7
    itmo_sync_days_ahead: int = 28

    # Запас перед истечением access-токена. Без него токен, живой на момент
    # проверки, успевает протухнуть по дороге до портала.
    itmo_token_leeway_seconds: int = 60
    # Повторы при отказе портала. Единственный внешний источник расписания,
    # и сетевая икота не повод оставить календарь без обновления.
    itmo_retries: int = 3
    itmo_retry_backoff_seconds: float = 2.0

    # --- Э4: Google Calendar -------------------------------------------------
    # JSON-ключ service account целиком, одной строкой (ADR-019: не OAuth
    # пользователя). Пустое значение - рабочее состояние, а не ошибка: API
    # обязан подниматься до того, как owner заведёт ключ, ровно как с ISU_*.
    # Отказывается работать при этом джоб, и с внятным текстом.
    google_sa_json: str = ""
    # Почта owner, которой расшариваются календари. Не секрет: календари
    # создаёт сервисный аккаунт, и без расшаривания owner их не увидит вовсе.
    google_calendar_owner_email: str = ""

    # Повторы при отказе Google. Отрабатывает их сам SDK внутри execute()
    # рандомизированным exponential backoff, поэтому своего цикла повторов
    # здесь нет - в отличие от портала, где повторы наши (integrations/itmo).
    gcal_retries: int = 3
    # Максимум событий на страницу выдачи. Потолок Google - 2500; берём его,
    # чтобы окно в 35 дней читалось одним запросом, а не десятком.
    gcal_page_size: int = 2500

    # --- Ф4а: разбор операций ------------------------------------------------
    # Окно поиска второго конца перевода между своими счетами (ADR-041).
    # Сутки - решение owner от 2026-09-17, и оно же самое узкое из разумных:
    # лишний день окна - это лишние ложные пары, а ложная пара стоит двух
    # неверных месяцев сразу (§15.5). Непарный конец при этом не теряется,
    # а уходит в разбор, то есть цена узкого окна - вопрос owner, цена
    # широкого - тихо неверные деньги.
    #
    # Числом в конфиге, а не константой: выходные сдвигают проводку, и
    # насколько - покажут первые настоящие выгрузки БСПБ, которых ещё нет.
    # Расширяется строкой в .env, а не пересборкой образа.
    finance_transfer_window_days: int = 1

    # --- Ф6: API финансов ----------------------------------------------------
    # Через сколько дней без новой выписки книжка считается несвежей и экран
    # показывает плашку «операции по <дата>, загружено N дней назад» (§15.6).
    # Восемь, а не семь: канал книжки недельный (ADR-024), напоминание уходит
    # по воскресеньям (Ф8), и порог в ровно неделю зажигал бы плашку в тот же
    # день, когда напоминание только отправлено. Сутки запаса - это время
    # owner на то, чтобы выгрузить файл, а не признак отставания.
    finance_stale_after_days: int = 8

    # --- Э5: планировщик -----------------------------------------------------
    # Рубильник. Включён по умолчанию (решение owner): выключенный по умолчанию
    # планировщик означает продукт, который молча не работает, если строчку
    # в .env забыли, - а этап делается ровно ради того, чтобы он работал сам.
    # Выключается там, где автоматический прогон вреден: в infra/dev.env и
    # в цели `make dev` (uvicorn --reload перезапускает процесс на каждую
    # правку файла, то есть каждый раз ходил бы в настоящий ИСУ и Google).
    scheduler_enabled: bool = True

    # Времена прогона цепочки по зоне owner, через запятую (решение owner:
    # каждые три часа с 06:30 до 21:30). Строкой, а не кортежем: значение
    # приходит из env, а pydantic-settings разбирает сложные типы как JSON -
    # "06:30,09:30" на кортеже даёт SettingsError, а не список времён.
    #
    # Шесть прогонов, а не один утренний, потому что расписание портала
    # меняется задним числом, и §4 требует пересчёта «при каждом изменении
    # расписания»: узнать об изменении можно только опросом.
    scheduler_daily_times: str = "06:30,09:30,12:30,15:30,18:30,21:30"

    # Пауза между попытками догоняющего запуска (§11.2). Защищает не от
    # параллельного прогона - от цикла перезапуска контейнера: без неё
    # каждый рестарт после неудачного прогона снова шёл бы в ИСУ, а за такое
    # портал банит. Живому `running` в момент старта взяться неоткуда:
    # процесс один, воркер у uvicorn один.
    scheduler_catchup_cooldown_minutes: int = 30

    # Сколько слот ждёт освободившегося воркера. Единственный воркер может
    # быть занят предыдущим прогоном; без запаса APScheduler такой слот
    # выбрасывает. К догону отношения не имеет: расписание строится заново
    # при каждом старте, и пропуски за время простоя процесса им не лечатся.
    scheduler_misfire_grace_seconds: int = 1800

    # --- Э6: API календаря ---------------------------------------------------
    # Через сколько часов без успешного забора расписание считается несвежим
    # и экран показывает полосу давности (§10). Число выведено из расписания
    # планировщика, а не взято на глаз: цепочка гоняется каждые три часа
    # с 06:30 до 21:30, значит законный ночной перерыв - девять часов, плюс
    # один пропущенный слот. Порог ниже девяти помечал бы расписание несвежим
    # каждое утро, и полоса давности перестала бы что-либо означать.
    # Прореживание SCHEDULER_DAILY_TIMES требует поднять и это значение.
    calendar_stale_after_hours: int = 12

    # Таймаут установки соединения с базой, секунды. Появился с первыми
    # эндпоинтами, и не для скорости: недоступная (в отличие от
    # ненастроенной) база не отказывает, а висит до таймаута TCP
    # операционной системы - это те самые «пустой экран и вечный спиннер»,
    # которые §10 запрещает прямо. pool_pre_ping от этого не спасает: сам
    # ping зависает так же. Джобам короткий таймаут не мешает - они падают
    # громко и повторяются следующим слотом.
    db_connect_timeout_seconds: int = 5

    # Сколько запрос ждёт свободного соединения в пуле. Планировщик живёт
    # в этом же процессе (ADR-027), и во время прогона цепочки десять
    # соединений пула могут быть заняты; без явного значения SQLAlchemy ждёт
    # 30 секунд, то есть экран показывает спиннер вместо честного отказа.
    db_pool_timeout_seconds: int = 10

    # --- Э7: аутентификация owner (Cloudflare Access, ADR-033) ---------------
    # Домен команды Cloudflare Zero Trust вида "имя.cloudflareaccess.com".
    # Из него собираются две вещи: адрес публичных ключей и ожидаемый `iss`
    # токена. Пустое значение - «аутентификация не настроена», и это не
    # тихое «выключено»: в prod все /api/* отвечают отказом, потому что
    # забытая строчка в .env обязана давать закрытую дверь, а не открытую.
    cf_access_team_domain: str = ""
    # Audience tag приложения из панели Cloudflare. Без сверки `aud` токен,
    # выписанный любому другому приложению той же команды, пускал бы сюда.
    cf_access_aud: str = ""
    # Почта owner, которой разрешён вход. Политика в панели Cloudflare -
    # первая дверь, эта проверка - вторая: политику правят мышкой, и промах
    # в ней не должен означать доступ к расписанию.
    cf_access_allowed_email: str = ""

    # Сколько живёт кэш публичных ключей. Cloudflare ротирует их порядка
    # раза в шесть недель, так что значение не про свежесть подписи, а про
    # число походов наружу: без кэша каждый запрос экрана тянул бы JWKS.
    cf_access_jwks_ttl_seconds: int = 600
    # Не чаще этого перечитываем ключи из-за неизвестного `kid`. Ротация
    # даёт законный незнакомый kid, но без паузы мусорный токен со случайным
    # kid гонял бы нас в Cloudflare на каждом запросе.
    cf_access_jwks_retry_seconds: int = 60
    # Таймаут похода за ключами. Короткий намеренно: он лежит на пути
    # запроса экрана, и §10 требует честного отказа, а не спиннера.
    # Общий http_timeout_seconds (30) здесь означал бы полминуты ожидания.
    cf_access_jwks_timeout_seconds: int = 5
    # Допуск на расхождение часов при проверке `exp` и `iat`. На плате время
    # синхронизируется NTP, но секунда расхождения не повод для 401.
    cf_access_leeway_seconds: int = 10

    # --- Э9б: второй маршрут туннеля, ssh (ADR-045) --------------------------
    # Публичное имя ssh-приложения Access вида "ssh.example.ru". Код за этой
    # дверью не стоит: маршрут ведёт мимо API, прямо на sshd платы, и проверить
    # её изнутри запроса нельзя - только снаружи, походом на само имя. Ради
    # этого похода имя и живёт в настройках; больше его никто не читает.
    #
    # Пустая строка означает «маршрут не заведён» и проверку не роняет: до Э9б
    # второго маршрута не существовало вовсе. Но и молчаливым OK она не
    # становится - `tunnel_check` печатает SKIP с причиной, иначе забытая
    # строчка выглядела бы как проверенный маршрут.
    cf_access_ssh_hostname: str = ""

    # --- Э8: захват событий --------------------------------------------------
    # Сколько живёт черновик, к которому не вернулись (§9). Трое суток, а не
    # сутки: захват случается на ходу, а возвращаются к нему за компьютером -
    # брошенное в пятницу вечером должно дожить до понедельника. Черновик
    # удаляется вместе с сырьём, поэтому число здесь - это ещё и срок, на
    # который фотография доски остаётся в базе и в ночном дампе.
    capture_draft_ttl_hours: int = 72

    # Потолок текста захвата. Не про модель (её цена считается в Э12), а про
    # базу: поле `source_text` без ограничения принимает вставленный буфер
    # обмена любого размера, и он уедет в каждый ночной pg_dump.
    capture_text_max_chars: int = 4000

    # Таймаут немедленной попытки записать подтверждённое событие в Google
    # (ADR-042). Отдельно от http_timeout_seconds намеренно: тридцать секунд
    # лежат на пути запроса экрана, и owner смотрел бы на них вместо ответа.
    # Не вышло за это время - событие остаётся в очереди, дошлёт джоб.
    capture_push_timeout_seconds: int = 5

    # --- Э9: живучесть (ADR-043) ---------------------------------------------
    # Сторож ежедневной цепочки. Сигнал уходит только после прогона, где
    # не отказал ни один шаг: монитор с периодом в сутки гаснет тогда, когда
    # расписание перестало доезжать до календаря, - а это отказ, которого
    # не видно ни по /health, ни по сторожу бэкапа.
    #
    # Пустое значение, в отличие от бэкапа, прогон НЕ запрещает: цепочка
    # полезна и без наблюдателя, а бэкап без контроля бесполезен (ADR-020).
    # Цена этой разницы - строка в логе на каждый прогон, чтобы «сторож
    # не настроен» не выглядело как «сторож молчит».
    jobs_heartbeat_url: str = ""

    # Сторож ежемесячной проверки восстановления. Отдельный адрес, а не
    # общий с цепочкой: у сигналов разный период (месяц против суток),
    # и один монитор на оба означал бы, что ежедневный сигнал гасит тревогу
    # о непроверенном бэкапе.
    restore_heartbeat_url: str = ""

    # База, в которую разворачивается дамп при проверке. Живую не трогаем
    # никогда: восстановление поверх неё не оставляет пути назад.
    restore_scratch_db: str = "jarvis_restore"

    # Предельный возраст дампа, который проверка согласна считать свежим.
    # Ежемесячная проверка прошлогодней копии не значит ничего: она скажет,
    # что pg_restore работает, и промолчит о том, что бэкап встал месяц
    # назад. Двое суток - ночной бэкап плюс один пропущенный день.
    restore_max_dump_age_hours: int = 48

    # --- Э12а: слой моделей (§5.1, §5.2) -------------------------------------
    # Назначение «задача - модель» целиком, JSON одной строкой. Пустая строка -
    # рабочее состояние, а не ошибка: назначение приходит от owner (Phase 0),
    # и до него платформа обязана подниматься, а вызов - отказывать внятно,
    # вместо того чтобы подставить модель наугад.
    #
    # Почему JSON в env, а не файл рядом с кодом: инвариант хоста 2. Файл
    # на диске платы не попадёт в pg_dump и не переживёт замену SSD, а смена
    # модели обязана быть правкой конфига, не деплоем (§5.2).
    llm_routing: str = ""

    # Месячный потолок расходов на все модели разом, доллары (решение owner
    # 2026-09-21). Именно на все, а не на задачу: счёт от провайдера один,
    # и потолки по задачам удержали бы каждую в своих рамках, оставив сумму
    # без присмотра.
    #
    # Decimal, а не float: это деньги (CLAUDE.md). Из env приходит строка,
    # и Decimal строится прямо из неё - промежуточный float превратил бы
    # "5.1" в 5.0999999999999996 ещё до первого сложения.
    llm_monthly_cap_usd: Decimal = Decimal("5")

    # Таймаут одного вызова модели. Отдельно от http_timeout_seconds намеренно:
    # модель думает секунды даже в норме, и подгонять под неё общий таймаут
    # значило бы разрешить минуту ожидания заодно и походу за расписанием.
    llm_timeout_seconds: int = 60

    # Сколько раз переспросить модель, ответившую мимо схемы (§5.2). Один
    # повтор: вторая неудача подряд - свойство модели, а не случайность,
    # и лечится она фолбэком на другую, а не третьим платным заходом.
    llm_schema_retries: int = 1

    # --- Э12б: адаптеры провайдеров (ADR-046, ADR-049) -----------------------
    # Ключи провайдеров. Пустой ключ - провайдер не подключён, и это рабочее
    # состояние: маршрут на него отказывает с перечислением подключённых,
    # вместо того чтобы ходить в никуда с пустым заголовком.
    gemini_api_key: str = ""
    anthropic_api_key: str = ""

    # Повторы на недоступность провайдера: сеть, таймаут, 429, 5xx. Отказ
    # по существу (ключ, доступ, длина входа) не повторяется вовсе - тот же
    # запрос вернёт тот же отказ, а платный вызов ещё и стоит денег на каждой
    # попытке. Отдельно от itmo_retries: там повторяется бесплатное чтение
    # портала, здесь - оплачиваемый вызов.
    llm_retries: int = 3
    llm_retry_backoff_seconds: float = 2.0

    # Пустая строка в env означает «умолчание», а не «ошибка». Причина
    # конкретная: в docker-compose.yml переменные прокидываются как
    # ${ИМЯ:-} (это проверяется tests/test_compose_env.py), и на bool и int
    # пустое значение даёт ValidationError при построении Settings - то есть
    # на импорте main.py, до всякого lifespan. Итог был бы такой: /health не
    # поднимается, healthcheck не проходит, restart: unless-stopped крутит
    # контейнер по кругу, а причина - незаполненная строчка в .env.
    @field_validator(
        "scheduler_enabled",
        "scheduler_daily_times",
        "scheduler_catchup_cooldown_minutes",
        "scheduler_misfire_grace_seconds",
        "calendar_stale_after_hours",
        "db_connect_timeout_seconds",
        "db_pool_timeout_seconds",
        "cf_access_jwks_ttl_seconds",
        "cf_access_jwks_retry_seconds",
        "cf_access_jwks_timeout_seconds",
        "cf_access_leeway_seconds",
        "capture_draft_ttl_hours",
        "capture_text_max_chars",
        "capture_push_timeout_seconds",
        "finance_transfer_window_days",
        "finance_stale_after_days",
        "restore_scratch_db",
        "restore_max_dump_age_hours",
        "llm_monthly_cap_usd",
        "llm_timeout_seconds",
        "llm_schema_retries",
        "llm_retries",
        "llm_retry_backoff_seconds",
        mode="before",
    )
    @classmethod
    def _пустое_значит_умолчание(cls, значение: Any, info: ValidationInfo) -> Any:
        if isinstance(значение, str) and not значение.strip():
            return cls.model_fields[str(info.field_name)].default
        return значение

    @field_validator("cf_access_team_domain", "cf_access_ssh_hostname")
    @classmethod
    def _домен_команды_без_схемы(cls, значение: str) -> str:
        """Панель Cloudflare показывает домен ссылкой - owner скопирует её целиком.

        Из домена команды собирается `iss` токена: "https://" + домен. Лишняя
        схема или слеш дали бы issuer вида "https://https://имя.../" и 401 на
        совершенно законном токене - причём с текстом про подпись, который
        уводит от настоящей причины на час.

        Имя ssh-приложения чистится тем же кодом и по той же причине: из него
        собирается адрес проверки, и "https://https://ssh..." не разобрался бы
        в адрес вовсе - проверка запертости маршрута упала бы на своём же
        запросе и назвала бы это недоступностью Cloudflare.
        """
        текст = значение.strip().removeprefix("https://").removeprefix("http://")
        return текст.rstrip("/")

    @field_validator("scheduler_daily_times")
    @classmethod
    def _слоты_разбираются(cls, значение: str) -> str:
        """Опечатка в расписании обязана падать при старте, а не в потоке.

        Иначе она всплывёт молчанием: планировщик поднялся, слотов нет,
        и выглядит это как рабочее состояние.
        """
        разобрать_слоты(значение)
        return значение


def разобрать_слоты(значение: str) -> tuple[dt.time, ...]:
    """ "06:30,09:30" -> два времени. Пустой список - отказ, а не тишина.

    Живёт в конфиге, а не в планировщике, чтобы валидатор настроек и
    построитель триггеров разбирали строку одним и тем же кодом: две
    независимые реализации разойдутся на первой же нестандартной записи.
    """
    слоты: list[dt.time] = []
    for кусок in значение.split(","):
        текст = кусок.strip()
        if not текст:
            continue
        try:
            час, _, минута = текст.partition(":")
            слоты.append(dt.time(hour=int(час), minute=int(минута)))
        except ValueError as ошибка:
            raise ValueError(
                f"расписание джобов: {текст!r} - не время вида ЧЧ:ММ (всё значение: {значение!r})"
            ) from ошибка

    if not слоты:
        raise ValueError(
            "расписание джобов пусто: планировщик поднялся бы без единого слота, "
            "и это выглядело бы как рабочее состояние"
        )
    return tuple(sorted(слоты))


