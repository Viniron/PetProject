"""Резюме о расходах после импорта (Ф11, §15.9, ADR-057).

Короткий текст о тратах «с прошлой загрузки»: что заметно больше или
меньше обычного. Текст пишет модель, но всё, о чём она пишет, считает код:
период, траты по категориям и «среднее». Модель получает готовые цифры
и только переводит их в слова.

Здесь - арифметика без базы и без модели. Чтение книжки и вызов модели
живут в `jobs/finance_summary.py`.

Четыре правила, и каждое ломается тихо.

**Период кончается днём, по который загружены все банки** (`покрыто_по`,
то же правило, что у плашки давности §15.6). Резюме по самому свежему банку
говорило бы «на этой неделе меньше на еду», когда на деле вторую карту ещё
не загрузили, - правдоподобная выдумка, которую §10 запрещает прямее, чем
пустой экран. Не продвинулся период - резюме нет, и причина названа.

**Период начинается с конца прошлого резюме, а не прошлого импорта.**
Резюме, пропущенное из-за отказа модели, не теряется: следующий импорт
охватит оба отрезка разом. Отдельной команды пересчёта поэтому нет
(решение owner, ADR-057).

**«Среднее» - трата прошлых недель в день, умноженная на длину периода.**
Периоды разной длины (выписку выгрузили на день позже) сравниваются тогда
честно, а не «восемь дней против средней недели». Сравнение - по ключу
основной категории (§15.4): подкатегории складываются в родителя, иначе
каждый месяц с новыми подкатегориями сравнивать было бы не с чем.

**Мало истории - сравнения нет вовсе.** Меньше
`FINANCE_SUMMARY_MIN_HISTORY_WEEKS` недель до периода - и модель получает
траты без «среднего». Ответ, где модель утверждает, что сравнивала,
отбрасывает код: сравнивать ей было не с чем, значит сравнение выдумано.
"""

import datetime as dt
import json
from collections.abc import Iterable
from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal
from typing import Any
from zoneinfo import ZoneInfo

from pydantic import BaseModel, ConfigDict

НОЛЬ = Decimal("0.00")
КОПЕЙКА = Decimal("0.01")
ДНЕЙ_В_НЕДЕЛЕ = 7

# Резюме - «короткий текст» (§15.9). Длиннее - это уже отчёт, и вероятнее
# всего модель ушла от формата: пересказывает таблицу вместо вывода.
ДЛИНА_ТЕКСТА = 800


@dataclass(frozen=True, slots=True)
class Период:
    """Дни в зоне owner, оба конца включительно."""

    с: dt.date
    по: dt.date

    @property
    def дней(self) -> int:
        return (self.по - self.с).days + 1

    def содержит(self, день: dt.date) -> bool:
        return self.с <= день <= self.по


@dataclass(frozen=True, slots=True)
class Трата:
    """Расход книжки глазами резюме: день, ключ основной категории, сумма.

    `amount` - уже за вычетом гашений (§15.5), той же арифметикой, что
    у сальдо. Резюме, где обед с друзьями стоит вчетверо дороже, чем
    в обзоре месяца, противоречило бы книжке в первой же строке.
    `key` пуст у неразобранного: такие идут отдельной строкой.
    """

    day: dt.date
    key: str | None
    title: str | None
    amount: Decimal


@dataclass(frozen=True, slots=True)
class СтрокаОсновы:
    """Одна категория в основе резюме. `average` пуст, когда истории мало."""

    key: str | None
    title: str | None
    spent: Decimal
    count: int
    average: Decimal | None


@dataclass(frozen=True, slots=True)
class Основа:
    """Всё, что видит модель, - и ровно это хранится в `fin_summaries.basis`.

    Одна структура на оба места намеренно: снимок, отличающийся от того,
    что ушло модели, не объяснил бы её текст через месяц.
    """

    период: Период
    история: Период | None
    достаточно: bool
    минимум_дней: int
    категории: tuple[СтрокаОсновы, ...]
    без_категории: СтрокаОсновы
    всего: СтрокаОсновы

    def как_json(self) -> dict[str, Any]:
        """Снимок для `basis`. Суммы строками: `Decimal` в JSON-число стал
        бы двоичной дробью, и снимок разошёлся бы с книжкой на копейки."""

        def строка(с: СтрокаОсновы) -> dict[str, Any]:
            return {
                "key": с.key,
                "title": с.title,
                "spent": str(с.spent),
                "count": с.count,
                "average": str(с.average) if с.average is not None else None,
            }

        def период(п: Период) -> dict[str, Any]:
            return {"from": п.с.isoformat(), "to": п.по.isoformat(), "days": п.дней}

        return {
            "period": период(self.период),
            "history": период(self.история) if self.история is not None else None,
            "enough_history": self.достаточно,
            "min_history_days": self.минимум_дней,
            "categories": [строка(с) for с in self.категории],
            "uncategorized": строка(self.без_категории),
            "total": строка(self.всего),
        }


class РезюмеМодели(BaseModel):
    """Схема ответа модели. Принадлежит точке вызова, а не адаптеру (ADR-049).

    `compared` - не украшение: по нему код ловит сравнение с историей,
    которой нет. Проверить текст на выдуманное «в среднем» код не может,
    а признание модели о том, что она сравнивала, - может.
    """

    model_config = ConfigDict(extra="forbid")

    text: str
    compared: bool


class ОтказРезюме(ValueError):
    """Ответ модели не годится в резюме. Текст - причина словами для owner."""


def определить_период(
    *,
    покрыто_по: dt.date | None,
    прошлое_по: dt.date | None,
    начало_захода: dt.date | None,
) -> Период | str:
    """Период резюме или причина, по которой его нет.

    `прошлое_по` - последний день прошлого резюме, `начало_захода` - самое
    раннее начало периода среди файлов этого импорта: первое резюме
    описывает то, что только что загружено (§15.9), а не всю книжку.
    """
    if покрыто_по is None:
        return "не у всех банков известен период выписки - покрытие книжки не определено"
    if прошлое_по is not None:
        начало = прошлое_по + dt.timedelta(days=1)
        if начало > покрыто_по:
            return (
                f"период не продвинулся: все банки загружены по {покрыто_по:%d.%m},"
                f" прошлое резюме - по {прошлое_по:%d.%m}"
            )
        return Период(с=начало, по=покрыто_по)
    if начало_захода is None or начало_захода > покрыто_по:
        # Файлы захода целиком позже покрытия: свежий банк загружен,
        # отстающий - нет. Резюме подождёт его, как и в общем случае.
        return f"выписки загружены не со всех банков: книжка покрыта по {покрыто_по:%d.%m}"
    return Период(с=начало_захода, по=покрыто_по)


def окно_истории(период: Период, *, ведётся_с: dt.date | None, недель: int) -> Период | None:
    """Прошлые дни, с которыми сравнивается период: до `недель` недель
    вплотную к нему, но не раньше начала книжки. None - истории нет."""
    if ведётся_с is None:
        return None
    конец = период.с - dt.timedelta(days=1)
    начало = max(период.с - dt.timedelta(days=недель * ДНЕЙ_В_НЕДЕЛЕ), ведётся_с)
    if начало > конец:
        return None
    return Период(с=начало, по=конец)


def _деньги(сумма: Decimal) -> Decimal:
    return сумма.quantize(КОПЕЙКА, rounding=ROUND_HALF_UP)


def свести(
    траты: Iterable[Трата],
    период: Период,
    история: Период | None,
    *,
    минимум_недель: int,
) -> Основа:
    """Траты периода и «среднее» по ключу основной категории.

    Категория, по которой в периоде трат не было, а в истории были,
    тоже в основе - с нулём: «на этой неделе ни разу не брал такси»
    такой же вывод, как «вдвое больше на еду».

    Порядок - сумма периода по убыванию, затем ключ: одна и та же
    книжка обязана давать один и тот же промпт.
    """
    минимум_дней = минимум_недель * ДНЕЙ_В_НЕДЕЛЕ
    достаточно = история is not None and история.дней >= минимум_дней

    в_периоде: dict[str | None, Decimal] = {}
    сколько: dict[str | None, int] = {}
    в_истории: dict[str | None, Decimal] = {}
    названия: dict[str, tuple[dt.date, str]] = {}
    for трата in траты:
        if период.содержит(трата.day):
            в_периоде[трата.key] = в_периоде.get(трата.key, НОЛЬ) + трата.amount
            сколько[трата.key] = сколько.get(трата.key, 0) + 1
        elif история is not None and история.содержит(трата.day):
            в_истории[трата.key] = в_истории.get(трата.key, НОЛЬ) + трата.amount
        else:
            continue
        # Название - из самого позднего месяца: ключ стабилен, а название
        # owner вправе поправить, и показывать стоит нынешнее.
        if трата.key is not None and трата.title:
            прежнее = названия.get(трата.key)
            if прежнее is None or трата.day >= прежнее[0]:
                названия[трата.key] = (трата.day, трата.title)

    def среднее(ключ: str | None) -> Decimal | None:
        if not достаточно or история is None:
            return None
        # В день по истории, умноженное на длину периода: периоды разной
        # длины сравниваются честно, а не восемь дней против недели.
        return _деньги(в_истории.get(ключ, НОЛЬ) * период.дней / история.дней)

    ключи = {к for к in (set(в_периоде) | set(в_истории)) if к is not None}
    категории = sorted(
        (
            СтрокаОсновы(
                key=ключ,
                title=названия[ключ][1] if ключ in названия else None,
                spent=_деньги(в_периоде.get(ключ, НОЛЬ)),
                count=сколько.get(ключ, 0),
                average=среднее(ключ),
            )
            for ключ in ключи
        ),
        key=lambda с: (-с.spent, с.key or ""),
    )
    без_категории = СтрокаОсновы(
        key=None,
        title=None,
        spent=_деньги(в_периоде.get(None, НОЛЬ)),
        count=сколько.get(None, 0),
        average=среднее(None),
    )
    всего_в_истории = sum(в_истории.values(), НОЛЬ)
    всего = СтрокаОсновы(
        key=None,
        title=None,
        spent=_деньги(sum(в_периоде.values(), НОЛЬ)),
        count=sum(сколько.values()),
        average=(
            _деньги(всего_в_истории * период.дней / история.дней)
            if достаточно and история is not None
            else None
        ),
    )
    return Основа(
        период=период,
        история=история,
        достаточно=достаточно,
        минимум_дней=минимум_дней,
        категории=tuple(категории),
        без_категории=без_категории,
        всего=всего,
    )


def описать_основу(основа: Основа) -> str:
    """Цифры для промпта: по JSON-строке на категорию, затем итог.

    Те же поля, что в снимке: модель и owner через месяц видят одно и то же.
    """

    def строка(с: СтрокаОсновы, **сверху: Any) -> str:
        return json.dumps(
            {
                **сверху,
                "key": с.key,
                "title": с.title,
                "spent": str(с.spent),
                "count": с.count,
                "average": str(с.average) if с.average is not None else None,
            },
            ensure_ascii=False,
        )

    строки = [строка(с) for с in основа.категории]
    if основа.без_категории.count or основа.без_категории.average:
        строки.append(строка(основа.без_категории, uncategorized=True))
    строки.append(строка(основа.всего, total=True))
    return "\n".join(строки)


def прочитать_ответ(ответ: РезюмеМодели, основа: Основа) -> str:
    """Ответ модели -> текст резюме или `ОтказРезюме` с причиной.

    Отказ здесь - деградация, а не провал: резюме не показывается (§15.6),
    импорт при этом записан целиком.
    """
    текст = ответ.text.strip()
    if not текст:
        raise ОтказРезюме("модель вернула пустой текст")
    if len(текст) > ДЛИНА_ТЕКСТА:
        raise ОтказРезюме(f"текст длиннее {ДЛИНА_ТЕКСТА} символов")
    if ответ.compared and not основа.достаточно:
        raise ОтказРезюме("модель сравнила с историей, которой нет")
    return текст


def день_окончания(конец: dt.datetime, зона: ZoneInfo) -> dt.date:
    """Последний день периода по `fin_summaries.period_end`.

    Конец в базе хранится полуоткрытым - полночь дня после периода в зоне
    owner: так `occurred_at < period_end` отбирает ровно его операции.
    """
    return (конец.astimezone(зона) - dt.timedelta(days=1)).date()


def границы(период: Период, зона: ZoneInfo) -> tuple[dt.datetime, dt.datetime]:
    """Период днями -> `[начало, конец)` моментами в зоне owner."""
    начало = dt.datetime.combine(период.с, dt.time.min, tzinfo=зона)
    конец = dt.datetime.combine(период.по + dt.timedelta(days=1), dt.time.min, tzinfo=зона)
    return начало, конец
