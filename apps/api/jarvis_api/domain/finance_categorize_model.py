"""Ступень 5 разбора: категория моделью (Ф9, §15.4, ADR-055).

Ни базы, ни сети - как и ступени 1-4 в `finance_categorize.py`. Здесь
решается, что отдать модели, как прочитать её ответ и что из него
записать; вызов и запись живут в `jobs/finance_categorize.py`.

Четыре правила, и каждое ломается тихо.

**Модели уходит только неразобранный расход.** Без категории, без ручного
решения owner (`manual` при пустой категории - это «категории здесь нет»,
§15.4), не в очереди разбора, не исключённый и не отменённый. Звать модель
на то, что разобрано правилом, - переплата (§5.1); на строку в разборе -
решение за owner там, где вопрос ему и задан.

**Мерчант, однажды разобранный моделью, второй раз ей не отправляется**
(решение owner, 2026-10-01). Его категория берётся из книжки: так один
мерчант не получает разных категорий в разные дни, когда маршрут ушёл
на резерв (ADR-046). Правила по мерчанту при этом не заводится - в
`fin_category_rules` нет признака происхождения, и правило от модели
стало бы неотличимо от правила owner.

**Ответ проверяет код, а не промпт.** Модель вправе заводить новые
категории и подкатегории без подтверждения (§15.4, решение owner
2026-10-01), но не вправе ломать набор: ключ подкатегории на месте
основной, подкатегория чужой основной, ключ не по форме, новая категория
без названия или с названием уже существующей - всё это оставляет
операцию без категории. Без категории - видно и чинится руками;
неверная категория правдоподобна и не проверяется (§10).

**Основные категории owner неприкосновенны.** Модель их не переименовывает
и не убирает - у ответа просто нет для этого полей. Новое создаётся рядом,
с `origin = ai`.
"""

import datetime as dt
import json
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from decimal import Decimal
from zoneinfo import ZoneInfo

from pydantic import BaseModel, ConfigDict

# Форма ключа новой категории. Тот же вид, что у ключей owner в файле набора:
# ключ - стабильная часть категории, по нему сравниваются месяцы (§15.9),
# и кириллица или пробел в нём однажды разойдутся с написанием в запросе.
ФОРМА_КЛЮЧА = re.compile(r"^[a-z][a-z0-9_]*$")
# Колонки `fin_categories.key` и `title` - String(64) и String(256). Длиннее
# упало бы на вставке, то есть уронило бы весь разбор вместо одной строки.
ДЛИНА_КЛЮЧА = 64
ДЛИНА_НАЗВАНИЯ = 256


@dataclass(frozen=True, slots=True)
class Кандидат:
    """Расход, который ступени 1-4 не разобрали. Ровно то, что уйдёт модели.

    Имя счёта и банк не отправляются: категории они не определяют, а лишнее
    в запросе - это и токены, и данные owner у провайдера.
    """

    id: int
    occurred_at: dt.datetime
    amount: Decimal
    merchant: str | None
    bank_category: str | None
    mcc: str | None


@dataclass(frozen=True, slots=True)
class КатегорияНабора:
    """Активная категория месяца. `parent_key` пуст у основной."""

    key: str
    title: str
    parent_key: str | None = None


class КатегорияОперации(BaseModel):
    """Один элемент ответа. Все поля обязательны и допускают `null`.

    «Не нашёл» - законный ответ (`category: null`), и модель обязана его
    произнести, а не пропустить элемент: пропуск неотличим от обрыва ответа.
    Форма ключа проверяется кодом, а не схемой (`прочитать_ответ`): ответ
    на сорок операций, переспрошенный целиком из-за одного кривого ключа,
    стоил бы второго вызова ради одной строки.
    """

    model_config = ConfigDict(extra="forbid")

    id: int
    category: str | None
    category_title: str | None
    subcategory: str | None
    subcategory_title: str | None


class РазборОпераций(BaseModel):
    """Схема ответа модели. Принадлежит точке вызова, а не адаптеру (ADR-049)."""

    model_config = ConfigDict(extra="forbid")

    operations: list[КатегорияОперации]


@dataclass(frozen=True, slots=True)
class Новая:
    """Категория, которую модель завела. Основные идут раньше подкатегорий."""

    key: str
    title: str
    parent_key: str | None


@dataclass(slots=True)
class Итог:
    """Что из ответа модели записывается.

    `назначения` - id операции и ключ категории, основной или подкатегории.
    `отклонено` - id и причина словами: её печатает дифф разбора.
    """

    назначения: dict[int, str] = field(default_factory=dict)
    новые: list[Новая] = field(default_factory=list)
    отклонено: dict[int, str] = field(default_factory=dict)


def ключ_мерчанта(значение: str | None) -> str | None:
    """Написание мерчанта к виду, в котором два написания считаются одним.

    То же правило, что у правил разбора (`finance_categorize._ключ`): регистр
    и края, и больше ничего. «Пятёрочка» и «Пятерочка» остаются разными -
    склейка догадкой разнесла бы деньги по категории, которой никто
    не выбирал.
    """
    if значение is None:
        return None
    очищенное = значение.strip().casefold()
    return очищенное or None


def повторы(
    кандидаты: Iterable[Кандидат],
    прежние: Mapping[str, str],
    набор: Iterable[КатегорияНабора],
) -> tuple[dict[int, str], list[Кандидат]]:
    """Категории мерчантов, уже разобранных моделью, - без нового вызова.

    `прежние` - ключ мерчанта -> ключ категории, которую модель ему дала.
    Ключа нет в наборе этого месяца - мерчант уходит модели заново: набор
    месяца свой (§15.4), и категория, заведённая моделью в сентябре,
    в октябре может уже не существовать.
    """
    ключи = {к.key for к in набор}
    назначено: dict[int, str] = {}
    остальные: list[Кандидат] = []
    for кандидат in кандидаты:
        мерчант = ключ_мерчанта(кандидат.merchant)
        прежний = прежние.get(мерчант) if мерчант is not None else None
        if прежний is not None and прежний in ключи:
            назначено[кандидат.id] = прежний
        else:
            остальные.append(кандидат)
    return назначено, остальные


def описать_набор(набор: Sequence[КатегорияНабора]) -> str:
    """Набор месяца для промпта: основная, под ней подкатегории с отступом."""
    основные = [к for к in набор if к.parent_key is None]
    строки: list[str] = []
    for основная in sorted(основные, key=lambda к: к.key):
        строки.append(f"- {основная.key}: {основная.title}")
        for под in sorted((к for к in набор if к.parent_key == основная.key), key=lambda к: к.key):
            строки.append(f"  - {под.key}: {под.title}")
    return "\n".join(строки)


def описать_операции(кандидаты: Sequence[Кандидат], зона: ZoneInfo) -> str:
    """Операции для промпта, по JSON-строке на каждую.

    JSON, а не таблица: описание банка бывает с точкой с запятой, кавычками
    и переводом строки, и в таблице оно сдвинуло бы соседние поля. Сумма -
    строкой: `Decimal` в JSON-число превратился бы в двоичную дробь.
    Дата - в зоне owner, как в выписке (инвариант 7).
    """
    return "\n".join(
        json.dumps(
            {
                "id": к.id,
                "date": к.occurred_at.astimezone(зона).date().isoformat(),
                "amount": str(к.amount),
                "merchant": к.merchant,
                "bank_category": к.bank_category,
                "mcc": к.mcc,
            },
            ensure_ascii=False,
        )
        for к in кандидаты
    )


def _название(значение: str | None) -> str | None:
    if значение is None:
        return None
    очищенное = значение.strip()
    return очищенное or None


def _новая(
    ключ: str,
    название: str | None,
    родитель: str | None,
    известные: Mapping[str, КатегорияНабора | Новая],
) -> tuple[Новая | None, str | None]:
    """Проверка новой категории: она сама или причина отказа.

    Ключ проверяется на уникальность **по всему месяцу**, включая
    подкатегории, - то же правило, что у файла набора owner
    (`jobs/finance_taxonomy.py`): правило разбора ссылается на ключ,
    и два одинаковых под разными родителями сделали бы его неоднозначным.
    Название - среди соседей того же уровня: «Кафе» под «Едой» и «Кафе»
    в основных - два места для одной траты, и owner не поймёт, где искать.
    """
    if len(ключ) > ДЛИНА_КЛЮЧА or not ФОРМА_КЛЮЧА.match(ключ):
        return None, f"ключ новой категории {ключ!r} не по форме"
    if ключ in известные:
        return None, f"ключ {ключ!r} в месяце уже занят"
    if название is None:
        return None, f"новая категория {ключ!r} без названия"
    if len(название) > ДЛИНА_НАЗВАНИЯ:
        return None, f"название новой категории {ключ!r} длиннее {ДЛИНА_НАЗВАНИЯ} символов"
    соседи = {к.title.strip().casefold() for к in известные.values() if к.parent_key == родитель}
    if название.casefold() in соседи:
        return None, f"новая категория {ключ!r} повторяет название {название!r}"
    return Новая(key=ключ, title=название, parent_key=родитель), None


def прочитать_ответ(
    ответ: РазборОпераций,
    отправлены: Iterable[int],
    набор: Sequence[КатегорияНабора],
) -> Итог:
    """Ответ модели -> назначения, новые категории и отказы по строкам.

    Отказ одной строки не трогает остальные: ответ на сорок операций,
    где одна с кривым ключом, обязан отдать тридцать девять.

    Новая категория, заведённая в одном элементе, видна следующим: две
    операции одной новой подкатегории - одна строка в наборе, а не отказ
    второй как «дубль ключа».
    """
    итог = Итог()
    ждём = set(отправлены)
    известные: dict[str, КатегорияНабора | Новая] = {к.key: к for к in набор}

    сколько: dict[int, int] = {}
    for элемент in ответ.operations:
        сколько[элемент.id] = сколько.get(элемент.id, 0) + 1

    for элемент in ответ.operations:
        номер = элемент.id
        if номер not in ждём:
            # Чужой id - модель выдумала операцию. Записывать нечего, а
            # причина отказа этой строки никому не нужна: строки нет.
            continue
        if номер in итог.назначения or номер in итог.отклонено:
            continue
        if сколько[номер] > 1:
            # Две категории одной операции - выбирать между ними наугад
            # значит выдать догадку за ответ.
            итог.отклонено[номер] = "модель назвала операцию дважды"
            continue

        основная = (элемент.category or "").strip()
        if not основная:
            итог.отклонено[номер] = "модель не нашла категории"
            continue

        создаём: list[Новая] = []
        прежняя = известные.get(основная)
        if прежняя is None:
            новая, причина = _новая(основная, _название(элемент.category_title), None, известные)
            if новая is None:
                итог.отклонено[номер] = причина or "новая категория не принята"
                continue
            создаём.append(новая)
        elif прежняя.parent_key is not None:
            итог.отклонено[номер] = f"ключ подкатегории {основная!r} на месте основной"
            continue

        назначить = основная
        под = (элемент.subcategory or "").strip()
        if под:
            прежняя_под = известные.get(под)
            if прежняя_под is None:
                пробные = {**известные, **{н.key: н for н in создаём}}
                новая, причина = _новая(
                    под, _название(элемент.subcategory_title), основная, пробные
                )
                if новая is None:
                    итог.отклонено[номер] = причина or "новая подкатегория не принята"
                    continue
                создаём.append(новая)
            elif прежняя_под.parent_key != основная:
                итог.отклонено[номер] = f"подкатегория {под!r} не из категории {основная!r}"
                continue
            назначить = под

        # Новые категории заводятся только вместе с операцией, которой они
        # достались: категория, ради которой строку потом отвергли, осталась
        # бы в наборе пустой и без единой траты.
        for новая in создаём:
            известные[новая.key] = новая
            итог.новые.append(новая)
        итог.назначения[номер] = назначить

    for номер in sorted(ждём - set(итог.назначения) - set(итог.отклонено)):
        итог.отклонено[номер] = "модель не ответила по операции"
    return итог
