def роли_счетов(session: Session) -> dict[tuple[str, str], str]:
    """Роли всех счетов книжки, ключ - пара «банк, имя счёта».

    Пара, а не имя: одинаково названные счета в двух банках - обычное дело,
    и склеить их значило бы посчитать «Отложено» по чужому счёту.
    """
    счета = session.scalars(select(FinAccount)).all()
    return {(счёт.bank, счёт.name): счёт.role for счёт in счета}


def назначить_роль(session: Session, *, банк: str, счёт: str, роль: str) -> bool:
    """Ставит роль счёту. Возвращает «изменилось», транзакцию коммитит вызывающий.

    Счёт не заводится: он появляется импортом выписки, где это имя
    встретилось. Разметить счёт, которого в книжке нет, - опечатка в имени,
    и молча создать его значило бы завести двойника, на который не смотрит
    ни одна операция.
    """
    if роль not in РОЛИ:
        raise ОшибкаРоли("неизвестная_роль", f"роль {роль!r} не из {', '.join(РОЛИ)}")

    строка = session.scalar(
        select(FinAccount).where(FinAccount.bank == банк, FinAccount.name == счёт)
    )
    if строка is None:
        raise ОшибкаРоли(
            "нет_счёта",
            f"счёта «{счёт}» в банке «{банк}» в книжке нет:"
            " счета заводит импорт выписки, проверь написание",
        )
    if строка.role == роль:
        return False
    строка.role = роль
    return True


def операции_книжки(session: Session) -> list[Операция]:
    """Вся книжка целиком - «Осталось» считается с начала ведения.

    Читается вся таблица, и это осознанно: накопленный итог по определению
    зависит от каждой строки, а книжка одного человека за год - тысячи
    строк, а не миллионы. Резать её окном значило бы хранить накопленный
    итог второй копией, которая однажды разойдётся с первой.
    """
    строки = session.scalars(select(FinTransaction).order_by(FinTransaction.occurred_at)).all()
    return [
        Операция(
            id=строка.id,
            occurred_at=строка.occurred_at,
            amount=строка.amount,
            amount_rub=строка.amount_rub,
            kind=строка.kind,
            kind_source=строка.kind_source,
            status=строка.status,
            excluded=строка.excluded,
            needs_review=строка.needs_review,
            offsets_transaction_id=строка.offsets_transaction_id,
            bank=строка.bank,
            account=строка.account,
        )
        for строка in строки
    ]


def собрать(
    session: Session,
    *,
    месяц_обзора: dt.date,
    сейчас: dt.datetime,
    зона: ZoneInfo,
) -> Обзор:
    """Обзор месяца из базы: сальдо, статьи и оговорки к ним."""
    роли = роли_счетов(session)
    сведённые = свести(операции_книжки(session), роли=роли, зона=зона)
    return Обзор(
        данные=взять_месяц(сведённые, месяц_обзора, все_размечены=размечены(роли)),
        покрыт_по=покрыто_по(session),
        # Окно берётся у гашения: пересчитать месяц может ровно оно,
        # и два разных окна разошлись бы на границе месяца.
        в_окне_пересчёта=в_окне(
            dt.datetime.combine(месяц_обзора, dt.time.min, tzinfo=зона), сейчас, зона
        ),
    )


def счета_списком(session: Session) -> Sequence[FinAccount]:
    """Счета книжки в порядке «банк, имя» - для показа owner."""
    return session.scalars(select(FinAccount).order_by(FinAccount.bank, FinAccount.name)).all()
