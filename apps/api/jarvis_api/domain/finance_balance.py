"""Сальдо месяца, «Отложено» и «Осталось» (§15.5, ADR-030, ADR-047).

Отвечает на три вопроса месяца: сколько пришло и ушло, сколько переложено
на накопительные счета и сколько денег остаётся всего. Три, а не один:
месяц с хорошим сальдо, но без единого перевода на накопительный счёт -
не накопление, а неизрасходованные деньги на карте (ADR-030).

Пять правил, из которых следует всё остальное.

**Из сальдо выпадают четыре вида строк:** `transfer`, `reverted`,
исключённые owner и всё, что стоит в очереди разбора (§15.5). Последнее -
обе причины пометки сразу: и кандидат в дубли от импорта, и входящий
перевод без правила отправителя. Пока owner не решил, обе двигают деньги
в сторону «выглядит правдоподобно», то есть в худшую по §10.

**Гашение уменьшает месяц расхода, а не месяц поступления.** Арифметика
берётся у `finance_offsets.разложить` целиком, вместе с фильтром
«идёт в счёт»: свой набор условий здесь завёл бы вторую стоимость одной
покупки - книжка показывала бы 115 ₽, недельный лимит 575 ₽.

**Расход месяца не опускается ниже нуля** (решение owner, 2026-09-21):
непривязанных возвратов может прийти больше, чем было расходов, и остаток
становится доходом - тем же правилом, каким излишек привязанного гашения
уходит в месяц поступления (§15.5). «Ушло минус три тысячи» читается
не как деньги, а как опечатка.

**«Отложено» - нетто** (решение owner, 2026-09-21): зачисления на счета
с ролью `savings` минус списания с них. Статья отвечает на вопрос «сколько
за месяц реально прибавилось на накопительных», и месяц, проеденный
из накоплений, обязан показывать минус, а не успешный брутто-перевод.

**Неразмеченные счета дают слова, а не ноль.** Хоть один счёт с ролью
`unknown` - и «Отложено» не показывается вовсе: ноль здесь был бы
правдоподобной выдумкой (§10, ADR-030). Роль ставит owner, угадывать
её по имени счёта нельзя - с несколькими банками угадывание ошибается
в деньгах.

Чего здесь нет намеренно: остатков по счетам и целей накопления (§15.8),
резюме о расходах (Ф11) и бюджета (Ф12) - у бюджета своя копилка, и она
**не равна** этой статье: та считает решения owner, эта - настоящие
переводы. Две цифры живут рядом, и разница между ними и есть напоминание
перевести деньги на самом деле.
"""

import datetime as dt
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from zoneinfo import ZoneInfo

from sqlalchemy import select
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinAccount, FinTransaction
from jarvis_api.domain.finance_budget import покрыто_по
from jarvis_api.domain.finance_offsets import Строка, в_окне, идёт_в_счёт, месяц, разложить

НОЛЬ = Decimal("0.00")

РАСХОД = "expense"
ДОХОД = "income"
ПЕРЕВОД = "transfer"
ВОЗВРАТ = "refund"

# Роли счёта (CHECK `role_known`). `unknown` - рабочее состояние, а не
# заглушка: новое имя счёта заводит импорт, роль ставит owner.
РАСЧЁТНЫЙ = "checking"
НАКОПИТЕЛЬНЫЙ = "savings"
НЕИЗВЕСТНАЯ_РОЛЬ = "unknown"
РОЛИ = (РАСЧЁТНЫЙ, НАКОПИТЕЛЬНЫЙ, НЕИЗВЕСТНАЯ_РОЛЬ)


class ОшибкаРоли(ValueError):
    """Разметка счёта отклонена.

    С кодом, а не только текстом, - по образцу `ОшибкаПривязки`: на Ф6 из
    него собирается тело отказа, и owner видит причину, а не «ошибка 400».
    """

    def __init__(self, код: str, сообщение: str) -> None:
        super().__init__(сообщение)
        self.код = код


@dataclass(frozen=True, slots=True)
class Операция(Строка):
    """Строка книжки глазами сальдо: та же, что у гашения, плюс счёт.

    Наследованием, а не второй копией полей: расход раскладывается
    `finance_offsets.разложить`, и объект обязан быть той же `Строкой`.
    Банк и счёт добавлены ради «Отложено» - оно считается по роли счёта,
    а гашению роль не нужна.
    """

    bank: str
    account: str


@dataclass(frozen=True, slots=True)
class Месяц:
    """Сальдо одного месяца и то, что о нём обязано быть сказано."""

    месяц: dt.date
    пришло: Decimal
    ушло: Decimal
    # None - счета не размечены. Не ноль: ноль здесь неотличим от «ничего
    # не откладывал», а это разные ответы (§15.5).
    отложено: Decimal | None
    # Накопленный итог с начала ведения по этот месяц включительно.
    осталось: Decimal
    # Строк, вошедших в сальдо. Ноль при непустой книжке - законный случай:
    # месяц, где всё исключено или стоит в очереди разбора.
    операций: int
    # Строки на накопительных счетах, не опознанные переводом себе:
    # в «Отложено» они не вошли. Называются числом, потому что молча
    # пропавший перевод выглядит как «книжка потеряла деньги».
    вне_переводов: int
    # Расход этого месяца погашен поступлением более позднего месяца,
    # то есть цифра изменилась после того, как месяц кончился (§15.5).
    пересчитан_позже: bool

    @property
    def сальдо(self) -> Decimal:
        return self.пришло - self.ушло

    @property
    def пустой(self) -> bool:
        return self.операций == 0


@dataclass(frozen=True, slots=True)
class Обзор:
    """Месяц вместе с оговорками, без которых цифру читать нельзя."""

    данные: Месяц
    # Последний день, по который загружены выписки **всех** банков.
    # None - покрытия нет вовсе.
    покрыт_по: dt.date | None
    # Месяц ещё может пересчитаться гашением задним числом: текущий
    # и предыдущий. Всё старше окончательно (§15.5).
    в_окне_пересчёта: bool

    @property
    def неполный(self) -> bool:
        """Выписки дошли не до конца месяца - цифра промежуточная.

        Экран обязан сказать «по 5 сентября», а не показать сальдо,
        выглядящее итоговым.
        """
        return self.покрыт_по is None or self.покрыт_по < последний_день(self.данные.месяц)


def последний_день(месяц_: dt.date) -> dt.date:
    """Последний календарный день месяца, заданного первым числом."""
    следующий = (месяц_.replace(day=28) + dt.timedelta(days=4)).replace(day=1)
    return следующий - dt.timedelta(days=1)


def размечены(роли: Mapping[tuple[str, str], str]) -> bool:
    """Все ли счета книжки получили роль от owner.

    Пустая книжка размечена: счетов нет, и «Отложено» в ней честный ноль,
    а не умолчание. Разметка проверяется по всем счетам сразу, а не по
    накопительным: неразмеченный счёт может оказаться накопительным,
    и статья, посчитанная без него, была бы занижена молча.
    """
    return all(роль != НЕИЗВЕСТНАЯ_РОЛЬ for роль in роли.values())


def свести(
    операции: Iterable[Операция],
    *,
    роли: Mapping[tuple[str, str], str],
    зона: ZoneInfo,
) -> dict[dt.date, Месяц]:
    """Все месяцы книжки разом - иначе «Осталось» неоткуда взять.

    «Осталось» - накопленный итог с начала ведения (§15.5), то есть сумма
    сальдо всех месяцев по этот включительно. Считать его по одному месяцу
    нельзя, поэтому и сводятся сразу все: книжка одного человека, и полный
    проход по ней дешевле, чем вторая правда о накопленном итоге.
    """
    все = list(операции)
    по_id = {о.id: о for о in все}
    гашения: dict[int, list[Операция]] = {}
    for о in все:
        if о.offsets_transaction_id is not None:
            гашения.setdefault(о.offsets_transaction_id, []).append(о)

    пришло: dict[dt.date, Decimal] = {}
    ушло: dict[dt.date, Decimal] = {}
    отложено: dict[dt.date, Decimal] = {}
    счёт_строк: dict[dt.date, int] = {}
    вне_переводов: dict[dt.date, int] = {}
    пересчитан: dict[dt.date, bool] = {}

    def завести(м: dt.date) -> None:
        пришло.setdefault(м, НОЛЬ)
        ушло.setdefault(м, НОЛЬ)
        отложено.setdefault(м, НОЛЬ)
        счёт_строк.setdefault(м, 0)
        вне_переводов.setdefault(м, 0)
        пересчитан.setdefault(м, False)

    for о in все:
        свой = месяц(о.occurred_at, зона)
        # Месяц заводится даже строкой, которая в сальдо не войдёт: месяц,
        # где всё исключено, обязан показываться нулями, а не отсутствовать.
        завести(свой)
        if not идёт_в_счёт(о):
            continue

        роль = роли.get((о.bank, о.account), НЕИЗВЕСТНАЯ_РОЛЬ)
        if о.kind == ПЕРЕВОД:
            # Перевод себе в сальдо не входит ни одним концом. На
            # накопительном счёте он и есть «Отложено», и знак суммы даёт
            # нетто сам: зачисление плюс, списание минус.
            if роль == НАКОПИТЕЛЬНЫЙ:
                отложено[свой] += о.amount_rub
            continue

        if роль == НАКОПИТЕЛЬНЫЙ:
            # Строка на накопительном счёте, которую разбор переводом
            # не признал. В «Отложено» она не идёт - основание перевода
            # это пара концов, а не роль счёта (ADR-041), - но и молчать
            # о ней нельзя: пара не собирается внутри одного банка.
            вне_переводов[свой] += 1

        if о.offsets_transaction_id is not None:
            # Привязанное гашение учтено месяцем своего расхода. По признаку
            # привязки, а не по `kind`: вид у него может быть любым, а месяц
            # решает именно ссылка.
            continue

        if о.kind == РАСХОД:
            разбор = разложить(о, гашения.get(о.id, []))
            ушло[свой] += разбор.эффективная
            счёт_строк[свой] += 1
            for часть in разбор.части:
                гашение = по_id[часть.гашение_id]
                месяц_гашения = месяц(гашение.occurred_at, зона)
                # Только погасившее: гашение, которому уже нечего было
                # гасить, цифру месяца не меняло, и объявлять месяц
                # пересчитанным из-за него значило бы пугать зря.
                if месяц_гашения > свой and часть.погасило > НОЛЬ:
                    пересчитан[свой] = True
                if часть.излишек > НОЛЬ:
                    # У гасящей части исходная покупка есть, у излишка её
                    # нет - поэтому он достаётся месяцу поступления (§15.5).
                    завести(месяц_гашения)
                    пришло[месяц_гашения] += часть.излишек
        elif о.kind == ВОЗВРАТ:
            # Непривязанный возврат исходной покупки не знает и гасит свой
            # месяц - прежнее правило §15.5, которое привязка отменяет
            # только для привязанных.
            ушло[свой] -= о.amount_rub
            счёт_строк[свой] += 1
        elif о.kind == ДОХОД:
            пришло[свой] += о.amount_rub
            счёт_строк[свой] += 1

    все_размечены = размечены(роли)
    итог: dict[dt.date, Месяц] = {}
    накоплено = НОЛЬ
    for м in sorted(пришло):
        ушло_месяца = ушло[м]
        пришло_месяца = пришло[м]
        if ушло_месяца < НОЛЬ:
            # Возвратов пришло больше, чем было расходов. Отрицательного
            # расхода не бывает - остаток становится доходом (решение owner).
            пришло_месяца += -ушло_месяца
            ушло_месяца = НОЛЬ
        накоплено += пришло_месяца - ушло_месяца
        итог[м] = Месяц(
            месяц=м,
            пришло=пришло_месяца,
            ушло=ушло_месяца,
            отложено=отложено[м] if все_размечены else None,
            осталось=накоплено,
            операций=счёт_строк[м],
            вне_переводов=вне_переводов[м],
            пересчитан_позже=пересчитан[м],
        )
    return итог


def взять_месяц(сведённые: Mapping[dt.date, Месяц], м: dt.date, *, все_размечены: bool) -> Месяц:
    """Месяц из сводки, а если операций в нём не было - пустой.

    Пустой месяц - нули и накопленный итог предыдущих, а не отсутствие
    ответа: «в сентябре ничего не было» и «сентябрь не считался» owner
    обязан различать. Деления ни на что здесь нет и быть не может -
    случай тестируемый, как пустой курс.
    """
    существующий = сведённые.get(м)
    if существующий is not None:
        return существующий

    прошлые = [сведённый for дата, сведённый in сведённые.items() if дата < м]
    накоплено = max(прошлые, key=lambda с: с.месяц).осталось if прошлые else НОЛЬ
    return Месяц(
        месяц=м,
        пришло=НОЛЬ,
        ушло=НОЛЬ,
        отложено=НОЛЬ if все_размечены else None,
        осталось=накоплено,
        операций=0,
        вне_переводов=0,
        пересчитан_позже=False,
    )


