"""Недельный бюджет и дневной лимит (§15.10, ADR-038).

Отвечает на один вопрос - **сколько можно потратить сегодня** - и на
производный от него: куда девать излишек или перерасход закрытой недели.

Три правила, из которых следует всё остальное.

**День, за который сумма известна, закрыт и из делителя выходит.** Утром
понедельника открыты семь дней; внёс трату вечером - открыто шесть, и та же
цифра означает уже «завтра», а не «ещё столько же сегодня». Решение owner
(2026-09-17), и оно же избавляет от отдельной ветки для импорта: день,
покрытый выпиской, закрывается тем же правилом, что и внесённый руками.

**Известна - значит из выписки, а если её ещё нет, то со слов owner.** Канал
операций один и приезжает раз в неделю (§15.1), а лимит нужен каждый вечер.
Поэтому день, покрытый выпиской, считается по `fin_transactions`, непокрытый -
по `fin_day_spend`. Ручная сумма при этом не стирается: расхождение между
нею и выпиской - единственный признак того, что owner недосчитывает.

**Закрытая неделя не переигрывается.** Гашение расхода задним числом (§15.5)
меняет траты недели, итог которой owner уже распределил. Разница уходит
поправкой в ближайшую нераспределённую неделю - `разнести_поправки`.

Чего здесь нет намеренно: лимитов по категориям, целей накопления и прогнозов.
ADR-038 сузил запрет §15.8 ровно до недельного бюджета, а не снял его.
"""

import datetime as dt
from dataclasses import dataclass
from decimal import ROUND_FLOOR, Decimal
from zoneinfo import ZoneInfo

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinDaySpend, FinImport, FinTransaction, FinWeekBudget

НОЛЬ = Decimal("0.00")
КОПЕЙКА = Decimal("0.01")
ДНЕЙ_В_НЕДЕЛЕ = 7

# Откуда взялась сумма дня. `unknown` - не ошибка, а рабочее состояние:
# так выглядит будущий день недели и прошедший, за который owner не вносил.
ВЫПИСКА = "statement"
РУЧНОЙ = "manual"
НЕИЗВЕСТЕН = "unknown"

# Операция участвует в трате дня, если она расход, не исключена и не отменена
# (§15.5). `pending` входит: покупка, ещё не проведённая банком, деньги
# с карты уже сняла, и не считать её значило бы завысить остаток.
СТАТУСЫ_В_СЧЁТ = ("posted", "pending")


class ОшибкаРаспределения(ValueError):
    """Распределение итога недели не сходится или не обеспечено копилкой."""


@dataclass(frozen=True)
class День:
    """Один день недели с точки зрения бюджета."""

    день: dt.date
    # None - сумма неизвестна: день ещё не наступил либо owner не вносил,
    # а выписка до него не дошла. Ноль и «неизвестно» - разные состояния:
    # ноль означает «в этот день не потрачено ничего», и он закрывает день.
    сумма: Decimal | None
    источник: str
    # Что внёс owner - даже когда сумма выше пришла из выписки. Хранится
    # рядом, а не вместо: разница между ними видна на экране.
    ручная: Decimal | None

    @property
    def известна(self) -> bool:
        return self.сумма is not None

    @property
    def расхождение(self) -> Decimal | None:
        """Выписка минус слова owner. None, если сравнивать не с чем.

        Положительное - потрачено больше, чем owner думал.
        """
        if self.источник != ВЫПИСКА or self.ручная is None or self.сумма is None:
            return None
        return self.сумма - self.ручная


@dataclass(frozen=True)
class Неделя:
    """Неделя целиком: бюджет, перенос и семь дней."""

    начало: dt.date
    # None - бюджет не задан. Показывается словами, а не нулём и не средней
    # по прошлым неделям: выдумка здесь правдоподобна, и потому хуже пустоты.
    бюджет: Decimal | None
    # Итог предыдущей недели плюс поправки задним числом.
    перенос: Decimal
    дни: tuple[День, ...]
    распределена: bool

    @property
    def конец(self) -> dt.date:
        return self.начало + dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ - 1)

    @property
    def потрачено(self) -> Decimal:
        """Сумма известных дней. Неизвестные не считаются нулём молча -
        их число отдельно называет `Лимит.дней_без_суммы`."""
        return sum((день.сумма for день in self.дни if день.сумма is not None), НОЛЬ)


@dataclass(frozen=True)
class Лимит:
    """Ответ на вопрос «сколько можно потратить»."""

    # None, когда бюджет не задан либо открытых дней не осталось.
    сумма: Decimal | None
    # День, к которому относится сумма: первый открытый. Подпись на экране
    # обязана его называть - без неё вечерняя цифра читается как «ещё
    # столько же сегодня», то есть ровно наоборот.
    на_день: dt.date | None
    открытых_дней: int
    # Прошедшие дни недели без известной суммы. В расчёт они идут нулём,
    # и экран обязан сказать, сколько их: молчаливый ноль завысил бы лимит.
    дней_без_суммы: int
    бюджет_задан: bool
    потрачено: Decimal
    # Бюджет с переносом минус потраченное. Отрицательный - перерасход.
    остаток: Decimal


@dataclass(frozen=True)
class Итог:
    """Итог недели, готовой к распределению."""

    начало: dt.date
    # Положительный - излишек, отрицательный - перерасход.
    сумма: Decimal
    потрачено: Decimal
    распределена: bool


def начало_недели(день: dt.date) -> dt.date:
    """Понедельник недели, которой принадлежит день.

    Пн-вс - решение owner (2026-09-17). Границы считаются в его зоне,
    как и всё календарное: в UTC воскресный вечер уехал бы в понедельник.
    """
    return день - dt.timedelta(days=день.weekday())


def дни_недели(начало: dt.date) -> list[dt.date]:
    return [начало + dt.timedelta(days=сдвиг) for сдвиг in range(ДНЕЙ_В_НЕДЕЛЕ)]


def лимит(неделя: Неделя, сегодня: dt.date) -> Лимит:
    """Сколько можно потратить в первый открытый день недели.

        (бюджет + перенос − Σ известных трат) / число открытых дней

    Открытый день - тот, что не раньше сегодняшнего и сумма которого
    неизвестна. Отсюда два свойства, ради которых формула написана через
    «известна», а не через «сегодня»:

    - внёс трату за сегодня - сегодня вышел из делителя, и цифра стала
      про завтра (решение owner);
    - воскресенье, за которое сумма внесена, обнуляет делитель. Деления
      на ноль не происходит: лимита нет, вместо него - `итог`.

    Округление вниз, а не арифметическое: при делении 100 ₽ на 3 дня вверх
    сумма трёх лимитов дала бы 100.02 ₽, то есть разрешила бы потратить
    больше бюджета.
    """
    потрачено = неделя.потрачено
    остаток = (неделя.бюджет or НОЛЬ) + неделя.перенос - потрачено
    открытые = [день for день in неделя.дни if not день.известна and день.день >= сегодня]
    без_суммы = [день for день in неделя.дни if not день.известна and день.день < сегодня]

    сумма: Decimal | None = None
    if неделя.бюджет is not None and открытые:
        сумма = (остаток / Decimal(len(открытые))).quantize(КОПЕЙКА, rounding=ROUND_FLOOR)

    return Лимит(
        сумма=сумма,
        на_день=открытые[0].день if открытые else None,
        открытых_дней=len(открытые),
        дней_без_суммы=len(без_суммы),
        бюджет_задан=неделя.бюджет is not None,
        потрачено=потрачено,
        остаток=остаток,
    )


def готова_к_распределению(неделя: Неделя, сегодня: dt.date) -> bool:
    """Неделя прошла целиком либо все её дни уже известны.

    Второе - то самое воскресенье, когда owner внёс вечернюю трату: неделя
    учтена вся, ждать до понедельника незачем.
    """
    if неделя.бюджет is None:
        return False
    return неделя.конец < сегодня or all(день.известна for день in неделя.дни)


def итог(неделя: Неделя, сегодня: dt.date) -> Итог | None:
    """Излишек (плюс) или перерасход (минус). None - неделя ещё не готова."""
    if not готова_к_распределению(неделя, сегодня):
        return None
    потрачено = неделя.потрачено
    return Итог(
        начало=неделя.начало,
        сумма=(неделя.бюджет or НОЛЬ) + неделя.перенос - потрачено,
        потрачено=потрачено,
        распределена=неделя.распределена,
    )


def проверить_распределение(
    итог_недели: Итог, в_следующую: Decimal, в_копилку: Decimal, копилка: Decimal
) -> None:
    """Распределение обязано сойтись с итогом и быть обеспеченным.

    Два отказа, а не поправка на ходу: молча доложить недостающее значило бы
    решить за owner, куда девать его деньги, - а вся эта фича ровно про то,
    что решает он.
    """
    if в_следующую + в_копилку != итог_недели.сумма:
        raise ОшибкаРаспределения(
            f"распределено {в_следующую + в_копилку}, а итог недели {итог_недели.сумма}"
        )
    # Перерасход можно покрыть из копилки - но только тем, что в ней есть.
    # Иначе копилка ушла бы в минус, то есть стала бы долгом, которого
    # в v1 нет и который на экране назвать нечем.
    if в_копилку < НОЛЬ and копилка + в_копилку < НОЛЬ:
        raise ОшибкаРаспределения(f"из копилки нужно {-в_копилку}, а в ней {копилка}")


