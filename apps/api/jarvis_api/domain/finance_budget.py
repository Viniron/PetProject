def покрыто_по(session: Session) -> dt.date | None:
    """Последний день, по который выписки загружены **со всех** банков.

    По самому старому из банков - тем же правилом, каким §15.1 считает
    давность данных. Второе правило здесь завело бы вторую правду о том,
    что такое «загружено».

    Банк, у которого ни у одного импорта нет `period_end`, покрытия не даёт
    вовсе: его файлы не говорят, за какой период выгружены, и считать
    их покрывающими значило бы угадывать. Ни одного импорта - None.
    """
    # `max` пропускает NULL: банк, у которого период есть хотя бы у одного
    # файла, покрытие даёт. Все файлы без периода - NULL на весь банк.
    границы = session.scalars(select(func.max(FinImport.period_end)).group_by(FinImport.bank)).all()
    известные = [граница for граница in границы if граница is not None]
    if not границы or len(известные) != len(границы):
        return None
    return min(известные)


def траты_по_выписке(
    session: Session, с: dt.date, по: dt.date, зона: ZoneInfo
) -> dict[dt.date, Decimal]:
    """Расходы по дням, уменьшенные привязанными гашениями (§15.5).

    Гашение уменьшает день **исходного расхода**, а не день поступления:
    оплатил стол в понедельник, доли скинули в среду - подешевел понедельник.
    Иначе среда ушла бы в минус, а понедельник съел бы недельный лимит.

    Расход гасится до нуля, но не ниже: скинули больше, чем стоил стол -
    излишек становится доходом (§15.5), а не отрицательной тратой дня.
    """
    начало = dt.datetime.combine(с, dt.time.min, tzinfo=зона)
    конец = dt.datetime.combine(по + dt.timedelta(days=1), dt.time.min, tzinfo=зона)

    расходы = session.scalars(
        select(FinTransaction).where(
            FinTransaction.occurred_at >= начало,
            FinTransaction.occurred_at < конец,
            FinTransaction.kind == "expense",
            FinTransaction.excluded.is_(False),
            # Неразобранный кандидат в дубли в сальдо не входит (§15.5):
            # пока owner не решил, дозрела операция или это вторая покупка,
            # трата дня по ней либо завышена вдвое, либо занижена вдвое.
            FinTransaction.needs_review.is_(False),
            FinTransaction.status.in_(СТАТУСЫ_В_СЧЁТ),
        )
    ).all()
    if not расходы:
        return {}

    гашения: dict[int, Decimal] = {}
    строки = session.execute(
        select(FinTransaction.offsets_transaction_id, FinTransaction.amount_rub).where(
            FinTransaction.offsets_transaction_id.in_([расход.id for расход in расходы]),
            FinTransaction.excluded.is_(False),
            FinTransaction.needs_review.is_(False),
            FinTransaction.status.in_(СТАТУСЫ_В_СЧЁТ),
        )
    ).all()
    for расход_id, сумма in строки:
        гашения[расход_id] = гашения.get(расход_id, НОЛЬ) + сумма

    по_дням: dict[dt.date, Decimal] = {}
    for расход in расходы:
        день = расход.occurred_at.astimezone(зона).date()
        # Расход в выписке отрицателен, трата дня - положительное число.
        своя = -расход.amount_rub - гашения.get(расход.id, НОЛЬ)
        по_дням[день] = по_дням.get(день, НОЛЬ) + max(своя, НОЛЬ)
    return по_дням


def ручные_траты(session: Session, с: dt.date, по: dt.date) -> dict[dt.date, Decimal]:
    строки = session.scalars(
        select(FinDaySpend).where(FinDaySpend.day >= с, FinDaySpend.day <= по)
    ).all()
    return {строка.day: строка.amount for строка in строки}


def собрать_неделю(session: Session, начало: dt.date, зона: ZoneInfo) -> Неделя:
    """Неделя из базы: бюджет, перенос и семь дней с их источниками."""
    строка = session.scalar(select(FinWeekBudget).where(FinWeekBudget.week_start == начало))
    предыдущая = session.scalar(
        select(FinWeekBudget).where(
            FinWeekBudget.week_start == начало - dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ)
        )
    )

    конец = начало + dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ - 1)
    граница = покрыто_по(session)
    из_выписки = траты_по_выписке(session, начало, конец, зона)
    руками = ручные_траты(session, начало, конец)

    дни: list[День] = []
    for день in дни_недели(начало):
        ручная = руками.get(день)
        if граница is not None and день <= граница:
            # День покрыт выпиской. Операций в нём может не быть вовсе -
            # это ноль трат, а не «неизвестно»: банк отчитался за этот день.
            дни.append(
                День(
                    день=день,
                    сумма=из_выписки.get(день, НОЛЬ),
                    источник=ВЫПИСКА,
                    ручная=ручная,
                )
            )
        elif ручная is not None:
            дни.append(День(день=день, сумма=ручная, источник=РУЧНОЙ, ручная=ручная))
        else:
            дни.append(День(день=день, сумма=None, источник=НЕИЗВЕСТЕН, ручная=None))

    # Перенос - итог предыдущей недели, если она распределена, плюс поправки
    # задним числом. Складывается здесь, а не хранится: вторая копия
    # разошлась бы с первой, стоило owner переиграть распределение.
    перенос = НОЛЬ
    if предыдущая is not None and предыдущая.to_next is not None:
        перенос += предыдущая.to_next
    if строка is not None:
        перенос += строка.carry_adjust

    return Неделя(
        начало=начало,
        бюджет=строка.amount if строка is not None else None,
        перенос=перенос,
        дни=tuple(дни),
        распределена=строка is not None and строка.settled_at is not None,
    )


def копилка(session: Session, *, кроме: dt.date | None = None) -> Decimal:
    """Сколько отложено бюджетом - сумма решений owner по всем неделям.

    Копилка виртуальная и **не равна** статье «Отложено» из §15.5: та
    считает настоящие переводы на счета с ролью `savings`. Две цифры живут
    рядом намеренно, и экран показывает разницу между ними - это и есть
    напоминание перевести деньги на самом деле (решение owner 2026-09-17).

    `кроме` исключает вклад одной недели, и нужен он ровно при её
    переигрывании: иначе owner не смог бы забрать назад то, что сам туда
    положил, - новое решение упиралось бы в собственное прошлое.
    """
    запрос = select(FinWeekBudget.to_savings).where(FinWeekBudget.to_savings.is_not(None))
    if кроме is not None:
        запрос = запрос.where(FinWeekBudget.week_start != кроме)
    строки = session.scalars(запрос).all()
    return sum((сумма for сумма in строки if сумма is not None), НОЛЬ)


def разнести_поправки(session: Session, сегодня: dt.date, зона: ZoneInfo) -> list[dt.date]:
    """Учесть изменения трат в уже распределённых неделях.

    Гашение расхода задним числом меняет траты недели, итог которой owner
    уже распределил. Переигрывать её нельзя - решение принято, - поэтому
    разница уходит поправкой в ближайшую нераспределённую неделю,
    а снимок `settled_spend` сдвигается на новый факт.

    Сдвиг снимка - не оптимизация, а то, что делает вызов идемпотентным:
    без него одна и та же поправка применялась бы заново при каждом вызове.

    Зовётся тем, кто меняет траты (правка дня, импорт выписки), а не чтением
    экрана: побочная запись в GET сделала бы показ лимита неповторимым.

    Возвращает недели, к которым поправка применена, - для следа в логе
    джоба и для пометки на экране «пересчитано позже».
    """
    закрытые = session.scalars(
        select(FinWeekBudget)
        .where(FinWeekBudget.settled_at.is_not(None))
        .order_by(FinWeekBudget.week_start)
    ).all()

    цель = _ближайшая_нераспределённая(session, начало_недели(сегодня))
    затронуты: list[dt.date] = []

    for строка in закрытые:
        if строка.week_start >= цель.week_start:
            continue
        факт = собрать_неделю(session, строка.week_start, зона).потрачено
        снимок = строка.settled_spend if строка.settled_spend is not None else НОЛЬ
        поправка = снимок - факт
        if поправка == НОЛЬ:
            continue
        цель.carry_adjust += поправка
        строка.settled_spend = факт
        затронуты.append(строка.week_start)

    session.flush()
    return затронуты


def _ближайшая_нераспределённая(session: Session, начало: dt.date) -> FinWeekBudget:
    """Строка недели, куда можно класть поправку, - с созданием при нужде.

    Текущая неделя, а если её итог owner уже распределил - следующая:
    класть поправку в замороженную неделю значило бы менять её итог,
    ровно то, чего это правило и избегает.

    Строка может родиться без бюджета: поправка существует независимо
    от того, внёс ли owner бюджет на эту неделю. `amount` поэтому nullable.
    """
    текущая = начало
    for _ in range(2):
        строка = session.scalar(select(FinWeekBudget).where(FinWeekBudget.week_start == текущая))
        if строка is None:
            строка = FinWeekBudget(week_start=текущая, carry_adjust=НОЛЬ)
            session.add(строка)
            session.flush()
            return строка
        if строка.settled_at is None:
            return строка
        текущая += dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ)

    строка = FinWeekBudget(week_start=текущая, carry_adjust=НОЛЬ)
    session.add(строка)
    session.flush()
    return строка


# --- запись и сводка для экрана (Ф13) -------------------------------------
#
# Всё, что ниже, - запись. Ф12 умел считать, но не умел ничего менять:
# бюджет недели, сумма дня и распределение итога приезжают отсюда, и ручки
# `/api/finance/budget` только разбирают параметры и переводят отказ в код.


@dataclass(frozen=True)
class Сводка:
    """Неделя вместе со всем, что о ней сказано наружу.

    Собирается одной функцией и для экрана недели, и для списка недель
    вперёд: вторая сборка разошлась бы с первой ровно в том, как считается
    перенос, - а это деньги.
    """

    неделя: Неделя
    лимит_: Лимит
    итог_: Итог | None
    # Решение owner, если оно принято. Хранится, а не выводится из трат:
    # распределение - это то, что owner решил в своё время, и переигрывает
    # его только он сам.
    в_следующую: Decimal | None
    в_копилку: Decimal | None
    # Снимок трат на момент распределения. Расхождение со `неделя.потрачено`
    # не ошибка, а след поправки: траты закрытой недели изменились задним
    # числом, и разница уже ушла в ближайшую нераспределённую неделю.
    снимок_трат: Decimal | None
    распределена_в: dt.datetime | None


@dataclass(frozen=True)
class ЗаписьДня:
    """Что стало с днём и какие закрытые недели пришлось поправить."""

    день: dt.date
    # None после снятия: день снова «неизвестен». Это не ноль - ноль означал
    # бы «в этот день не потрачено ничего» и закрывал бы день (§15.10).
    сумма: Decimal | None
    было: Decimal | None
    поправлены: tuple[dt.date, ...]


def проверить_понедельник(начало: dt.date) -> None:
    """Неделя начинается с понедельника - это же держит CHECK в базе.

    Проверяется и здесь, потому что отказ базы приходит на коммите и без
    имени поля: owner увидел бы «нарушено ограничение», а не «22 сентября -
    вторник».
    """
    if начало.weekday() != 0:
        raise ОшибкаБюджета(
            "не_понедельник",
            f"неделя начинается с понедельника, а {начало.isoformat()} - это"
            f" {начало.strftime('%A').lower()}; ближайший: {начало_недели(начало).isoformat()}",
        )


def строка_недели(session: Session, начало: dt.date) -> FinWeekBudget | None:
    return session.scalar(select(FinWeekBudget).where(FinWeekBudget.week_start == начало))


def внести_бюджет(session: Session, *, начало: dt.date, сумма: Decimal) -> FinWeekBudget:
    """Бюджет недели: заводит строку или правит сумму существующей.

    **Распределённая неделя не правится.** Её итог уже разошёлся по двум
    адресам - в следующую неделю и в копилку, - и новая сумма бюджета
    не нашла бы, откуда взяться: перенос равен решению owner, а не
    пересчитанному итогу (§15.10). Правка молча разошлась бы с деньгами,
    поэтому здесь отказ, а не тихая запись. Ошибка в бюджете прошедшей
    недели чинится там, где деньги ещё есть, - бюджетом следующей.
    """
    проверить_понедельник(начало)
    if сумма < НОЛЬ:
        raise ОшибкаБюджета("бюджет_отрицателен", f"бюджет недели не может быть {сумма}")

    строка = строка_недели(session, начало)
    if строка is None:
        строка = FinWeekBudget(week_start=начало, amount=сумма, carry_adjust=НОЛЬ)
        session.add(строка)
    elif строка.settled_at is not None:
        raise ОшибкаБюджета(
            "неделя_распределена",
            f"итог недели {начало.isoformat()} уже распределён и заморожен:"
            " бюджет этой недели не меняется, поправьте следующую",
        )
    else:
        строка.amount = сумма
    session.flush()
    return строка


def внести_день(
    session: Session,
    *,
    день: dt.date,
    сумма: Decimal,
    заметка: str | None,
    сегодня: dt.date,
    зона: ZoneInfo,
) -> ЗаписьДня:
    """Сумма, потраченная за день, со слов owner (§15.10).

    Повторный ввод правит сумму, а не копит варианты, - одна строка на день.
    Внесённая сумма **закрывает** день: он выходит из делителя, и лимит
    после ввода означает «завтра».

    Поправки разносятся здесь же: ввод дня - один из двух путей, которым
    §15.10 поручает разнос. Делать это показом экрана нельзя - побочная
    запись в GET сделала бы показ лимита неповторимым.
    """
    if сумма < НОЛЬ:
        raise ОшибкаБюджета(
            "трата_отрицательна",
            f"трата за день не может быть {сумма}: возврат вносится не"
            " отрицательным днём, а привязкой к своей покупке",
        )

    строка = session.scalar(select(FinDaySpend).where(FinDaySpend.day == день))
    было = строка.amount if строка is not None else None
    if строка is None:
        строка = FinDaySpend(day=день, amount=сумма, note=заметка)
        session.add(строка)
    else:
        строка.amount = сумма
        строка.note = заметка
    session.flush()

    return ЗаписьДня(
        день=день,
        сумма=сумма,
        было=было,
        поправлены=tuple(разнести_поправки(session, сегодня, зона)),
    )


def снять_день(session: Session, *, день: dt.date, сегодня: dt.date, зона: ZoneInfo) -> ЗаписьДня:
    """Убрать внесённую сумму: день возвращается в «неизвестно», а не в ноль.

    Нужно ровно для одного случая, и он денежный: ошибочный ввод закрывает
    день, то есть выводит его из делителя и завышает лимит остальных дней.
    Правкой это не чинится - нолём день закрыт так же, как любой суммой.

    День, покрытый выпиской, снятием не меняется: его сумма приходит
    из операций, а строка ручного ввода остаётся видна расхождением.
    """
    строка = session.scalar(select(FinDaySpend).where(FinDaySpend.day == день))
    if строка is None:
        raise ОшибкаБюджета("нет_дня", f"за {день.isoformat()} сумма не вносилась")

    было = строка.amount
    session.delete(строка)
    session.flush()

    return ЗаписьДня(
        день=день,
        сумма=None,
        было=было,
        поправлены=tuple(разнести_поправки(session, сегодня, зона)),
    )


def распределить(
    session: Session,
    *,
    начало: dt.date,
    в_следующую: Decimal,
    в_копилку: Decimal,
    сегодня: dt.date,
    сейчас: dt.datetime,
    зона: ZoneInfo,
) -> Сводка:
    """Развести итог недели между следующей неделей и копилкой (§15.10).

    **Переигрывание разрешено** (решение owner), но меняет оно только то,
    **куда** ушёл итог, а не сколько его: сумма к раскладке берётся у самого
    прошлого решения (`to_next + to_savings`), а не считается заново.

    Причина не в педантизме, а в арифметике. Траты закрытой недели меняются
    задним числом, и разница уже ушла поправкой в ближайшую нераспределённую
    неделю, сдвинув снимок. Пересчитай итог по сегодняшнему факту - и та же
    разница досталась бы вперёд второй раз. Деньги, посчитанные дважды,
    выглядят правдоподобно и потому хуже пустоты (§10).

    Копилка при проверке считается **без вклада этой же недели**: иначе
    owner не смог бы забрать назад то, что сам туда положил, - повторное
    решение упиралось бы в собственную прошлую щедрость.
    """
    проверить_понедельник(начало)
    неделя = собрать_неделю(session, начало, зона)
    строка = строка_недели(session, начало)

    if неделя.бюджет is None:
        raise ОшибкаБюджета(
            "бюджет_не_задан",
            f"на неделю {начало.isoformat()} бюджет не внесён: распределять нечего",
        )
    if not готова_к_распределению(неделя, сегодня):
        неизвестных = sum(1 for день in неделя.дни if not день.известна)
        raise ОшибкаБюджета(
            "неделя_не_готова",
            f"неделя {начало.isoformat()} ещё идёт: неизвестны суммы за"
            f" {неизвестных} дн. Внесите их или дождитесь конца недели",
        )

    assert строка is not None  # бюджет задан - значит строка есть
    переигрывается = (
        строка.settled_at is not None
        and строка.to_next is not None
        and строка.to_savings is not None
        and строка.settled_spend is not None
    )
    if переигрывается:
        assert строка.to_next is not None and строка.to_savings is not None
        assert строка.settled_spend is not None
        это = Итог(
            начало=начало,
            сумма=строка.to_next + строка.to_savings,
            потрачено=строка.settled_spend,
            распределена=True,
        )
    else:
        это = Итог(
            начало=начало,
            сумма=неделя.бюджет + неделя.перенос - неделя.потрачено,
            потрачено=неделя.потрачено,
            распределена=False,
        )

    проверить_распределение(
        это, в_следующую, в_копилку, копилка(session, кроме=начало if переигрывается else None)
    )

    строка.to_next = в_следующую
    строка.to_savings = в_копилку
    # Снимок ставится один раз, при первом решении, и дальше его двигает
    # только разнос поправок. Переписать его переигрыванием значило бы
    # объявить «фактом на момент решения» то, чем факт стал позже.
    строка.settled_spend = это.потрачено
    строка.settled_at = сейчас
    session.flush()

    return сводка(session, начало, сегодня=сегодня, зона=зона)


def сводка(session: Session, начало: dt.date, *, сегодня: dt.date, зона: ZoneInfo) -> Сводка:
    """Всё об одной неделе разом: дни, лимит, итог и решение owner."""
    проверить_понедельник(начало)
    неделя = собрать_неделю(session, начало, зона)
    строка = строка_недели(session, начало)
    return Сводка(
        неделя=неделя,
        лимит_=лимит(неделя, сегодня),
        итог_=итог(неделя, сегодня),
        в_следующую=строка.to_next if строка is not None else None,
        в_копилку=строка.to_savings if строка is not None else None,
        снимок_трат=строка.settled_spend if строка is not None else None,
        распределена_в=строка.settled_at if строка is not None else None,
    )


def сводки(
    session: Session, *, с: dt.date, сколько: int, сегодня: dt.date, зона: ZoneInfo
) -> list[Сводка]:
    """Подряд идущие недели - экрану, где бюджет вносится на месяц вперёд.

    Недели, которой нет в базе, здесь не пропускается: «бюджет не задан» -
    это ответ, а дыра в списке выглядела бы как сбой выборки.
    """
    проверить_понедельник(с)
    return [
        сводка(session, с + dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ * сдвиг), сегодня=сегодня, зона=зона)
        for сдвиг in range(сколько)
    ]
