def покрыто_по(session: Session) -> dt.date | None:
    """Последний день, по который выписки загружены **со всех** банков.

    По самому старому из банков - тем же правилом, каким §15.1 считает
    давность данных. Второе правило здесь завело бы вторую правду о том,
    что такое «загружено».

    Банк, у которого ни у одного импорта нет `period_end`, покрытия не даёт
    вовсе: его файлы не говорят, за какой период выгружены, и считать
    их покрывающими значило бы угадывать. Ни одного импорта - None.
    """
    # `max` пропускает NULL: банк, у которого период есть хотя бы у одного
    # файла, покрытие даёт. Все файлы без периода - NULL на весь банк.
    границы = session.scalars(select(func.max(FinImport.period_end)).group_by(FinImport.bank)).all()
    известные = [граница for граница in границы if граница is not None]
    if not границы or len(известные) != len(границы):
        return None
    return min(известные)


def траты_по_выписке(
    session: Session, с: dt.date, по: dt.date, зона: ZoneInfo
) -> dict[dt.date, Decimal]:
    """Расходы по дням, уменьшенные привязанными гашениями (§15.5).

    Гашение уменьшает день **исходного расхода**, а не день поступления:
    оплатил стол в понедельник, доли скинули в среду - подешевел понедельник.
    Иначе среда ушла бы в минус, а понедельник съел бы недельный лимит.

    Расход гасится до нуля, но не ниже: скинули больше, чем стоил стол -
    излишек становится доходом (§15.5), а не отрицательной тратой дня.
    """
    начало = dt.datetime.combine(с, dt.time.min, tzinfo=зона)
    конец = dt.datetime.combine(по + dt.timedelta(days=1), dt.time.min, tzinfo=зона)

    расходы = session.scalars(
        select(FinTransaction).where(
            FinTransaction.occurred_at >= начало,
            FinTransaction.occurred_at < конец,
            FinTransaction.kind == "expense",
            FinTransaction.excluded.is_(False),
            # Неразобранный кандидат в дубли в сальдо не входит (§15.5):
            # пока owner не решил, дозрела операция или это вторая покупка,
            # трата дня по ней либо завышена вдвое, либо занижена вдвое.
            FinTransaction.needs_review.is_(False),
            FinTransaction.status.in_(СТАТУСЫ_В_СЧЁТ),
        )
    ).all()
    if not расходы:
        return {}

    гашения: dict[int, Decimal] = {}
    строки = session.execute(
        select(FinTransaction.offsets_transaction_id, FinTransaction.amount_rub).where(
            FinTransaction.offsets_transaction_id.in_([расход.id for расход in расходы]),
            FinTransaction.excluded.is_(False),
            FinTransaction.needs_review.is_(False),
            FinTransaction.status.in_(СТАТУСЫ_В_СЧЁТ),
        )
    ).all()
    for расход_id, сумма in строки:
        гашения[расход_id] = гашения.get(расход_id, НОЛЬ) + сумма

    по_дням: dict[dt.date, Decimal] = {}
    for расход in расходы:
        день = расход.occurred_at.astimezone(зона).date()
        # Расход в выписке отрицателен, трата дня - положительное число.
        своя = -расход.amount_rub - гашения.get(расход.id, НОЛЬ)
        по_дням[день] = по_дням.get(день, НОЛЬ) + max(своя, НОЛЬ)
    return по_дням


def ручные_траты(session: Session, с: dt.date, по: dt.date) -> dict[dt.date, Decimal]:
    строки = session.scalars(
        select(FinDaySpend).where(FinDaySpend.day >= с, FinDaySpend.day <= по)
    ).all()
    return {строка.day: строка.amount for строка in строки}


def собрать_неделю(session: Session, начало: dt.date, зона: ZoneInfo) -> Неделя:
    """Неделя из базы: бюджет, перенос и семь дней с их источниками."""
    строка = session.scalar(select(FinWeekBudget).where(FinWeekBudget.week_start == начало))
    предыдущая = session.scalar(
        select(FinWeekBudget).where(
            FinWeekBudget.week_start == начало - dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ)
        )
    )

    конец = начало + dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ - 1)
    граница = покрыто_по(session)
    из_выписки = траты_по_выписке(session, начало, конец, зона)
    руками = ручные_траты(session, начало, конец)

    дни: list[День] = []
    for день in дни_недели(начало):
        ручная = руками.get(день)
        if граница is not None and день <= граница:
            # День покрыт выпиской. Операций в нём может не быть вовсе -
            # это ноль трат, а не «неизвестно»: банк отчитался за этот день.
            дни.append(
                День(
                    день=день,
                    сумма=из_выписки.get(день, НОЛЬ),
                    источник=ВЫПИСКА,
                    ручная=ручная,
                )
            )
        elif ручная is not None:
            дни.append(День(день=день, сумма=ручная, источник=РУЧНОЙ, ручная=ручная))
        else:
            дни.append(День(день=день, сумма=None, источник=НЕИЗВЕСТЕН, ручная=None))

    # Перенос - итог предыдущей недели, если она распределена, плюс поправки
    # задним числом. Складывается здесь, а не хранится: вторая копия
    # разошлась бы с первой, стоило owner переиграть распределение.
    перенос = НОЛЬ
    if предыдущая is not None and предыдущая.to_next is not None:
        перенос += предыдущая.to_next
    if строка is not None:
        перенос += строка.carry_adjust

    return Неделя(
        начало=начало,
        бюджет=строка.amount if строка is not None else None,
        перенос=перенос,
        дни=tuple(дни),
        распределена=строка is not None and строка.settled_at is not None,
    )


def копилка(session: Session) -> Decimal:
    """Сколько отложено бюджетом - сумма решений owner по всем неделям.

    Копилка виртуальная и **не равна** статье «Отложено» из §15.5: та
    считает настоящие переводы на счета с ролью `savings`. Две цифры живут
    рядом намеренно, и экран показывает разницу между ними - это и есть
    напоминание перевести деньги на самом деле (решение owner 2026-09-17).
    """
    строки = session.scalars(
        select(FinWeekBudget.to_savings).where(FinWeekBudget.to_savings.is_not(None))
    ).all()
    return sum((сумма for сумма in строки if сумма is not None), НОЛЬ)


def разнести_поправки(session: Session, сегодня: dt.date, зона: ZoneInfo) -> list[dt.date]:
    """Учесть изменения трат в уже распределённых неделях.

    Гашение расхода задним числом меняет траты недели, итог которой owner
    уже распределил. Переигрывать её нельзя - решение принято, - поэтому
    разница уходит поправкой в ближайшую нераспределённую неделю,
    а снимок `settled_spend` сдвигается на новый факт.

    Сдвиг снимка - не оптимизация, а то, что делает вызов идемпотентным:
    без него одна и та же поправка применялась бы заново при каждом вызове.

    Зовётся тем, кто меняет траты (правка дня, импорт выписки), а не чтением
    экрана: побочная запись в GET сделала бы показ лимита неповторимым.

    Возвращает недели, к которым поправка применена, - для следа в логе
    джоба и для пометки на экране «пересчитано позже».
    """
    закрытые = session.scalars(
        select(FinWeekBudget)
        .where(FinWeekBudget.settled_at.is_not(None))
        .order_by(FinWeekBudget.week_start)
    ).all()

    цель = _ближайшая_нераспределённая(session, начало_недели(сегодня))
    затронуты: list[dt.date] = []

    for строка in закрытые:
        if строка.week_start >= цель.week_start:
            continue
        факт = собрать_неделю(session, строка.week_start, зона).потрачено
        снимок = строка.settled_spend if строка.settled_spend is not None else НОЛЬ
        поправка = снимок - факт
        if поправка == НОЛЬ:
            continue
        цель.carry_adjust += поправка
        строка.settled_spend = факт
        затронуты.append(строка.week_start)

    session.flush()
    return затронуты


def _ближайшая_нераспределённая(session: Session, начало: dt.date) -> FinWeekBudget:
    """Строка недели, куда можно класть поправку, - с созданием при нужде.

    Текущая неделя, а если её итог owner уже распределил - следующая:
    класть поправку в замороженную неделю значило бы менять её итог,
    ровно то, чего это правило и избегает.

    Строка может родиться без бюджета: поправка существует независимо
    от того, внёс ли owner бюджет на эту неделю. `amount` поэтому nullable.
    """
    текущая = начало
    for _ in range(2):
        строка = session.scalar(select(FinWeekBudget).where(FinWeekBudget.week_start == текущая))
        if строка is None:
            строка = FinWeekBudget(week_start=текущая, carry_adjust=НОЛЬ)
            session.add(строка)
            session.flush()
            return строка
        if строка.settled_at is None:
            return строка
        текущая += dt.timedelta(days=ДНЕЙ_В_НЕДЕЛЕ)

    строка = FinWeekBudget(week_start=текущая, carry_adjust=НОЛЬ)
    session.add(строка)
    session.flush()
    return строка
