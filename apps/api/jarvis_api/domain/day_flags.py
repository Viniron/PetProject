"""Периоды исключений `day_flags` (§2.5): чтение и правила причины.

Причина - свободное слово, а не перечисление. Словаря причин нет нигде:
экран внесения периодов (этап 9 дизайна) не нарисован, а в утверждённом
макете календаря видно «отъезд» - то есть буквально то, что owner напечатал.
Придумать перечисление сейчас значило бы придумать содержание, которого owner
не задавал. Колонка остаётся `String(64)` без CHECK намеренно: словарь причин
будет меняться, а CHECK ради нового слова ничего не защищает.

Цена решения названа честно: опечатка даёт вторую причину, и группировка по
причинам невозможна. Сегодня по ним никто не группирует - §4 фильтрует одну
`late_classes`, а отставание считает дни, не причины.
"""

import datetime as dt
from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.orm import Session

from jarvis_api.db.models import AuditLogEntry, DayFlag

# Единственная причина, которую ставит система, а не owner (§2.5, §4). У неё
# в базе свой частичный уникальный индекс - повторный прогон джоба не должен
# множить строки на один день. Руками она не вносится и не снимается: §4
# в календарный релиз не входит, и снятая руками пометка вернулась бы сама.
АВТОПОМЕТКА = "late_classes"

# Колонка `audit_log.actor` описана как «имя джоба или эндпоинта» - это
# первый эндпоинт, который туда пишет.
АКТОР = "api.day_flags"

# Ограничения полей повторяют колонки (`db/models.py`): проверка в Pydantic
# нужна, чтобы длинная причина давала внятный 422, а не DataError из драйвера,
# который в Postgres приходит отдельным от IntegrityError типом.
ПРЕДЕЛ_ПРИЧИНЫ = 64
ПРЕДЕЛ_ЗАМЕТКИ = 256


@dataclass(frozen=True)
class Пометка:
    """Период исключений в том виде, в каком его отдают наружу.

    Живёт здесь, а не в `calendar.py`, хотя день сетки показывает именно её:
    признак `manual` считается из `АВТОПОМЕТКА`, и правило обязано быть
    в одном месте с самой константой. Разъехавшись, они дали бы период,
    который в сетке «системный», а в списке периодов «ручной».
    """

    id: int
    reason: str
    note: str | None
    starts_on: dt.date
    ends_on: dt.date
    # От этого признака зависит текст объяснения на экране дня: период,
    # внесённый owner, и пометка, проставленная системой, читаются по-разному.
    manual: bool


def из_строки(строка: DayFlag) -> Пометка:
    """Строка базы наружу. Единственное место, где решается `manual`."""
    return Пометка(
        id=строка.id,
        reason=строка.reason,
        note=строка.note,
        starts_on=строка.starts_on,
        ends_on=строка.ends_on,
        manual=строка.reason != АВТОПОМЕТКА,
    )


def пометки(session: Session, начало: dt.date, конец: dt.date) -> list[DayFlag]:
    """Периоды, **пересекающие** интервал, а не лежащие внутри него.

    «Отъезд с 10 по 20 октября» обязан быть виден на неделе 12-18, иначе
    экран покажет обычную неделю посреди периода исключений. Границы
    включительные с обеих сторон: `ends_on` включительная по модели.
    """
    запрос = (
        select(DayFlag)
        .where(DayFlag.starts_on <= конец, DayFlag.ends_on >= начало)
        .order_by(DayFlag.starts_on, DayFlag.id)
    )
    return list(session.scalars(запрос))


def найти(session: Session, id_: int) -> DayFlag | None:
    """Период по идентификатору. `None` - решение о 404 принимает слой `api/`."""
    return session.get(DayFlag, id_)


def создать(
    session: Session,
    *,
    starts_on: dt.date,
    ends_on: dt.date,
    reason: str,
    note: str | None,
) -> DayFlag:
    """Внести период. Коммит - на вызывающем (§11.2).

    Проверки причины и порядка дат сюда не дублируются: они живут в
    `DayFlagIn` и в ограничениях базы. Две проверки в трёх местах разошлись
    бы, а разошедшаяся проверка хуже отсутствующей.

    `flush` нужен до аудита: строка аудита называет `id` периода, а до
    вставки его не существует. Обе строки уходят одной транзакцией -
    период без следа в аудите означал бы, что на вопрос «откуда взялась
    эта неделя исключений» ответить нечем.
    """
    строка = DayFlag(starts_on=starts_on, ends_on=ends_on, reason=reason, note=note)
    session.add(строка)
    session.flush()
    _записать_в_аудит(session, "created", строка)
    return строка


def удалить(session: Session, строка: DayFlag) -> None:
    """Убрать период. Коммит - на вызывающем.

    Аудит пишется до удаления: после него у строки нет ни `id`, ни причины,
    а именно они и составляют ответ на вопрос «что тут было».
    """
    _записать_в_аудит(session, "deleted", строка)
    session.delete(строка)


def _записать_в_аудит(session: Session, действие: str, строка: DayFlag) -> None:
    """След ручной правки периодов (инвариант 8, комментарий `audit_log.actor`).

    Пишется только на запись. Чтение сетки следа не оставляет: аудит нужен
    там, где состояние изменилось, а не там, где его показали, - иначе
    журнал заполняется открытиями экрана, и найти в нём правку owner
    становится нечем.
    """
    session.add(
        AuditLogEntry(
            kind="day_flag_write",
            actor=АКТОР,
            status="ok",
            target=str(строка.id),
            detail={
                "action": действие,
                "reason": строка.reason,
                "starts_on": строка.starts_on.isoformat(),
                "ends_on": строка.ends_on.isoformat(),
                "note": строка.note,
            },
        )
    )
