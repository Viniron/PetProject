"""Сверка выписки с книжкой: что добавить, что обновить, что отменить (§15.3).

Ни базы, ни файлов: на вход - строки, отданные адаптером, и то, что книжка
уже знает про этот банк за этот период. Причина отделения не в чистоте слоёв,
а в том, что здесь считаются деньги owner. Ошибка сверки не падает, а тихо
искажает суммы: обнаружится через месяцы и не лечится переимпортом. Такое
проверяется прямым вызовом на выдуманных краях, а не прогоном по живой базе.

Четыре правила, из которых следует всё остальное.

**Дедупликация по кратности, а не по факту.** Выгрузки за перекрывающиеся
периоды - норма, поэтому одна и та же операция приезжает много раз.
Но **две одинаковые покупки в один день законны**: два кофе по 200 рублей
в одном месте дают один `fingerprint` и две настоящие операции. Поэтому
сравнивается число строк с этим ключом в файле и число уже лежащих в базе,
а добавляется разница. «Есть такая - пропустить» теряет деньги owner.

**Банк в ключе обязателен** (ADR-030). Без него одинаковая покупка из двух
банков попала бы в одну группу кратности, и правило «добавить разницу»
добавило бы ноль строк вместо одной.

**Ожидающая операция обновляется, а не дублируется.** `pending` в следующей
выгрузке приходит как `posted`, и сумма могла измениться - валютная покупка,
чаевые, отель. По `fingerprint` это не ловится: сумма входит в хэш. Поэтому
остатки сверяются вторым проходом - по дате, карте и описанию мимо суммы.

**Неоднозначность не решается угадыванием.** Два ожидающих кандидата на одну
свежую строку - это либо дозревание, либо вторая настоящая покупка, и выбор
между ними стоит денег. Оба конца уходят в разбор и остаются вне сальдо:
тихо смержить и тихо задвоить одинаково запрещено (§15.6).

Чего здесь нет намеренно: категорий и правил (Ф4), разделения `transfer`
и `refund` (Ф4), сальдо (Ф5). Сверка отвечает на один вопрос - какие строки
книжки соответствуют этому файлу.
"""

import datetime as dt
import hashlib
from collections.abc import Sequence
from dataclasses import dataclass, field
from decimal import Decimal
from zoneinfo import ZoneInfo

from jarvis_api.integrations.statements.base import StatementRow

# Части ключа склеиваются через символ, которого не бывает в данных банка.
# Обычный разделитель вроде «|» дал бы одинаковый ключ у двух разных
# операций, если он встретится в названии мерчанта: «А|Б» + «В» и «А» +
# «Б|В» склеиваются в одну строку.
РАЗДЕЛИТЕЛЬ = "\x1f"

# Деньги в ключе - ровно с той точностью, с какой они лежат в базе.
# `numeric(12,2)` возвращает `Decimal('-330.00')`, а адаптер мог отдать
# `Decimal('-330.0')`: строки разные, ключ разошёлся бы после первого же
# круга «записали - прочитали», и переимпорт добавил бы всё заново.
КОПЕЙКА = Decimal("0.01")

# Статус, ради которого существует второй проход сверки.
ОЖИДАЕТ = "pending"
ОТМЕНЕНА = "reverted"


def отпечаток(
    банк: str,
    occurred_at: dt.datetime,
    amount: Decimal,
    currency: str,
    merchant: str | None,
    card_last4: str | None,
) -> str:
    """Ключ дедупликации: банк, дата, сумма, валюта, описание, хвост карты.

    Идентификатор операции есть только у Ozon Bank (номер документа),
    и одного банка мало: ключ общий для всех, поэтому он собирается
    из полей, которые есть у каждого. **Время до секунды обязательно:** в настоящей
    выгрузке за август полных совпадений ключа нет ни одного именно
    из-за секунд, но совпадений по дню, сумме и описанию - две пары
    (575 рублей 23 августа и 65 рублей 2 августа). Огрубив время, мы бы
    объявили четыре настоящие операции двумя.

    Дата приводится к UTC: в базе она лежит в UTC (инвариант 7), и ключ,
    посчитанный до и после записи, обязан совпасть.
    """
    части = (
        банк,
        occurred_at.astimezone(dt.UTC).isoformat(),
        str(amount.quantize(КОПЕЙКА)),
        currency,
        merchant or "",
        card_last4 or "",
    )
    return hashlib.sha256(РАЗДЕЛИТЕЛЬ.join(части).encode("utf-8")).hexdigest()


@dataclass(frozen=True, slots=True)
class Существующая:
    """Операция книжки в том виде, в каком её видит сверка.

    Не ORM-объект: планирование проверяется без базы вовсе. Полей ровно
    шесть - те, по которым операция ищется; сумма среди них не нужна,
    потому что она уже внутри `fingerprint`.
    """

    id: int
    fingerprint: str
    occurrence_no: int
    status: str
    occurred_at: dt.datetime
    card_last4: str | None
    merchant: str | None


@dataclass(frozen=True, slots=True)
class Новая:
    """Строка файла, которой в книжке нет."""

    строка: StatementRow
    fingerprint: str
    # Номер внутри группы одинаковых операций. Единица - не «единственная»,
    # а «первая из сколько-нибудь».
    occurrence_no: int
    # Второй конец неоднозначного дозревания: строку добавляем, но в сальдо
    # она не входит, пока owner не решит (§15.6).
    в_разбор: bool = False


@dataclass(frozen=True, slots=True)
class Обновление:
    """Операция книжки, которую этот файл меняет.

    Два случая в одном типе: дозревание со сменой суммы и смена одного
    статуса. Отличаются флагом, потому что для owner это разные новости -
    «банк провёл покупку на другую сумму» и «банк провёл покупку».
    """

    id: int
    строка: StatementRow
    fingerprint: str
    было: str
    стало: str
    сумма_менялась: bool


@dataclass(slots=True)
class ПланИмпорта:
    """Что файл сделает с книжкой. Считается одинаково в dry-run и в --apply."""

    новые: list[Новая] = field(default_factory=list)
    обновления: list[Обновление] = field(default_factory=list)
    # Строки, пропавшие из выгрузки за тот же период: помечаются `reverted`,
    # а не удаляются. История правок сальдо важнее аккуратности таблицы.
    отменённые: list[int] = field(default_factory=list)
    # Строки книжки, ушедшие в разбор: неоднозначные кандидаты на дозревание.
    в_разбор: list[int] = field(default_factory=list)
    неизменных: int = 0

    @property
    def есть_изменения(self) -> bool:
        return bool(self.новые or self.обновления or self.отменённые or self.в_разбор)


def спланировать(
    банк: str,
    существующие: Sequence[Существующая],
    свежие: Sequence[StatementRow],
    зона: ZoneInfo,
) -> ПланИмпорта:
    """Сверяет файл с книжкой. Ничего не меняет - только решает, что менять.

    `существующие` - операции **этого банка за период файла**, кроме
    введённых руками: наличные и переводы с рук на руки ни в одной выписке
    не появятся, и пометить их отменёнными значило бы стереть из сальдо
    ровно то, чего в файлах не бывает.
    """
    план = ПланИмпорта()
    ключи = [
        отпечаток(банк, с.occurred_at, с.amount, с.currency, с.merchant, с.card_last4)
        for с in свежие
    ]

    свежие_по_ключу: dict[str, list[int]] = {}
    for индекс, ключ in enumerate(ключи):
        свежие_по_ключу.setdefault(ключ, []).append(индекс)

    старые_по_ключу: dict[str, list[Существующая]] = {}
    for операция in существующие:
        старые_по_ключу.setdefault(операция.fingerprint, []).append(операция)
    for группа in старые_по_ключу.values():
        группа.sort(key=lambda о: о.occurrence_no)

    свободные_свежие: list[int] = []
    свободные_старые: list[Существующая] = []

    # Первый проход - кратность. Ключи перебираются отсортированными, чтобы
    # дифф dry-run был одинаков от запуска к запуску: owner его читает.
    for ключ in sorted(set(свежие_по_ключу) | set(старые_по_ключу)):
        свежая_группа = свежие_по_ключу.get(ключ, [])
        старая_группа = старые_по_ключу.get(ключ, [])
        пар = min(len(свежая_группа), len(старая_группа))
        for позиция in range(пар):
            строка = свежие[свежая_группа[позиция]]
            старая = старая_группа[позиция]
            # Пара с совпавшим ключом - это одна и та же операция: сумма,
            # дата, описание и карта уже внутри ключа. Меняться может только
            # статус - в том числе обратно из `reverted`, если банк вернул
            # операцию в выгрузку.
            if старая.status != строка.status:
                план.обновления.append(
                    Обновление(
                        id=старая.id,
                        строка=строка,
                        fingerprint=ключ,
                        было=старая.status,
                        стало=строка.status,
                        сумма_менялась=False,
                    )
                )
            else:
                план.неизменных += 1
        свободные_свежие.extend(свежая_группа[пар:])
        свободные_старые.extend(старая_группа[пар:])

    занятые_свежие, неоднозначные_свежие, занятые_старые = _дозревание(
        план, свободные_свежие, свободные_старые, свежие, ключи, зона
    )

    # Остаток книжки: операция была, в новой выгрузке за тот же период её нет.
    for старая in свободные_старые:
        if старая.id in занятые_старые:
            continue
        if старая.status == ОТМЕНЕНА:
            план.неизменных += 1  # уже помечена прошлым импортом
            continue
        план.отменённые.append(старая.id)

    # Остаток файла: новые операции. Номер внутри группы продолжает
    # существующие, а не начинается с единицы, - иначе вторая одинаковая
    # покупка столкнулась бы с первой по ключу `(bank, fingerprint,
    # occurrence_no)` и импорт упал бы на ограничении базы.
    счётчики = {
        ключ: max(о.occurrence_no for о in группа) for ключ, группа in старые_по_ключу.items()
    }
    for индекс in sorted(свободные_свежие):
        if индекс in занятые_свежие:
            continue
        ключ = ключи[индекс]
        счётчики[ключ] = счётчики.get(ключ, 0) + 1
        план.новые.append(
            Новая(
                строка=свежие[индекс],
                fingerprint=ключ,
                occurrence_no=счётчики[ключ],
                в_разбор=индекс in неоднозначные_свежие,
            )
        )

    план.отменённые.sort()
    план.в_разбор.sort()
    return план


def _дозревание(
    план: ПланИмпорта,
    свободные_свежие: Sequence[int],
    свободные_старые: Sequence[Существующая],
    свежие: Sequence[StatementRow],
    ключи: Sequence[str],
    зона: ZoneInfo,
) -> tuple[set[int], set[int], set[int]]:
    """Второй проход: `pending` → `posted` с изменившейся суммой (§15.3).

    Ключ здесь другой - дата, карта и описание, **без суммы**: она и есть
    то, что изменилось. День считается в зоне owner, а не в UTC: банк
    вправе переписать время, когда проводит покупку, и ночная операция
    иначе разъехалась бы на двое суток.

    Возвращает три множества: занятые строки файла, из них неоднозначные,
    и занятые строки книжки. Занятая строка книжки не помечается отменённой,
    даже если пары ей не нашлось, - неоднозначность это не отмена.
    """

    def ключ_дозревания(
        occurred_at: dt.datetime, card_last4: str | None, merchant: str | None
    ) -> tuple[dt.date, str, str]:
        return (occurred_at.astimezone(зона).date(), card_last4 or "", merchant or "")

    ожидающие: dict[tuple[dt.date, str, str], list[Существующая]] = {}
    for старая in свободные_старые:
        if старая.status != ОЖИДАЕТ:
            continue
        ключ = ключ_дозревания(старая.occurred_at, старая.card_last4, старая.merchant)
        ожидающие.setdefault(ключ, []).append(старая)

    кандидаты: dict[tuple[dt.date, str, str], list[int]] = {}
    for индекс in свободные_свежие:
        строка = свежие[индекс]
        ключ = ключ_дозревания(строка.occurred_at, строка.card_last4, строка.merchant)
        кандидаты.setdefault(ключ, []).append(индекс)

    занятые_свежие: set[int] = set()
    неоднозначные: set[int] = set()
    занятые_старые: set[int] = set()

    for ключ in sorted(ожидающие):
        старые = ожидающие[ключ]
        свежие_кандидаты = кандидаты.get(ключ, [])
        if not свежие_кандидаты:
            continue  # операция пропала из выгрузки - это отмена, не дозревание
        if len(старые) == 1 and len(свежие_кандидаты) == 1:
            индекс = свежие_кандидаты[0]
            строка = свежие[индекс]
            старая = старые[0]
            план.обновления.append(
                Обновление(
                    id=старая.id,
                    строка=строка,
                    fingerprint=ключи[индекс],
                    было=старая.status,
                    стало=строка.status,
                    сумма_менялась=True,
                )
            )
            занятые_свежие.add(индекс)
            занятые_старые.add(старая.id)
            continue
        # Кандидатов больше одного с какой-то стороны: дозрело ли ожидание
        # или это вторая настоящая покупка - из файла не видно. Оба конца
        # в разбор: строка книжки остаётся ожидающей, строка файла заводится
        # новой, и обе не входят в сальдо, пока owner не решит.
        план.в_разбор.extend(старая.id for старая in старые)
        занятые_старые.update(старая.id for старая in старые)
        неоднозначные.update(свежие_кандидаты)

    return занятые_свежие, неоднозначные, занятые_старые
