"""Ручная правка операции: вид, категория, исключение, заметка (Ф6, §15.4).

Пятая ступень разбора - owner. Правка ставит `manual` источником решения,
и следующий `finance-categorize` такую строку не пересматривает (§15.4):
ровно этим ручное решение отличается от решения правила.

**Правка не ограничена окном пересчёта.** Окно §15.5 держит гашение: оно
меняет месяц чужого расхода задним числом. Здесь месяц свой, и запрет правки
означал бы, что неразобранные строки августа останутся в очереди навсегда -
очередь разбора живёт ровно столько, сколько owner до неё добирается.
Цена названа: правка вида в старом месяце меняет его сальдо, и месяц,
объявленный §15.5 окончательным, перестаёт быть таким по решению owner.

**Запоминание решения - отдельный флаг, по умолчанию выключен** (решение
owner на Ф4а). Разовое исключение не должно расползаться на весь поток:
«этот перевод от брата - доход» и «все переводы с этим именем - доход» -
разные утверждения, и второе owner делает осознанно.

**Правило применяется не здесь.** Заведённое правило меняет только будущий
разбор; книжку по нему пересчитывает `POST /finance/recategorize`. Иначе
галочка на карточке одной операции молча меняла бы сальдо двух месяцев.
"""

import datetime as dt
from dataclasses import dataclass, field
from typing import Any
from zoneinfo import ZoneInfo

from sqlalchemy.orm import Session

from jarvis_api.db.models import FinCategory, FinTransaction
from jarvis_api.domain import finance_rules

# Виды операции (CHECK `kind_known`).
ВИДЫ = ("expense", "income", "transfer", "refund")

# Источник решения, которое разбор не пересматривает.
ВРУЧНУЮ = "manual"

# Маркер «поле не передано». Отличать его от `None` обязательно: `None`
# у заметки и категории - это законное значение «снять», а не «не трогать».
НЕ_ЗАДАНО: Any = object()


class ОшибкаПравки(ValueError):
    """Правка отклонена. С кодом - из него собирается тело отказа API."""

    def __init__(self, код: str, сообщение: str) -> None:
        super().__init__(сообщение)
        self.код = код


@dataclass(frozen=True, slots=True)
class Правка:
    """Что изменилось и что из этого запомнено правилом."""

    id: int
    изменилось: bool
    поля: list[str] = field(default_factory=list)
    правила: list[int] = field(default_factory=list)
    предупреждения: list[str] = field(default_factory=list)


def _месяц(момент: dt.datetime, зона: ZoneInfo) -> dt.date:
    """Первое число месяца операции в зоне owner (инвариант 7)."""
    return момент.astimezone(зона).date().replace(day=1)


def _категория(
    session: Session, номер: int, операция: FinTransaction, зона: ZoneInfo
) -> FinCategory:
    """Категория для этой операции: существующая и её месяца.

    Месяц проверяется, потому что набор категорий - версия месяца (§15.4):
    категория сентября, поставленная августовской операции, сделала бы
    сравнение месяцев по стабильному ключу (§15.9) бессмысленным, а в отчёте
    август ссылался бы на набор, которого у него не было.
    """
    категория = session.get(FinCategory, номер)
    if категория is None:
        raise ОшибкаПравки("нет_категории", f"категории {номер} в книжке нет")
    свой = _месяц(операция.occurred_at, зона)
    if категория.period_month != свой:
        raise ОшибкаПравки(
            "категория_другого_месяца",
            f"категория {категория.key!r} принадлежит набору"
            f" {категория.period_month:%Y-%m}, а операция - месяцу {свой:%Y-%m}",
        )
    return категория


def _запомнить(
    session: Session,
    операция: FinTransaction,
    *,
    вид_изменён: bool,
    категория: FinCategory | None,
) -> tuple[list[int], list[str]]:
    """Заводит правила по только что сделанной правке (§15.4, §15.5).

    Два правила разных ступеней: вид запоминается правилом отправителя,
    категория - правилом мерчанта. Образец у обоих один - написание из
    колонки «Описание», то есть ровно то, с чем сопоставляет разбор.
    """
    образец = (операция.merchant or "").strip()
    if not образец:
        raise ОшибкаПравки(
            "нет_образца",
            "запомнить решение не по чему: в операции пусто поле «Описание»,"
            " а правило сопоставляется именно с ним",
        )

    правила: list[int] = []
    предупреждения: list[str] = []

    if вид_изменён:
        if операция.kind not in finance_rules.ВИДЫ:
            raise ОшибкаПравки(
                "вид_не_запоминается",
                f"правилом запоминается только {' или '.join(finance_rules.ВИДЫ)}:"
                f" вид {операция.kind!r} решается знаком суммы или парой концов",
            )
        правило, изменилось = finance_rules.создать(
            session,
            rule_type="sender",
            pattern=образец,
            kind=операция.kind,
            переписать=True,
        )
        правила.append(правило.id)
        if not изменилось:
            предупреждения.append(f"правило отправителя для {образец!r} уже было таким")

    if категория is not None:
        правило, изменилось = finance_rules.создать(
            session,
            rule_type="merchant",
            pattern=образец,
            category_key=категория.key,
            переписать=True,
        )
        правила.append(правило.id)
        if not изменилось:
            предупреждения.append(f"правило мерчанта для {образец!r} уже было таким")

    if not правила:
        raise ОшибкаПравки(
            "нечего_запоминать",
            "запоминать нечего: правилом заводятся вид и категория,"
            " а в этой правке не менялось ни то, ни другое",
        )
    предупреждения.append(
        "правило заведено, но книжка по нему не пересчитана:"
        " это отдельное действие (POST /api/finance/recategorize)"
    )
    return правила, предупреждения


def править(
    session: Session,
    *,
    tx_id: int,
    зона: ZoneInfo,
    kind: str | None = НЕ_ЗАДАНО,
    category_id: int | None = НЕ_ЗАДАНО,
    excluded: bool | None = НЕ_ЗАДАНО,
    needs_review: bool | None = НЕ_ЗАДАНО,
    note: str | None = НЕ_ЗАДАНО,
    запомнить: bool = False,
) -> Правка:
    """Правит операцию решением owner. Транзакцию коммитит вызывающий код.

    Переданными считаются только те поля, что не остались `НЕ_ЗАДАНО`:
    экран правит одно поле карточки, а не переприсылает её целиком, и
    умолчание, затирающее заметку при смене категории, стоило бы owner
    ровно того текста, который он туда вписал.
    """
    операция = session.get(FinTransaction, tx_id)
    if операция is None:
        raise ОшибкаПравки("нет_операции", f"операции {tx_id} в книжке нет")

    поля: list[str] = []
    предупреждения: list[str] = []
    категория: FinCategory | None = None
    вид_изменён = False

    if kind is not НЕ_ЗАДАНО:
        # `None` здесь - не «не трогать», а попытка снять вид: колонка
        # `not null`, вида «неизвестно» в книжке не бывает (CHECK
        # `kind_known`), и операция без него не легла бы в сальдо никак.
        if kind is None:
            raise ОшибкаПравки("вид_не_снимается", f"вид обязателен: один из {', '.join(ВИДЫ)}")
        if kind not in ВИДЫ:
            raise ОшибкаПравки("неизвестный_вид", f"вид {kind!r} не из {', '.join(ВИДЫ)}")
        if операция.kind != kind or операция.kind_source != ВРУЧНУЮ:
            вид_изменён = операция.kind != kind
            операция.kind = kind
            # Источник ставится даже тогда, когда вид не изменился: это
            # и есть «owner подтвердил», и разбор такую строку больше
            # не пересматривает (§15.4).
            операция.kind_source = ВРУЧНУЮ
            поля.append("kind")
        if kind == "transfer" and операция.transfer_pair_id is None:
            предупреждения.append(
                "перевод помечен без пары концов: второй конец остаётся"
                " неразобранным, пока не загружена выписка второго банка (ADR-041)"
            )

    if category_id is not НЕ_ЗАДАНО:
        if category_id is None:
            if операция.category_id is not None or операция.category_source != ВРУЧНУЮ:
                операция.category_id = None
                # `manual` без категории - это «owner снял её руками»,
                # и разбор не вправе вернуть её обратно (CHECK
                # `category_source_shape` такую форму разрешает намеренно).
                операция.category_source = ВРУЧНУЮ
                поля.append("category_id")
        else:
            категория = _категория(session, category_id, операция, зона)
            if операция.category_id != категория.id or операция.category_source != ВРУЧНУЮ:
                операция.category_id = категория.id
                операция.category_source = ВРУЧНУЮ
                поля.append("category_id")

    # Булевы флаги `None` не принимают по той же причине, что и вид:
    # «исключена неизвестно» - не состояние, а потерянный запрос.
    if excluded is not НЕ_ЗАДАНО:
        if excluded is None:
            raise ОшибкаПравки("флаг_не_снимается", "excluded принимает true или false")
        if операция.excluded != excluded:
            операция.excluded = excluded
            поля.append("excluded")

    if needs_review is not НЕ_ЗАДАНО:
        if needs_review is None:
            raise ОшибкаПравки("флаг_не_снимается", "needs_review принимает true или false")
        if операция.needs_review != needs_review:
            операция.needs_review = needs_review
            поля.append("needs_review")

    if note is not НЕ_ЗАДАНО and операция.note != note:
        операция.note = note
        поля.append("note")

    правила: list[int] = []
    if запомнить:
        правила, предупреждения_правил = _запомнить(
            session,
            операция,
            вид_изменён=вид_изменён or "kind" in поля,
            категория=категория,
        )
        предупреждения.extend(предупреждения_правил)

    return Правка(
        id=tx_id,
        изменилось=bool(поля) or bool(правила),
        поля=поля,
        правила=правила,
        предупреждения=предупреждения,
    )
