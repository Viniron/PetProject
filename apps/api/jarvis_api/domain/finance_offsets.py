"""Гашение конкретного расхода поступлениями (§15.5, ADR-030).

«Оплатил стол в ресторане, потом скидывают доли»: доли привязываются
к этому расходу, и строка показывает эффективную сумму - свою минус
погашенное. Много поступлений на один расход, ссылка живёт у поступления.

Пять правил, из которых следует всё остальное.

**Гашение уменьшает месяц расхода, а не месяц поступления.** Это единственная
причина, по которой привязка вообще существует отдельно от `refund`:
непривязанный возврат по правилу отправителя исходной покупки не знает
и гасит свой месяц, а привязанный - знает.

**Окно привязки - текущий месяц и предыдущий, и проверяется оно по обоим
концам** (решение owner, 2026-09-17). §15.5 называет только расход, но
поступление тоже принадлежит месяцу: непривязанное оно гасило свой, и
привязка июльского поступления к сентябрьскому расходу пересчитала бы июль,
объявленный окончательным. Окно считается от «сейчас» в зоне owner, поэтому
CHECK его не выражает и живёт оно здесь - под тестом.

**Снятие ограничено тем же окном.** Иначе старый месяц поехал бы через
отмену: привязал в сентябре к августу, снял в декабре - и август изменился.
По той же причине запрещена перепривязка одним действием: она равна снятию
и привязке, и оба окна обязаны проверяться порознь.

**Расход гасится до нуля, но не ниже. Излишек - доход месяца поступления.**
Скинули больше, чем стоил стол: отрицательного расхода не бывает, остаток
показывается доходом. У гасящей части исходная покупка есть, у излишка её
нет - поэтому они и лежат в разных месяцах.

**В счёт идут те же строки, что и в трату дня** (`finance_budget`):
не исключённые, не отменённые, не стоящие в очереди разбора. Второй набор
фильтров здесь завёл бы вторую правду о том, что такое погашенный расход,
и эффективная сумма в книжке разошлась бы с недельным лимитом.

Чего здесь нет намеренно: сальдо месяца (Ф5) и агрегатов по категориям.
Гашение отвечает на один вопрос - сколько на самом деле стоил этот расход.
"""

import datetime as dt
from collections.abc import Sequence
from dataclasses import dataclass, field
from decimal import Decimal
from zoneinfo import ZoneInfo

from sqlalchemy import select
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinTransaction

НОЛЬ = Decimal("0.00")
КОПЕЙКА = Decimal("0.01")

РАСХОД = "expense"
ВОЗВРАТ = "refund"

# Чем решён вид операции (§15.4, миграция c4d1e77b0a92). Привязка - действие
# owner, поэтому она пишет `manual`: переразбор ручное решение не трогает.
ВРУЧНУЮ = "manual"
УМОЛЧАНИЕ = "default"

# Те же статусы, что считает трата дня (`finance_budget.СТАТУСЫ_В_СЧЁТ`).
# `pending` гасит: деньги с карты уже ушли, и не считать их значило бы
# показать расход дороже, чем он есть.
СТАТУСЫ_В_СЧЁТ = ("posted", "pending")


class ОшибкаПривязки(ValueError):
    """Привязка или снятие отклонены.

    С кодом, а не только текстом: на Ф6 из него собирается тело отказа,
    а owner на экране должен увидеть причину, а не «ошибка 400».
    """

    def __init__(self, код: str, сообщение: str) -> None:
        super().__init__(сообщение)
        self.код = код


@dataclass(frozen=True, slots=True)
class Строка:
    """Операция в том виде, в каком её видит гашение.

    Не ORM-объект: проверки окна и знаков проверяются прямым вызовом без
    базы - прецедент `domain/finance_categorize.py`.
    """

    id: int
    occurred_at: dt.datetime
    amount: Decimal
    amount_rub: Decimal
    kind: str
    kind_source: str
    status: str
    excluded: bool
    needs_review: bool
    offsets_transaction_id: int | None


@dataclass(frozen=True, slots=True)
class Часть:
    """Один гасящий приход в разбивке расхода."""

    гашение_id: int
    погасило: Decimal
    излишек: Decimal


@dataclass(frozen=True, slots=True)
class Разбивка:
    """Сколько на самом деле стоил расход и что из поступлений стало доходом."""

    расход_id: int
    сумма: Decimal
    погашено: Decimal
    эффективная: Decimal
    излишек: Decimal
    части: list[Часть] = field(default_factory=list)
    # Привязанные, но в счёт не идущие: отменённые, исключённые или стоящие
    # в очереди разбора. Показываются отдельно, потому что молча пропавшее
    # гашение выглядит как «привязка не сработала».
    вне_счёта: list[int] = field(default_factory=list)


@dataclass(frozen=True, slots=True)
class Привязка:
    """Результат действия. `предупреждения` читает owner в дифф-выводе."""

    гашение_id: int
    расход_id: int | None
    изменилось: bool
    предупреждения: list[str] = field(default_factory=list)


def месяц(момент: dt.datetime, зона: ZoneInfo) -> dt.date:
    """Первое число месяца операции в зоне owner (инвариант 7)."""
    return момент.astimezone(зона).date().replace(day=1)


def окно(сейчас: dt.datetime, зона: ZoneInfo) -> tuple[dt.date, dt.date]:
    """Месяцы, которые ещё можно пересчитать: предыдущий и текущий.

    Возвращает первые числа обоих. Считается от «сейчас», а не от даты
    операции: закрытый месяц становится окончательным по календарю, а не
    по тому, когда его трогали в последний раз.
    """
    текущий = сейчас.astimezone(зона).date().replace(day=1)
    предыдущий = (текущий - dt.timedelta(days=1)).replace(day=1)
    return предыдущий, текущий


def в_окне(момент: dt.datetime, сейчас: dt.datetime, зона: ZoneInfo) -> bool:
    предыдущий, текущий = окно(сейчас, зона)
    return месяц(момент, зона) in (предыдущий, текущий)


def _проверить_окно(строка: Строка, роль: str, сейчас: dt.datetime, зона: ZoneInfo) -> None:
    if в_окне(строка.occurred_at, сейчас, зона):
        return
    предыдущий, _ = окно(сейчас, зона)
    raise ОшибкаПривязки(
        "вне_окна",
        f"{роль} за {месяц(строка.occurred_at, зона):%Y-%m} вне окна:"
        f" пересчитать можно только с {предыдущий:%Y-%m} (§15.5)",
    )


def проверить_привязку(
    гашение: Строка,
    расход: Строка,
    сейчас: dt.datetime,
    зона: ZoneInfo,
) -> None:
    """Можно ли привязать это поступление к этому расходу. Иначе - отказ.

    Порядок проверок - от грубого к тонкому, чтобы сообщение называло
    настоящую причину: «это не расход» полезнее, чем «вне окна», когда
    неверно и то и другое.
    """
    if гашение.id == расход.id:
        raise ОшибкаПривязки("сама_себя", "операция не может гасить саму себя")

    # Гасить может только приход - то же, что CHECK `offsets_only_incoming`.
    # Расход, «погашающий» другой расход, - не деньги от друзей, а ошибка
    # привязки, и стоит она сразу двух неверных месяцев (§15.5).
    if гашение.amount <= 0 or гашение.amount_rub <= 0:
        raise ОшибкаПривязки("не_приход", "гасить расход может только поступление")

    if расход.kind != РАСХОД or расход.amount >= 0:
        raise ОшибкаПривязки(
            "не_расход",
            f"погасить можно только расход, а это {расход.kind}",
        )

    # Поступление гасит расход, а расходом быть не может - значит цепочки
    # «гашение гасит гашение» невозможны по построению, отдельной проверки
    # на них нет намеренно.
    if расход.status == "reverted" or гашение.status == "reverted":
        raise ОшибкаПривязки(
            "отменена",
            "отменённая операция в гашении не участвует: она исчезла из выгрузки (§15.3)",
        )

    if расход.excluded or гашение.excluded:
        raise ОшибкаПривязки(
            "исключена",
            "исключённая из сальдо операция в гашении не участвует (§15.5)",
        )

    if гашение.offsets_transaction_id not in (None, расход.id):
        # Перепривязка одним действием обошла бы окно снятия: старый расход
        # мог бы измениться тогда, когда его месяц уже окончателен.
        raise ОшибкаПривязки(
            "уже_привязано",
            f"поступление уже гасит операцию {гашение.offsets_transaction_id}:"
            " сначала снять привязку",
        )

    _проверить_окно(расход, "расход", сейчас, зона)
    _проверить_окно(гашение, "поступление", сейчас, зона)


def проверить_снятие(гашение: Строка, расход: Строка, сейчас: dt.datetime, зона: ZoneInfo) -> None:
    """Снятие ограничено тем же окном, что и привязка (§15.5)."""
    _проверить_окно(расход, "расход", сейчас, зона)
    _проверить_окно(гашение, "поступление", сейчас, зона)


def идёт_в_счёт(строка: Строка) -> bool:
    """Уменьшает ли это гашение расход сегодня.

    Ровно те же условия, что у траты дня в `finance_budget`: иначе книжка
    и недельный лимит показали бы разную стоимость одной покупки.
    """
    return not строка.excluded and not строка.needs_review and строка.status in СТАТУСЫ_В_СЧЁТ


def разложить(расход: Строка, гашения: Sequence[Строка]) -> Разбивка:
    """Эффективная сумма расхода и излишек по каждому поступлению.

    Порядок гашений - хронологический: раннее гасит первым, излишек достаётся
    позднему. Порядок важен не для суммы, а для месяца излишка: два
    поступления в разных месяцах дают разный ответ на вопрос «в каком месяце
    появился доход», и выбирать его произвольно значит двигать деньги между
    закрытыми месяцами.
    """
    # Расход в выписке отрицателен, стоимость покупки - положительное число.
    сумма = (-расход.amount_rub).quantize(КОПЕЙКА)
    остаток = сумма
    части: list[Часть] = []
    вне_счёта: list[int] = []

    for гашение in sorted(гашения, key=lambda с: (с.occurred_at, с.id)):
        if not идёт_в_счёт(гашение):
            вне_счёта.append(гашение.id)
            continue
        своя = гашение.amount_rub.quantize(КОПЕЙКА)
        погасило = min(своя, остаток) if остаток > НОЛЬ else НОЛЬ
        остаток -= погасило
        части.append(Часть(гашение_id=гашение.id, погасило=погасило, излишек=своя - погасило))

    погашено = sum((часть.погасило for часть in части), НОЛЬ)
    излишек = sum((часть.излишек for часть in части), НОЛЬ)
    return Разбивка(
        расход_id=расход.id,
        сумма=сумма,
        погашено=погашено,
        # Не ниже нуля: отрицательного расхода не бывает, излишек - доход.
        эффективная=max(сумма - погашено, НОЛЬ),
        излишек=излишек,
        части=части,
        вне_счёта=вне_счёта,
    )


def строка_операции(операция: FinTransaction) -> Строка:
    """Операция базы в том виде, в каком её видит гашение.

    Публичная, а не приватная: второй потребитель - лента Ф6, где
    эффективная сумма расхода считается тем же `разложить`. Своя копия
    этого перевода в ленте разошлась бы с гашением молча.
    """
    return Строка(
        id=операция.id,
        occurred_at=операция.occurred_at,
        amount=операция.amount,
        amount_rub=операция.amount_rub,
        kind=операция.kind,
        kind_source=операция.kind_source,
        status=операция.status,
        excluded=операция.excluded,
        needs_review=операция.needs_review,
        offsets_transaction_id=операция.offsets_transaction_id,
    )


def _взять(session: Session, номер: int, роль: str) -> FinTransaction:
    операция = session.get(FinTransaction, номер)
    if операция is None:
        raise ОшибкаПривязки("нет_операции", f"{роль} {номер} в книжке не найден")
    return операция


def привязать(
    session: Session,
    *,
    гашение_id: int,
    расход_id: int,
    сейчас: dt.datetime,
    зона: ZoneInfo,
) -> Привязка:
    """Привязывает поступление к расходу. Транзакцию коммитит вызывающий код.

    Привязка - решение owner, поэтому вид становится `refund` с источником
    `manual`: разбор ручное решение не пересматривает (§15.4), и следующий
    `finance-categorize` не вернёт поступлению `income` по правилу
    отправителя.
    """
    гашение = _взять(session, гашение_id, "поступление")
    расход = _взять(session, расход_id, "расход")
    проверить_привязку(строка_операции(гашение), строка_операции(расход), сейчас, зона)

    if гашение.offsets_transaction_id == расход_id and гашение.kind_source == ВРУЧНУЮ:
        return Привязка(гашение_id, расход_id, изменилось=False)

    предупреждения: list[str] = []
    # Решение о пометке принимается по `kind_source` **до** записи: после неё
    # он станет `manual`, и отличить пометку разбора от пометки импорта будет
    # уже нечем. Снимает пометку только тот, кто её поставил (§15.3, §15.5):
    # `default` - это разбор, и привязка как раз отвечает на его вопрос;
    # кандидат в дубли от импорта - причина другая, и молча закрыть её
    # значит однажды потерять строку, где выбор стоит денег.
    if гашение.needs_review:
        if гашение.kind_source == УМОЛЧАНИЕ:
            гашение.needs_review = False
        else:
            предупреждения.append(
                f"поступление {гашение_id} остаётся в очереди разбора"
                " (пометку ставил импорт) и расход пока не уменьшает"
            )

    гашение.offsets_transaction_id = расход_id
    гашение.kind = ВОЗВРАТ
    гашение.kind_source = ВРУЧНУЮ
    return Привязка(гашение_id, расход_id, изменилось=True, предупреждения=предупреждения)


def снять(
    session: Session,
    *,
    гашение_id: int,
    сейчас: dt.datetime,
    зона: ZoneInfo,
) -> Привязка:
    """Снимает привязку. Окно то же, что у привязки.

    Вид остаётся `refund` с источником `manual`: owner уже решил, чем эта
    операция является, и снятие привязки этого решения не отменяет -
    отменяет оно только то, чей месяц она гасит.
    """
    гашение = _взять(session, гашение_id, "поступление")
    расход_id = гашение.offsets_transaction_id
    if расход_id is None:
        return Привязка(гашение_id, None, изменилось=False)

    расход = _взять(session, расход_id, "расход")
    проверить_снятие(строка_операции(гашение), строка_операции(расход), сейчас, зона)

    гашение.offsets_transaction_id = None
    return Привязка(гашение_id, None, изменилось=True)


def разбивка(session: Session, расход_id: int) -> Разбивка:
    """Разбивка расхода из базы: сколько погашено, что осталось, что доход."""
    расход = _взять(session, расход_id, "расход")
    гашения = session.scalars(
        select(FinTransaction)
        .where(FinTransaction.offsets_transaction_id == расход_id)
        .order_by(FinTransaction.occurred_at, FinTransaction.id)
    ).all()
    return разложить(строка_операции(расход), [строка_операции(г) for г in гашения])
