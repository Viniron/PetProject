"""Воскресное напоминание о выписках: кому и когда (Ф8, §15.7, ADR-053).

Здесь только решение. Запись в календарь - дело джоба
(`jobs/finance_remind.py`): домен не ходит наружу, и правило проверяется
прямым вызовом, без базы и без Google.

**Условие - неделя, а не срок давности** (решение owner, ADR-053). Порог
плашки `FINANCE_STALE_AFTER_DAYS` равен восьми дням, а выписка, загруженная
в прошлое воскресенье, к этому воскресенью лежит ровно семь: напоминание,
привязанное к порогу, при недельном ритме не пришло бы ни разу. Поэтому
спрашивается другое - загружен ли каждый банк **на этой неделе**, начиная
с понедельника по зоне owner.

**По каждому банку, а не по самому свежему файлу** - то же правило, что
у плашки давности (§15.6): загруженная вчера выписка одного банка не делает
свежим другой.
"""

import datetime as dt
from collections.abc import Sequence
from dataclasses import dataclass
from zoneinfo import ZoneInfo

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinImport

# Префикс ключа события. Ключ детерминирован от даты воскресенья и ни от
# чего больше (инвариант 5): повторный прогон, догон после рестарта и
# восстановление из дампа попадают в то же событие.
ПРЕФИКС_КЛЮЧА = "finance:statements:"

ЗАГОЛОВОК = "Загрузить выписки"

ВОСКРЕСЕНЬЕ = 6

СЕКУНД_В_СУТКАХ = 24 * 60 * 60


@dataclass(frozen=True, slots=True)
class Загрузка:
    """Последнее, что известно о банке: когда грузили и по какой день."""

    банк: str
    загружено_в: dt.datetime
    # Конец периода самой свежей выписки. Пусто, если файлы банка период
    # не называют: тогда в описании так и сказано, а не подставлена дата.
    покрыто_по: dt.date | None


@dataclass(frozen=True, slots=True)
class Напоминание:
    """Событие, которое должно стоять в календаре в это воскресенье."""

    ключ: str
    начало: dt.datetime
    конец: dt.datetime
    описание: str


@dataclass(frozen=True, slots=True)
class Решение:
    """Нужно ли событие и почему. Причина - для лога и dry-run."""

    напоминание: Напоминание | None
    причина: str


def последние_загрузки(session: Session) -> list[Загрузка]:
    """По строке на банк, у которого была хоть одна выписка."""
    строки = session.execute(
        select(
            FinImport.bank,
            func.max(FinImport.imported_at),
            func.max(FinImport.period_end),
        ).group_by(FinImport.bank)
    ).all()
    return [Загрузка(банк, загружено, по) for банк, загружено, по in строки]


def ключ_недели(воскресенье: dt.date) -> str:
    return f"{ПРЕФИКС_КЛЮЧА}{воскресенье.isoformat()}"


def решить(
    загрузки: Sequence[Загрузка],
    *,
    сейчас: dt.datetime,
    зона: ZoneInfo,
    время: dt.time,
    минут: int,
    шаг_минут: int,
) -> Решение:
    """Ставить ли событие сегодня, на какое время и с каким текстом."""
    местное = сейчас.astimezone(зона)
    сегодня = местное.date()
    if сегодня.weekday() != ВОСКРЕСЕНЬЕ:
        return Решение(None, f"сегодня {сегодня:%d.%m.%Y} не воскресенье")

    if not загрузки:
        # То же правило, что у плашки давности: пустая книжка не просрочена.
        # Завести книжку - отдельное действие owner, а не отставание.
        return Решение(None, "в книжке нет ни одной выписки - напоминать не о чем")

    понедельник = сегодня - dt.timedelta(days=сегодня.weekday())
    # Сравниваются даты по зоне owner, а не моменты UTC: выписка, загруженная
    # в понедельник в 01:00 по Москве, в UTC приходится на воскресенье
    # и иначе числилась бы прошлой неделей.
    отстающие = sorted(
        (з for з in загрузки if з.загружено_в.astimezone(зона).date() < понедельник),
        key=lambda з: з.загружено_в,
    )
    if not отстающие:
        return Решение(None, "все банки загружены на этой неделе")

    начало = _начало(местное, время, шаг_минут)
    if начало is None:
        return Решение(
            None,
            "до конца воскресенья не осталось места для события; "
            "задним числом в понедельник не ставлю - остаётся плашка давности",
        )

    return Решение(
        Напоминание(
            ключ=ключ_недели(сегодня),
            начало=начало.astimezone(dt.UTC),
            конец=(начало + dt.timedelta(minutes=минут)).astimezone(dt.UTC),
            описание=_описание(отстающие, сегодня, зона),
        ),
        "не загружены на этой неделе: " + ", ".join(з.банк for з in отстающие),
    )


def _начало(местное: dt.datetime, время: dt.time, шаг_минут: int) -> dt.datetime | None:
    """Назначенное время или, если оно прошло, ближайшая отметка шага.

    Опоздание - это догон после простоя платы (инвариант 11) или отказ
    Google на утренних слотах. Событие в прошлом уведомления уже не даст,
    поэтому оно сдвигается вперёд, но только в пределах того же дня: «сегодня»
    для напоминания - воскресенье, а не ближайшие сутки.
    """
    назначенное = dt.datetime.combine(местное.date(), время, tzinfo=местное.tzinfo)
    if назначенное >= местное:
        return назначенное

    полночь = dt.datetime.combine(местное.date(), dt.time.min, tzinfo=местное.tzinfo)
    прошло = (местное - полночь).total_seconds()
    шаг = шаг_минут * 60
    # Округление вверх: 18:07 - это 18:15, а не 18:00, которое уже прошло.
    # Ровно на отметке остаётся на ней.
    отметка = -(-прошло // шаг) * шаг
    if отметка >= СЕКУНД_В_СУТКАХ:
        return None
    return полночь + dt.timedelta(seconds=отметка)


def _описание(отстающие: Sequence[Загрузка], сегодня: dt.date, зона: ZoneInfo) -> str:
    """Текст события: какие банки отстают и насколько.

    Банк назван так, как он записан в книжке. Отображаемых имён банков
    в коде нет, и придумывать их здесь значило бы завести второе написание.
    """
    строки = ["Не загружены выписки этой недели:"]
    for з in отстающие:
        дней = (сегодня - з.загружено_в.astimezone(зона).date()).days
        покрытие = (
            f"операции по {з.покрыто_по:%d.%m.%Y}"
            if з.покрыто_по is not None
            else "период в выписке не указан"
        )
        строки.append(f"- {з.банк}: {покрытие}, загружено {дней} {_дней(дней)} назад")
    строки.append("")
    строки.append("Поставлено JARVIS: воскресное напоминание книжки")
    return "\n".join(строки)


def _дней(число: int) -> str:
    """Склонение: 1 день, 2 дня, 5 дней, 11 дней, 21 день."""
    if число % 10 == 1 and число % 100 != 11:
        return "день"
    if число % 10 in (2, 3, 4) and число % 100 not in (12, 13, 14):
        return "дня"
    return "дней"
