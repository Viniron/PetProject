"""Разбор операций: категория, вид и перевод себе (§15.4, §15.5).

Ни базы, ни файлов - как и сверка импорта, по той же причине: здесь решается,
какие деньги owner считаются расходом, а какие не считаются вовсе. Ошибка
не падает, а тихо искажает сальдо, и проверяется она прямым вызовом на
выдуманных краях, а не прогоном по живой базе.

Пять правил, из которых следует всё остальное.

**Ручная правка сильнее любого правила и переживает переразбор.** Отличить
её от проставленного правилом можно только по `category_source`/`kind_source`
(миграция c4d1e77b0a92): в самой категории обе выглядят одинаково. Правила
приезжают позже данных, переразбор неизбежен, и без этой проверки он молча
вернул бы операции категорию, которую owner руками снял.

**Ступени 1-4 применяются от слабого к сильному, выигрывает сильнейшая.**
MCC, категория банка, «Ваша категория» из выгрузки, правило по мерчанту.
Модель (ступень 5) здесь не участвует вовсе - её черёд на Э12, и звать её
на то, что разобрано сравнением строк, запрещено §5.1.

**Входящий перевод без правила отправителя уходит в разбор.** Умолчание
§15.5 - `refund`, то есть «гасит расход месяца», и случаться молча оно
не вправе: `kind_source` становится `default`, а операция помечается
`needs_review` и в сальдо не входит, пока owner не решит. Родные дают
`income` правилом, всё прочее owner размечает сам.

**Перевод себе опознаётся парой концов, а не именем** (ADR-041): списание
в одном банке и зачисление в другом, та же сумма, окно в несколько дней,
**оба счёта размечены**. Имя owner в описании - подтверждение, а не
основание: оно спасает непарный конец от умолчания `refund`, уводя его
в разбор, но само по себе `transfer` не назначает. Однофамилец ломает имя,
а пару концов - нет.

**Неоднозначность не решается угадыванием.** Два кандидата на пару - оба
конца в разбор: выбор между «переложил себе» и «перевёл человеку» стоит
двух неверных месяцев сразу, потому что ошибка тут раздувает расход одного
банка и гасит расход другого (§15.5).

Чего здесь нет намеренно: сальдо (Ф5), гашения конкретного расхода (Ф4б),
модели (Э12). Разбор отвечает на один вопрос - чем эта операция является.
"""

import datetime as dt
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from zoneinfo import ZoneInfo

# Виды операции (§15.2). `transfer` и `refund` появляются только здесь:
# импорт их не ставит, потому что из одной строки файла они не выводятся.
РАСХОД = "expense"
ДОХОД = "income"
ПЕРЕВОД = "transfer"
ВОЗВРАТ = "refund"

# Чем решение принято. `sign` пишет импорт, `manual` - owner, остальное - этот
# модуль. Значения совпадают с CHECK `kind_source_known`.
ПО_ЗНАКУ = "sign"
УМОЛЧАНИЕ = "default"
ПО_ОТПРАВИТЕЛЮ = "sender_rule"
ПО_ПАРЕ = "transfer_pair"
ВРУЧНУЮ = "manual"

# Ступени разбора категории, от слабой к сильной (§15.4). Порядок в кортеже
# и есть порядок применения: сильнейшая сработавшая выигрывает.
ПО_MCC = "mcc"
ПО_КАТЕГОРИИ_БАНКА = "bank_category"
ПО_СВОЕЙ_КАТЕГОРИИ = "own_category"
ПО_МЕРЧАНТУ = "merchant"
СТУПЕНИ = (ПО_MCC, ПО_КАТЕГОРИИ_БАНКА, ПО_СВОЕЙ_КАТЕГОРИИ, ПО_МЕРЧАНТУ)

# Ступень 5 (§15.4). Здесь не назначается никогда - только уважается порядок:
# детерминированное правило точнее модели, потому что оно и есть ответ owner.
ПО_МОДЕЛИ = "model"

# Тип правила, которым owner объявляет, как банк пишет его самого (ADR-041).
СВОЁ_ИМЯ = "self"

# Роль счёта, означающая «owner ещё не сказал». Пара концов из таких счетов
# не собирается: перевод человеку и перевод себе тогда неотличимы (§15.5).
НЕИЗВЕСТНАЯ_РОЛЬ = "unknown"

КОПЕЙКА = Decimal("0.01")


def _ключ(значение: str | None) -> str | None:
    """Написание банка к виду, в котором оно сравнивается с образцом правила.

    Регистр и края - единственное, что нормализуется. Всё остальное остаётся
    как в файле: «Пятёрочка» и «Пятерочка» - разные образцы, и склеивать их
    догадкой значило бы разносить деньги по категории, которой owner
    не выбирал.
    """
    if значение is None:
        return None
    очищенное = значение.strip().casefold()
    return очищенное or None


@dataclass(frozen=True, slots=True)
class Операция:
    """Строка книжки в том виде, в каком её видит разбор.

    Не ORM-объект: разбор проверяется без базы вовсе - прецедент
    `domain/finance_import.py`. Поля - ровно те, по которым принимается
    решение, плюс текущее состояние, чтобы отличить «уже разобрано» от
    «разобрано вручную».
    """

    id: int
    bank: str
    account: str
    occurred_at: dt.datetime
    amount: Decimal
    merchant: str | None
    bank_category: str | None
    own_category: str | None
    mcc: str | None
    kind: str
    kind_source: str
    category_id: int | None
    category_source: str | None
    transfer_pair_id: int | None
    needs_review: bool


@dataclass(frozen=True, slots=True)
class Правило:
    """Строка `fin_category_rules` (§15.4, §15.5).

    `category_key`, а не идентификатор категории: категория - версия месяца,
    и правило, указывающее на строку сентября, в октябре осиротело бы.
    """

    rule_type: str
    pattern: str
    category_key: str | None = None
    kind: str | None = None


@dataclass(frozen=True, slots=True)
class Категория:
    """Версия категории на месяц. В разборе участвуют только `active`."""

    id: int
    period_month: dt.date
    key: str
    title: str
    status: str = "active"


@dataclass(frozen=True, slots=True)
class Счёт:
    """Свой счёт owner. Роль решает, годится ли он в пару перевода."""

    bank: str
    name: str
    role: str


@dataclass(frozen=True, slots=True)
class Разбор:
    """Новое состояние операции. Возвращаются только изменившиеся строки."""

    id: int
    kind: str
    kind_source: str
    category_id: int | None
    category_source: str | None
    transfer_pair_id: int | None
    needs_review: bool
    # Зачем это решение принято - строкой для dry-run. Дифф читает owner,
    # и «стало transfer» без причины он проверить не может.
    причина: str


def _месяц(момент: dt.datetime, зона: ZoneInfo) -> dt.date:
    """Первое число месяца операции в зоне owner.

    В зоне owner, а не в UTC: операция 1 сентября в 01:00 по Москве лежит
    в базе августовской, и её категорию искать надо в сентябрьском наборе
    (инвариант 7).
    """
    местная = момент.astimezone(зона).date()
    return местная.replace(day=1)


def _размеченные(счета: Iterable[Счёт]) -> set[tuple[str, str]]:
    """Счета с известной ролью - те, что вправе участвовать в паре перевода."""
    return {(с.bank, с.name) for с in счета if с.role != НЕИЗВЕСТНАЯ_РОЛЬ}


def _пары(
    операции: Sequence[Операция],
    счета: Iterable[Счёт],
    зона: ZoneInfo,
    окно_дней: int,
) -> tuple[dict[int, int], set[int]]:
    """Переводы между своими счетами: пары концов и неоднозначные концы.

    Условия пары (ADR-041): **разные банки**, противоположный знак, равная
    по модулю сумма, разница дат в зоне owner не больше окна, и **оба счёта
    размечены**. Разные банки - не придирка: внутри одного банка перевод
    между своими счетами приезжает одной строкой выгрузки, а не двумя, и
    пара там не собирается по построению.

    Кандидатов больше одного с какой-то стороны - пары нет, **оба конца
    в разбор**. Молча выбрать ближайший значило бы раздуть расход одного
    банка и погасить расход другого - две ошибки в сторону «выглядит
    правдоподобно», то есть худшие по §10.
    """
    годные = _размеченные(счета)
    кандидаты = [
        о
        for о in операции
        # Ручное решение owner не пересматривается даже парой: он мог снять
        # пометку с настоящей пары, и разбор не вправе вернуть её обратно.
        if о.kind_source != ВРУЧНУЮ and (о.bank, о.account) in годные and о.amount != 0
    ]

    по_сумме: dict[Decimal, list[Операция]] = {}
    for о in кандидаты:
        по_сумме.setdefault(abs(о.amount).quantize(КОПЕЙКА), []).append(о)

    окно = dt.timedelta(days=окно_дней)
    возможные: dict[int, list[int]] = {}
    for группа in по_сумме.values():
        for приход in группа:
            if приход.amount <= 0:
                continue
            for расход in группа:
                if расход.amount >= 0 or расход.bank == приход.bank:
                    continue
                день_прихода = приход.occurred_at.astimezone(зона).date()
                день_расхода = расход.occurred_at.astimezone(зона).date()
                if abs(день_прихода - день_расхода) > окно:
                    continue
                возможные.setdefault(приход.id, []).append(расход.id)
                возможные.setdefault(расход.id, []).append(приход.id)

    пары: dict[int, int] = {}
    неоднозначные: set[int] = set()
    for номер, соседи in возможные.items():
        if len(соседи) > 1:
            неоднозначные.add(номер)
    for номер, соседи in возможные.items():
        if номер in неоднозначные:
            continue
        сосед = соседи[0]
        # Пара засчитывается, только если она взаимна: у второго конца
        # тоже ровно один кандидат, и это мы. Иначе один перевод себе
        # притянул бы к себе строку, которая на самом деле чужая.
        if сосед in неоднозначные or len(возможные[сосед]) != 1:
            неоднозначные.add(номер)
            continue
        пары[номер] = сосед

    return пары, неоднозначные


def _категория(
    операция: Операция,
    правила_по_типу: Mapping[str, Mapping[str, Правило]],
    ключи_месяца: Mapping[tuple[dt.date, str], int],
    заголовки_месяца: Mapping[tuple[dt.date, str], int],
    зона: ZoneInfo,
) -> tuple[int | None, str | None]:
    """Категория по ступеням 1-4. Сильнейшая сработавшая выигрывает (§15.4).

    Ступень 3 - «Ваша категория» из выгрузки - сопоставляется не с правилом,
    а с **названием** категории месяца: это уже разметка owner, только
    сделанная в приложении банка, и лишнее правило-переходник между ней
    и одноимённой категорией книжки было бы ручной работой на ровном месте.

    Правило, указывающее на ключ, которого в этом месяце нет, ступень
    не проходит - и это не отказ: набор категорий месяца owner правит сам,
    а до утверждения работает унаследованный (§15.4). Разбор спускается
    к более слабой ступени, а не оставляет операцию без категории назло.
    """
    месяц = _месяц(операция.occurred_at, зона)
    найдено: tuple[int, str] | None = None

    for ступень in СТУПЕНИ:
        if ступень == ПО_СВОЕЙ_КАТЕГОРИИ:
            название = _ключ(операция.own_category)
            номер = заголовки_месяца.get((месяц, название)) if название else None
            if номер is not None:
                найдено = (номер, ступень)
            continue

        значение = _ключ(
            операция.mcc
            if ступень == ПО_MCC
            else операция.bank_category if ступень == ПО_КАТЕГОРИИ_БАНКА else операция.merchant
        )
        if значение is None:
            continue
        правило = правила_по_типу.get(ступень, {}).get(значение)
        if правило is None or правило.category_key is None:
            continue
        номер = ключи_месяца.get((месяц, правило.category_key))
        if номер is not None:
            найдено = (номер, ступень)

    if найдено is None:
        # Ни одна ступень не сработала - прежняя категория остаётся. Снимать
        # её значило бы терять разметку каждый раз, когда owner переименовал
        # правило или ещё не утвердил набор категорий нового месяца; вернуть
        # снятую можно только руками, а это работа по чужой ошибке.
        return операция.category_id, операция.category_source
    return найдено


def разобрать(
    операции: Sequence[Операция],
    правила: Sequence[Правило],
    категории: Sequence[Категория],
    счета: Sequence[Счёт],
    зона: ZoneInfo,
    *,
    окно_перевода_дней: int,
) -> list[Разбор]:
    """Что разбор сделает с книжкой. Возвращает только изменившиеся строки.

    `операции` - весь срез, по которому ищутся пары: перевод себе приезжает
    двумя файлами двух банков, и разбор одного банка в отрыве от другого
    не нашёл бы ни одной пары. Отсюда же следует, что после загрузки второго
    файла книжку надо переразобрать целиком, а не только новые строки.

    Порядок решений: сперва пары (они сильнее умолчаний), затем вид, затем
    категория. Обратный порядок дал бы `refund` переводу себе на один проход,
    а один проход с неверным `kind` - это уже искажённое сальдо в отчёте,
    который owner мог успеть увидеть.
    """
    пары, неоднозначные = _пары(операции, счета, зона, окно_перевода_дней)

    правила_по_типу: dict[str, dict[str, Правило]] = {}
    for правило in правила:
        образец = _ключ(правило.pattern)
        if образец is None:
            continue
        правила_по_типу.setdefault(правило.rule_type, {})[образец] = правило

    свои_имена = set(правила_по_типу.get(СВОЁ_ИМЯ, {}))
    отправители = правила_по_типу.get("sender", {})

    активные = [к for к in категории if к.status == "active"]
    ключи_месяца = {(к.period_month, к.key): к.id for к in активные}
    заголовки_месяца: dict[tuple[dt.date, str], int] = {}
    for к in активные:
        название = _ключ(к.title)
        if название is not None:
            заголовки_месяца[(к.period_month, название)] = к.id

    решения: list[Разбор] = []
    for операция in операции:
        kind, kind_source, пара, разбор_нужен, причина = _вид(
            операция, пары, неоднозначные, свои_имена, отправители
        )

        category_id: int | None
        category_source: str | None
        if операция.category_source == ВРУЧНУЮ:
            # Ручная правка сильнее всех ступеней - включая снятую категорию:
            # `category_source = 'manual'` при пустой категории означает
            # «owner решил, что категории здесь нет» (§15.4).
            category_id, category_source = операция.category_id, операция.category_source
        else:
            category_id, category_source = _категория(
                операция, правила_по_типу, ключи_месяца, заголовки_месяца, зона
            )

        # Причина склеивается из двух: вид и категория меняются независимо,
        # и строка «списание» у операции, которой разбор поставил категорию,
        # не объясняет ровно того, что произошло. Дифф читает owner - он
        # обязан отвечать на вопрос «почему эта строка в списке».
        if category_source != операция.category_source or category_id != операция.category_id:
            причина = (
                f"{причина}; категория по ступени {category_source}"
                if category_source is not None
                else f"{причина}; категория снята"
            )

        новое = Разбор(
            id=операция.id,
            kind=kind,
            kind_source=kind_source,
            category_id=category_id,
            category_source=category_source,
            transfer_pair_id=пара,
            needs_review=разбор_нужен,
            причина=причина,
        )
        if (
            новое.kind == операция.kind
            and новое.kind_source == операция.kind_source
            and новое.category_id == операция.category_id
            and новое.category_source == операция.category_source
            and новое.transfer_pair_id == операция.transfer_pair_id
            and новое.needs_review == операция.needs_review
        ):
            continue
        решения.append(новое)

    решения.sort(key=lambda р: р.id)
    return решения


def _вид(
    операция: Операция,
    пары: Mapping[int, int],
    неоднозначные: set[int],
    свои_имена: set[str],
    отправители: Mapping[str, Правило],
) -> tuple[str, str, int | None, bool, str]:
    """Вид операции, источник решения, пара, нужда в разборе и причина.

    Ветвлений ровно пять, и порядок между ними не произволен: ручное решение
    owner не пересматривается, пара сильнее умолчаний, имя owner уводит
    непарный конец в разбор раньше, чем к нему применится `refund`,
    и только потом расход отличается от прихода знаком.
    """
    if операция.kind_source == ВРУЧНУЮ:
        return (
            операция.kind,
            операция.kind_source,
            операция.transfer_pair_id,
            операция.needs_review,
            "решение owner",
        )

    пара = пары.get(операция.id)
    if пара is not None:
        # Пара найдена - операция перестаёт быть непонятной, и пометка
        # разбора, если её ставил разбор же, снимается. Пометку импорта
        # (кандидат в дубли, §15.3) снимать нельзя: причина у неё другая.
        снять = операция.kind_source in (ПО_ЗНАКУ, УМОЛЧАНИЕ)
        return (
            ПЕРЕВОД,
            ПО_ПАРЕ,
            пара,
            False if снять else операция.needs_review,
            "пара концов в двух банках",
        )

    if операция.id in неоднозначные:
        # Кандидатов на пару больше одного. Вид оставляем как есть - он
        # всё равно не участвует в сальдо, пока строка в разборе, - а вот
        # умолчание `refund` к ней применить нельзя ни в коем случае.
        return (
            операция.kind,
            операция.kind_source,
            None,
            True,
            "несколько кандидатов на пару перевода",
        )

    имя = _ключ(операция.merchant)
    if имя is not None and имя in свои_имена:
        return (
            операция.kind,
            операция.kind_source,
            None,
            True,
            "написание owner, но пары не нашлось",
        )

    if операция.amount < 0:
        return (РАСХОД, ПО_ЗНАКУ, None, операция.needs_review, "списание")

    правило = отправители.get(имя) if имя is not None else None
    if правило is not None and правило.kind is not None:
        # Пометку разбора снимаем только свою: `default` её и ставил.
        снять = операция.kind_source == УМОЛЧАНИЕ
        return (
            правило.kind,
            ПО_ОТПРАВИТЕЛЮ,
            None,
            False if снять else операция.needs_review,
            f"правило отправителя {правило.pattern!r}",
        )

    # Умолчание §15.5: прочий входящий перевод гасит расход. Ошибка в эту
    # сторону занижает доступные деньги и заметна; обратная - завышает
    # и приход, и остаток, выглядит правдоподобно и не проверяется. Но
    # применяется оно с пометкой: owner обязан увидеть, кто эти люди.
    return (ВОЗВРАТ, УМОЛЧАНИЕ, None, True, "входящий перевод без правила отправителя")
