def test_пары_подряд_не_конфликтуют() -> None:
    """10:00-11:30 и 11:40-13:10 - обычный учебный день, а не наложение."""
    первая, вторая = событие("10:00", "11:30", "а"), событие("11:40", "13:10", "б")

    пометить_конфликты([первая, вторая])

    assert (первая.conflict, вторая.conflict) == (False, False)


def test_встык_не_конфликт() -> None:
    """Конец одного в минуту начала другого. Нестрогое сравнение пометило бы
    «⚠» весь день, и пометка перестала бы что-либо значить."""
    первое, второе = событие("13:40", "14:40", "а"), событие("14:40", "15:25", "б")

    пометить_конфликты([первое, второе])

    assert (первое.conflict, второе.conflict) == (False, False)


def test_наложение_помечает_оба() -> None:
    """Случай макета: пара 15:20-16:50 и визит к врачу 16:30-17:30."""
    пара_, врач = событие("15:20", "16:50", "пара"), событие("16:30", "17:30", "врач")

    пометить_конфликты([пара_, врач])

    assert (пара_.conflict, врач.conflict) == (True, True)


def test_три_наложения_помечают_все_три() -> None:
    """Группировки в ответе нет: раскладка - забота клиента."""
    события = [
        событие("10:00", "12:00", "а"),
        событие("11:00", "13:00", "б"),
        событие("11:30", "11:45", "в"),
    ]

    пометить_конфликты(события)

    assert [с.conflict for с in события] == [True, True, True]


def test_событие_нулевой_длительности_не_конфликтует_ни_с_чем() -> None:
    """Пустой интервал не пересекается ни с чем, а «минимум одна минута»
    было бы придуманным числом. На сетке событие при этом остаётся."""
    объемлющая, точка = событие("10:00", "12:00", "пара"), событие("11:00", "11:00", "точка")

    пометить_конфликты([объемлющая, точка])

    assert (объемлющая.conflict, точка.conflict) == (False, False)


def test_перевёрнутое_событие_не_роняет_расчёт() -> None:
    """CHECK на порядок времён есть только у day_flags, поэтому такое
    возможно физически. Времена наружу отдаются настоящими."""
    перевёрнутое = событие("18:00", "17:00", "оно")
    сосед = событие("17:30", "18:30", "сосед")

    пометить_конфликты([перевёрнутое, сосед])

    assert перевёрнутое.ends_at < перевёрнутое.starts_at
    assert сосед.conflict is False


