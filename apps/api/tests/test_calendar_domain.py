    забор = dt.datetime(2026, 10, 11, 4, tzinfo=dt.UTC)
    сессия.add(пара("пара", dt.date(2026, 10, 11), 7, забор=забор))
    сессия.flush()

    итог = давность(сессия, настройки(), СЕЙЧАС + dt.timedelta(days=3), МОСКВА)

    assert итог.covered_from == dt.date(2026, 10, 4)
    assert итог.covered_to == dt.date(2026, 11, 8)


