МОСКВА = ZoneInfo("Europe/Moscow")

# Среда 14 октября 2026, 07:10 по Москве. Неделя этой даты - Пн 12 ... Вс 18,
# ровно та, что нарисована в утверждённом макете.
СЕЙЧАС = dt.datetime(2026, 10, 14, 4, 10, tzinfo=dt.UTC)
СРЕДА = dt.date(2026, 10, 14)


def настройки(**переопределения: object) -> Settings:
    return Settings(**переопределения)  # type: ignore[arg-type]


def пара(
    ключ: str,
    день: dt.date,
    час_utc: int,
    минута_utc: int = 0,
    длительность: dt.timedelta = dt.timedelta(hours=1, minutes=30),
    забор: dt.datetime = СЕЙЧАС,
) -> ItmoLesson:
    начало = dt.datetime.combine(день, dt.time(час_utc, минута_utc), tzinfo=dt.UTC)
    return ItmoLesson(
        source_key=ключ,
        lesson_date=день,
        starts_at=начало,
        ends_at=начало + длительность,
        subject="Математический анализ",
        kind="Лекции",
        teacher="Иванов И. И.",
        room="ауд. 285",
        building="Кронверкский пр., 49",
        mode="Очный",
        online_url=None,
        fetched_at=забор,
    )


def личное(
    ключ: str,
    начало: dt.datetime,
    длительность: dt.timedelta = dt.timedelta(hours=1),
    календарь: str = "events",
) -> CalendarEvent:
    return CalendarEvent(
        external_key=ключ,
        calendar=календарь,
        source="capture",
        title="Стоматолог",
        starts_at=начало,
        ends_at=начало + длительность,
        location="ул. Марата 12",
        description=None,
        content_hash="хэш",
        sync_state="pending",
    )


def событие(начало: str, конец: str, ключ: str = "к") -> Событие:
    """Событие для проверки конфликтов. Времена - "HH:MM" того же дня."""

    def момент(текст: str) -> dt.datetime:
        часы, минуты = текст.split(":")
        return dt.datetime.combine(СРЕДА, dt.time(int(часы), int(минуты)), tzinfo=МОСКВА)

    return Событие(
        key=ключ,
        source="event",
        starts_at=момент(начало),
        ends_at=момент(конец),
        title=ключ,
    )


