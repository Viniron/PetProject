def test_пустой_день_внутри_покрытия_отличим_от_дня_без_данных(сессия: Session) -> None:
    """Три вида пустоты обязаны различаться. Здесь два из них: четверг внутри
    окна забора - «пар нет», а день за окном - «сохранённых данных нет»."""
    сессия.add(пара("пара", СРЕДА, 7))
    сессия.flush()

