def test_конфликт_считается_через_полночь(сессия: Session) -> None:
    """Событие через полночь принадлежит дню начала, но наложение с событием
    следующего дня посчитано - иначе «⚠» пропало бы у обоих."""
    сессия.add_all(
        [
            личное(
                "ночное",
                dt.datetime(2026, 10, 14, 21, tzinfo=dt.UTC),
                длительность=dt.timedelta(hours=4),
            ),
            личное("утреннее", dt.datetime(2026, 10, 14, 23, tzinfo=dt.UTC)),
        ]
    )
    сессия.flush()

    сетка = собрать(сессия, настройки(), СЕЙЧАС, "week")
    конфликты = {с.key: с.conflict for д in сетка.days for с in д.events}

    assert конфликты == {"ночное": True, "утреннее": True}


