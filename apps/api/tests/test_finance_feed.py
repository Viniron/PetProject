"""Лента, карточка и давность книжки (Ф6, §15.7, §15.6).

Лента показывает деньги, а не строки: у расхода с гашениями видна
эффективная сумма, и она обязана совпадать с той, по которой посчитано
сальдо. Разойдись они - книжка показывала бы одну цену покупки в ленте
и другую в обзоре месяца, и какая из них верна, owner бы не узнал.

Давность проверяется отдельно и по одному правилу с `покрыто_по`: книжка
свежа настолько, насколько свежа её отстающая часть (§15.6).
"""

import datetime as dt
from decimal import Decimal
from typing import Any
from zoneinfo import ZoneInfo

import pytest
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinAccount, FinCategory, FinImport, FinTransaction
from jarvis_api.domain.finance_feed import давность, карточка, лента

МОСКВА = ZoneInfo("Europe/Moscow")
БАНК = "tbank"
ВТОРОЙ_БАНК = "ozon"
КАРТА = "Black"
АВГУСТ = dt.date(2026, 8, 1)

В_АВГУСТЕ = dt.datetime(2026, 8, 23, 12, 0, tzinfo=МОСКВА)
ПОЗЖЕ_В_АВГУСТЕ = dt.datetime(2026, 8, 24, 12, 0, tzinfo=МОСКВА)
В_СЕНТЯБРЕ = dt.datetime(2026, 9, 15, 12, 0, tzinfo=МОСКВА)
СЕЙЧАС = dt.datetime(2026, 9, 21, 12, 0, tzinfo=МОСКВА)


def операция(сессия: Session, момент: dt.datetime, сумма: str, **поля: Any) -> FinTransaction:
    значение = Decimal(сумма)
    все: dict[str, Any] = {
        "bank": БАНК,
        "account": КАРТА,
        "occurred_at": момент,
        "amount": значение,
        "amount_rub": значение,
        "currency": "RUB",
        "kind": "expense" if значение < 0 else "income",
        "fingerprint": f"{момент.isoformat()}{сумма}{поля.get('merchant', '')}".ljust(64, "0")[:64],
    }
    все.update(поля)
    строка = FinTransaction(**все)
    сессия.add(строка)
    сессия.flush()
    return строка


@pytest.fixture
def книжка(сессия: Session) -> Session:
    сессия.add(FinAccount(bank=БАНК, name=КАРТА, role="checking"))
    сессия.flush()
    return сессия


# --- лента ------------------------------------------------------------------


def test_эффективная_сумма_расхода_учитывает_гашения(книжка: Session) -> None:
    """Оплатил стол 5 750 ₽, скинули 2 300 ₽ - расход стоил 3 450 ₽ (§15.5)."""
    расход = операция(книжка, В_АВГУСТЕ, "-5750.00")
    операция(
        книжка,
        ПОЗЖЕ_В_АВГУСТЕ,
        "2300.00",
        kind="refund",
        kind_source="manual",
        offsets_transaction_id=расход.id,
    )

    строки = {с.id: с for с in лента(книжка, месяц_=АВГУСТ, только_разбор=False, зона=МОСКВА)}

    assert строки[расход.id].эффективная == Decimal("3450.00")
    assert строки[расход.id].погашено == Decimal("2300.00")


def test_у_прихода_эффективной_суммы_нет(книжка: Session) -> None:
    """`null`, а не ноль: ноль читался бы как «всё погашено»."""
    приход = операция(книжка, В_АВГУСТЕ, "11080.00")

    строка = лента(книжка, месяц_=АВГУСТ, только_разбор=False, зона=МОСКВА)[0]

    assert строка.id == приход.id
    assert строка.эффективная is None
    assert строка.погашено is None


def test_строка_в_разборе_в_счёт_не_идёт(книжка: Session) -> None:
    операция(книжка, В_АВГУСТЕ, "-1200.00", needs_review=True)

    строка = лента(книжка, месяц_=АВГУСТ, только_разбор=False, зона=МОСКВА)[0]

    assert строка.в_счёт is False


def test_месяц_считается_в_зоне_owner(книжка: Session) -> None:
    """Полночь 1 сентября по Москве - это август по UTC (инвариант 7)."""
    операция(книжка, dt.datetime(2026, 9, 1, 0, 30, tzinfo=МОСКВА), "-100.00")

    в_августе = лента(книжка, месяц_=АВГУСТ, только_разбор=False, зона=МОСКВА)
    в_сентябре = лента(книжка, месяц_=dt.date(2026, 9, 1), только_разбор=False, зона=МОСКВА)

    assert в_августе == []
    assert len(в_сентябре) == 1


def test_очередь_разбора_собирается_по_всей_книжке(книжка: Session) -> None:
    """Вопрос августа не перестаёт быть вопросом в сентябре."""
    операция(книжка, В_АВГУСТЕ, "2300.00", needs_review=True)
    операция(книжка, В_СЕНТЯБРЕ, "-100.00")

    очередь = лента(книжка, месяц_=None, только_разбор=True, зона=МОСКВА)

    assert len(очередь) == 1
    assert очередь[0].needs_review


def test_свежая_операция_сверху(книжка: Session) -> None:
    ранняя = операция(книжка, В_АВГУСТЕ, "-100.00")
    поздняя = операция(книжка, ПОЗЖЕ_В_АВГУСТЕ, "-200.00")

    строки = лента(книжка, месяц_=АВГУСТ, только_разбор=False, зона=МОСКВА)

    assert [с.id for с in строки] == [поздняя.id, ранняя.id]


def test_категория_приезжает_ключом_и_названием(книжка: Session) -> None:
    книжка.add(FinCategory(key="food", period_month=АВГУСТ, level=1, title="Еда", origin="owner"))
    книжка.flush()
    категория = книжка.query(FinCategory).one()
    операция(книжка, В_АВГУСТЕ, "-1200.00", category_id=категория.id, category_source="mcc")

    строка = лента(книжка, месяц_=АВГУСТ, только_разбор=False, зона=МОСКВА)[0]

    assert (строка.category_key, строка.category_title) == ("food", "Еда")


# --- карточка ---------------------------------------------------------------


def test_карточка_расхода_несёт_разбивку_и_гашения(книжка: Session) -> None:
    расход = операция(книжка, В_АВГУСТЕ, "-5750.00")
    гашение = операция(
        книжка,
        ПОЗЖЕ_В_АВГУСТЕ,
        "6000.00",
        kind="refund",
        kind_source="manual",
        offsets_transaction_id=расход.id,
    )

    это = карточка(книжка, расход.id)

    assert это is not None
    assert это.разбивка is not None
    # Скинули больше, чем стоил стол: расход гасится до нуля, остаток - доход.
    assert это.разбивка.эффективная == Decimal("0.00")
    assert это.разбивка.излишек == Decimal("250.00")
    assert [г.id for г in это.гашения] == [гашение.id]


def test_карточка_поступления_показывает_расход(книжка: Session) -> None:
    """У поступления виден расход, который оно гасит, - с его эффективной суммой."""
    расход = операция(книжка, В_АВГУСТЕ, "-5750.00")
    гашение = операция(
        книжка,
        ПОЗЖЕ_В_АВГУСТЕ,
        "2300.00",
        kind="refund",
        kind_source="manual",
        offsets_transaction_id=расход.id,
    )

    это = карточка(книжка, гашение.id)

    assert это is not None
    assert это.разбивка is None
    assert это.гасит is not None
    assert это.гасит.эффективная == Decimal("3450.00")


def test_карточки_несуществующей_операции_нет(книжка: Session) -> None:
    assert карточка(книжка, 10_000) is None


# --- давность ---------------------------------------------------------------


def выгрузка(банк: str, по: dt.date, загружено: dt.datetime) -> FinImport:
    return FinImport(
        bank=банк,
        filename=f"{банк}.csv",
        sha256=f"{банк}{по}".ljust(64, "0")[:64],
        period_start=dt.date(2026, 8, 1),
        period_end=по,
        imported_at=загружено,
    )


def test_пустая_книжка_не_просрочена(книжка: Session) -> None:
    """Напоминать не о чем: выписок не было ни одной (§15.6)."""
    это = давность(книжка, сейчас=СЕЙЧАС, зона=МОСКВА, порог_дней=8)

    assert (это.покрыто_по, это.отстающий_банк, это.дней_назад) == (None, None, None)
    assert это.просрочено is False


def test_давность_считается_по_отстающему_банку(книжка: Session) -> None:
    """Один банк загружен вчера, другой три недели назад - книжка отстаёт."""
    книжка.add_all(
        [
            выгрузка(БАНК, dt.date(2026, 9, 20), dt.datetime(2026, 9, 20, 10, tzinfo=МОСКВА)),
            выгрузка(
                ВТОРОЙ_БАНК, dt.date(2026, 8, 31), dt.datetime(2026, 8, 31, 10, tzinfo=МОСКВА)
            ),
        ]
    )
    книжка.flush()

    это = давность(книжка, сейчас=СЕЙЧАС, зона=МОСКВА, порог_дней=8)

    assert это.отстающий_банк == ВТОРОЙ_БАНК
    assert это.покрыто_по == dt.date(2026, 8, 31)
    assert это.дней_назад == 21
    assert это.просрочено


def test_свежая_книжка_не_просрочена(книжка: Session) -> None:
    книжка.add(выгрузка(БАНК, dt.date(2026, 9, 20), dt.datetime(2026, 9, 20, 10, tzinfo=МОСКВА)))
    книжка.flush()

    это = давность(книжка, сейчас=СЕЙЧАС, зона=МОСКВА, порог_дней=8)

    assert это.дней_назад == 1
    assert это.просрочено is False


def test_банк_без_периода_покрытия_не_даёт(книжка: Session) -> None:
    """Файл, не называющий период, покрывающим не считается - и это не догадка."""
    книжка.add(выгрузка(БАНК, dt.date(2026, 9, 20), dt.datetime(2026, 9, 20, 10, tzinfo=МОСКВА)))
    безымянный = выгрузка(
        ВТОРОЙ_БАНК, dt.date(2026, 9, 1), dt.datetime(2026, 9, 1, 10, tzinfo=МОСКВА)
    )
    безымянный.period_start = None
    безымянный.period_end = None
    книжка.add(безымянный)
    книжка.flush()

    это = давность(книжка, сейчас=СЕЙЧАС, зона=МОСКВА, порог_дней=8)

    assert это.покрыто_по is None
    assert это.отстающий_банк == ВТОРОЙ_БАНК
