"""Отложенная пачка на стороне ядра (Э12б, ADR-046).

Проверяется то, что в пачке ломается тихо и дорого:

- **скидка вдвое доезжает до `audit_log`.** Без неё месячный потолок считает
  вдвое больше потраченного и однажды остановит работу на ровном месте;
- **строка аудита на каждое задание**, а не одна на пачку: сотня операций,
  записанная как один дешёвый вызов, делает потолок бессмысленным;
- **отказ по одному заданию не роняет остальные**: они оплачены.
"""

from decimal import Decimal

import pytest
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.orm import Session

from jarvis_api.config import Settings
from jarvis_api.db.models import AuditLogEntry
from jarvis_api.integrations.llm import batch
from jarvis_api.integrations.llm.base import Ответ, ОтказПровайдера, СостояниеБатча
from jarvis_api.integrations.llm.client import ОшибкаСлоя
from jarvis_api.integrations.llm.prompts import Промпт
from jarvis_api.integrations.llm.routing import Маршрут
from jarvis_api.integrations.llm.tasks import Задача

АКТОР = "tests.batch"


class Категория(BaseModel):
    category: str


def промпт(текст: str) -> Промпт:
    return Промпт(имя="проба", версия=1, стабильная_часть="Правила.", переменная_часть=текст)


def маршрут(*, batch_режим: bool = True) -> Маршрут:
    return Маршрут(
        provider="провайдер-а",
        model="модель-1",
        max_tokens=64,
        price_in=Decimal("1"),
        price_out=Decimal("5"),
        batch=batch_режим,
    )


class ПодставнойБатч:
    """Провайдер с пачками: запоминает отправленное, отвечает по сценарию."""

    имя = "провайдер-а"

    def __init__(self, результаты: list[tuple[str, Ответ | Exception]]) -> None:
        self.результаты = результаты
        self.отправленное: dict[str, object] = {}

    def выполнить(self, запрос: object) -> Ответ:
        raise AssertionError("пачка не ходит обычным вызовом")

    def отправить_батч(self, запросы: dict[str, object]) -> str:
        self.отправленное = dict(запросы)
        return "batch-1"

    def состояние_батча(self, идентификатор: str) -> СостояниеБатча:
        return СостояниеБатча(готов=True, сырое="ended")

    def результаты_батча(self, идентификатор: str):  # type: ignore[no-untyped-def]
        yield from self.результаты


class БезПачек:
    имя = "провайдер-а"

    def выполнить(self, запрос: object) -> Ответ:
        raise AssertionError("не должно вызываться")


def настройки() -> Settings:
    return Settings(llm_timeout_seconds=42)


def ответ(текст: str = '{"category": "Еда"}') -> Ответ:
    return Ответ(текст=текст, токенов_вход=1000, токенов_выход=100)


# --- отправка ---------------------------------------------------------------


def test_потолок_ответа_и_модель_доезжают_до_каждого_задания() -> None:
    провайдер = ПодставнойБатч([])
    batch.отправить(
        маршрут=маршрут(),
        задания={
            "оп-1": batch.Задание(промпт=промпт("кофе")),
            "оп-2": batch.Задание(промпт=промпт("метро")),
        },
        схема=Категория,
        настройки=настройки(),
        адаптеры={"провайдер-а": провайдер},
    )

    assert set(провайдер.отправленное) == {"оп-1", "оп-2"}
    assert all(з.max_tokens == 64 for з in провайдер.отправленное.values())  # type: ignore[attr-defined]


def test_пустая_пачка_отвергается() -> None:
    with pytest.raises(ОшибкаСлоя, match="пустая"):
        batch.отправить(
            маршрут=маршрут(),
            задания={},
            схема=Категория,
            настройки=настройки(),
            адаптеры={"провайдер-а": ПодставнойБатч([])},
        )


def test_провайдер_без_пачек_говорит_это_словами() -> None:
    """Ошибка назначения, а не вызова: чинится строкой в LLM_ROUTING."""
    with pytest.raises(batch.БатчНеПоддержан, match="пачек не умеет"):
        batch.отправить(
            маршрут=маршрут(),
            задания={"оп-1": batch.Задание(промпт=промпт("кофе"))},
            схема=Категория,
            настройки=настройки(),
            адаптеры={"провайдер-а": БезПачек()},
        )


# --- разбор -----------------------------------------------------------------


def test_скидка_вдвое_доезжает_до_аудита(сессия: Session) -> None:
    """Иначе месячный потолок считает вдвое больше потраченного - молча."""
    провайдер = ПодставнойБатч([("оп-1", ответ())])

    исход = batch.забрать(
        сессия,
        задача=Задача.КНИЖКА_КАТЕГОРИЯ,
        маршрут=маршрут(),
        идентификатор="batch-1",
        схема=Категория,
        актор=АКТОР,
        промпты={"оп-1": промпт("кофе")},
        адаптеры={"провайдер-а": провайдер},
    )

    # 1000 входа по $1 и 100 выхода по $5 за 1M - это $0.0015, пачкой вдвое.
    assert исход[0].стоимость_usd == Decimal("0.000750")
    запись = сессия.scalars(select(AuditLogEntry)).one()
    assert запись.cost_usd == Decimal("0.000750")
    assert (запись.detail or {})["batch"] is True


def test_строка_аудита_на_каждое_задание(сессия: Session) -> None:
    провайдер = ПодставнойБатч([("оп-1", ответ()), ("оп-2", ответ()), ("оп-3", ответ())])

    batch.забрать(
        сессия,
        задача=Задача.КНИЖКА_КАТЕГОРИЯ,
        маршрут=маршрут(),
        идентификатор="batch-1",
        схема=Категория,
        актор=АКТОР,
        промпты={},
        адаптеры={"провайдер-а": провайдер},
    )

    assert len(сессия.scalars(select(AuditLogEntry)).all()) == 3


def test_отказ_по_заданию_не_роняет_соседей(сессия: Session) -> None:
    """Сотня операций, где одна не разобралась, обязана отдать девяносто девять."""
    провайдер = ПодставнойБатч(
        [("оп-1", ответ()), ("оп-2", ОтказПровайдера("вход слишком длинный"))]
    )

    исход = batch.забрать(
        сессия,
        задача=Задача.КНИЖКА_КАТЕГОРИЯ,
        маршрут=маршрут(),
        идентификатор="batch-1",
        схема=Категория,
        актор=АКТОР,
        промпты={},
        адаптеры={"провайдер-а": провайдер},
    )

    по_ключу = {строка.ключ: строка for строка in исход}
    assert по_ключу["оп-1"].значение is not None
    assert по_ключу["оп-2"].значение is None
    # За отказ провайдер токенов не назвал - платим за ответы, а не за отказы.
    assert по_ключу["оп-2"].стоимость_usd == Decimal(0)


def test_ответ_мимо_схемы_всё_равно_оплачен(сессия: Session) -> None:
    """Токены за него списаны, и потолок обязан их видеть (ADR-047).

    Повтора нет намеренно: переспросить можно вызов, а не пачку - это новая
    пачка и ещё сутки.
    """
    провайдер = ПодставнойБатч([("оп-1", ответ('{"нет-такого-поля": 1}'))])

    исход = batch.забрать(
        сессия,
        задача=Задача.КНИЖКА_КАТЕГОРИЯ,
        маршрут=маршрут(),
        идентификатор="batch-1",
        схема=Категория,
        актор=АКТОР,
        промпты={},
        адаптеры={"провайдер-а": провайдер},
    )

    assert исход[0].значение is None
    assert исход[0].ошибка == "ответ мимо схемы"
    запись = сессия.scalars(select(AuditLogEntry)).one()
    assert запись.status == "error"
    assert запись.cost_usd == Decimal("0.000750")


def test_аудит_переживает_откат_вызывающего(сессия: Session) -> None:
    """Токены списаны провайдером, и откат работы вызывающего их не возвращает."""
    провайдер = ПодставнойБатч([("оп-1", ответ())])

    batch.забрать(
        сессия,
        задача=Задача.КНИЖКА_КАТЕГОРИЯ,
        маршрут=маршрут(),
        идентификатор="batch-1",
        схема=Категория,
        актор=АКТОР,
        промпты={},
        адаптеры={"провайдер-а": провайдер},
    )
    сессия.rollback()

    assert len(сессия.scalars(select(AuditLogEntry)).all()) == 1
