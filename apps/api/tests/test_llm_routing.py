def test_ни_одного_имени_модели_в_исходниках() -> None:
    """§5: платформа работает с любым назначением.

    Имя модели, просочившееся в код, превращает смену назначения в правку
    исходников - ровно то, что §5.2 запрещает. Проверяем весь пакет, а не
    только слой моделей: `if model == ...` опаснее всего как раз вне его.
    """
    import re
    from pathlib import Path

    корень = Path(__file__).resolve().parents[1] / "jarvis_api"
    # Ищем именно имена моделей с версией, а не слова «gemini» и «anthropic»:
    # имя переменной с ключом провайдера (GEMINI_API_KEY) кодом, зависящим
    # от модели, не является, и запрет на него был бы запретом на адаптер.
    имена_моделей = re.compile(r"(gemini|gpt|claude|llama|mistral)[-_][a-z0-9.]*\d", re.IGNORECASE)

    найдено: list[str] = []
    for файл in корень.rglob("*.py"):
        for номер, строка in enumerate(файл.read_text(encoding="utf-8").splitlines(), 1):
            if имена_моделей.search(строка):
                найдено.append(f"{файл.name}:{номер}")

    assert not найдено, f"имена моделей в коде: {найдено}"


