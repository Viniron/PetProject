def test_потолок_ответа_обязателен() -> None:
    """§5.2: `max_tokens` на каждом типе вызова. Умолчания нет намеренно."""
    без_потолка = {ключ: значение for ключ, значение in МАРШРУТ.items() if ключ != "max_tokens"}

