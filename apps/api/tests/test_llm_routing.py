def test_пример_из_env_example_разбирается() -> None:
    """Строку из `.env.example` owner скопирует на плату как есть.

    Опечатка в ней выглядела бы как «модель не назначена» - то самое рабочее
    состояние, от которого её не отличить глазами. Между примером и разбором
    нет ничего, что связывало бы их автоматически, поэтому связываем тестом,
    как с `environment:` в compose.
    """
    from pathlib import Path

    пример = Path(__file__).resolve().parents[3] / ".env.example"
    строки = [
        строка
        for строка in пример.read_text(encoding="utf-8").splitlines()
        if строка.startswith("LLM_ROUTING=")
    ]

    assert len(строки) == 1, "в .env.example ровно одна строка назначения"

    маршруты = загрузить_маршруты(строки[0].removeprefix("LLM_ROUTING="))

    # Календарь по ADR-046: одна задача, у неё резерв у второго провайдера.
    assert Задача.РАЗБОР_СОБЫТИЯ in маршруты
    разбор = маршруты[Задача.РАЗБОР_СОБЫТИЯ]
    assert разбор.fallback, "фолбэк внутри одного аккаунта не спасает от отказа аккаунта"
    assert разбор.provider != разбор.fallback[0].provider
    assert разбор.price_in > 0 and разбор.price_out > 0
