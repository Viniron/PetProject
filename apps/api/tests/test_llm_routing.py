"""Разбор назначения `LLM_ROUTING` (Э12а, §5.1, §5.2).

Главное требование §5.2 - «смена модели это правка конфига, не деплой» -
проверяется буквально: два разных значения переменной дают два разных
назначения, и ни одно имя модели не встречается в исходниках.
"""

import json
from decimal import Decimal

import pytest
from pydantic import ValidationError

from jarvis_api.integrations.llm.routing import (
    ПРЕДЕЛ_РЕЗЕРВОВ,
    Маршрут,
    МаршрутИспорчен,
    загрузить_маршруты,
    цепочка,
)
from jarvis_api.integrations.llm.tasks import Задача

МАРШРУТ = {
    "provider": "провайдер-а",
    "model": "модель-1",
    "max_tokens": 1024,
    "price_in": "0.25",
    "price_out": "1.50",
}


def назначение(**задачи: dict[str, object]) -> str:
    return json.dumps(задачи, ensure_ascii=False)


def test_пустое_назначение_не_ошибка() -> None:
    """Ключи у owner есть, маршрута нет - платформа обязана жить в этом виде."""
    assert загрузить_маршруты("") == {}
    assert загрузить_маршруты("   ") == {}


def test_маршрут_разбирается_целиком() -> None:
    маршруты = загрузить_маршруты(назначение(capture_parse=МАРШРУТ))

    маршрут = маршруты[Задача.РАЗБОР_СОБЫТИЯ]
    assert маршрут.provider == "провайдер-а"
    assert маршрут.model == "модель-1"
    assert маршрут.max_tokens == 1024
    assert маршрут.price_in == Decimal("0.25")
    assert маршрут.price_out == Decimal("1.50")


def test_смена_модели_это_правка_переменной() -> None:
    """§5.2: назначение меняется без единой правки кода."""
    было = загрузить_маршруты(назначение(capture_parse=МАРШРУТ))
    стало = загрузить_маршруты(назначение(capture_parse={**МАРШРУТ, "model": "модель-2"}))

    assert было[Задача.РАЗБОР_СОБЫТИЯ].model == "модель-1"
    assert стало[Задача.РАЗБОР_СОБЫТИЯ].model == "модель-2"


def test_цена_числом_с_плавающей_точкой_отвергается() -> None:
    """Деньги - Decimal (CLAUDE.md). JSON не различает 0.25 и "0.25", различаем мы."""
    with pytest.raises(МаршрутИспорчен) as отказ:
        загрузить_маршруты(назначение(capture_parse={**МАРШРУТ, "price_in": 0.25}))

    assert "строкой" in str(отказ.value)


