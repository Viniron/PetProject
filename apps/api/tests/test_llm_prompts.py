def test_промпт_разбора_события_на_месте() -> None:
    """Единственный промпт этапа: назначение моделей на курсы owner не давал."""
    промпт = собрать(
        "capture_parse",
        now="2026-09-21T10:00:00",
        zone="Europe/Moscow",
        text="зубной в среду в 15:00",
    )

    assert промпт.версия >= 1
    assert "зубной в среду" in промпт.переменная_часть
    # Правило «не угадывать» (CLAUDE.md: нет даты или низкая уверенность -
    # спросить) обязано быть в стабильной части: в переменную оно уехало бы
    # вместе с кэшем.
    assert "Не угадывай" in промпт.стабильная_часть


def test_промпт_лежит_в_пакете() -> None:
    """Иначе он не доедет до образа, и отказ случится на плате, а не здесь."""
    assert (КАТАЛОГ / "capture_parse.md").is_file()
    assert КАТАЛОГ.name == "prompts"
    assert КАТАЛОГ.parent.name == "jarvis_api"


def test_промпты_объявлены_данными_пакета() -> None:
    """`packages` тянет в дистрибутив только .py - каталог приехал бы пустым.

    Тот же класс ошибки, что с подпакетами и с `environment:` в compose:
    между раскладкой на диске и содержимым образа нет ничего, что связывало
    бы их автоматически.
    """
    pyproject = Path(__file__).resolve().parents[1] / "pyproject.toml"
    текст = pyproject.read_text(encoding="utf-8")

    assert "[tool.setuptools.package-data]" in текст
    assert "prompts/*.md" in текст
    assert '"jarvis_api.integrations.llm"' in текст
