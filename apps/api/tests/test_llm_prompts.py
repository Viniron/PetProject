"""Промпты: версия, границы кэша, подстановки (Э12а, CLAUDE.md, §5.2).

Главная проверка здесь одна: **стабильная часть не меняется от входных
данных.** Кэш провайдера работает по общему префиксу, и подстановка, заехавшая
в начало, не ломает ничего видимого - ответы те же, ошибок нет, - но вход
перестаёт дешеветь. Обнаруживается это счётом в конце месяца, поэтому
CLAUDE.md требует держать инвариант тестом.

Имена промптов и подстановок здесь латиницей не случайно: имя файла - ключ,
которым промпт зовут из кода и которым он подписан в аудите, и разбирается
оно тем же ASCII-правилом `string.Template`, что и `$text`. Текст самого
промпта при этом какой угодно.
"""

from pathlib import Path

import pytest

from jarvis_api.integrations.llm.prompts import КАТАЛОГ, ПромптИспорчен, собрать

ЗАГОЛОВОК = "<!-- prompt: proba, version: 3 -->"
ТЕЛО = """
Роль и правила. Тут подстановок нет и быть не может.
<!-- variable -->
Сейчас: $now.
Заметка: $text
"""


@pytest.fixture
def каталог(tmp_path: Path) -> Path:
    (tmp_path / "proba.md").write_text(ЗАГОЛОВОК + ТЕЛО, encoding="utf-8")
    return tmp_path


def test_промпт_разбирается(каталог: Path) -> None:
    промпт = собрать("proba", каталог=каталог, now="2026-09-21T10:00:00", text="зубной в среду")

    assert промпт.версия == 3
    assert промпт.стабильная_часть.startswith("Роль и правила")
    assert "зубной в среду" in промпт.переменная_часть


def test_стабильная_часть_не_зависит_от_входа(каталог: Path) -> None:
    """Тот самый инвариант: префикс байт в байт одинаков на любых данных."""
    первый = собрать("proba", каталог=каталог, now="2026-09-21T10:00:00", text="а")
    второй = собрать("proba", каталог=каталог, now="2027-01-01T23:59:00", text="я" * 500)

    assert первый.стабильная_часть == второй.стабильная_часть
    assert первый.стабильная_часть.encode() == второй.стабильная_часть.encode()


def test_подстановка_в_стабильной_части_отвергается(tmp_path: Path) -> None:
    """Иначе кэш молча перестаёт попадать - отказ без единой ошибки в логе."""
    содержимое = "<!-- prompt: holey, version: 1 -->\nПривет, $name!\n<!-- variable -->\nтекст"
    (tmp_path / "holey.md").write_text(содержимое, encoding="utf-8")

    with pytest.raises(ПромптИспорчен) as отказ:
        собрать("holey", каталог=tmp_path, name="кто-то")

    assert "кэш" in str(отказ.value)


def test_нехватка_поля_это_отказ(каталог: Path) -> None:
    """Промпт с дырой вместо текста события уехал бы разбирать пустоту."""
    with pytest.raises(ПромптИспорчен) as отказ:
        собрать("proba", каталог=каталог, now="2026-09-21T10:00:00")

    assert "text" in str(отказ.value)


def test_имя_в_заголовке_сверяется_с_файлом(tmp_path: Path) -> None:
    """Переименованный файл иначе тихо стал бы другим промптом с чужой версией."""
    содержимое = "<!-- prompt: original, version: 1 -->\nправила\n<!-- variable -->\nтекст"
    (tmp_path / "renamed.md").write_text(содержимое, encoding="utf-8")

    with pytest.raises(ПромптИспорчен) as отказ:
        собрать("renamed", каталог=tmp_path)

    assert "original" in str(отказ.value)


