# Понедельник 14 сентября 2026 - неделя, на которой идёт вся арифметика ниже.
ПОНЕДЕЛЬНИК = dt.date(2026, 9, 14)
СРЕДА = dt.date(2026, 9, 16)
ВОСКРЕСЕНЬЕ = dt.date(2026, 9, 20)

БАНК = "tbank"
СЧЁТ = "Black"


def неделя(
    *,
    бюджет: Decimal | None = Decimal("7000.00"),
    перенос: Decimal = НОЛЬ,
    траты: dict[int, str] | None = None,
    распределена: bool = False,
) -> Неделя:
    """Неделя из семи дней. `траты` - {номер дня с нуля: сумма строкой}.

    День, которого нет в `траты`, остаётся неизвестным: именно он и делает
    делитель, поэтому «не указан» здесь никогда не значит «ноль».
    """
    траты = траты or {}
    дни = tuple(
        День(
            день=ПОНЕДЕЛЬНИК + dt.timedelta(days=номер),
            сумма=Decimal(траты[номер]) if номер in траты else None,
            источник=РУЧНОЙ if номер in траты else НЕИЗВЕСТЕН,
            ручная=Decimal(траты[номер]) if номер in траты else None,
        )
        for номер in range(7)
    )
    return Неделя(
        начало=ПОНЕДЕЛЬНИК,
        бюджет=бюджет,
        перенос=перенос,
        дни=дни,
        распределена=распределена,
    )


