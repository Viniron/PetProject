"""Недельный бюджет и дневной лимит (Ф12, §15.10).

Арифметика здесь тихая: ошибка не падает, а показывает правдоподобную цифру,
по которой owner тратит деньги. Поэтому проверяется не «функция вернула
число», а поведение на краях - воскресенье без открытых дней, неделя без
бюджета, гашение в уже распределённую неделю.

Первая половина файла без базы вовсе: `лимит` и `итог` - чистые функции
от `Неделя`, и собирать ради них Postgres значило бы проверять сборку
вместо арифметики. Вторая половина - сборка из базы, где проверяется ровно
обратное: что неделя собирается из строк такой, какой арифметика её ждёт.
"""

