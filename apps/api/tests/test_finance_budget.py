def test_лимит_округляется_вниз() -> None:
    """Сумма дневных лимитов не должна превышать недельный бюджет.

    100 ₽ на 3 дня вверх дали бы 33.34 × 3 = 100.02 - разрешение потратить
    больше, чем есть.
    """
    полная = {номер: "0.00" for номер in range(4)}
    пятница = ПОНЕДЕЛЬНИК + dt.timedelta(days=4)
    результат = лимит(неделя(бюджет=Decimal("100.00"), траты=полная), пятница)

    assert результат.открытых_дней == 3
    assert результат.сумма == Decimal("33.33")


