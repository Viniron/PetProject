def test_гашение_в_закрытую_неделю_уходит_поправкой_в_текущую(сессия: Session) -> None:
    """Распределённая неделя не переигрывается: решение owner уже принято.

    Разница между снимком и новым фактом уходит в ближайшую нераспределённую
    неделю - иначе изменился бы итог, который owner уже разложил по двум
    статьям, и копилка задним числом стала бы другой.
    """
    прошлая = ПОНЕДЕЛЬНИК - dt.timedelta(days=7)
    сессия.add(счёт())
    сессия.add(выгрузка(по=ВОСКРЕСЕНЬЕ))
    стол = расход(прошлая, "5000.00")
    сессия.add(стол)
    сессия.add(
        FinWeekBudget(
            week_start=прошлая,
            amount=Decimal("7000.00"),
            to_next=Decimal("2000.00"),
            to_savings=НОЛЬ,
            settled_spend=Decimal("5000.00"),
            settled_at=dt.datetime(2026, 9, 14, 6, 0, tzinfo=dt.UTC),
        )
    )
    сессия.add(FinWeekBudget(week_start=ПОНЕДЕЛЬНИК, amount=Decimal("7000.00")))
    сессия.flush()

    # Доли за стол скинули уже на новой неделе - расход прошлой подешевел.
    сессия.add(
        расход(
            СРЕДА,
            "0.00",
            amount=Decimal("1200.00"),
            amount_rub=Decimal("1200.00"),
            kind="refund",
            offsets_transaction_id=стол.id,
            fingerprint="dolya".ljust(64, "0"),
        )
    )
    сессия.flush()

    затронуты = разнести_поправки(сессия, СРЕДА, МОСКВА)

    закрытая = сессия.scalar(select(FinWeekBudget).where(FinWeekBudget.week_start == прошлая))
    текущая = собрать_неделю(сессия, ПОНЕДЕЛЬНИК, МОСКВА)

    assert затронуты == [прошлая]
    # Итог закрытой недели не тронут: owner распределил 2000, так и осталось.
    assert закрытая is not None
    assert текущая.перенос == Decimal("3200.00")  # 2000 переноса + 1200 поправки


def test_поправка_не_применяется_дважды(сессия: Session) -> None:
    """Снимок сдвигается на новый факт - иначе повторный вызов удвоил бы деньги."""
    прошлая = ПОНЕДЕЛЬНИК - dt.timedelta(days=7)
    сессия.add(счёт())
    сессия.add(выгрузка(по=ВОСКРЕСЕНЬЕ))
    сессия.add(расход(прошлая, "4000.00"))
    сессия.add(
        FinWeekBudget(
            week_start=прошлая,
            amount=Decimal("7000.00"),
            to_next=НОЛЬ,
            to_savings=НОЛЬ,
            settled_spend=Decimal("5000.00"),
            settled_at=dt.datetime(2026, 9, 14, 6, 0, tzinfo=dt.UTC),
        )
    )
    сессия.flush()

    первый = разнести_поправки(сессия, СРЕДА, МОСКВА)
    после_первого = собрать_неделю(сессия, ПОНЕДЕЛЬНИК, МОСКВА).перенос
