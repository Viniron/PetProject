def test_понедельник_делит_бюджет_на_семь() -> None:
    результат = лимит(неделя(), ПОНЕДЕЛЬНИК)

    assert результат.сумма == Decimal("1000.00")
    assert результат.на_день == ПОНЕДЕЛЬНИК
    assert результат.открытых_дней == 7


def test_внесённая_трата_закрывает_сегодня_и_лимит_становится_завтрашним() -> None:
    """Главное решение owner: внёс сумму за сегодня - сегодня вышел из делителя.

    До ввода цифра означает «сегодня», после - «завтра». Без этого сдвига
    вечерний лимит читался бы как разрешение потратить ещё столько же.
    """
    до = лимит(неделя(), ПОНЕДЕЛЬНИК)
    после = лимит(неделя(траты={0: "1500.00"}), ПОНЕДЕЛЬНИК)

    assert до.на_день == ПОНЕДЕЛЬНИК
    assert до.открытых_дней == 7
    # 7000 − 1500 = 5500 на шесть оставшихся дней.
    assert после.на_день == ПОНЕДЕЛЬНИК + dt.timedelta(days=1)
    assert после.открытых_дней == 6
    assert после.сумма == Decimal("916.66")


def test_перерасход_урезает_следующие_дни() -> None:
    """Потратил вчера много - завтрашний лимит просел, а не остался прежним."""
    результат = лимит(неделя(траты={0: "3000.00", 1: "2000.00"}), СРЕДА)

    # 7000 − 5000 = 2000 на пять оставшихся дней.
    assert результат.сумма == Decimal("400.00")
    assert результат.открытых_дней == 5


