# --- сборка из базы -------------------------------------------------------


def счёт() -> FinAccount:
    return FinAccount(bank=БАНК, name=СЧЁТ, role="checking")


def расход(день: dt.date, сумма: str, **переопределения: Any) -> FinTransaction:
    """Расход в московский полдень - чтобы смена зоны не переносила его в сутки рядом."""
    поля: dict[str, Any] = {
        "bank": БАНК,
        "account": СЧЁТ,
        "occurred_at": dt.datetime.combine(день, dt.time(12, 0), tzinfo=МОСКВА),
        "amount": Decimal(f"-{сумма}"),
        "amount_rub": Decimal(f"-{сумма}"),
        "currency": "RUB",
        "kind": "expense",
        "fingerprint": f"{день.isoformat()}-{сумма}".ljust(64, "0"),
    }
    поля.update(переопределения)
    return FinTransaction(**поля)


def выгрузка(по: dt.date | None, банк: str = БАНК, **переопределения: Any) -> FinImport:
    поля: dict[str, Any] = {
        "bank": банк,
        "filename": f"{банк}.csv",
        "sha256": f"{банк}{по}".ljust(64, "0")[:64],
        "period_start": dt.date(2026, 9, 1),
        "period_end": по,
    }
    поля.update(переопределения)
    return FinImport(**поля)


