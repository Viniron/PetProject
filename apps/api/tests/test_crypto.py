"""Тесты шифрования секретов (Э3).

Проверяется не «шифрует ли AES-GCM» - это работа библиотеки. Проверяется
то, ради чего модуль написан: значение возвращается байт в байт, чужой ключ
не открывает, испорченная строка не открывается молча, и кривой ISU_CRED_KEY
даёт внятный отказ, а не падение где-то в недрах.
"""

import base64
import os

import pytest

from jarvis_api.config import Settings
from jarvis_api.crypto import SecretCipher, SecretCipherError, build_cipher

# Ключ теста, а не боевой: тридцать два нуля. Секретом он быть не может
# и им не является - это ровно та величина, которую проверяют на длину.
КЛЮЧ = base64.b64encode(bytes(32)).decode()
ДРУГОЙ_КЛЮЧ = base64.b64encode(bytes(range(32))).decode()


def test_пароль_возвращается_в_точности_каким_был() -> None:
    """Круг «зашифровали - расшифровали» не должен менять ни знака.

    Пароль ИСУ вводится в чужую форму: лишний пробел или потерянная буква
    выглядят как неверные учётные данные, и искать причину будут в портале.
    """
    шифр = SecretCipher.from_base64(КЛЮЧ)
    пароль = "п@роль с пробелом, юникодом ★ и хвостом  "

    assert шифр.decrypt(шифр.encrypt(пароль)) == пароль


def test_один_пароль_даёт_разные_шифротексты() -> None:
    """Nonce случаен на каждое шифрование - иначе GCM теряет стойкость.

    Заодно это означает, что по базе нельзя понять, совпадает ли новый
    пароль со старым.
    """
    шифр = SecretCipher.from_base64(КЛЮЧ)

    assert шифр.encrypt("одно и то же") != шифр.encrypt("одно и то же")


def test_чужой_ключ_не_открывает_значение() -> None:
    """Смысл всей затеи: дамп без ключа бесполезен."""
    свой = SecretCipher.from_base64(КЛЮЧ)
    чужой = SecretCipher.from_base64(ДРУГОЙ_КЛЮЧ)
    хранимое = свой.encrypt("пароль ИСУ")

    with pytest.raises(SecretCipherError, match="не расшифровывается"):
        чужой.decrypt(хранимое)


def test_подменённый_шифротекст_не_открывается_молча() -> None:
    """GCM аутентифицирует. Иначе битый байт дал бы другой пароль без ошибки."""
    шифр = SecretCipher.from_base64(КЛЮЧ)
    хранимое = bytearray(шифр.encrypt("пароль ИСУ"))
    хранимое[-1] ^= 0x01

    with pytest.raises(SecretCipherError):
        шифр.decrypt(bytes(хранимое))


def test_обрезанное_значение_отвергается_с_понятным_текстом() -> None:
    """Строка короче собственного заголовка - испорченная база, а не чужой ключ."""
    шифр = SecretCipher.from_base64(КЛЮЧ)

    with pytest.raises(SecretCipherError, match="короче собственного заголовка"):
        шифр.decrypt(os.urandom(8))


@pytest.mark.parametrize(
    ("значение", "ожидаемое"),
    [
        ("", "ISU_CRED_KEY пуст"),
        ("не base64!!", "не разбирается как base64"),
        (base64.b64encode(bytes(20)).decode(), "длиной 20 байт"),
    ],
)
def test_кривой_ключ_даёт_внятный_отказ(значение: str, ожидаемое: str) -> None:
    """Ошибка в .env должна читаться как ошибка в .env.

    Это единственное место, где owner может ошибиться руками, и текст
    отказа здесь - вся диагностика, которая у него будет.
    """
    with pytest.raises(SecretCipherError, match=ожидаемое):
        SecretCipher.from_base64(значение)


def test_ключ_из_настроек_терпит_перевод_строки() -> None:
    """`openssl rand -base64 32` копируется из терминала вместе с переводом строки.

    Падать на нём - издевательство: значение верное, а сообщение будет
    про неверный base64.
    """
    настройки = Settings(isu_cred_key=f"  {КЛЮЧ}\n")

    assert build_cipher(настройки).decrypt(build_cipher(настройки).encrypt("x")) == "x"
