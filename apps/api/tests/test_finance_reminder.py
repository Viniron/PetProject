"""Правило воскресного напоминания о выписках (Ф8, ADR-053): без базы и сети.

Ошибка здесь не падает, а выражается тишиной или лишним событием:
напоминание не пришло в то воскресенье, когда выписку забыли, или пришло,
когда всё загружено. Поэтому проверяются границы - неделя по зоне owner,
банк по отдельности, опоздание и конец дня.
"""

import datetime as dt
from zoneinfo import ZoneInfo

import pytest

from jarvis_api.domain.finance_reminder import Загрузка, Решение, _дней, ключ_недели, решить

МОСКВА = ZoneInfo("Europe/Moscow")
# 4 октября 2026 - воскресенье; неделя начинается в понедельник 28 сентября.
ВОСКРЕСЕНЬЕ = dt.date(2026, 10, 4)
УТРО = dt.datetime(2026, 10, 4, 6, 30, tzinfo=МОСКВА)
ПРОШЛОЕ_ВОСКРЕСЕНЬЕ = dt.datetime(2026, 9, 27, 19, 0, tzinfo=МОСКВА)
НА_ЭТОЙ_НЕДЕЛЕ = dt.datetime(2026, 10, 1, 20, 0, tzinfo=МОСКВА)


def загрузка(
    банк: str, загружено: dt.datetime, по: dt.date | None = dt.date(2026, 9, 26)
) -> Загрузка:
    return Загрузка(банк=банк, загружено_в=загружено.astimezone(dt.UTC), покрыто_по=по)


def решение(загрузки: list[Загрузка], сейчас: dt.datetime = УТРО) -> Решение:
    return решить(
        загрузки,
        сейчас=сейчас.astimezone(dt.UTC),
        зона=МОСКВА,
        время=dt.time(18, 0),
        минут=30,
        шаг_минут=15,
    )


def test_в_будни_не_напоминает() -> None:
    итог = решение(
        [загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)], dt.datetime(2026, 10, 3, 12, 0, tzinfo=МОСКВА)
    )

    assert итог.напоминание is None
    assert "не воскресенье" in итог.причина


def test_пустая_книжка_не_напоминает() -> None:
    """То же правило, что у плашки давности: напоминать не о чем."""
    итог = решение([])

    assert итог.напоминание is None


def test_все_банки_загружены_на_неделе_напоминания_нет() -> None:
    итог = решение([загрузка("tbank", НА_ЭТОЙ_НЕДЕЛЕ), загрузка("ozon", НА_ЭТОЙ_НЕДЕЛЕ)])

    assert итог.напоминание is None
    assert итог.причина == "все банки загружены на этой неделе"


def test_неделя_назад_это_уже_отставание() -> None:
    """Ровно та ошибка, из-за которой условие - неделя, а не порог давности.

    Выписка прошлого воскресенья лежит семь дней, порог плашки - восемь.
    Привязанное к порогу напоминание здесь промолчало бы.
    """
    итог = решение([загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)])

    assert итог.напоминание is not None
    assert "tbank: операции по 26.09.2026, загружено 7 дней назад" in итог.напоминание.описание


def test_один_банк_свежий_другой_отстаёт() -> None:
    """Свежая выписка одного банка не делает свежим другой (§15.6)."""
    итог = решение([загрузка("tbank", НА_ЭТОЙ_НЕДЕЛЕ), загрузка("ozon", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)])

    assert итог.напоминание is not None
    assert "ozon" in итог.напоминание.описание
    assert "tbank" not in итог.напоминание.описание
    assert итог.причина == "не загружены на этой неделе: ozon"


def test_понедельник_считается_по_зоне_owner() -> None:
    """01:00 понедельника по Москве - это ещё воскресенье по UTC.

    Сравнение моментов UTC отнесло бы такую выписку к прошлой неделе
    и напомнило о загруженном.
    """
    ночь_понедельника = dt.datetime(2026, 9, 28, 1, 0, tzinfo=МОСКВА)
    assert ночь_понедельника.astimezone(dt.UTC).date() == dt.date(2026, 9, 27)

    assert решение([загрузка("tbank", ночь_понедельника)]).напоминание is None
    поздний_вечер = dt.datetime(2026, 9, 27, 23, 30, tzinfo=МОСКВА)
    assert решение([загрузка("tbank", поздний_вечер)]).напоминание is not None


def test_событие_стоит_на_назначенное_время() -> None:
    напоминание = решение([загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)]).напоминание

    assert напоминание is not None
    assert напоминание.начало == dt.datetime(2026, 10, 4, 18, 0, tzinfo=МОСКВА)
    assert напоминание.конец == dt.datetime(2026, 10, 4, 18, 30, tzinfo=МОСКВА)
    # В UTC, как всё время в базе (инвариант 7).
    assert напоминание.начало.utcoffset() == dt.timedelta(0)


@pytest.mark.parametrize(
    ("сейчас", "начало"),
    [
        (dt.time(18, 0), dt.time(18, 0)),
        (dt.time(18, 0, 1), dt.time(18, 15)),
        (dt.time(18, 7), dt.time(18, 15)),
        (dt.time(18, 15), dt.time(18, 15)),
        (dt.time(21, 30), dt.time(21, 30)),
        (dt.time(23, 44), dt.time(23, 45)),
    ],
)
def test_опоздание_сдвигает_на_ближайшую_отметку(сейчас: dt.time, начало: dt.time) -> None:
    """Плата поднялась после 18:00: событие в прошлом не дало бы уведомления."""
    момент = dt.datetime.combine(ВОСКРЕСЕНЬЕ, сейчас, tzinfo=МОСКВА)

    напоминание = решение([загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)], момент).напоминание

    assert напоминание is not None
    assert напоминание.начало == dt.datetime.combine(ВОСКРЕСЕНЬЕ, начало, tzinfo=МОСКВА)


def test_к_полуночи_события_нет() -> None:
    """Задним числом в понедельник не пишем (инвариант 11): остаётся плашка."""
    момент = dt.datetime.combine(ВОСКРЕСЕНЬЕ, dt.time(23, 50), tzinfo=МОСКВА)

    итог = решение([загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)], момент)

    assert итог.напоминание is None
    assert "плашка давности" in итог.причина


def test_ключ_зависит_только_от_воскресенья() -> None:
    """Инвариант 5: утренний прогон и вечерний догон попадают в одно событие."""
    утро = решение([загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)]).напоминание
    вечер = решение(
        [загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ), загрузка("ozon", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ)],
        dt.datetime.combine(ВОСКРЕСЕНЬЕ, dt.time(20, 5), tzinfo=МОСКВА),
    ).напоминание

    assert утро is not None and вечер is not None
    assert утро.ключ == вечер.ключ == ключ_недели(ВОСКРЕСЕНЬЕ) == "finance:statements:2026-10-04"


def test_описание_по_порядку_отставания_и_без_выдумки() -> None:
    """Самый отстающий первым; банк без периода так и назван, без подставленной даты."""
    давно = dt.datetime(2026, 9, 13, 12, 0, tzinfo=МОСКВА)
    итог = решение([загрузка("tbank", ПРОШЛОЕ_ВОСКРЕСЕНЬЕ), загрузка("ozon", давно, по=None)])

    assert итог.напоминание is not None
    строки = итог.напоминание.описание.splitlines()
    assert строки[1] == "- ozon: период в выписке не указан, загружено 21 день назад"
    assert строки[2] == "- tbank: операции по 26.09.2026, загружено 7 дней назад"


