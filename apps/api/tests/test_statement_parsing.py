def test_секунды_не_потеряны(август: ParsedStatement) -> None:
    """Две пары операций различаются **только** секундами (§15.3).

    Это главное, что Ф2 обязан сохранить для Ф3: по дню, сумме и описанию
    пары совпадают, и любое упрощение времени превратило бы четыре операции
    в две — то есть потеряло бы деньги owner.
    """
    по_дню: dict[tuple[dt.date, Decimal, str | None], list[dt.datetime]] = {}
    for с in август.rows:
        местное = с.occurred_at.astimezone(МОСКВА)
        по_дню.setdefault((местное.date(), с.amount, с.merchant), []).append(с.occurred_at)
    пары = {к: v for к, v in по_дню.items() if len(v) > 1}
    assert len(пары) == 2, "в выгрузке за август таких пар ровно две"
    for моменты in пары.values():
        assert len(set(моменты)) == len(моменты), "секунды обязаны различать операции"


