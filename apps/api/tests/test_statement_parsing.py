@pytest.mark.parametrize(
    ("колонка", "значение", "в_сообщении"),
    [
        ("Дата операции", "31.08.2026 13:36", "не в формате"),
        ("Дата операции", "31-08-2026 13:36:02", "не в формате"),
        ("Номер карты", "3417", "не вида *1234"),
        ("MCC", "58-14", "не из цифр"),
        ("Имя счёта", "", "пустое имя счёта"),
        ("Валюта операции", "", "пустая валюта"),
        ("Сумма операции", "", "пуста"),
        ("Учёт в аналитике", "Возможно", "Учёт в аналитике"),
        # Четыре написания, которые `Decimal` принимает молча. Каждое прошло бы
        # в книжку, и арифметика сальдо не упала бы, а соврала: `NaN` отравляет
        # любую сумму, `Infinity` - тоже, `1e3` тихо становится тысячей,
        # разделитель тысяч пробелом - десятью рублями вместо десяти тысяч.
        ("Сумма операции", "NaN", "не похоже на сумму"),
        ("Сумма операции", "-Infinity", "не похоже на сумму"),
        ("Сумма операции", "-1e3", "не похоже на сумму"),
        ("Сумма операции", "-10 000,00", "не похоже на сумму"),
        ("Сумма в валюте счёта", "NaN", "не похоже на сумму"),
    ],
)
def test_каждое_поле_отклоняется_с_указанием_причины(
    колонка: str, значение: str, в_сообщении: str
) -> None:
    """Порча одного значения в настоящей строке — отказ, называющий её.

    Параметризацией, а не восемью фикстурами: файл на каждый случай пришлось
    бы держать в репозитории, а отличается он от настоящего одним полем.
    """
    сырьё = байты_фикстуры("statements", "tbank_august.csv").decode("utf-8")
    строки = сырьё.split("\r\n")
    поля = строки[1].split(";")
    поля[ADAPTER.columns.index(колонка)] = f'"{значение}"'
    испорченный = "\r\n".join([строки[0], ";".join(поля)]).encode("utf-8")
    with pytest.raises(RowError) as отказ:
        parse_statement(испорченный, МОСКВА)
    assert в_сообщении in str(отказ.value)
    assert "строка 2" in str(отказ.value)


def test_пропавшее_поле_в_строке_это_отказ() -> None:
    """Строка короче заголовка — сдвиг всех значений, а не пустая колонка.

    Без этой проверки `csv` подставил бы `None` в хвост, и сумма
    прочиталась бы из колонки валюты.
    """
    сырьё = байты_фикстуры("statements", "tbank_august.csv").decode("utf-8")
    строки = сырьё.split("\r\n")
    обрезанная = ";".join(строки[1].split(";")[:-1])
    with pytest.raises(RowError, match="полей 16"):
        parse_statement("\r\n".join([строки[0], обрезанная]).encode("utf-8"), МОСКВА)


def test_перевод_строки_внутри_кавычек_часть_поля() -> None:
    """Комментарий к переводу в две строки — одна операция, а не отказ.

    В августе «Сообщение» пусто во всех строках, поэтому случай синтетический.
    Заведён он не про запас: owner вправе подписать перевод в две строки,
    и тогда наивное чтение по строкам обвалило бы **весь файл** «числом
    полей» — при том что файл правильный.

    Номер строки при этом обязан остаться номером строки файла: операция
    занимает две, и вторая — та, на которой owner её увидит.
    """
    сырьё = байты_фикстуры("statements", "tbank_august.csv").decode("utf-8")
    строки = сырьё.split("\r\n")
    поля = строки[1].split(";")
    поля[ADAPTER.columns.index("Сообщение")] = '"за обед\r\nи за кофе"'
    файл = "\r\n".join([строки[0], ";".join(поля), строки[2]]).encode("utf-8")

    разобранная = parse_statement(файл, МОСКВА)
    assert len(разобранная.rows) == 2
    assert разобранная.rows[0].message == "за обед\r\nи за кофе"
    assert разобранная.rows[0].row_no == 3
    assert разобранная.rows[1].row_no == 4


def test_bom_не_ломает_опознание() -> None:
    """BOM в начале файла — не смена формата.

    Приехав однажды, он прилип бы к имени первой колонки, и файл перестал бы
    опознаваться как выписка Т-Банка вовсе: owner получил бы «неизвестный
    банк» на обычной выгрузке.
    """
    с_bom = b"\xef\xbb\xbf" + байты_фикстуры("statements", "tbank_august.csv")
    разобранная = parse_statement(с_bom, МОСКВА)
    assert разобранная.bank == "tbank"
    assert len(разобранная.rows) == 62


def test_зона_приходит_параметром() -> None:
    """Одна и та же строка в другой зоне — другой момент UTC.

    Зона не читается из настроек внутри разбора намеренно: иначе разбор
    нельзя было бы проверить без базы, а вторая копия зоны в коде рано или
    поздно разошлась бы с той, что в `settings`.
    """
    в_москве = разобрать("tbank_analytics_no.csv").rows[0].occurred_at
    в_utc = parse_statement(
        байты_фикстуры("statements", "tbank_analytics_no.csv"), ZoneInfo("UTC")
    ).rows[0]
    assert в_utc.occurred_at - в_москве == dt.timedelta(hours=3)
