def test_суммы_сходятся_с_августом(август: ParsedStatement) -> None:
    """Приход и расход августа — цель первого прогона Ф5.

    Здесь они проверяют разбор: потерянная на округлении копейка или
    проглоченная строка видны именно так, а не по числу строк.
    """
    приход = sum((с.amount for с in август.rows if с.amount > 0), Decimal("0"))
    расход = -sum((с.amount for с in август.rows if с.amount < 0), Decimal("0"))
    assert приход == ПРИХОД_АВГУСТА
    assert расход == РАСХОД_АВГУСТА
    assert приход - расход == Decimal("1160.21")


def test_необязательные_поля_переживают_пустоту(август: ParsedStatement) -> None:
    """Пустая строка CSV — это NULL. Проверено счётом настоящей выгрузки."""
    assert sum(1 for с in август.rows if с.card_last4 is None) == 25
    assert sum(1 for с in август.rows if с.mcc is None) == 18
    # Банковскими категориями owner не пользуется, комментариев к переводам
    # не пишет - обе колонки пусты во всех 62 строках.
    assert all(с.own_category is None for с in август.rows)
    assert all(с.message is None for с in август.rows)
    # А вот подсказки, которые есть всегда: без них разбор был бы слепым.
    assert all(с.bank_category for с in август.rows)
    assert all(с.merchant for с in август.rows)


