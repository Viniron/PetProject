"""Разбор CSV-выписок банков (Ф2).

Главная фикстура — **настоящая выгрузка Т-Банка**, обезличенная: заменены
имена людей, названия мерчантов и номер карты, всё остальное как отдал банк
(`fixtures/statements/README.md`). Фикстура, написанная по предположению
о формате, проверяла бы наши представления о банке, а не банк — урок
фикстур my.itmo.ru, стоивший трёх неверных полей.

Сеть здесь не участвует вообще: разбор — чистая функция от байтов и зоны.
Базы тоже нет — `StatementRow` не ORM-объект намеренно.

Чего в этих тестах нет, потому что этого нет в Ф2: `fingerprint`,
`occurrence_no` и кратность одинаковых операций (Ф3), `kind` и категории
(Ф4), сальдо (Ф5). Единственное, что проверяется здесь **ради** Ф3, —
что секунды из даты не потерялись: на них держится вся дедупликация.
"""

import datetime as dt
from decimal import Decimal
from zoneinfo import ZoneInfo

import pytest
from conftest import байты_фикстуры

from jarvis_api.integrations.statements import (
    ColumnMismatchError,
    ParsedStatement,
    RowError,
    StatementRow,
    UnknownBankError,
    parse_statement,
)
from jarvis_api.integrations.statements.tbank import ADAPTER

МОСКВА = ZoneInfo("Europe/Moscow")

# Сальдо августа по настоящей выгрузке. Эти три числа — цель первого прогона
# Ф5; здесь они проверяют, что до сальдо доходят все 62 суммы без потерь.
ПРИХОД_АВГУСТА = Decimal("11080.02")
РАСХОД_АВГУСТА = Decimal("9919.81")


def разобрать(имя: str) -> ParsedStatement:
    return parse_statement(байты_фикстуры("statements", имя), МОСКВА)


@pytest.fixture(scope="module")
def август() -> ParsedStatement:
    return разобрать("tbank_august.csv")


