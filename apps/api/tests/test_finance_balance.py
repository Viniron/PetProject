"""Сальдо месяца, «Отложено» и «Осталось» (Ф5, §15.5).

Ошибка здесь не падает, а тихо показывает owner неверную сумму денег -
худший исход по §10. Поэтому проверяются не «функция вернула число»,
а края: месяц, в котором возвратов больше расходов; гашение из следующего
месяца; операция на накопительном счёте, которую разбор переводом
не признал; и неразмеченный счёт, из-за которого статья обязана молчать
словами, а не нулём.

Первая половина файла без базы вовсе: свод - чистая функция, и собирать
ради неё Postgres значило бы проверять сборку вместо арифметики. Вторая -
чтение через сессию и обе команды, где проверяется ровно обратное: что
цифра доходит до терминала и что разметка без `--apply` не пишет ничего.
"""

import datetime as dt
import logging
from decimal import Decimal
from typing import Any
from zoneinfo import ZoneInfo

import pytest
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinAccount, FinImport, FinTransaction
from jarvis_api.domain.finance_balance import (
    НОЛЬ,
    Месяц,
    Обзор,
    Операция,
    взять_месяц,
    последний_день,
    размечены,
    свести,
    собрать,
)
from jarvis_api.jobs.finance_balance import run_once, описать, разобрать_месяц

МОСКВА = ZoneInfo("Europe/Moscow")
БАНК = "tbank"
КАРТА = "Black"
КОПИЛКА = "Накопительный счёт"

АВГУСТ = dt.date(2026, 8, 1)
СЕНТЯБРЬ = dt.date(2026, 9, 1)
ИЮЛЬ = dt.date(2026, 7, 1)

В_АВГУСТЕ = dt.datetime(2026, 8, 23, 12, 0, tzinfo=МОСКВА)
В_СЕНТЯБРЕ = dt.datetime(2026, 9, 15, 12, 0, tzinfo=МОСКВА)
В_ИЮЛЕ = dt.datetime(2026, 7, 20, 12, 0, tzinfo=МОСКВА)

# «Сейчас» всех проверок: середина сентября. Окно пересчёта - август
# и сентябрь, июль за краем. Дата фиксированная: тест, зависящий
# от системных часов, однажды позеленел бы по календарю.
СЕЙЧАС = dt.datetime(2026, 9, 21, 12, 0, tzinfo=МОСКВА)

РАЗМЕЧЕНО = {(БАНК, КАРТА): "checking", (БАНК, КОПИЛКА): "savings"}


def операция(номер: int, момент: dt.datetime, сумма: str, **переопределения: Any) -> Операция:
    """Строка книжки для чистых проверок. Знак суммы решает вид по умолчанию."""
    значение = Decimal(сумма)
    поля: dict[str, Any] = {
        "id": номер,
        "occurred_at": момент,
        "amount": значение,
        "amount_rub": значение,
        "kind": "expense" if значение < 0 else "income",
        "kind_source": "sign",
        "status": "posted",
        "excluded": False,
        "needs_review": False,
        "offsets_transaction_id": None,
        "bank": БАНК,
        "account": КАРТА,
    }
    поля.update(переопределения)
    return Операция(**поля)


def месяц_из(операции: list[Операция], м: dt.date, роли: dict[tuple[str, str], str]) -> Месяц:
    сведённые = свести(операции, роли=роли, зона=МОСКВА)
    return взять_месяц(сведённые, м, все_размечены=размечены(роли))


