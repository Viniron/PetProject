def операция_в_базе(момент: dt.datetime, сумма: str, **переопределения: Any) -> FinTransaction:
    значение = Decimal(сумма)
    поля: dict[str, Any] = {
        "bank": БАНК,
        "account": КАРТА,
        "occurred_at": момент,
        "amount": значение,
        "amount_rub": значение,
        "currency": "RUB",
        "kind": "expense" if значение < 0 else "income",
        "fingerprint": f"{момент.isoformat()}{сумма}".ljust(64, "0")[:64],
    }
    поля.update(переопределения)
    return FinTransaction(**поля)


def выгрузка(по: dt.date) -> FinImport:
    return FinImport(
        bank=БАНК,
        filename="tbank.csv",
        sha256=f"{по}".ljust(64, "0")[:64],
        period_start=dt.date(2026, 8, 1),
        period_end=по,
    )


