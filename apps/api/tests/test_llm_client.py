СЕЙЧАС = dt.datetime(2026, 9, 21, 12, 0, tzinfo=dt.UTC)
АКТОР = "tests.llm"


class Разбор(BaseModel):
    """Схема ответа. Своя, тестовая: настоящая приезжает с точкой вызова (Э12в)."""

    title: str
    confidence: float


@dataclass
class ПодставнойАдаптер:
    """Провайдер, отвечающий по сценарию. Запоминает, что у него просили."""

    имя: str
    сценарий: list[Ответ | Exception]
    запросы: list[Запрос] = field(default_factory=list)

    def выполнить(self, запрос: Запрос) -> Ответ:
        self.запросы.append(запрос)
        что = self.сценарий.pop(0)
        if isinstance(что, Exception):
            raise что
        return что


def ответ(
    текст: str = '{"title": "Зубной", "confidence": 0.9}', *, вход: int = 1000, выход: int = 100
) -> Ответ:
    return Ответ(текст=текст, токенов_вход=вход, токенов_выход=выход)


def маршрут(
    провайдер: str = "провайдер-а",
    модель: str = "модель-1",
    *,
    max_tokens: int = 1024,
    price_in: str = "0.25",
    price_out: str = "1.50",
    fallback: tuple[Маршрут, ...] = (),
    degraded: Маршрут | None = None,
) -> Маршрут:
    return Маршрут(
        provider=провайдер,
        model=модель,
        max_tokens=max_tokens,
        price_in=Decimal(price_in),
        price_out=Decimal(price_out),
        fallback=fallback,
        degraded=degraded,
    )


def промпт() -> Промпт:
    return Промпт(
        имя="проба",
        версия=2,
        стабильная_часть="Правила разбора. Одинаковы на каждом вызове.",
        переменная_часть="Заметка: зубной в среду",
    )


def настройки(**поля: object) -> Settings:
    основа: dict[str, object] = {
        "llm_monthly_cap_usd": Decimal("5"),
        "llm_timeout_seconds": 42,
        "llm_schema_retries": 1,
    }
    return Settings(**{**основа, **поля})  # type: ignore[arg-type]


def позвать(
    сессия: Session,
    *,
    задача: Задача = Задача.РАЗБОР_СОБЫТИЯ,
    маршруты: dict[Задача, Маршрут] | None = None,
    адаптеры: dict[str, Адаптер] | None = None,
    конфиг: Settings | None = None,
) -> Результат[Разбор]:
    return вызвать(
        сессия,
        задача=задача,
        промпт=промпт(),
        схема=Разбор,
        актор=АКТОР,
        сейчас=СЕЙЧАС,
        зона=ЗОНА,
        настройки=конфиг or настройки(),
        маршруты=маршруты if маршруты is not None else {Задача.РАЗБОР_СОБЫТИЯ: маршрут()},
        адаптеры=адаптеры or {},
    )


def журнал(сессия: Session, вид: str = "llm_call") -> list[AuditLogEntry]:
    запрос = select(AuditLogEntry).where(AuditLogEntry.kind == вид).order_by(AuditLogEntry.id)
    return list(сессия.execute(запрос).scalars())


def потратить(сессия: Session, сумма: str, *, когда: dt.datetime | None = None) -> None:
    """Готовая строка расхода: месячный потолок считается по `audit_log`."""
    сессия.add(
        AuditLogEntry(
            kind="llm_call",
            actor=АКТОР,
            status="ok",
            target=Задача.РАЗБОР_СОБЫТИЯ.value,
            provider="провайдер-а",
            model="модель-1",
            tokens_in=1,
            tokens_out=1,
            cost_usd=Decimal(сумма),
            at=когда or СЕЙЧАС - dt.timedelta(days=1),
        )
    )
    сессия.flush()


