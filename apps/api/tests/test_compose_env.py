"""Настройки, объявленные в коде, проброшены в контейнер (Э3).

Тест написан по следам живого прогона на плате. `ISU_LOGIN`, `ISU_PASSWORD`
и `ISU_CRED_KEY` были заведены в `config.py`, вписаны owner в `.env` и
покрыты тестами — но в `environment:` сервиса `api` их никто не дописал.
Все 119 тестов оставались зелёными: они конструируют `Settings` напрямую
и до compose-файла не дотягиваются. Обнаружилось это единственным способом,
каким такое вообще обнаруживается, — отказом на живом запуске.

Класс ошибки шире одного этапа: **между `config.py` и `docker-compose.yml`
нет ничего, что связывало бы их автоматически.** Каждая следующая настройка,
приходящая из env, повторит эту дыру — на Э4 это будет `GOOGLE_SA_JSON`,
на Э8 ключи моделей.

Compose-файл читается как текст, без `pyyaml`: он не объявлен зависимостью
проекта, а стоит в venv транзитивно через `uvicorn[standard]`. Тест, молча
опирающийся на чужую транзитивную зависимость, ломается в день, когда она
перестаёт быть транзитивной.
"""

from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
COMPOSE = REPO_ROOT / "infra" / "docker-compose.yml"

# Переменные, без которых джоб забора расписания не работает (Э3).
# Список ведётся руками намеренно: вывести его из `Settings` нельзя -
# там же лежат поля с рабочими умолчаниями, которым в compose делать нечего.
ПЕРЕМЕННЫЕ_ИСУ = ("ISU_LOGIN", "ISU_PASSWORD", "ISU_CRED_KEY")


def окружение_сервиса(текст: str, сервис: str) -> dict[str, str]:
    """Блок `environment:` одного сервиса compose-файла.

    Разбор по отступам, а не по YAML-библиотеке. Оправдано узостью задачи:
    нужны имена ключей и их значения-подстановки, а не полная семантика YAML
    с якорями и слияниями, которых в этом файле нет.
    """
    строки = текст.splitlines()
    внутри_сервиса = False
    внутри_окружения = False
    собранное: dict[str, str] = {}

    for строка in строки:
        голая = строка.strip()
        if not голая or голая.startswith("#"):
            continue

        # Сервис объявлен на четырёх пробелах внутри `services:`.
        if строка.startswith("  ") and not строка.startswith("   ") and голая.endswith(":"):
            внутри_сервиса = голая[:-1] == сервис
            внутри_окружения = False
            continue

        if not внутри_сервиса:
            continue

        # Ключи сервиса - на четырёх пробелах.
        if строка.startswith("    ") and not строка.startswith("     "):
            внутри_окружения = голая == "environment:"
            continue

        if внутри_окружения and ":" in голая:
            имя, _, значение = голая.partition(":")
            собранное[имя.strip()] = значение.strip()

    return собранное


@pytest.fixture(scope="module")
def окружение_api() -> dict[str, str]:
    return окружение_сервиса(COMPOSE.read_text(encoding="utf-8"), "api")


def test_compose_файл_на_месте() -> None:
    """Если файл переехал, остальные проверки этого модуля молча опустеют."""
    assert COMPOSE.is_file(), f"не найден {COMPOSE}"


def test_база_прокидывается_в_api(окружение_api: dict[str, str]) -> None:
    """Заодно проверяем сам разборщик: он обязан что-то находить.

    Без этой проверки опечатка в разборе дала бы пустой словарь, и все
    утверждения ниже прошли бы по недоразумению.
    """
    assert "DATABASE_URL" in окружение_api
    assert "ENV" in окружение_api


@pytest.mark.parametrize("переменная", ПЕРЕМЕННЫЕ_ИСУ)
def test_учётные_данные_ису_доходят_до_контейнера(
    окружение_api: dict[str, str], переменная: str
) -> None:
    """Та самая дыра: настройка есть в коде и в .env, но не в контейнере.

    Симптом на плате - «ISU_CRED_KEY пуст» при заполненном .env, и искать
    причину идёшь в шифрование, а она в проброске.
    """
    assert переменная in окружение_api, (
        f"{переменная} объявлена в config.py, но не проброшена в сервис api "
        f"в {COMPOSE.name} - на плате джоб увидит пустое значение"
    )


@pytest.mark.parametrize("переменная", ПЕРЕМЕННЫЕ_ИСУ)
def test_учётные_данные_ису_не_обязательны_для_подъёма_стека(
    окружение_api: dict[str, str], переменная: str
) -> None:
    """Пустое значение допустимо, `${...:?}` - нет.

    Стек на чистой плате обязан подняться до того, как owner заведёт учётные
    данные ИСУ: иначе Э1 нельзя было бы закрыть раньше Э3. Отказывается
    работать без них джоб, и его текст объясняет, где значение взять, -
    сообщение compose о недостающей переменной этого не объясняет.
    """
    значение = окружение_api[переменная]

    assert значение == "${" + переменная + ":-}", (
        f"{переменная} должна прокидываться с пустым умолчанием, "
        f"а прокидывается как {значение!r}"
    )


def test_секреты_ису_не_вписаны_в_compose_значениями() -> None:
    """Инвариант 6: ни одного секрета в репозитории.

    Compose-файл коммитится, поэтому значение здесь может быть только
    подстановкой из env. Буквальная строка означала бы утёкший пароль.
    """
    окружение = окружение_сервиса(COMPOSE.read_text(encoding="utf-8"), "api")

    for переменная in ПЕРЕМЕННЫЕ_ИСУ:
        assert окружение[переменная].startswith("${"), (
            f"{переменная} в {COMPOSE.name} задана буквальным значением, "
            "а не подстановкой из env - это секрет в репозитории"
        )
