"""Разбор PDF-справки Ozon Bank (Ф2).

Главная фикстура - **настоящая справка о движении средств**, обезличенная:
заменены имя владельца, номер счёта и номера операций, всё остальное как
отдал банк (`fixtures/statements/README.md`). Суммы, даты со временем до
секунды и контрольные итоги настоящие: на них держится и дедупликация
(§15.3), и сверка полноты разбора.

Сеть здесь не участвует, базы нет: разбор - чистая функция от байтов и зоны.

Отдельно от `test_statement_parsing.py`, потому что проверяет другое.
Там - CSV: кодировка, разделитель, заголовок. Здесь - PDF: ячейки таблицы,
переносы внутри них, шапка бланка и контрольные итоги. Общий у двух файлов
только реестр, и он проверяется с обеих сторон: чужой CSV и чужой PDF
отклоняются по-разному.
"""

import datetime as dt
from decimal import Decimal
from zoneinfo import ZoneInfo

import pytest
from conftest import байты_фикстуры

from jarvis_api.integrations.statements import (
    ColumnMismatchError,
    ParsedStatement,
    RowError,
    TotalsMismatchError,
    UnknownBankError,
    parse_statement,
)
from jarvis_api.integrations.statements.ozon import ADAPTER, _сумма

МОСКВА = ZoneInfo("Europe/Moscow")

# Контрольные итоги из подвала справки. Ф5 обязан сойтись с этими числами,
# и проверять это глазами один раз - не проверять вовсе.
ЗАЧИСЛЕНИЯ = Decimal("2178.00")
СПИСАНИЯ = Decimal("2177.00")


def разобрать(имя: str) -> ParsedStatement:
    return parse_statement(байты_фикстуры("statements", имя), МОСКВА)


@pytest.fixture(scope="module")
def справка() -> ParsedStatement:
    return разобрать("ozon_2026-09.pdf")


# --- опознание банка --------------------------------------------------------


def test_банк_опознан_по_содержимому(справка: ParsedStatement) -> None:
    """Банк из текста справки, а не из имени файла: имя переименовывают."""
    assert справка.bank == "ozon"


def test_чужой_pdf_отклонён_с_описанием_файла() -> None:
    """Неизвестный банк - отказ, показывающий, что это был за файл (§15.1).

    Колонок у PDF нет, поэтому сообщение строится из начала текста: по нему
    owner видит, выписка это вообще и какого банка. Проверяется здесь и то,
    что описание даёт **PDF-адаптер**: CSV-адаптер декодирует несжатый PDF
    без ошибки и однажды уже отвечал за него «пришли колонки: ['%PDF-1.4']».
    """
    with pytest.raises(UnknownBankError) as отказ:
        разобрать("foreign_bank.pdf")
    текст = str(отказ.value)
    assert "файл PDF" in текст
    assert "Drugoy bank" in текст
    assert "ozon" in текст  # и список банков, которых мы знаем


def test_pdf_без_текстового_слоя_объясняет_причину() -> None:
    """Скан вместо текста - частая беда, и она обязана называться прямо.

    Без этого owner получил бы «неизвестный банк» на своей же справке,
    распечатанной и отсканированной, и искал бы несуществующий адаптер.
    """
    данные = байты_фикстуры("statements", "no_text_layer.pdf")
    assert ADAPTER.claims(данные) is False
    assert ADAPTER.describe(данные) == (
        "файл PDF, но текста в нём нет: похоже, страницы - картинки"
    )


def test_csv_чужого_банка_по_прежнему_отвечает_колонками() -> None:
    """Правило «молчим без разделителя» не должно съесть настоящий CSV.

    Проверка соседней ветки: у чужой CSV-выписки колонки есть, и отказ
    обязан их перечислить - иначе новый адаптер писать не по чему.
    """
    with pytest.raises(UnknownBankError) as отказ:
        разобрать("unknown_bank.csv")
    assert "Описание операции" in str(отказ.value)


# --- строки таблицы ---------------------------------------------------------


def test_разобраны_все_операции(справка: ParsedStatement) -> None:
    assert len(справка.rows) == 10


def test_порядок_строк_как_в_справке(справка: ParsedStatement) -> None:
    """Порядок обратный хронологическому - так отдаёт банк, и он сохранён.

    Импорт не вправе рассчитывать на сортировку, и проверка стоит здесь,
    чтобы сортировка не завелась «для удобства» в разборе.
    """
    даты = [строка.occurred_at for строка in справка.rows]
    assert даты == sorted(даты, reverse=True)


def test_номер_документа_склеен_через_перенос(справка: ParsedStatement) -> None:
    """`1300000000` + `7` - один номер, разорванный вёрсткой ячейки.

    Главная причина, по которой таблица читается по ячейкам, а не по
    плоскому тексту: в тексте вторая половина номера неотличима от начала
    соседнего поля, и склейка по догадке дала бы в книжке чужой номер.
    """
    седьмая = справка.rows[6]
    assert седьмая.source_row["Документ"] == "88888455317"


def test_операции_со_второй_страницы_на_месте(справка: ParsedStatement) -> None:
    """Таблица разорвана разрывом страницы, и её хвост - тоже операции.

    На второй странице шапки таблицы нет вовсе; трактуй разбор страницы
    по-разному - пять операций из десяти потерялись бы молча.
    """
    первые_сентября = [
        строка for строка in справка.rows if строка.occurred_at.astimezone(МОСКВА).day == 1
    ]
    assert len(первые_сентября) == 2


def test_время_до_секунды_и_в_utc(справка: ParsedStatement) -> None:
    """Секунды - единственное, что различает соседние операции (§15.3).

    В этой справке две пары операций идут в одну минуту (17:26/17:27
    и 11:59:14/11:59:16), и без секунд ключ дедупликации схлопнул бы их.
    """
    первая = справка.rows[0]
    assert первая.occurred_at == dt.datetime(2026, 9, 10, 14, 27, 3, tzinfo=dt.UTC)
    assert all(строка.occurred_at.tzinfo is dt.UTC for строка in справка.rows)


def test_назначение_платежа_склеено_без_рваных_номеров(справка: ParsedStatement) -> None:
    """Переносы внутри ячейки - вёрстка; номер заказа не должен их сохранить.

    Назначение платежа идёт в `merchant`, а тот входит в ключ дедупликации.
    Пробел, попавший внутрь номера заказа, сделал бы ключ зависящим от того,
    как банк сверстал ячейку.
    """
    оплата = справка.rows[0]
    assert оплата.merchant == (
        "Оплата товаров/услуг на Платформе Ozon, заказ № 5555555471-0080. Без НДС."
    )


def test_счёт_взят_маской_последних_цифр(справка: ParsedStatement) -> None:
    """Полный номер счёта персональный, а различать счета хватает хвоста.

    Одна справка - одна карта (уточнено owner), поэтому счёт один на все
    строки и берётся из шапки, а не из строки.
    """
    assert {строка.account for строка in справка.rows} == {"Ozon ·1237"}


def test_чего_в_справке_нет_остаётся_пустым(справка: ParsedStatement) -> None:
    """`None` - это «банк не сказал», и подставлять вместо него нечего.

    Ни карты, ни MCC, ни категорий в справке Ozon нет. Ступень категоризации
    (Ф4а) обязана уметь работать с такими строками: у них нет ни одного
    детерминированного признака, кроме назначения платежа.
    """
    for строка in справка.rows:
        assert строка.card_last4 is None
        assert строка.mcc is None
        assert строка.bank_category is None
        assert строка.own_category is None
        assert строка.message is None
        assert строка.analytics_hint is None


def test_статус_всем_строкам_posted(справка: ParsedStatement) -> None:
    """Справка о движении средств показывает состоявшееся движение.

    Ожидающих операций в ней не бывает - это допущение формата, названное
    допущением в §15.1. Придёт справка с ожидающей операцией - формат
    придётся уточнить по ней, а не угадать сейчас.
    """
    assert {строка.status for строка in справка.rows} == {"posted"}


def test_валюта_из_шапки(справка: ParsedStatement) -> None:
    """В строке валюта не написана - она одна на справку и стоит в бланке."""
    assert {строка.currency for строка in справка.rows} == {"RUB"}


# --- период и итоги ---------------------------------------------------------


def test_период_из_шапки_а_не_по_операциям(справка: ParsedStatement) -> None:
    """Границы берутся из бланка, и это меняет поведение §15.3.

    По операциям период сжался бы до 01.09-10.09 - недели, в которые
    движения не было, выпали бы из проверки на исчезнувшую операцию,
    и отменённая банком операция осталась бы в книжке живой.
    """
    assert справка.period_start == dt.date(2026, 8, 16)
    assert справка.period_end == dt.date(2026, 9, 16)
    самая_ранняя = min(строка.occurred_at.astimezone(МОСКВА).date() for строка in справка.rows)
    assert самая_ранняя > справка.period_start


def test_суммы_сходятся_с_итогами_справки(справка: ParsedStatement) -> None:
    """Приход, расход и сальдо - те же, что банк напечатал в подвале."""
    приход = sum((с.amount_rub for с in справка.rows if с.amount_rub > 0), Decimal(0))
    расход = -sum((с.amount_rub for с in справка.rows if с.amount_rub < 0), Decimal(0))
    assert приход == ЗАЧИСЛЕНИЯ
    assert расход == СПИСАНИЯ
    assert приход - расход == Decimal("1.00")


def test_итоги_не_сошлись_файл_отклонён_целиком() -> None:
    """Потерянная строка - единственная беда, невидимая в тексте файла.

    Отказ отдельным типом: `ColumnMismatchError` и `RowError` означают, что
    разбор остановился на понятном месте, а здесь он дошёл до конца и всё
    равно неполон.
    """
    with pytest.raises(TotalsMismatchError) as отказ:
        разобрать("ozon_bad_totals.pdf")
    текст = str(отказ.value)
    assert "зачисления" in текст
    assert "2178.00" in текст and "2179.00" in текст


def test_сменился_бланк_отказ_называет_строку() -> None:
    """Шапка - часть формата, и её пропажа обязана называться прямо.

    То же правило, что «отказ называет колонку» у CSV: owner должен видеть,
    что чинить, а не читать десяток отказов на операциях.
    """
    with pytest.raises(ColumnMismatchError) as отказ:
        разобрать("ozon_bad_header.pdf")
    assert "Период выписки" in str(отказ.value)


# --- написание сумм ---------------------------------------------------------


def test_написания_сумм_ozon() -> None:
    """Точка, пробел после знака, символ валюты - и разделитель тысяч.

    Написание Т-Банка (`-250,00`) здесь обязано отказать: принять оба
    значило бы, что сменившийся формат больше не ловится ни у одного банка.
    """
    assert _сумма("- 250.00 ₽", "Российские рубли", 1) == Decimal("-250.00")
    assert _сумма("+ 250.00 ₽", "Российские рубли", 1) == Decimal("250.00")
    # Разделитель тысяч банк ставит неразрывным пробелом - в итогах
    # он есть, и увидеть его глазами в PDF невозможно.
    assert _сумма("2 178.00 ₽", "Итого зачислений за период") == Decimal("2178.00")
    assert _сумма("0.00 ₽", "Входящий остаток") == Decimal("0.00")


@pytest.mark.parametrize(
    "значение",
    [
        "- 250,00 ₽",  # написание Т-Банка
        "- 25O.00 ₽",  # латинская O вместо нуля
        "1e5 ₽",  # `Decimal` принял бы, книжка - нет
        "NaN ₽",
        "",
    ],
)
def test_непонятное_написание_суммы_отказ(значение: str) -> None:
    with pytest.raises(RowError):
        _сумма(значение, "Российские рубли", 1)


def test_сумма_операции_без_знака_отказ() -> None:
    """Знак - единственное, чем банк отличает зачисление от списания.

    У остатка и итога знака нет, и там он не нужен: «Итого списаний»
    уже сказано словом. У операции его отсутствие означает смену формата.
    """
    assert _сумма("250.00 ₽", "Исходящий остаток") == Decimal("250.00")
    with pytest.raises(RowError, match="без знака"):
        _сумма("250.00 ₽", "Российские рубли", 1)
