"""Сверка контракта `packages/contracts/openapi.json` (Э6).

Файл коммитится, потому что из него на Э7 генерируется клиент. Тест
краснеет в двух случаях, и оба - настоящие изменения контракта: правка
эндпоинтов без `make contract` и поднятая версия FastAPI, от которой
меняется генерируемый клиент.
"""

import json
from collections.abc import Iterator

from jarvis_api.contract import ФАЙЛ, сериализовать, схема

КАК_ЧИНИТЬ = (
    "Контракт разошёлся с приложением. Выполните `make contract` и закоммитьте "
    "packages/contracts/openapi.json вместе с правкой эндпоинтов. Если эндпоинты "
    "не менялись - значит поднялась версия FastAPI, и это тоже правка контракта: "
    "от неё меняется клиент, генерируемый на Э7."
)


def test_контракт_совпадает_с_приложением() -> None:
    assert ФАЙЛ.exists(), f"Файла контракта нет. {КАК_ЧИНИТЬ}"
    assert ФАЙЛ.read_text(encoding="utf-8") == сериализовать(схема()), КАК_ЧИНИТЬ


def test_файл_в_каноничной_форме() -> None:
    """Повторный `make contract` не даёт дифф.

    Проверяется чтением, а не записью: тест, перезаписывающий файл
    репозитория, чинил бы расхождение молча - и соседний тест сверки
    начинал бы зеленеть или краснеть в зависимости от порядка запуска.
    """
    текст = ФАЙЛ.read_text(encoding="utf-8")

    assert сериализовать(json.loads(текст)) == текст


def имена_и_значения(узел: object) -> Iterator[str]:
    """Имена свойств и значения перечислений по всей схеме, вглубь.

    Проза описаний сюда не попадает намеренно: слово `study` в них есть
    и должно быть - докстринг `EventOut` объясняет, почему занятий курсов
    в релизе нет. Запрет касается того, что читает клиент, а не того,
    что читает человек.
    """
    if isinstance(узел, dict):
        for ключ, значение in узел.items():
            if ключ == "properties" and isinstance(значение, dict):
                yield from (str(имя) for имя in значение)
            if ключ == "enum" and isinstance(значение, list):
                yield from (str(вариант) for вариант in значение)
            yield from имена_и_значения(значение)
    elif isinstance(узел, list):
        for элемент in узел:
            yield from имена_и_значения(элемент)


def test_занятий_курсов_в_контракте_нет() -> None:
    """Ограничение объёма этапа, сделанное исполняемым.

    Время занятия курса считается по манифесту курса (§4), который уехал
    в дорожку курсов (ADR-027 п. 11), а курсов ноль. Появившись в контракте,
    `study` дорисовался бы на Э7 молча - и экран показал бы занятия,
    которых платформа не планирует.
    """
    assert "study" not in set(имена_и_значения(схема()))


def test_тело_отказа_в_контракте_одно() -> None:
    """Штатные тела FastAPI переопределены в `api/errors.py` ради этого:
    клиент Э7 разбирает один тип ошибки, а не три."""
    схемы = схема()["components"]["schemas"]

    assert "ErrorBody" in схемы
    assert "HTTPValidationError" not in схемы


def test_имена_схем_и_полей_латиницей() -> None:
    """Имена моделей Pydantic становятся именами типов TypeScript, имена
    полей - именами свойств. Кириллица там формально законна и ломает
    генераторы и автодополнение; остальной код проекта остаётся русским."""
    for имя in схема()["components"]["schemas"]:
        assert имя.isascii(), f"схема {имя!r} названа не латиницей"
    for имя in имена_и_значения(схема()):
        assert имя.isascii(), f"поле {имя!r} названо не латиницей"
