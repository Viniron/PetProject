def строка(
    номер: int,
    момент: dt.datetime,
    сумма: str,
    **переопределения: Any,
) -> Строка:
    """Операция для чистых проверок. Знак суммы решает, расход это или приход."""
    значение = Decimal(сумма)
    поля: dict[str, Any] = {
        "id": номер,
        "occurred_at": момент,
        "amount": значение,
        "amount_rub": значение,
        "kind": "expense" if значение < 0 else "refund",
        "kind_source": "sign",
        "status": "posted",
        "excluded": False,
        "needs_review": False,
        "offsets_transaction_id": None,
    }
    поля.update(переопределения)
    return Строка(**поля)


