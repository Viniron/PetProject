"""Гашение расхода поступлениями (Ф4б, §15.5).

Ошибка здесь не падает, а тихо двигает деньги между месяцами: погашенный
расход дешевеет, излишек становится доходом, а закрытый месяц обязан
остаться закрытым. Поэтому проверяется не «функция вернула число», а края -
привязка к позапрошлому месяцу, снятие через полгода, гашение больше
стоимости покупки и гашение, которое ещё стоит в очереди разбора.

Первая половина файла без базы вовсе: окно и разбивка - чистые функции,
и собирать ради них Postgres значило бы проверять сборку вместо арифметики.
Вторая - запись через сессию и джоб, где проверяется ровно обратное:
что решение доходит до строки и что dry-run не пишет ничего.
"""

