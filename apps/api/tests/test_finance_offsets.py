def test_много_поступлений_не_уводят_расход_в_минус() -> None:
    """Четыре доли по 230 ₽ на стол за 575 ₽: расход гасится до нуля, не ниже."""
    расход = строка(1, АВГУСТ, "-575.00")
    доли = [строка(номер, АВГУСТ, "230.00", offsets_transaction_id=1) for номер in (2, 3, 4, 5)]

