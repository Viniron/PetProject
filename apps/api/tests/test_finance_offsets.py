def test_dry_run_не_пишет_в_базу(
    сессия: Session, пара: tuple[FinTransaction, FinTransaction]
) -> None:
    """Всё, что пишет, по умолчанию `--dry-run` - и это проверяется, а не заявляется."""
    расход, приход = пара

    код = run_once(
        сессия,
        гашение_id=приход.id,
        расход_id=расход.id,
        отвязать=False,
        показать=None,
        apply=False,
        сейчас=СЕЙЧАС,
    )

    assert код == 0
    # После отката строка перечитывается из базы: привязки там нет.
    assert перечитать(сессия, приход).offsets_transaction_id is None


def test_apply_пишет_привязку(сессия: Session, пара: tuple[FinTransaction, FinTransaction]) -> None:
    расход, приход = пара

    код = run_once(
        сессия,
        гашение_id=приход.id,
        расход_id=расход.id,
        отвязать=False,
        показать=None,
        apply=True,
        сейчас=СЕЙЧАС,
    )

    assert код == 0
    assert перечитать(сессия, приход).offsets_transaction_id == расход.id


