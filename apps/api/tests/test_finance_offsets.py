# --- запись через сессию ---------------------------------------------------


def операция(момент: dt.datetime, сумма: str, **переопределения: Any) -> FinTransaction:
    значение = Decimal(сумма)
    поля: dict[str, Any] = {
        "bank": БАНК,
        "account": СЧЁТ,
        "occurred_at": момент,
        "amount": значение,
        "amount_rub": значение,
        "currency": "RUB",
        "kind": "expense" if значение < 0 else "refund",
        "fingerprint": f"{момент.isoformat()}{сумма}".ljust(64, "0")[:64],
    }
    поля.update(переопределения)
    return FinTransaction(**поля)


def завести(сессия: Session, *строки: FinTransaction) -> None:
    """Кладёт операции в книжку и **коммитит**.

    Коммит, а не `flush`: dry-run джоба заканчивается `rollback`, и данные,
    доживающие только до него, исчезли бы вместе с проверяемым откатом.
    Внешнюю транзакцию теста это не отпускает - её держит фикстура `сессия`.
    """
    есть = сессия.scalar(select(FinAccount).where(FinAccount.bank == БАНК, FinAccount.name == СЧЁТ))
    if есть is None:
        сессия.add(FinAccount(bank=БАНК, name=СЧЁТ, role="checking"))
    сессия.add_all(строки)
    сессия.commit()


def перечитать(сессия: Session, строка: FinTransaction) -> FinTransaction:
    """Строка из базы заново - после отката джоба объект в сессии уже не тот."""
    свежая = сессия.get(FinTransaction, строка.id)
    assert свежая is not None
    return свежая


