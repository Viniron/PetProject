def test_привязка_записывается_и_снимает_пометку_разбора(
    сессия: Session, пара: tuple[FinTransaction, FinTransaction]
) -> None:
    """Привязка - решение owner: вид становится ручным, и разбор его не тронет."""
    расход, приход = пара

    это = привязать(сессия, гашение_id=приход.id, расход_id=расход.id, сейчас=СЕЙЧАС, зона=МОСКВА)

    assert это.изменилось
    assert приход.offsets_transaction_id == расход.id
    assert (приход.kind, приход.kind_source) == ("refund", "manual")
    assert приход.needs_review is False
    assert разбивка(сессия, расход.id).эффективная == Decimal("345.00")


def test_пометка_импорта_привязкой_не_снимается(сессия: Session) -> None:
    """Кандидата в дубли закрывает тот, кто его пометил, - иначе строка теряется."""
    расход = операция(АВГУСТ, "-575.00")
    приход = операция(АВГУСТ, "230.00", kind_source="sign", needs_review=True)
    завести(сессия, расход, приход)

    это = привязать(сессия, гашение_id=приход.id, расход_id=расход.id, сейчас=СЕЙЧАС, зона=МОСКВА)

    assert приход.needs_review is True
    assert это.предупреждения
    # Пока строка в очереди, расход она не уменьшает - и это видно.
    assert разбивка(сессия, расход.id).эффективная == Decimal("575.00")
    assert разбивка(сессия, расход.id).вне_счёта == [приход.id]


