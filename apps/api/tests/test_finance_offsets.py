def test_доли_за_общую_покупку_на_августовской_выгрузке(сессия: Session) -> None:
    """Случай, ради которого гашение и заведено (§15.5).

    23 августа приходят четыре перевода по 230 ₽ от разных людей и уходят
    две оплаты «Тренировки Альфа» по 575 ₽. Разбор Ф4а увёл переводы
    в очередь: правила отправителя на этих людей нет, а умолчание `refund`
    молча гасило бы месяц. Привязка отвечает на его вопрос - по две доли
    на каждую тренировку.
    """
    assert импорт_once(сессия, [(ФАЙЛ, байты_фикстуры("statements", ФАЙЛ))], apply=True) == 0
    assert разобрать_книжку_once(сессия, Settings(), apply=True) == 0

    тренировки = сессия.scalars(
        select(FinTransaction)
        .where(FinTransaction.amount == Decimal("-575.00"))
        .order_by(FinTransaction.occurred_at)
    ).all()
    доли = сессия.scalars(
        select(FinTransaction)
        .where(FinTransaction.amount == Decimal("230.00"))
        .order_by(FinTransaction.occurred_at)
    ).all()
    assert len(тренировки) == 2 and len(доли) == 4
    # Разбор оставил их в очереди: это и есть та строка, которую закрывает owner.
    assert {доля.needs_review for доля in доли} == {True}

    for номер, доля in enumerate(доли):
        привязать(
            сессия,
            гашение_id=доля.id,
            расход_id=тренировки[номер % 2].id,
            сейчас=СЕЙЧАС,
            зона=МОСКВА,
        )

    for тренировка in тренировки:
        это = разбивка(сессия, тренировка.id)
        assert это.погашено == Decimal("460.00")
        assert это.эффективная == Decimal("115.00")
        assert это.излишек == НОЛЬ
    assert {доля.needs_review for доля in доли} == {False}
