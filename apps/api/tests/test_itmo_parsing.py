"""Разбор ответа my.itmo.ru и отображение в зеркало (Э3).

`CLAUDE.md` требует покрыть «парсинг my.itmo.ru на фикстурах» отдельным
пунктом, и вот почему это отдельный пункт: схема портала неофициальная,
меняется без предупреждения, а неверно разобранное расписание уезжает
в календарь и звонит в телефон.

**Главная фикстура — настоящий ответ портала,** обезличенный (ADR-019).
До первого живого прогона здесь лежала выдуманная по референсу, и она
врала в трёх местах: у портала есть поле `format` (референс его не читает),
нет поля `teacher_fio`, а день без пар приходит пустым списком, а не `null`.
Тесты, написанные на выдуманной фикстуре, доказывали наши представления
о портале, и ничего больше.

Сеть здесь не участвует вообще — ни одного запроса, только файлы.
"""

import datetime as dt
from zoneinfo import ZoneInfo

import pytest
from conftest import загрузить_фикстуру
from pydantic import ValidationError

from jarvis_api.integrations.itmo.mapping import (
    MappingError,
    MirrorRow,
    build_source_key,
    lesson_to_row,
    payload_to_rows,
)
from jarvis_api.integrations.itmo.schema import RawLesson, SchedulePayload, parse_portal_time

МОСКВА = ZoneInfo("Europe/Moscow")


def разобрать(имя: str) -> SchedulePayload:
    return SchedulePayload.model_validate(загрузить_фикстуру("itmo", имя))


def по_предмету(имя: str) -> dict[str, MirrorRow]:
    return {с.subject: с for с in payload_to_rows(разобрать(имя), МОСКВА)}


# --- формат ответа ----------------------------------------------------------


def test_настоящий_ответ_портала_разбирается_целиком() -> None:
    """Три дня обезличенной выборки: две пары, ни одной, четыре."""
    ответ = разобрать("schedule_live.json")

    assert [день.date for день in ответ.data] == [
        dt.date(2026, 8, 30),
        dt.date(2026, 9, 3),
        dt.date(2026, 9, 8),
    ]
    assert [len(день.lessons) for день in ответ.data] == [2, 0, 4]


def test_день_без_пар_приходит_пустым_списком() -> None:
    """Так шлёт живой портал: `[]`, а не `null`.

    Проверено на живом ответе — из 36 дней десять пришли пустым списком
    и ни одного `null`.
    """
    сырое = загрузить_фикстуру("itmo", "schedule_live.json")

    assert сырое["data"][1]["lessons"] == []


def test_null_вместо_списка_разбор_не_ломает() -> None:
    """Оборонительный случай, живым ответом не подтверждённый.

    Портал шлёт `[]`, но `null` в этом месте — настолько дешёвая проверка,
    что держать её стоит: цена ошибки — падение ночного джоба на пустом дне.
    """
    ответ = разобрать("schedule_online.json")

    assert ответ.data[1].lessons == []


def test_пустое_расписание_это_рабочее_состояние() -> None:
    """Каникулы — не ошибка. Джоб обязан пройти и записать пустое окно."""
    ответ = разобрать("schedule_empty.json")

    assert ответ.data == []
    assert payload_to_rows(ответ, МОСКВА) == []


def test_неизвестные_поля_не_роняют_разбор() -> None:
    """В настоящем ответе двадцать три поля пары, читаем мы девять.

    `pair_id`, `subject_id`, `flow_id`, `work_type_id` и прочие нам не нужны,
    и падать на них не за что. Опасна обратная перемена, и её проверяет
    следующий тест.
    """
    сырое = загрузить_фикстуру("itmo", "schedule_live.json")
    поля_пары = set(сырое["data"][0]["lessons"][0])

    assert {"pair_id", "subject_id", "flow_id", "work_type_id"} <= поля_пары
    assert разобрать("schedule_live.json").data[0].lessons[0].subject


def test_исчезнувшее_обязательное_поле_роняет_разбор() -> None:
    """Инвариант 9 и §10: формат изменился — падаем, а не пишем мусор.

    Без `subject` пара не является парой, и подставить название неоткуда.
    """
    with pytest.raises(ValidationError, match="subject"):
        разобрать("schedule_broken.json")


@pytest.mark.parametrize(
    ("строка", "ожидание"),
    [
        ("10:00", dt.time(10, 0)),
        ("10:00:00", dt.time(10, 0)),
        ("9:05", dt.time(9, 5)),
        ("23:59:59", dt.time(23, 59, 59)),
    ],
)
def test_время_портала_разбирается_в_обоих_видах(строка: str, ожидание: dt.time) -> None:
    """Живой портал шлёт "10:00"; вид с секундами оставлен на всякий случай."""
    assert parse_portal_time(строка) == ожидание


@pytest.mark.parametrize("строка", ["", "10", "10-00", "25:00", "10:60", "утро"])
def test_нечитаемое_время_отвергается(строка: str) -> None:
    """Разобрать «как получится» здесь нельзя: ошибка уедет в напоминание."""
    with pytest.raises(ValueError, match="время"):
        parse_portal_time(строка)


def test_слишком_длинное_поле_роняет_разбор_а_не_вставку() -> None:
    """Ширина поля проверяется здесь, а не в базе.

    Иначе портал, приславший килобайт в «аудиторию», даёт в логе ошибку
    драйвера вместо имени поля, и разбираться придётся в дампе SQL.
    """
    with pytest.raises(ValidationError, match="room"):
        RawLesson.model_validate(
            {
                "subject": "Дисциплина",
                "time_start": "10:00",
                "time_end": "11:30",
                "room": "х" * 300,
            }
        )


# --- отображение в зеркало --------------------------------------------------


def test_местное_время_портала_переводится_в_utc() -> None:
    """Портал отдаёт "10:00" без смещения. В базе только UTC (инвариант 7).

    Сверено с живым прогоном на плате: 10:00 портала легло как 07:00Z.
    """
    строки = payload_to_rows(разобрать("schedule_live.json"), МОСКВА)

    assert строки[0].starts_at == dt.datetime(2026, 8, 30, 7, 0, tzinfo=dt.UTC)
    assert строки[0].ends_at == dt.datetime(2026, 8, 30, 8, 0, tzinfo=dt.UTC)


def test_дата_занятия_остаётся_местной() -> None:
    """`lesson_date` — день, который owner видит в расписании.

    Хранится отдельно от `starts_at` именно поэтому: вечерняя пара в UTC
    попадает во вчера или в завтра, и выборка «пары на такой-то день»
    начала бы зависеть от зоны выполнения запроса.
    """
    строки = payload_to_rows(разобрать("schedule_live.json"), МОСКВА)

    assert строки[0].lesson_date == dt.date(2026, 8, 30)


def test_поздняя_пара_не_переползает_на_другую_дату() -> None:
    """Проверка на границе, на зоне восточнее MSK.

    Тест держит `lesson_date` независимой от перевода в UTC: возьми код
    дату из `starts_at`, для Владивостока она уехала бы на день назад.
    """
    пара = RawLesson.model_validate(
        {"subject": "Вечерняя", "time_start": "23:00", "time_end": "23:59"}
    )
    строка = lesson_to_row(dt.date(2026, 9, 7), пара, ZoneInfo("Asia/Vladivostok"))

    assert строка.lesson_date == dt.date(2026, 9, 7)
    assert строка.starts_at == dt.datetime(2026, 9, 7, 13, 0, tzinfo=dt.UTC)


def test_преподаватель_берётся_из_teacher_name() -> None:
    """Живой портал шлёт именно это поле; `teacher_fio` в ответе нет вовсе."""
    строки = по_предмету("schedule_live.json")

    assert строки["Дискретная математика"].teacher == "Преподаватель Б. Б."


def test_преподаватель_берётся_и_из_teacher_fio() -> None:
    """Оборонительный случай: референс читает оба имени поля.

    В живом ответе за сентябрь 2026 `teacher_fio` не встретился ни разу,
    поэтому проверяется на синтетической фикстуре и помечен как таковой.
    """
    строки = payload_to_rows(разобрать("schedule_online.json"), МОСКВА)
    через_fio = next(с for с in строки if "другим полем" in с.subject)

    assert через_fio.teacher == "Преподаватель Д. Д."


def test_отсутствующие_реквизиты_становятся_пустотой() -> None:
    """У «Распределительного теста» в живом ответе нет ни преподавателя,
    ни аудитории, ни здания — и это нормальная пара, а не сломанная."""
    тест = по_предмету("schedule_live.json")["Распределительный тест"]

    assert тест.teacher is None
    assert тест.room is None
    assert тест.building is None


def test_формат_берётся_из_поля_портала() -> None:
    """Главная поправка живого прогона: поле `format` у портала **есть**.

    Референс его не читает, и по нему мы выводили бы формат из наличия
    ссылки на Zoom — то есть писали бы пусто у каждой очной пары.
    Хвостовой пробел портала (`'Очно - дистанционный '`) срезается разбором.
    """
    строки = по_предмету("schedule_live.json")

    assert строки["Дискретная математика"].mode == "Очно - дистанционный"
    assert строки["Чирлидинг (перфоманс)"].mode == "Очный"


def test_дистанционная_пара_отдаёт_ссылку() -> None:
    """Синтетическая фикстура: в живом ответе дистанционных пар не было."""
    строки = payload_to_rows(разобрать("schedule_online.json"), МОСКВА)
    удалённая = next(с for с in строки if с.subject == "Дистанционная дисциплина")

    assert удалённая.mode == "Дистанционный"
    assert удалённая.online_url == "https://us02web.zoom.us/j/00000000000"


def test_режим_не_выдумывается_когда_признаков_нет() -> None:
    """Инвариант 9: нет ни поля формата, ни ссылки — оставляем пусто.

    Написать «очно» на основании отсутствия ссылки значило бы соврать
    с уверенным видом.
    """
    строки = payload_to_rows(разобрать("schedule_online.json"), МОСКВА)
    без_признаков = next(с for с in строки if "другим полем" in с.subject)

    assert без_признаков.mode is None
    assert без_признаков.online_url is None


def test_пара_кончающаяся_раньше_начала_роняет_джоб() -> None:
    """Референс молча меняет концы местами. Мы падаем.

    У него календарь-подписка, у нас источник для расчёта напоминаний (§4):
    молчаливое исправление скрыло бы, что портал отдаёт мусор.
    """
    with pytest.raises(MappingError, match="не позже начала"):
        payload_to_rows(разобрать("schedule_backwards.json"), МОСКВА)


# --- ключ строки ------------------------------------------------------------


def test_ключ_не_меняется_от_прогона_к_прогону() -> None:
    """Инвариант хоста 5: ключ детерминирован от данных источника.

    База, восстановленная из дампа, обязана попасть в те же строки, а не
    задвоить семестр при первом же заборе.
    """
    первый = [с.source_key for с in payload_to_rows(разобрать("schedule_live.json"), МОСКВА)]
    второй = [с.source_key for с in payload_to_rows(разобрать("schedule_live.json"), МОСКВА)]

    assert первый == второй


def test_смена_аудитории_ключ_не_меняет() -> None:
    """Это та же пара с исправленным реквизитом — она обязана обновить строку.

    Меняйся ключ, зеркало получило бы вторую пару в то же время, а календарь —
    два события вместо одного.
    """
    было = RawLesson.model_validate(
        {
            "subject": "Линейная алгебра",
            "type": "Лекции",
            "time_start": "11:30",
            "time_end": "13:00",
            "room": "2337",
        }
    )
    стало = было.model_copy(update={"room": "2304", "teacher_name": "Преподаватель Е. Е."})

    assert build_source_key(dt.date(2026, 9, 8), было) == build_source_key(
        dt.date(2026, 9, 8), стало
    )


def test_лекция_и_практика_по_одному_предмету_различаются() -> None:
    """Случай из живого расписания: «Линейная алгебра» идёт в один день
    и лекцией, и практикой. Без `type` в ключе они схлопнулись бы в одну."""
    лекция = RawLesson.model_validate(
        {
            "subject": "Линейная алгебра",
            "type": "Лекции",
            "time_start": "11:30",
            "time_end": "13:00",
        }
    )
    практика = лекция.model_copy(update={"type": "Практические занятия"})

    assert build_source_key(dt.date(2026, 9, 8), лекция) != build_source_key(
        dt.date(2026, 9, 8), практика
    )


def test_одинаковые_пары_в_одном_ответе_роняют_разбор() -> None:
    """Задвоенный ключ означает, что состав ключа больше не различает пары.

    Узнать об этом надо сразу, а не по пропавшей паре в календаре через месяц.
    """
    пара = {
        "subject": "Дискретная математика",
        "type": "Лекции",
        "time_start": "09:50",
        "time_end": "11:20",
    }
    ответ = SchedulePayload.model_validate(
        {"data": [{"date": "2026-09-08", "lessons": [пара, пара]}]}
    )

    with pytest.raises(MappingError, match="один ключ"):
        payload_to_rows(ответ, МОСКВА)


def test_строки_отсортированы_по_времени() -> None:
    """Дифф джоба читается глазами, и порядок в нём должен быть предсказуем."""
    строки = payload_to_rows(разобрать("schedule_live.json"), МОСКВА)

    assert [с.starts_at for с in строки] == sorted(с.starts_at for с in строки)
