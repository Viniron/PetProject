"""Реестр адаптеров (Э12б): подключён тот, у кого есть ключ.

Пустой ключ - рабочее состояние, а не поломка. Заглушка вместо адаптера
отвечала бы выдумкой там, где нужен отказ (инвариант 9), поэтому провайдера
без ключа в реестре просто нет, а ядро об этом говорит вслух.
"""

from jarvis_api.config import Settings
from jarvis_api.integrations.llm.registry import собрать_адаптеры


def настройки(**поля: object) -> Settings:
    return Settings(**поля)  # type: ignore[arg-type]


def test_без_ключей_реестр_пуст() -> None:
    assert собрать_адаптеры(настройки()) == {}


def test_один_ключ_один_провайдер() -> None:
    реестр = собрать_адаптеры(настройки(gemini_api_key="test-key"))
    assert list(реестр) == ["google"]


def test_оба_ключа_оба_провайдера() -> None:
    реестр = собрать_адаптеры(настройки(gemini_api_key="test-key", anthropic_api_key="test-key"))
    assert sorted(реестр) == ["anthropic", "google"]


def test_пробелы_вместо_ключа_это_отсутствие_ключа() -> None:
    """`.env` правят руками, и строка из пробелов там - обычное дело.

    Провайдер, собранный с пустым заголовком, ходил бы наружу и получал 401,
    то есть выглядел бы сломанным ключом вместо ненастроенного.
    """
    assert собрать_адаптеры(настройки(gemini_api_key="   ")) == {}


def test_имена_совпадают_с_теми_что_пишут_в_назначении() -> None:
    """Имя провайдера в реестре и в `LLM_ROUTING` - одна и та же строка.

    Разойдись они - вызов отказывал бы «провайдер не подключён» при обоих
    заданных ключах, и искать причину owner пошёл бы в панель провайдера.
    """
    реестр = собрать_адаптеры(настройки(gemini_api_key="test-key", anthropic_api_key="test-key"))
    assert all(имя == адаптер.имя for имя, адаптер in реестр.items())
