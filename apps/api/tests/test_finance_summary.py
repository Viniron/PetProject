НАЗНАЧЕНИЕ = json.dumps(
    {
        "finance_summary": {
            "provider": "провайдер-а",
            "model": "модель-1",
            "max_tokens": 1024,
            "price_in": "2",
            "price_out": "10",
        }
    }
)


@dataclass
class Модель:
    """Провайдер с заготовленным ответом; помнит, что ушло."""

    имя: str = "провайдер-а"
    тело: dict[str, Any] | None = None
    сбой: Exception | None = None
    запросы: list[llm.Запрос] = field(default_factory=list)

    def выполнить(self, запрос: llm.Запрос) -> llm.Ответ:
        self.запросы.append(запрос)
        if self.сбой is not None:
            raise self.сбой
        assert self.тело is not None, "модель позвали, хотя сценарий этого не ждал"
        return llm.Ответ(
            текст=json.dumps(self.тело, ensure_ascii=False), токенов_вход=1000, токенов_выход=100
        )


def пишет(текст: str, *, сравнила: bool = True) -> Модель:
    return Модель(тело={"text": текст, "compared": сравнила})


def настройки() -> Settings:
    return Settings().model_copy(update={"llm_routing": НАЗНАЧЕНИЕ})


def адаптеры(модель: Модель) -> dict[str, llm.Адаптер]:
    return {модель.имя: модель}


_номера = itertools.count(1)


def импорт(сессия: Session, банк: str, с: dt.date, по: dt.date) -> FinImport:
    строка = FinImport(
        bank=банк,
        filename=f"{банк}-{по}.csv",
        sha256=f"f11-{next(_номера)}".ljust(64, "0"),
        period_start=с,
        period_end=по,
    )
    сессия.add(строка)
    сессия.flush()
    return строка


def категория(
    сессия: Session, месяц: dt.date, key: str, title: str, parent: FinCategory | None = None
) -> FinCategory:
    строка = FinCategory(
        key=key,
        period_month=месяц,
        level=1 if parent is None else 2,
        parent_id=parent.id if parent is not None else None,
        parent_level=1 if parent is not None else None,
        title=title,
        origin="owner",
        status="active",
    )
    сессия.add(строка)
    сессия.flush()
    return строка


def операция(
    сессия: Session,
    день: dt.date,
    сумма: str,
    *,
    категория_: FinCategory | None = None,
    kind: str = "expense",
    гасит: FinTransaction | None = None,
    **поля: Any,
) -> FinTransaction:
    значение = Decimal(сумма)
    строка = FinTransaction(
        bank="tbank",
        account="Карта",
        # Полдень по Москве: день операции однозначен в зоне owner.
        occurred_at=dt.datetime.combine(день, dt.time(12, 0), tzinfo=МОСКВА),
        amount=значение,
        amount_rub=значение,
        currency="RUB",
        kind=kind,
        merchant="Магазин",
        category_id=категория_.id if категория_ is not None else None,
        category_source="merchant" if категория_ is not None else None,
        offsets_transaction_id=гасит.id if гасит is not None else None,
        fingerprint=f"f11-{next(_номера)}".ljust(64, "0"),
        **поля,
    )
    сессия.add(строка)
    сессия.flush()
    return строка


def прошлое_резюме(сессия: Session, импорт_: FinImport, с: dt.date, по: dt.date) -> FinSummary:
    начало, конец = границы(Период(с=с, по=по), МОСКВА)
    строка = FinSummary(
        import_id=импорт_.id, period_start=начало, period_end=конец, text_ru="прошлое"
    )
    сессия.add(строка)
    сессия.flush()
    return строка


def подвести_(
    сессия: Session,
    модель: Модель | None,
    импорты: list[int],
    настройки_: Settings | None = None,
) -> ОтчётРезюме:
    return подвести(
        сессия,
        настройки_ or настройки(),
        импорты=импорты,
        адаптеры=адаптеры(модель) if модель is not None else None,
        сейчас=СЕЙЧАС,
        зона=МОСКВА,
    )


def книжка_с_историей(сессия: Session) -> FinImport:
    """Книжка с 1 августа, прошлое резюме по 7 сентября, новая выписка
    до 14-го. Август и сентябрь - разные наборы, ключ «Еды» один."""
    сессия.add(FinAccount(bank="tbank", name="Карта", role="checking"))
    первый = импорт(сессия, "tbank", д(8, 1), д(9, 7))
    прошлое_резюме(сессия, первый, д(8, 1), д(9, 7))
    еда_авг = категория(сессия, д(8, 1), "food", "Еда")
    фастфуд_авг = категория(сессия, д(8, 1), "fastfood", "Фастфуд", parent=еда_авг)
    еда_сен = категория(сессия, д(9, 1), "food", "Еда")
    # 38 дней истории (1.08-7.09): 3 800 ₽ - 100 ₽ в день, 700 ₽ за неделю.
    операция(сессия, д(8, 10), "-1900.00", категория_=фастфуд_авг)
    операция(сессия, д(9, 2), "-1900.00", категория_=еда_сен)
    обед = операция(сессия, д(9, 9), "-2000.00", категория_=еда_сен)
    # Друзья вернули долю за обед - трата 1 500, как в сальдо.
    операция(сессия, д(9, 10), "500.00", kind="refund", гасит=обед)
    операция(сессия, д(9, 11), "-300.00")
    # Не идут в счёт: исключённая и стоящая в разборе.
    операция(сессия, д(9, 12), "-9000.00", категория_=еда_сен, excluded=True)
    операция(сессия, д(9, 12), "-7000.00", категория_=еда_сен, needs_review=True)
    return импорт(сессия, "tbank", д(9, 1), д(9, 14))


def test_резюме_записывается_со_снимком_и_стоимостью(сессия: Session) -> None:
    новый = книжка_с_историей(сессия)
    модель = пишет("На еду ушло 1 500 ₽ - вдвое больше обычных 700 ₽.")

    отчёт = подвести_(сессия, модель, [новый.id])

    assert отчёт.отказ is None
    строка = отчёт.строка
    assert строка is not None
    assert строка.import_id == новый.id
    assert строка.text_ru == "На еду ушло 1 500 ₽ - вдвое больше обычных 700 ₽."
    assert (строка.period_start, строка.period_end) == границы(НЕДЕЛЯ, МОСКВА)
    assert (строка.provider, строка.model) == ("провайдер-а", "модель-1")
    assert (строка.tokens_in, строка.tokens_out) == (1000, 100)
    # 1000 входа по $2 и 100 выхода по $10 за миллион.
    assert строка.cost_usd == Decimal("0.003000")

    основа = строка.basis
    assert основа is not None
    assert основа["period"] == {"from": "2026-09-08", "to": "2026-09-14", "days": 7}
    assert основа["history"] == {"from": "2026-08-01", "to": "2026-09-07", "days": 38}
    assert основа["enough_history"] is True
    assert основа["categories"] == [
        {"key": "food", "title": "Еда", "spent": "1500.00", "count": 1, "average": "700.00"}
    ]
    assert основа["uncategorized"]["spent"] == "300.00"
    assert основа["total"]["spent"] == "1800.00"

    # Модели ушли те же цифры, что легли в снимок.
    assert '"average": "700.00"' in модель.запросы[0].переменная_часть
