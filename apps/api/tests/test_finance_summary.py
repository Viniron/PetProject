def test_прошлое_резюме_не_переписывается_пересчётом(сессия: Session) -> None:
    """Гашение задним числом меняет траты (§15.5), но прошлое резюме держит
    свой снимок: следующий импорт заводит новую строку, а не правит старую."""
    новый = книжка_с_историей(сессия)
    первое = подвести_(сессия, пишет("На еду 1 500 ₽."), [новый.id]).строка
    assert первое is not None
    снимок = json.dumps(первое.basis, sort_keys=True)
    обед = сессия.scalars(
        select(FinTransaction).where(FinTransaction.amount == Decimal("-2000.00"))
    ).one()
    операция(сессия, д(9, 16), "1500.00", kind="refund", гасит=обед)
    ещё = импорт(сессия, "tbank", д(9, 8), д(9, 21))

    второе = подвести_(сессия, пишет("Неделя тише."), [ещё.id]).строка

    assert второе is not None and второе.id != первое.id
    сессия.refresh(первое)
    assert первое.text_ru == "На еду 1 500 ₽."
    assert json.dumps(первое.basis, sort_keys=True) == снимок
    assert второе.basis is not None
    assert второе.basis["period"]["from"] == "2026-09-15"
