"""Резюме о расходах после импорта (Ф11, §15.9, ADR-058).

Модель подставная и отвечает по сценарию: сеть в прогоне замокана всегда
(`CLAUDE.md`). Проверяется то, что ломается тихо:

- **период кончается днём, по который загружены все банки** - иначе резюме
  по самому свежему банку называло бы «меньше на еду» незагруженную карту;
- **период начинается с конца прошлого резюме** - пропущенное из-за отказа
  модели охватывается следующим импортом, а не теряется;
- **«среднее» - по ключу основной категории, в день, умноженное на длину
  периода**: подкатегории и наборы месяцев меняются, ключ - нет;
- **мало истории - сравнения нет**, и ответ модели, утверждающий обратное,
  отбрасывает код;
- **траты - за вычетом гашений**, как в сальдо;
- **отказ модели строки не оставляет**, а вызов при этом в аудите.

Первая половина без базы, вторая - против настоящей Postgres.
"""

