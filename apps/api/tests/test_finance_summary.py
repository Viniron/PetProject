def test_импорт_заканчивается_резюме(
    сессия: Session, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
) -> None:
    """Справка Ozon за 16.08-16.09 - первая выписка книжки. Резюме описывает
    её период, повторная загрузка того же файла резюме не добавляет."""
    monkeypatch.setenv("LLM_ROUTING", НАЗНАЧЕНИЕ)
    from jarvis_api.config import get_settings

