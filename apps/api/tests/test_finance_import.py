"""Импорт со сверкой (Ф3, §15.3).

Ошибка сверки не падает, а тихо искажает суммы: обнаружится через месяцы
и не лечится переимпортом. Поэтому проверяется не «строки записались»,
а ровно те случаи, в которых деньги теряются, - кратность одинаковых
операций, дозревание с изменившейся суммой, пропажа из выгрузки.

Первая половина файла без базы: `спланировать` - чистая функция от того,
что отдал адаптер, и от того, что книжка уже знает. Вторая половина -
джоб целиком против настоящей Postgres, на обезличенной выгрузке Т-Банка.

Два файла тестов сделаны производными **в коде**, а не фикстурами на диске:
перестановка строк и удаление одной операции - это разница, которую тест
обязан назвать сам, иначе она молча превратится в «чем ещё отличается файл».
"""

import datetime as dt
from decimal import Decimal
from typing import Any
from zoneinfo import ZoneInfo

import pytest
from conftest import байты_фикстуры
from sqlalchemy import select
from sqlalchemy.orm import Session

from jarvis_api.db.models import FinAccount, FinImport, FinTransaction
from jarvis_api.domain.finance_import import (
    Существующая,
    отпечаток,
    спланировать,
)
from jarvis_api.integrations.statements.base import StatementRow
from jarvis_api.jobs.finance_import import run_once

МОСКВА = ZoneInfo("Europe/Moscow")
БАНК = "tbank"
СЧЁТ = "Black"
ФАЙЛ = "tbank_august.csv"

# Столько операций в настоящей выгрузке за август 2026.
ОПЕРАЦИЙ_В_АВГУСТЕ = 62


# --- разбор без базы -------------------------------------------------------


def строка(
    *,
    когда: str = "31.08.2026 13:36:02",
    сумма: str = "-330.00",
    мерчант: str | None = "Фастфуд Альфа",
    карта: str | None = "0000",
    статус: str = "posted",
    валюта: str = "RUB",
) -> StatementRow:
    """Строка выписки. Время - московское, как его пишет банк."""
    момент = dt.datetime.strptime(когда, "%d.%m.%Y %H:%M:%S").replace(tzinfo=МОСКВА)
    return StatementRow(
        row_no=2,
        occurred_at=момент.astimezone(dt.UTC),
        account=СЧЁТ,
        card_last4=карта,
        amount=Decimal(сумма),
        currency=валюта,
        amount_rub=Decimal(сумма),
        merchant=мерчант,
        bank_category="Фастфуд",
        own_category=None,
        mcc="5814",
        message=None,
        analytics_hint=True,
        status=статус,
        source_row={"Описание": мерчант or ""},
    )


def уже_в_книжке(
    источник: StatementRow,
    *,
    номер: int = 1,
    occurrence_no: int = 1,
    статус: str | None = None,
    банк: str = БАНК,
) -> Существующая:
    """Операция книжки, соответствующая этой строке файла."""
    return Существующая(
        id=номер,
        fingerprint=отпечаток(
            банк,
            источник.occurred_at,
            источник.amount,
            источник.currency,
            источник.merchant,
            источник.card_last4,
        ),
        occurrence_no=occurrence_no,
        status=статус or источник.status,
        occurred_at=источник.occurred_at,
        card_last4=источник.card_last4,
        merchant=источник.merchant,
    )


def ключ_строки(с: StatementRow, банк: str = БАНК) -> str:
    """Отпечаток строки файла - тот же вызов, что делает сверка."""
    return отпечаток(банк, с.occurred_at, с.amount, с.currency, с.merchant, с.card_last4)


def test_банк_входит_в_ключ() -> None:
    """Одинаковая покупка из двух банков - две операции, а не одна.

    Проверяется на уровне ключа, а не файлом второго банка: формат выгрузки -
    входные данные от owner, и выдуманный файл проверял бы выдумку (§15.1).
    """
    одна = строка()

    assert ключ_строки(одна) != ключ_строки(одна, банк="bspb")

    # И то же самое через план: книжка знает такую операцию, но другого банка.
    план = спланировать(БАНК, [уже_в_книжке(одна, банк="bspb")], [одна], МОСКВА)
    assert len(план.новые) == 1


def test_секунды_различают_операции() -> None:
    """Две оплаты 575 рублей 23 августа: 15:13:33 и 15:13:53 - разные операции."""
    первая = строка(когда="23.08.2026 15:13:33", сумма="-575.00", мерчант="Тренировки Альфа")
    вторая = строка(когда="23.08.2026 15:13:53", сумма="-575.00", мерчант="Тренировки Альфа")

    assert ключ_строки(первая) != ключ_строки(вторая)


def test_ключ_не_зависит_от_написания_суммы() -> None:
    """`-330.0` из адаптера и `-330.00` из `numeric(12,2)` - один ключ.

    Иначе после первого же круга «записали - прочитали» переимпорт добавил
    бы всю выписку заново.
    """
    из_файла = отпечаток(БАНК, строка().occurred_at, Decimal("-330.0"), "RUB", "М", "0000")
    из_базы = отпечаток(БАНК, строка().occurred_at, Decimal("-330.00"), "RUB", "М", "0000")

    assert из_файла == из_базы


