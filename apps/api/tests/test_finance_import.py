def test_дозревание_через_полночь_по_зоне_owner() -> None:
    """День считается в зоне owner: ночная покупка не разъезжается на двое суток.

    21:30 UTC - это 00:30 следующего дня в Москве, и обе строки обязаны
    оказаться в одном дне, иначе дозревание не найдётся.
    """
    ожидание = строка(когда="02.08.2026 00:30:00", сумма="-1000.00", статус="pending")
    проведено = строка(когда="02.08.2026 00:31:00", сумма="-1030.00")
    assert ожидание.occurred_at.date() == dt.date(2026, 8, 1)  # в UTC это ещё первое

    план = спланировать(БАНК, [уже_в_книжке(ожидание)], [проведено], МОСКВА)

    assert len(план.обновления) == 1


def test_неоднозначное_дозревание_уходит_в_разбор() -> None:
    """Два ожидания на одну свежую строку - выбор стоит денег, значит в разбор."""
    первое = строка(сумма="-500.00", статус="pending")
    второе = строка(когда="31.08.2026 14:00:00", сумма="-700.00", статус="pending")
    проведено = строка(сумма="-575.00")
    книжка = [уже_в_книжке(первое, номер=1), уже_в_книжке(второе, номер=2)]

    план = спланировать(БАНК, книжка, [проведено], МОСКВА)

    # Ничего не смержено и ничего не отменено: обе строки книжки ждут owner.
    assert not план.обновления
    assert not план.отменённые
    assert план.в_разбор == [1, 2]
    # Строка файла всё равно заводится - терять её нельзя, - но вне сальдо.
    assert [новая.в_разбор for новая in план.новые] == [True]


