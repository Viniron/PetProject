def test_две_одинаковые_покупки_остаются_двумя() -> None:
    """Два кофе по 200 рублей в одном месте дают один ключ и две операции."""
    кофе = строка(когда="02.08.2026 10:00:00", сумма="-200.00", карта=None)

    первый_импорт = спланировать(БАНК, [], [кофе, кофе], МОСКВА)
    assert [новая.occurrence_no for новая in первый_импорт.новые] == [1, 2]

    книжка = [
        уже_в_книжке(кофе, номер=1, occurrence_no=1),
        уже_в_книжке(кофе, номер=2, occurrence_no=2),
    ]
    второй_импорт = спланировать(БАНК, книжка, [кофе, кофе], МОСКВА)
    assert not второй_импорт.есть_изменения
    assert второй_импорт.неизменных == 2

    # Третий файл принёс ту же покупку третий раз за день - это третья
    # настоящая операция, а не дубль: добавляется разница, а не ноль.
    третий_импорт = спланировать(БАНК, книжка, [кофе, кофе, кофе], МОСКВА)
    assert [новая.occurrence_no for новая in третий_импорт.новые] == [3]


