def test_ручная_операция_не_отменяется(сессия: Session) -> None:
    """Наличных в выписке не будет никогда - это не повод их стирать."""
    сессия.add(FinAccount(bank=БАНК, name=СЧЁТ, role="checking"))
    сессия.add(операция_книжки(entered_manually=True))
    сессия.commit()

    импорт(сессия, (ФАЙЛ, август()))

    ручная = сессия.scalars(
        select(FinTransaction).where(FinTransaction.entered_manually.is_(True))
    ).one()
