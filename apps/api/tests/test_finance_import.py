def без_строки(данные: bytes, подстрока: str) -> bytes:
    """Та же выписка без одной операции - для проверки отмены."""
    строки = [с for с in данные.split(b"\r\n") if с]
    оставшиеся = [строки[0]] + [с for с in строки[1:] if подстрока.encode("utf-8") not in с]
    assert len(оставшиеся) == len(строки) - 1, "подстрока должна найтись ровно в одной строке"
    return b"\r\n".join(оставшиеся) + b"\r\n"


def только_день(данные: bytes, день: str) -> bytes:
    """Выгрузка за один день: перекрывающийся период, а не новый файл."""
    строки = [с for с in данные.split(b"\r\n") if с]
    return (
        b"\r\n".join([строки[0]] + [с for с in строки[1:] if день.encode("utf-8") in с]) + b"\r\n"
    )


def наоборот(данные: bytes) -> bytes:
    """Те же операции в обратном порядке: другой файл, та же выписка."""
    строки = [с for с in данные.split(b"\r\n") if с]
    return b"\r\n".join([строки[0]] + list(reversed(строки[1:]))) + b"\r\n"


def август() -> bytes:
    return байты_фикстуры("statements", ФАЙЛ)


def импорт(
    сессия: Session,
    *файлы: tuple[str, bytes],
    apply: bool = True,
) -> int:
    return run_once(сессия, list(файлы), apply=apply)


def операции(сессия: Session) -> list[FinTransaction]:
    return list(сессия.scalars(select(FinTransaction).order_by(FinTransaction.occurred_at)).all())


def операция_книжки(**переопределения: Any) -> FinTransaction:
    """Операция, лежащая в книжке до импорта: ручная либо ожидающая."""
    поля: dict[str, Any] = {
        "bank": БАНК,
        "account": СЧЁТ,
        "occurred_at": dt.datetime(2026, 8, 15, 12, 0, tzinfo=МОСКВА),
        "amount": Decimal("-100.00"),
        "amount_rub": Decimal("-100.00"),
        "currency": "RUB",
        "kind": "expense",
        "status": "posted",
        "fingerprint": "вручную".ljust(64, "0"),
    }
    поля.update(переопределения)
    return FinTransaction(**поля)


def test_импорт_заводит_операции_и_счёт(сессия: Session) -> None:
    код = импорт(сессия, (ФАЙЛ, август()))

    assert код == 0
    assert len(операции(сессия)) == ОПЕРАЦИЙ_В_АВГУСТЕ

    # Оба счёта выгрузки, и «Накопительный счет» - через «е», как в файле:
    # имя счёта это ключ, и «исправленная» буква дала бы операцию без счёта
    # в разметке, то есть тихое расхождение в статье «Отложено» (§15.1).
    счета = sorted((с.bank, с.name, с.role) for с in сессия.scalars(select(FinAccount)).all())
    assert счета == [
        (БАНК, СЧЁТ, "unknown"),
        (БАНК, "Накопительный счет", "unknown"),
    ]

    запись = сессия.scalars(select(FinImport)).one()
    assert запись.bank == БАНК
    assert (запись.period_start, запись.period_end) == (
        dt.date(2026, 8, 1),
        dt.date(2026, 8, 31),
    )
    assert (запись.rows_added, запись.rows_updated, запись.rows_skipped) == (
        ОПЕРАЦИЙ_В_АВГУСТЕ,
        0,
        0,
    )


def test_знак_суммы_даёт_вид_операции(сессия: Session) -> None:
    """Импорт заводит строку видом по знаку и честно помечает это `sign`.

    С Ф4а вслед за импортом идёт разбор, и входящий перевод без правила
    отправителя он переводит в `refund` с пометкой (§15.5) - поэтому знак
    проверяется по расходам и по `kind_source`, а не по итоговому виду
    прихода. Сам знак при этом решает по-прежнему: правил в этой книжке нет
    ни одного, и расход остался расходом именно из-за него.
    """
    импорт(сессия, (ФАЙЛ, август()))

    расходы = {
        (строка.kind, строка.kind_source)
        for строка in операции(сессия)
        if строка.merchant == "Фастфуд Альфа"
    }
    приходы = {
        (строка.kind, строка.kind_source)
        for строка in операции(сессия)
        if строка.merchant == "Алексей А."
    }
    assert расходы == {("expense", "sign")}
    assert приходы == {("refund", "default")}


