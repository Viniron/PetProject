def test_неоднозначное_дозревание_помечает_обе_стороны(сессия: Session) -> None:
    """Две оплаты 575 в один день с одним описанием - кандидатов два, выбора нет."""
    сессия.add(FinAccount(bank=БАНК, name=СЧЁТ, role="checking"))
    сессия.add(
        операция_книжки(
            occurred_at=dt.datetime(2026, 8, 23, 15, 0, tzinfo=МОСКВА),
            amount=Decimal("-500.00"),
            amount_rub=Decimal("-500.00"),
            card_last4="0000",
            merchant="Тренировки Альфа",
            status="pending",
        )
    )
    сессия.commit()

    импорт(сессия, (ФАЙЛ, август()))

    # Пометки импорта отличаются от пометок разбора источником вида:
    # разбор ставит свою вместе с `default` (§15.5), импорт оставляет `sign`.
    # Без этого различия очередь «Требует внимания» смешала бы кандидатов
    # в дубли с неразмеченными переводами, и снять одну, не тронув другую,
    # было бы нечем.
    в_разборе = [
        строка
        for строка in сессия.scalars(
            select(FinTransaction).where(FinTransaction.needs_review.is_(True))
        ).all()
        if строка.kind_source == "sign"
    ]
    # Ожидание книжки и обе строки файла: ни одна из трёх не входит в сальдо,
    # пока owner не решит, что из них одна операция.
    assert len(в_разборе) == 3
    ожидание = [строка for строка in в_разборе if строка.status == "pending"]
    assert len(ожидание) == 1
    assert ожидание[0].amount == Decimal("-500.00")


