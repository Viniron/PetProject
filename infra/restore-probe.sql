-- Проба восстановления. Живёт в базе до Э2 и удаляется первой миграцией.
--
-- Зачем она: на Э1 схемы приложения ещё нет, и восстановление пустой базы
-- проверяет только тракт "дамп скачался, pg_restore прошёл". С пробой
-- проверяется то, ради чего бэкап и делается - что данные вернулись.
--
-- Почему это не Alembic: инвариант "схема только через Alembic" говорит о
-- схеме приложения. Эта таблица к приложению не относится, ни одна строка
-- кода её не читает, и на Э2 её сносит первая же миграция. Решение owner,
-- зафиксировано в docs/BUILD-PROGRESS.md.
--
-- Применяется один раз на хосте:
--   docker exec -i jarvis-db-1 psql -U jarvis -d jarvis < infra/restore-probe.sql

CREATE TABLE IF NOT EXISTS restore_probe (
    id          integer PRIMARY KEY,
    note        text        NOT NULL,
    -- timestamptz, а не timestamp: инвариант 7 действует и здесь, а проба
    -- как раз и должна поймать сдвиг времени при заливке дампа на хост
    -- с другой локалью.
    created_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO restore_probe (id, note) VALUES
    (1, 'проба Э1: если эта строка видна после pg_restore, восстановились данные, а не только схема'),
    (2, 'вторая строка нужна, чтобы count(*) отличал восстановление от случайного пустого успеха'),
    (3, 'удаляется первой миграцией Alembic на Э2')
ON CONFLICT (id) DO NOTHING;
