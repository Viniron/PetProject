#!/bin/sh
# Проверка восстановления: разворачивает свежайший локальный дамп в отдельную
# базу и показывает, что в ней оказалось.
#
# Зачем отдельная база: непроверенный дамп бэкапом не считается (ADR-020),
# но проверка не должна ставить под удар единственную живую копию данных.
# jarvis_restore создаётся заново каждый прогон и никем не читается.
#
# Почему shell, а не Python-джоб: логики, которую можно сломать незаметно,
# здесь нет - две команды psql и одна pg_restore. Ежемесячный автоматический
# restore-тест из ADR-020 - это джоб этапа Э9, у него будут и расписание,
# и разбор результата, и тесты.
#
# Запускается на хосте, где поднят стек: make restore-check

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"

if [ ! -f "$ENV_FILE" ]; then
    echo "нет файла окружения $ENV_FILE - без него не собрать подключение к базе" >&2
    exit 1
fi

docker compose --env-file "$ENV_FILE" \
    -f "$ROOT/infra/docker-compose.yml" \
    -f "$ROOT/infra/docker-compose.pi.yml" \
    run --rm --entrypoint /usr/local/bin/restore-check.sh backup

echo "готово: база jarvis_restore оставлена для осмотра, следующий прогон её пересоздаст"
