#!/bin/sh
# Проверка восстановления: разворачивает свежайший локальный дамп в отдельную
# базу и разбирает, что в ней оказалось.
#
# Зачем отдельная база: непроверенный дамп бэкапом не считается (ADR-020),
# но проверка не должна ставить под удар единственную живую копию данных.
# jarvis_restore создаётся заново каждый прогон и никем не читается.
#
# Работу делает джоб jarvis_api.jobs.restore_check (Э9), а не этот файл.
# До Э9 здесь был shell-скрипт на две команды psql; с расписанием,
# разбором результата и сторожем он стал кодом, который надо покрывать
# тестами, - а тестировать shell в этом проекте нечем.
#
# Джоб запускается в контейнере backup: только в этом образе есть
# одновременно pg_restore нужной мажорной версии и том с копиями.
#
# Запускается на хосте, где поднят стек:
#   make restore-check        - проверка без записи наружу
#   make restore-check-apply  - то же плюс ping сторожу (так делает таймер)

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"

if [ ! -f "$ENV_FILE" ]; then
    echo "нет файла окружения $ENV_FILE - без него не собрать подключение к базе" >&2
    exit 1
fi

docker compose --env-file "$ENV_FILE" \
    -f "$ROOT/infra/docker-compose.yml" \
    -f "$ROOT/infra/docker-compose.pi.yml" \
    run --rm --entrypoint python3 backup -m jarvis_api.jobs.restore_check "$@"
